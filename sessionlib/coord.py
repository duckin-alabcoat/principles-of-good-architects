def _entry_block(text: str, entry: dict) -> str:
    """The verbatim lines of a handoff `entry` — its header through just before
    the next entry header. Used to INJECT the prior session's entry into context
    (ADR-0035 inject-don't-read) instead of the Architect re-reading the growing
    handoff file."""
    lines = text.splitlines()
    i = entry["header_index"]
    j = i + 1
    while j < len(lines) and not ENTRY_RE.match(lines[j]):
        j += 1
    return "\n".join(lines[i:j]).strip()


def _inject_block(prior_block: str) -> tuple[str, list[str]]:
    """Assemble the ADR-0035 injected context: the prior session's handoff entry
    (bounded — one entry, never the ~300KB file) + the user profile/overrides.

    Returns (text, labels) — `labels` names the parts ACTUALLY assembled, so the banner
    can report what was delivered instead of asserting a fixed string. The old signature
    returned text only and the caller printed `prior-entry + user-profile` whenever
    anything at all was injected: a session that assembled only the prior entry still
    claimed the profile. A status line that cannot express the failure it describes is
    fabricated data ([no-fabricated-data], P18) — in the substrate that ships that very
    habit to the fleet."""
    parts, labels = [], []
    if prior_block:
        parts.append("--- PRIOR SESSION ENTRY (injected — no need to re-read the "
                     "handoff) ---\n" + prior_block)
        labels.append("prior-entry")
    prof, dropped = _user_profile_text()
    if prof:
        # A truncated profile is delivered AND said so, in the same breath. The label is
        # what the banner prints, so the loss lands in front of a person rather than
        # living in a return value nobody renders (WI-0066). Consumers match on the
        # `user-profile` PREFIX, never equality, so this line can carry detail safely.
        parts.append("--- USER PROFILE / OVERRIDES (injected — no need to re-read"
                     + (f"; TRUNCATED, {dropped} char(s) NOT delivered — raise "
                        f"PROFILE_INJECT_CAP" if dropped else "") + ") ---\n" + prof)
        labels.append("user-profile" if not dropped
                      else f"user-profile (TRUNCATED — {dropped} char(s) dropped)")
    return "\n\n".join(parts), labels


def _claim_prepped_journal(session_id: str) -> Path | None:
    """Bind the journal the wrapper prepped for this lane to the runtime session that has
    just started, and return it (ADR-0082 D1).

    Returns None — leaving the caller on the ordinary allocate-my-own path — for every
    case that is not an unambiguous match: no marker, a marker naming a journal that no
    longer exists, one already closed, or one already held by a DIFFERENT runtime session.
    That last case is the one that matters: adopting a journal another live session owns
    would give two sessions one record, which is the very defect this handshake exists to
    prevent, so it declines rather than guesses.

    The marker is consumed on success, so a second runtime launched into the same lane
    cannot claim the same journal. Never raises — a failed adoption must degrade to an
    extra journal, never to a failed start."""
    m = _prep_marker()
    try:
        if not m.is_file():
            return None
        rec = json.loads(m.read_text(encoding="utf-8"))
        did = (rec.get("session_id") or "").strip()
        if not did:
            return None
        p = journal_path(did)
        if not p.is_file():
            return None
        fm, body = parse_journal(p.read_text(encoding="utf-8"))
        if not fm or fm.get("ended"):
            return None
        held = (fm.get("claude-session-id") or "").strip()
        if held and held != session_id:
            return None
        fm["claude-session-id"] = session_id
        atomic_write(p, _rerender_journal(fm, body))
        m.unlink()
        return p
    except Exception:
        return None


def _coord_iso(epoch: float) -> str:
    """ISO stamp for an epoch in the configured tz (UTC if config is absent). Cosmetic —
    expiry math is on the epoch field; this is for human-readable record inspection."""
    tz = CFG["tz"] if CFG else timezone.utc
    return datetime.fromtimestamp(epoch, tz).isoformat()


def _coord_epoch(stamp: str) -> float:
    """The inverse of `_coord_iso` — an ISO record stamp back to an epoch (WI-0298).

    `_coord_iso` calls itself cosmetic because expiry math reads the epoch field beside
    it. `heartbeat_at` has no such twin: it is written only as ISO, and the dead-holder
    detector needs its AGE. Rather than add a second epoch field to every record (and a
    second thing that can disagree with the first), the one stamp is parsed. Naive stamps
    — a record written before a tz was configured — are read in the configured tz rather
    than as UTC, because that is the clock that wrote them; guessing UTC would shift the
    age by hours and could call a live holder dead."""
    dt = datetime.fromisoformat(stamp)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=CFG["tz"] if CFG else timezone.utc)
    return dt.timestamp()


