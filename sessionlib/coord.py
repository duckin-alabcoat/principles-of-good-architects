def _coord_holder() -> tuple[str, str, str]:
    """(durable-journal-id, runtime, runtime-source) of the session holding a
    coordination record — the facts the record could not previously state (WI-0061).

    `session_id` on a record is really an OWNERSHIP KEY (`_coord_identity`: the lane
    branch, or the Claude session id) and is not a session's identity: in a lane it is
    the *checkout*, so every record written through the main-checkout-anchored front door
    (`poga work`, `adr-next` — both by design, ADR-0073) reads as held by `main` no matter
    which session actually holds it. Observed live in session ~113: the ADR-0069 land gate
    refused this lane's own ADR number as reserved by `main`, because from the record it
    genuinely was. That cost a renumber and a permanent gap at ADR-0083.

    The third element is why this was REOPENED in session ~121. The runtime shipped and
    printed, but it reported a DEFAULT dressed as an observation: the old code seeded
    `runtime` from config and overwrote it only when a journal matched, so a non-Claude
    session — which by construction could never match — kept the `claude-code` default
    and the record asserted the one thing it could not know. `runtime_source` names which
    tier answered, so "observed" and "assumed" stop printing identically
    ([`declare-what-a-check-assumes`]). Four tiers, most authoritative first:

      journal   the holding session's own journal frontmatter — an observation
      launcher  POGA_RUNTIME_ID, exported by `poga` from the registry row it resolved
      config    this member's declared `runtime`
      default   CLAUDE_RUNTIME, because something has to be written

    These fields are ADDITIVE and identifying only — the ownership key is unchanged, so
    matching, release and the land gate behave exactly as before. Whether the *gate*
    should compare on the journal id instead is a real question with a real blast radius
    (it changes who may land), left recorded on WI-0061 rather than folded in silently.

    Best-effort and never raises: a coordination write must not fail because a journal
    could not be read."""
    journal_id, fm_runtime, foreign = "", "", False
    try:
        found = _find_holder_journal()
        if found is not None:
            jpath, fm = found
            journal_id = fm.get("session-id", "") or ""
            fm_runtime = (fm.get("runtime") or "").strip()
            foreign = _journal_is_from_another_lane(jpath)
    except Exception:
        pass
    if fm_runtime:
        # WI-0106's second path. `journal` stays exactly as it was — it is the OWNERSHIP
        # key the gate matches on, and weakening it here would re-break the case WI-0093
        # had just fixed. What changes is only the PROVENANCE CLAIM: a runtime read from
        # a journal that lives in a different LANE was observed of the reader, not of the
        # lane the record is about, and printing that as a plain observation is the
        # confidently-wrong reading this item names.
        return journal_id, fm_runtime, "journal-foreign" if foreign else "journal"
    launcher = os.environ.get("POGA_RUNTIME_ID", "").strip()
    if launcher:
        return journal_id, launcher, "launcher"
    cfg_runtime = ((CFG or {}).get("runtime") or "").strip()
    if cfg_runtime:
        return journal_id, cfg_runtime, "config"
    return journal_id, CLAUDE_RUNTIME, "default"


def _coord_record(session_id: str, ttl: int, **extra) -> dict:
    """Build a coordination record: who holds it, on which branch/machine, when it was
    taken and when it expires (epoch is authoritative; the *_iso fields are cosmetic).

    `journal`/`runtime` (WI-0061) say WHICH SESSION and which agent holds it — a record
    that named only a branch could not distinguish two sessions in one checkout, could
    not survive being read by a different runtime, and misattributed every lane's
    front-door write to `main`. `runtime_source` says whether the runtime was OBSERVED
    or merely assumed, so the two can never again print identically."""
    now = time.time()
    try:
        machine = detect_machine() if CFG else ""
    except Exception:
        machine = ""
    journal_id, runtime, runtime_source = _coord_holder()
    rec = {
        "session_id": session_id or "",
        "journal": journal_id,
        "runtime": runtime,
        "runtime_source": runtime_source,
        "machine": machine,
        "branch": _current_branch(),
        "created_at": _coord_iso(now),
        "expires_at": now + ttl,
        "expires_iso": _coord_iso(now + ttl),
        "ttl_seconds": ttl,
    }
    rec.update(extra)
    return rec


def _coord_read(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def _coord_runtime_label(rec: dict) -> str:
    """How a record's runtime should PRINT — never a bare value when it was not observed.

    WI-0061's reopened half: the field shipped and printed, but `claude-code` written
    from a default looked exactly like `claude-code` read off a session's own journal,
    so the store appeared to answer a question it had never actually asked. The marker is
    the whole point ([`declare-what-a-check-assumes`]): `(assumed)` for a config/default
    fallback, `(unverified)` for a record written before the source field existed."""
    rt = rec.get("runtime") or "?"
    src = rec.get("runtime_source", "")
    if src in ("config", "default"):
        return f"{rt} (assumed)"
    if src == "journal-foreign":
        # WI-0106: observed, but of the READER rather than of the lane this record is
        # about — a session in one lane that reached into another and drew a record
        # there. Distinguished from a plain observation for the same reason `(assumed)`
        # is: two different questions must not print the same answer.
        return f"{rt} (observed of the reader, not this lane)"
    if not src:
        return f"{rt} (unverified)"
    return rt


def _coord_who(rec: dict, *, runtime: bool = True) -> str:
    """Who holds a record, as one printable phrase.

    The branch alone is not a holder: every record written through the anchored front
    door reads `main` whichever session took it (WI-0061), so the journal id — the
    session's own durable identity — is what actually distinguishes two holders and is
    never omitted here. `runtime=False` is the narrow view for `claims`, whose rows
    already carry an item title and would wrap; `coord` is the full picture.

    WI-0157 SWAPPED THE TWO HALVES. Both facts were already here — the phrase read
    `worktree-poga-3 [20260912T1200Z-devbox-87e5]` — but the RECYCLED slot sat in the
    reading position and the durable id was parenthetical. A slot is freed on teardown and
    reissued to the next lane, so the leading half of this phrase was precisely the half
    that cannot be relied on to mean the same thing an hour later. The holder now leads
    with `<machine>-<tail>` — the same compression `_coord_short_holder` renders in the
    narrow STATE cell, so the two surfaces finally agree on what a holder is called — and
    the branch follows as what it actually is: the ref a reader types. The full journal id
    is not dropped; it stays in the `coord` view, which has the width for it."""
    who = rec.get("branch") or rec.get("session_id", "?")
    journal = (rec.get("journal") or "").strip()
    # A journal-less record has no session to name, so it gets the SAME answer
    # `lane_identity` tier 3 gives a lane that never ran: the project-qualified label,
    # never the bare slot and never the string "no journal" — which named nothing, and
    # printed twice on the runtime line.
    holder = _coord_short_holder(rec) if journal else _lane_label(who)
    if runtime:
        return f"{holder}  [{_coord_runtime_label(rec)} · {journal or 'no journal'} · {who}]"
    return f"{holder} [{who}]"


def _durable_id_parts(sid: str) -> tuple[str, str]:
    """`20260912T1200Z-devbox-d5b9` -> `('devbox', 'd5b9')` — the machine and the tail.

    The durable session id (ADR-0051 C1, `durable_session_id`) is the one identifier in
    the harness that is unique forever, and its own shape already carries both halves a
    human-facing lane label needs. Reading them OUT OF THE ID rather than off two sidecar
    fields is deliberate: a machine and a tail read from separate places can disagree
    about which session they describe, and a label assembled from two sources cannot be
    checked against any single id.

    This is the PARSE, shared; it is not the spelling. `_coord_short_holder` joins the
    pair with a hyphen because its cell is narrow, and `lane_identity` uses `·` because
    it is rendering a wide identity column next to an address column — one separator
    forced on both would make one of the two surfaces worse. What must not be duplicated
    is the knowledge of how the id is built, and that now lives here (WI-0157).

    Anything that is not the three-part id returns a pair of empties: absence is not
    identity ([`declare-what-a-check-assumes`](habits/master.md#declare-what-a-check-assumes))."""
    parts = (sid or "").strip().split("-")
    if len(parts) < 3:
        return "", ""
    # Indexed from the FRONT for the machine and the BACK for the tail, which is what
    # the id's shape actually guarantees: the timestamp half carries no hyphen and
    # `durable_session_id` slugs the machine to `[a-z0-9]+`, so the machine is always
    # parts[1]. Counting the machine from the end instead would silently rename it the
    # day the documented `...-<person>-<random>` extension lands.
    return parts[1], parts[-1]


def _coord_short_holder(rec: dict) -> str:
    """The holder, compressed to fit a table cell (WI-0130).

    `_coord_who` is the full phrase and is right for the claims/coord views, which have
    a line to spend. The work-item list has a narrow STATE cell, and it rendered
    `rec["branch"]` — which for every claim taken through the anchored front door
    (`poga work claim` cd's to the main checkout by design, ADR-0073) is literally
    `main`. So a row held by a specific session in a specific lane printed `open·main`,
    which reads as *held by main*: a wrong answer shaped like a right one, on the surface
    an operator actually scans. Reported by a member Architect, who hit the same field from
    the matching side and whose own rung read a false `none held` off it.

    The journal id is the only field that names the SESSION rather than the checkout, so
    it wins when present. Compressed to its `<machine>-<token>` tail because the cell is
    narrow and the timestamp half is the part two concurrent holders share; the full id
    is one `poga work claims` away. Falls back to the historical fields when there is no
    journal — absence is not identity, so it must not print an empty holder."""
    journal = (rec.get("journal") or "").strip()
    if journal:
        machine, tail = _durable_id_parts(journal)
        return f"{machine}-{tail}" if machine else journal
    return (rec.get("branch") or rec.get("session_id") or "?").replace("worktree-", "")


def _coord_expired(rec: dict, now: float | None = None) -> bool:
    """A record is stale once its epoch `expires_at` passes. A missing/malformed expiry
    counts as expired (reclaimable): a record we can't read a TTL from must never hold a
    resource forever."""
    if now is None:
        now = time.time()
    try:
        return float(rec.get("expires_at", 0)) <= now
    except (TypeError, ValueError):
        return True


def _coord_try_acquire(kind: str, name: str, session_id: str, ttl: int,
                       **extra) -> tuple[bool, dict]:
    """Atomically acquire the coordination name `<kind>/<name>` for this session.
    Returns (acquired, holder). On success holder is our own record. On failure the name
    is held by a DIFFERENT live session and holder is that session's record. Reclaims a
    name that is ours (re-acquire = refresh) or expired. Fail-OPEN: if the shared dir
    can't be resolved, returns (True, {}) — coordination degrades to a no-op, never
    bricks the caller (isolation via worktrees still holds)."""
    d = _coord_dir(kind, create=True)
    if d is None:
        return True, {}
    path = d / f"{name}.json"
    rec = _coord_record(session_id, ttl, name=name, kind=kind, **extra)
    payload = json.dumps(rec, ensure_ascii=False, indent=2) + "\n"
    # Fast path: atomic exclusive create wins iff the name did not exist. This is the
    # load-bearing guarantee — two lanes racing for a FREE name, exactly one wins.
    try:
        fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(payload)
        if kind == "claims":
            _wi_feed_write()                 # a new claim is board-visible state
        return True, rec
    except FileExistsError:
        pass
    except Exception:
        return True, {}  # unexpected fs error → fail-open, don't block the caller
    holder = _coord_read(path)
    if holder is None:
        atomic_write(path, payload)          # corrupt record → reclaim
        if kind == "claims":
            _wi_feed_write()
        return True, rec
    # `rec["journal"]` was just resolved for THIS session by `_coord_record`, so reuse it
    # rather than paying `_coord_holder()` a second time on the contended path.
    mine = _coord_mine(holder, session_id, rec.get("journal", ""))
    if mine or _coord_expired(holder):
        atomic_write(path, payload)          # ours or dead → reclaim (benign last-writer race)
        if kind == "claims":
            _wi_feed_write()
        return True, rec
    return False, holder


def _coord_refresh(kind: str, name: str, session_id: str, ttl: int) -> bool:
    """Bump the expiry of a name THIS session holds (the heartbeat keep-alive). No-op
    (False) if the name is missing or held by another session."""
    d = _coord_dir(kind)
    if d is None or not session_id:
        return False
    path = d / f"{name}.json"
    holder = _coord_read(path)
    # WI-0298: REFRESH ownership, not release ownership. `_coord_mine` matches the lane
    # branch too, and every session that ever runs in a lane shares it — which is how a
    # waiter kept a dead holder's record alive for 28 minutes. See `_coord_mine_for_refresh`.
    if holder is None or not _coord_mine_for_refresh(holder, session_id, _coord_my_journal()):
        return False
    now = time.time()
    holder["expires_at"] = now + ttl
    holder["expires_iso"] = _coord_iso(now + ttl)
    holder["heartbeat_at"] = _coord_iso(now)
    try:
        atomic_write(path, json.dumps(holder, ensure_ascii=False, indent=2) + "\n")
        return True
    except Exception:
        return False


def _coord_mine(rec: dict, session_id: str, journal: str = "") -> bool:
    """Does this coordination record belong to the caller? (WI-0123)

    Two keys, either sufficient. `session_id` is the historical OWNERSHIP KEY and is kept
    first so nothing that worked before changes. But it is computed from *the checkout
    that executed the write* (`_coord_identity`: the lane branch inside a lane, else the
    Claude session id), and the front door anchors on main by design (ADR-0073) — so a
    lane claiming through `poga work claim` records the session id while the same lane's
    own `release` computes its branch, and the two never meet. Reproduced live in session
    ~140: a lane was told its own claim was `held by main`, with `--force` — the flag for
    overriding OTHER sessions — offered as the way out.

    `journal` is the fix, and it is not a new fact: `_coord_record` has written it since
    WI-0061 precisely because a record naming only a checkout cannot say which session
    holds it. That work stopped short of changing what MATCHES, deliberately, because the
    land gate's blast radius (it decides who may land) deserved its own decision. This
    helper is therefore scoped to OWNERSHIP — release, refresh, reclaim, teardown — and
    the gate is deliberately not routed through it.

    Journal matching is strictly MORE precise than the key it supplements: a lane branch
    is reused by every session that ever runs in that lane, while a journal id is durable
    and unique to one session. An empty journal on either side never matches — absence is
    not identity ([`declare-what-a-check-assumes`])."""
    if session_id and rec.get("session_id") == session_id:
        return True
    return bool(journal) and rec.get("journal") == journal


def _coord_mine_for_refresh(rec: dict, session_id: str, journal: str = "") -> bool:
    """May the caller RENEW this record? (WI-0298.)

    `_coord_mine` answers a different question — may the caller RELEASE it — and answers
    it deliberately loosely, because a release that misses is a leaked record while a
    release that over-matches only frees something early. Renewal is the opposite trade:
    over-matching does not free anything, it makes a record IMMORTAL, and an immortal
    record on the land gate is a repo nobody can land in.

    So refresh keys on the JOURNAL, which is one session, and never on `session_id`, which
    inside a lane is the lane BRANCH and is therefore shared by every session that ever
    runs there. Measured 2026-09-06: journal `a1ef` closed leaving the gate
    record behind; journal `83dd` opened in the same lane, queued behind it as a foreign
    holder (`_coord_mine` correctly said not-mine), and then its own heartbeat matched the
    SAME record on the lane name and pushed the expiry out every minute. The record could
    not expire, the queue could not advance, and the only exit was the 90-minute fail-open
    cap. Ownership said one thing and renewal said another about the same record; the fix
    is that they now ask the same question with the same key.

    The journal is NECESSARY, and there are three cases it has to separate — the suite
    pins each, and the third is why the rule is not simply "both keys must agree":

      1. **Same lane, different sessions** — the 2026-09-06 incident above. The lane branch is
         identical for both; only the JOURNAL tells them apart. Deny.
      2. **Different lanes, one journal** — dispatched siblings. `tmux new-session` hands
         each child the dispatcher's environment, so a whole wave inherits ONE journal id.
         The journal cannot separate them; a sibling renewing the holder's grip would hide
         a wedged lane from the one mechanism that frees it. Deny
         (`SiblingLanesShareAJournalTest`).
      3. **One session, two doors** — WI-0123. A lane claiming through the main-anchored
         front door (`poga work claim`, ADR-0073) writes the CLAUDE SESSION ID, while the
         same lane refreshing from inside computes its BRANCH. Same journal, same session,
         two `session_id`s, and it must still be able to keep its own claim alive. Allow.

    So the tie-break between 2 and 3 — both are "journals match, session ids differ" — is
    what KIND of id each side is. A `worktree-` id is a LOCATION; two different locations
    under one journal are two different processes, which is case 2. A location paired with
    a non-location is one process reaching through a different door, which is case 3. This
    is the same scoping rule `_coord_holder_is_dead` already applies for the same reason:
    a lane branch is evidence about a place, a session id is evidence about a session.

    The `session_id`-only fallback is kept for records that carry NO journal — the
    pre-WI-0061 shape, and any record written by a runtime that cannot resolve one.
    Absence is not identity, so it is a fallback and never an alternative."""
    if rec.get("journal"):
        if not journal or rec.get("journal") != journal:
            return False
        theirs = (rec.get("session_id") or "").strip()
        ours = (session_id or "").strip()
        if theirs and ours and theirs != ours \
                and theirs.startswith("worktree-") and ours.startswith("worktree-"):
            return False                 # case 2: two lanes, one inherited journal
        return True
    return bool(session_id) and rec.get("session_id") == session_id


def _coord_host() -> str:
    """This machine's hostname, for records whose liveness proof is a local pid. Empty on
    any failure — an unknowable host must degrade to "cannot probe from here", never to a
    wrong same-host verdict that would evict a live holder."""
    try:
        return _socket.gethostname() or ""
    except Exception:
        return ""


def _coord_my_journal() -> str:
    """This session's durable journal id for ownership matching, or "" if it cannot be
    resolved. Best-effort by construction — an unresolvable journal must degrade to the
    old session_id-only behaviour, never raise inside a release."""
    try:
        journal_id, _runtime, _src = _coord_holder()
        return journal_id or ""
    except Exception:
        return ""


def _coord_tombstone_dir(kind: str, create: bool = False) -> Path | None:
    """`<kind>/released/` — where a released record's tombstone lives (WI-0074).

    A SUBDIR rather than a `<name>.released.json` sibling, deliberately: every reader of a
    kind globs `*.json` at the top level, so a subdir is invisible to all of them without
    a single filter needing to be added in N places (and a claim genuinely named
    `foo.released` could never be confused for a tombstone)."""
    d = _coord_dir(kind, create=create)
    if d is None:
        return None
    t = d / COORD_RELEASED_DIRNAME
    if create:
        try:
            t.mkdir(parents=True, exist_ok=True)
        except Exception:
            return None
    return t


def _coord_tombstone(kind: str, name: str, holder: dict, reason: str) -> None:
    """Record that `<kind>/<name>` was released, and why (WI-0074).

    Without this, a released record and one that was never taken are byte-identical from
    outside — `_coord_release` ended in a bare `unlink()`, and a claim release appears in
    no log (`guard-firings.jsonl` records guard DENIALS only). That gap costs most in the
    case this substrate exists for: reconstructing a session that died mid-flight, where
    *"did it ever take the claim?"* is part of the story. A member's diagnostic ladder reads this
    rung and, until now, had to answer *"released or never claimed — not distinguishable."*

    `reason` distinguishes the three ways a hold ends, which are genuinely different
    events: `released` (the holder let go), `reclaimed` (someone cleared expired residue),
    `teardown` (the lane died and its holds were freed for it).

    Carries its own TTL so the directory cannot grow without bound
    ([`retention-enforced-by-code`](habits/master.md#retention-enforced-by-code)) —
    `_coord_reap` prunes it on the same pass that reaps live records. Best-effort: a
    tombstone that cannot be written must never fail the release it records."""
    try:
        t = _coord_tombstone_dir(kind, create=True)
        if t is None:
            return
        now = time.time()
        rec = {
            "name": name,
            "kind": kind,
            "reason": reason,
            "session_id": holder.get("session_id", ""),
            "branch": holder.get("branch", ""),
            "journal": holder.get("journal", ""),
            "runtime": holder.get("runtime", ""),
            "machine": holder.get("machine", ""),
            "claimed_at": holder.get("created_at", ""),
            "released_at": _coord_iso(now),
            "expires_at": now + COORD_TOMBSTONE_TTL_SECONDS,
            "expires_iso": _coord_iso(now + COORD_TOMBSTONE_TTL_SECONDS),
        }
        atomic_write(t / f"{name}.json", json.dumps(rec, ensure_ascii=False, indent=2) + "\n")
        if kind == "claims":
            _wi_feed_write()                 # every way a hold ends routes
            # through the tombstone, so this one hook covers release/reclaim/teardown.
    except Exception:
        pass


def _coord_tombstones(kind: str) -> dict[str, dict]:
    """Unexpired release tombstones under `<kind>`, keyed by name. Never raises."""
    out: dict[str, dict] = {}
    t = _coord_tombstone_dir(kind)
    if t is None or not t.is_dir():
        return out
    now = time.time()
    try:
        for p in sorted(t.glob("*.json")):
            rec = _coord_read(p)
            if rec is not None and not _coord_expired(rec, now):
                out[p.stem] = rec
    except Exception:
        pass
    return out


def _coord_release(kind: str, name: str, session_id: str, force: bool = False,
                   reason: str = "released") -> bool:
    """Release a name this session holds (delete the record). `force` releases regardless
    of holder (operator override). False if the name is absent or held by another session
    and not forced.

    Leaves a tombstone (WI-0074) so the release is visible after the fact — see
    `_coord_tombstone` for why a bare unlink was not enough."""
    d = _coord_dir(kind)
    if d is None:
        return False
    path = d / f"{name}.json"
    holder = _coord_read(path)
    if holder is None:
        return False
    if not force and session_id and not _coord_mine(holder, session_id,
                                                    _coord_my_journal()):
        return False
    try:
        path.unlink()
    except Exception:
        return False
    _coord_tombstone(kind, name, holder, reason)
    return True


def _coord_release_exact(kind: str, name: str, rec: dict, reason: str = "released",
                         emit=None) -> bool:
    """Release `<kind>/<name>` ONLY if the record on disk is the one `rec` describes.

    WI-0346. The gate and the trunk lock released with `force=True` under a comment
    arguing that a True return from their reserve PROVED the record was theirs. It did
    not, twice over:

      - the reserve's fail-open paths returned True having written nothing, so the unlink
        hit whichever lane actually held the single shared record; and
      - `serialized` is a fact about the past. A lapsed record whose holder reads as gone
        may legitimately be reclaimed by a second lane (`_land_gate_holder_dead`) while
        the first is still inside its block — after which the first lane's `finally`
        deletes the second lane's live gate, and two lands run on one trunk.

    So this does not ask "did we take it?" but "is what is here still what we wrote?",
    keyed on the three fields a record is identified by everywhere else in this file —
    `created_at` (microsecond ISO), `session_id`, and the WI-0061 `journal` that alone
    distinguishes two sessions in one lane. A heartbeat touches none of them, so a long
    land can still free its own record. An empty `rec` — what every fail-open hands back
    — matches nothing, which is the whole point: "we hold nothing" becomes a no-op by
    construction rather than by a caller remembering to check.

    Deliberately NOT `_coord_mine`: that also matches on the ambient journal, which
    sibling lanes share, and it is the hole the gate's acquire is built to avoid. This is
    strictly narrower than both `force` and ownership.

    A residual race remains — the record could be reclaimed between the read and the
    unlink — and it is not closable with POSIX primitives at this layer. It is a
    microsecond window in place of a certainty, and `_coord_tombstone` (WI-0074) records
    which record was freed either way.

    Returns True iff a record was actually removed. A mismatch SAYS SO through `emit`:
    finding someone else's record where ours should be is not housekeeping, it means our
    hold was lost mid-land and whatever we did under it was unserialized."""
    d = _coord_dir(kind)
    if d is None or not rec:
        return False
    path = d / f"{name}.json"
    on_disk = _coord_read(path)
    if on_disk is None:
        return False
    keys = ("created_at", "session_id", "journal")
    if any(on_disk.get(k, "") != rec.get(k, "") for k in keys):
        if callable(emit):
            emit(f"{kind}: NOT releasing {name} — the record there is "
                 f"{_coord_short_holder(on_disk)}, not the one we wrote. Our hold was "
                 f"lost before we let go of it; anything done under it ran unserialized.")
        return False
    try:
        path.unlink()
    except FileNotFoundError:
        return False
    except Exception:
        return False
    _coord_tombstone(kind, name, on_disk, reason)
    return True


def _coord_list(kind: str, include_expired: bool = False) -> dict[str, dict]:
    """All live records under `<kind>` keyed by name. Expired records are excluded unless
    asked for (they are reclaimable — not live holders)."""
    out: dict[str, dict] = {}
    d = _coord_dir(kind)
    if d is None or not d.is_dir():
        return out
    now = time.time()
    for p in sorted(d.glob("*.json")):
        rec = _coord_read(p)
        if rec is None:
            continue
        if not include_expired and _coord_expired(rec, now):
            continue
        out[p.stem] = rec
    return out


def _coord_reap(kinds: tuple[str, ...] = COORD_KINDS) -> int:
    """Delete expired (or unreadable) coordination records across `kinds`; return the
    count removed. Tidying only — read-time expiry is authoritative, so a missed reap
    never causes a stale record to be honored as live. Never raises."""
    n = 0
    now = time.time()
    for kind in kinds:
        d = _coord_dir(kind)
        if d is None or not d.is_dir():
            continue
        # The registry row that owns this kind, if any — `claims`, `leases` and
        # `attention` are not numbered and resolve to None, which switches both of the
        # number rules below off without either of them naming a kind.
        try:
            c = _counter_by_namespace(kind)
        except Exception:
            c = None
        trunk_nums: set[int] | None = None    # resolved once per kind, and only if used
        for p in sorted(d.glob("*.json")):
            rec = _coord_read(p)
            # WI-0182: an attention record whose session is PROVABLY over is reapable on
            # the same evidence rule the journal reaper uses, regardless of its TTL. The
            # 24h expiry is deliberately long — a question asked at 23:00 is still real at
            # 08:00 — which makes it a terrible mechanism for a record that was never valid
            # in the first place, and a fine backstop once it is only a backstop. Without
            # this the write-side guard fixes only records made AFTER it ships, and the one
            # that exposed the defect would have gone on claiming a human was waiting.
            if (kind == ATTENTION_KIND and rec is not None
                    and _attention_session_is_over(rec.get("session_id", ""))):
                with contextlib.suppress(Exception):
                    p.unlink()
                    n += 1
                continue
            num = int(p.stem) if (c is not None and rec is not None
                                  and p.stem.isdigit()) else None
            if num is not None and trunk_nums is None:
                try:
                    trunk_nums = _counter_trunk_nums(c)
                except Exception:
                    trunk_nums = set()        # cannot tell → free nothing on this ground
            # WI-0237 — A RESERVATION WHOSE FILE IS ON THE TRUNK IS NOT PROTECTING
            # ANYTHING, whatever its TTL says, so it is freed here regardless of expiry.
            #
            # This is the READ side of the same fix. The write side releases the ticket at
            # the moment the item file is committed (`_release_committed_numbers`), which
            # by construction can only fix records made AFTER it ships — the WI-0166
            # lesson one namespace over. The records that caused the incident were made
            # before it, and there were twelve of them in the live store when this was
            # written, every one for a number already committed on the trunk, each able to
            # refuse a land for the remainder of its 8h TTL.
            #
            # It cannot re-issue a number. `_counter_reserve_next` draws above
            # `max(landed files, sibling lane tips, trunk, held reservations)`, and a
            # number on the trunk is inside the third term whether or not a reservation
            # also names it — so dropping the hold is arithmetically invisible to the
            # allocator. What it changes is only who gets REFUSED by a ticket that has
            # already been spent.
            #
            # Deliberately NOT the mirror of the keep rule below. Freeing a spent number
            # is safe for every counter; the KEEP rule needed a decision about `ops-alloc`,
            # which WI-0244 has since taken on the trunk — it now reads the rule off
            # `_counters()` rather than a hand-listed pair of kinds, and this land takes
            # that side. `lane-alloc` reaches neither — its names are lanes, not numbers.
            if num is not None and num in (trunk_nums or set()):
                with contextlib.suppress(Exception):
                    p.unlink()
                    n += 1
                continue
            if rec is not None and not _coord_expired(rec, now):
                continue
            # R5b: an ALLOCATOR reservation's lifetime is tied to TRUNK VISIBILITY, not
            # wall-clock. The reserved file is lane-local until land, so a TTL-expired
            # reservation whose lane branch still exists is NOT reclaimable — reaping it
            # would let the number be re-issued while its file is committed-but-unlanded.
            # The TTL stays as the orphan backstop: it frees the number once the lane
            # branch is gone (or the number is already visible on the trunk).
            #
            # `br != _trunk()` is what keeps that rule from creating IMMORTAL residue
            # (session ~125). The hold is released when its branch disappears — but the
            # trunk never disappears, so a reservation drawn from the MAIN checkout and
            # then abandoned was held forever. Three were found sitting in the store, the
            # oldest expired 11 days: 0072, and 0083/0086, both numbers deliberately burned
            # and therefore guaranteed never to appear on the trunk. The protection is also
            # MEANINGLESS on the trunk: "committed but not yet landed" cannot describe a
            # trunk branch — a file committed there is on the trunk, and the WI-0237 rule
            # above has already freed it.
            # A live main-checkout session still keeps its own hold alive by heartbeat.
            #
            # WI-0244: this rule was once written TWICE — once for `adr-alloc`, once for
            # `wi-alloc` — so the third counter inherited neither copy. `ops-alloc` shipped
            # with ADR-0076 D2, was added to `COORD_ALLOC_KINDS` and gated at the land by
            # the same registry, and was reaped here on its 8h TTL alone: a lane holding an
            # unlanded `OPS-NNNN` past the TTL could have its number re-issued to a
            # sibling — precisely the collision the carve-out exists to prevent, one
            # namespace over. The rule is a property of the COUNTER, not of a hand-listed
            # pair of kinds, so it is read off `_counters()` instead. Same by-construction
            # argument ADR-0076 D2 made for the land gate: the next counter added is
            # covered with no edit here, and cannot inherit half a rule.
            #
            # `lane-alloc` is in `COORD_ALLOC_KINDS` and deliberately has NO counter row —
            # it reserves a lane number, which has no file to be invisible on the trunk.
            # It falls through to the TTL, which is the whole of its rule.
            #
            # `trunk_has` is KEPT rather than deleted as the now-dead half of the WI-0237
            # rule above. It is dead only while `_counter_trunk_nums` SUCCEEDS: when that
            # scan raises, `trunk_nums` is set to the empty set — "cannot tell, free
            # nothing on this ground" — and every record reaches this line with its trunk
            # visibility still unanswered. Deleting the scan would therefore change
            # behaviour on the failure path, not remove dead code. That question is open
            # in the record and is not this land's to settle.
            if c is not None and num is not None:
                br = rec.get("branch", "")
                # `_counter_num_in_path` verifies BOTH the directory prefix and the
                # filename shape — the ADR allocator's own hard-won two-place defense,
                # and the FIFTH site of the hardcoded-`adr/` assumption a member's report did
                # not enumerate. Left hardcoded it would defeat the other four: on a
                # member with a different ADR directory `trunk_has` is always False, so a
                # reservation would be held forever by a lane branch that had already
                # landed, and numbers would leak out of the pool one per ADR.
                _d = c.dirname()
                trunk_has = any(
                    _counter_num_in_path(c, name) == num
                    for name in (sh(["git", "ls-tree", "--name-only", _trunk(), f"{_d}/"],
                                    check=False).stdout or "").split()
                )
                if not trunk_has and br and br != _trunk() and _ref_exists(f"refs/heads/{br}"):
                    continue
            try:
                p.unlink()
                n += 1
            except Exception:
                pass
        # WI-0074: tombstones expire on the same pass. They are retention, not state —
        # nothing reads an expired one, and a trace directory that only ever grows would
        # trade one litter class for another
        # ([`retention-enforced-by-code`](habits/master.md#retention-enforced-by-code)).
        t = d / COORD_RELEASED_DIRNAME
        if t.is_dir():
            for p in sorted(t.glob("*.json")):
                rec = _coord_read(p)
                if rec is not None and not _coord_expired(rec, now):
                    continue
                try:
                    p.unlink()
                    n += 1
                except Exception:
                    pass
    return n


def _coord_identity() -> str:
    """The identity that holds this session's coordination records. In a poga lane it is
    the lane branch (worktree-poga-N) — stable across a claude-session restart in the lane
    and the natural 'which lane' key. Otherwise the Claude session id, then the invoking
    lane's own key, and 'app' only when the caller is in no lane at all.

    That third tier is WI-0107. The key is what `release` and `refresh` MATCH ON, so it is
    an ownership key, not a label — and it used to fall straight from the Claude session id
    to the literal `'app'`. A non-Claude runtime exports no session id, and the front door
    anchors on main so `_on_worktree_lane()` is false there, which meant **every** codex or
    antigravity session on the machine held its records under one shared key: one agent
    could release another's claim (reproduced live, session ~129), and one live session's
    heartbeat refreshed every other's holds, so a dead session's claims never lapsed. The
    Claude family was never exposed — its two tiers are both unique — so the failure
    reached only the callers using the front door correctly, which is why a lane-local
    test could not see it."""
    if _on_worktree_lane():
        return _current_branch()
    sid = os.environ.get("CLAUDE_CODE_SESSION_ID", "").strip()
    if sid:
        return sid
    return _invoked_session_key() or "app"


def _lane_alloc(root: Path, identity: str, limit: int = 64) -> tuple[str, str]:
    """DRAW the lowest free lane, exclusively. (lane, why-not) — lane is "" on failure.

    WHY THIS IS NOT `while lane_taken n; do n++; done` (WI-0185). That shell loop is
    check-then-act with nothing between the check and the act, so two dispatches spawning
    at the same instant both saw `poga-1` free and both tried to create it. One won; the
    loser's `git worktree add` failed, `poga` exited, its tmux session ended with the
    command, and the diagnostic went with it. Observed live at the first attach drill:
    `poga dispatch WI-0146,WI-0152 --go` reported "2 lane(s) spawned", WI-0152 came up in
    poga-2, and WI-0146 had no session and no worktree seconds later. Re-dispatched ALONE
    thirty seconds later it came up fine — which is what identifies a race for the slot
    rather than anything about the item.

    So the slot is DRAWN from the coord store, the way ADR/WI numbers are
    (`numbers-are-drawn-never-picked`): the exclusive create is the arbitration, and
    exactly one racer can win a free name. A lane already on disk is skipped before the
    draw, so this never contends over a name that is settled anyway."""
    for n in range(1, max(2, limit) + 1):
        lane = f"poga-{n}"
        if _lane_taken(root, lane):
            continue
        if _lane_reserve(lane, identity, root):
            return lane, ""
        # Someone else drew it in the last instant. Keep walking — that is the whole
        # point: the loser of a race gets the NEXT lane, not a failed launch.
        continue
    return "", (f"no free lane under poga-{limit} — every one is either a live worktree, "
                f"an un-landed branch, or reserved. `poga lanes` shows which.")


def _release_lane_reservation(reason: str = "session closed") -> str | None:
    """Let go of THIS lane's `lane-alloc` reservation. Returns the lane name released, or
    None when there was nothing to release (not on a lane, or no record).

    WHY A CLOSED JOURNAL MUST DO THIS (WI-0249). Before this, NOTHING released a lane's
    reservation on any ordinary path, and that is stronger than the item claimed. The
    apparent release was `cmd_worktree_remove`'s teardown sweep, which matches a record on
    `session_id == "worktree-<lane>"` or on its journal — but a lane-alloc record is
    written by the LAUNCHER, before any journal exists, so it carries
    `session_id: "app"` and `journal: ""` and matches neither arm. Measured on the live
    store, 2026-09-04: all six records. `_coord_release_dead_lanes` declines them for the
    same reason (`_coord_holder_is_dead` returns False for any identity not starting
    `worktree-`). So the only real releases were `cmd_lane_rollback`, an operator's
    `release --force`, and a TTL that a shared-identity heartbeat kept re-stamping — which
    is why a lane that finished hours ago went on holding a record carrying `dispatch_id`,
    and `_dispatch_live_lane_count` went on counting it against the cap.

    Releasing at the CLOSE ties the record to the fact it is supposed to represent (a
    session working this lane) rather than to a teardown that never fired.

    RELEASING EARLY IS SAFE, and this is the part worth checking before you believe it.
    The reservation is load-bearing only in the seconds between drawing a lane name and
    the worktree existing — after that `_lane_taken` sees the directory and the branch,
    and the allocator skips the name before it ever reaches the draw (see `_lane_alloc`).
    So a released record cannot hand this lane's name to a second launch while the lane is
    still on disk. What it can no longer do is misreport a finished lane as dispatch load.

    THROUGH THE ONE EXIT SINCE WI-0312, and this record is the reason `_lane_exit_owns`
    has a third arm. It is written by the LAUNCHER, before the runtime has adopted a
    journal, so it carries `session_id: "app"` and `journal: ""` — measured on the live
    store, 2026-09-04 — while a lane's own `_coord_identity()` is its branch. It matches
    neither of the exit's other two arms, which is why this used to be a force-delete by
    name standing outside the exit altogether: an unforced release would consult
    `_coord_mine`, fail that comparison, and quietly leave the record in place.

    Matching on the NAME is right; matching on the name ALONE was not. A lane name is a
    recycled address, so a close whose cleanup ran late would free the reservation of
    whichever session is sitting in that lane NOW — dropping a live lane out of the
    dispatch cap it is genuinely occupying. The exit's epoch guard is what makes the name
    safe to match on: this runs after the journal is stamped closed, so our own reservation
    — drawn before this session even began — predates that stamp, and a successor's is
    drawn after it.

    NEVER AGAINST A FIXTURE (WI-0035). This runs early in `cmd_end`, before the guard that
    refuses git work on a half-patched test repo — and a test that patches `JOURNAL_DIR` to
    a temp dir while leaving `ROOT` on the live checkout would resolve `worktree-poga-N`
    from the REAL machine and force-delete that lane's live reservation. Not hypothetical:
    `test_session.test_lane_close_refuses_git_against_a_fixture` mocks `_on_worktree_lane`
    to True and calls `cmd_end` for real. The guard belongs here rather than at the call
    site so it defends every future caller, not just the one that exists today.

    Fail-closed to None and never raises: a coordination write must not turn a completed
    close into a failed one."""
    try:
        if _running_against_fixture() or not _on_worktree_lane():
            return None
        identity = _current_branch()
        lane = identity.removeprefix("worktree-")
        if not lane:
            return None
        freed = _lane_exit_release(identity, kinds=(LANE_ALLOC_KIND,), reason=reason,
                                   epoch=_lane_exit_epoch())
        if any(name == lane for _kind, name in freed):
            return lane
    except Exception:
        pass
    return None


def cmd_lane_alloc(args: argparse.Namespace) -> None:
    """Print the lane this launch may use, having drawn it exclusively (WI-0185).

    Called by the `poga` wrapper in place of its own shell loop. Prints ONLY the lane name
    on stdout so the wrapper can capture it; everything else goes to stderr."""
    root = _shared_work_root()
    identity = args.identity or _coord_identity()
    lane, why = _lane_alloc(root, identity)
    if not lane:
        print(f"lane-alloc: {why}", file=sys.stderr)
        raise SystemExit(2)
    print(lane)


def _wi_claimable_items() -> list[tuple[str, str]]:
    """Claimable work items = every store entry with status open/in-progress, PLUS any
    live drill items. Returns [(id, title)] in file order. [] if there is no store.

    DRILL ITEMS ARE CLAIMABLE ON PURPOSE (the operator's ruling, session ~173: tests get as close
    to the real thing as possible). Claim and release are the first and last
    things a dispatched lane does, they write to the shared coordination store, and the
    drill skipped exactly them — so the part of a dispatch that can leave residue was the
    part never rehearsed, and a claim that had gone wrong would have shown up first on a
    real backlog item.

    THIS IS THE ONLY READER THAT SEES THEM. `_wi_parse` is untouched, so the list, the
    chart, ROADMAP.md, the feed, `wi-check` and the number allocator are all exactly as
    they were — a drill cannot pollute the backlog because the backlog never reads them.
    They are also normally absent: `_drill_items_dir` is empty except while a drill is
    running, and `poga drill --clean` empties it."""
    items = [(it["id"], it["title"]) for it in _wi_parse()
             if it.get("status") in ("open", "in-progress")]
    items += [(it["id"], it["title"]) for it in _drill_items()
              if it.get("status") in ("open", "in-progress")]
    return items


def _claims_status() -> dict:
    """Structured claimed-vs-available view over the work-item store + live claims."""
    items = _wi_claimable_items()
    ids = {i for i, _ in items}
    live = _coord_list("claims")
    claimed = dict(live)
    available = [(wid, title) for wid, title in items if wid not in claimed]
    orphan = {wid: rec for wid, rec in claimed.items() if wid not in ids}
    return {"items": items, "titles": dict(items), "claimed": claimed,
            "available": available, "orphan": orphan}


def _claims_orientation_line() -> str | None:
    """One-line coordination summary for the start block. None if no work-item store."""
    st = _claims_status()
    if not st["items"]:
        return None
    claimed = st["claimed"]
    if not claimed:
        return f"none held · {len(st['available'])} item(s) available"
    # WI-0157: `WI-0001→worktree-poga-3` named the holder by a RECYCLED slot while the
    # record's own journal id — durable, unique forever — sat unread one field away. The
    # slot is not what a reader of this line needs: there is no verb to type it at from
    # here, and the item on the left is already the address for `poga work claim`.
    held = ", ".join(f"{wid}→{_coord_short_holder(rec)}"
                     for wid, rec in sorted(claimed.items()))
    return f"{len(claimed)} claimed ({held}) · {len(st['available'])} available"


def _coord_refresh_identity(identity: str | None = None,
                            kinds: tuple[str, ...] = COORD_KINDS) -> int:
    """Bump the expiry of every coordination record THIS session (or `identity`) holds —
    the heartbeat keep-alive that makes a live session's holds never expire while a dead
    session's lapse. Revives an own record that expired but nobody reclaimed yet. Returns
    the count refreshed. Never raises."""
    ident = identity or _coord_identity()
    # Every COORD_KINDS member needs its own row: the `.get` default is the CLAIM ttl, so a
    # kind missing here is silently re-stamped with someone else's lifetime — which for
    # `attention` would quietly shorten a 24h record to 8h on the first heartbeat that
    # touched it (WI-0182).
    ttl = {"claims": CLAIM_TTL_SECONDS, "leases": LEASE_TTL_SECONDS,
           "adr-alloc": ADR_ALLOC_TTL_SECONDS, "wi-alloc": WI_ALLOC_TTL_SECONDS,
           "ops-alloc": OPS_ALLOC_TTL_SECONDS, "attention": ATTENTION_TTL_SECONDS,
           # Its OWN short lifetime, deliberately, not the 8h claim default: a lane
           # reservation is load-bearing only between the draw and the worktree existing.
           # Re-stamping it with a claim's TTL would make a crashed launcher cost a lane
           # for the rest of the day — the exact silent-shortening-or-lengthening this map
           # exists to prevent (WI-0182).
           "lane-alloc": LANE_ALLOC_TTL_SECONDS,
           # WI-0267. The heartbeat only reaches these two when a land is in flight in a
           # session that is ALSO taking tool calls, which is rare — `session.py merge`
           # blocks the shell — so the land keeps them alive itself. They are listed
           # anyway, because the failure this map exists to prevent is silent: without a
           # row, a heartbeat that DID land here would re-stamp a 10-minute queue ticket
           # with an 8-hour lifetime, and a lane that then died would hold the head of the
           # line until tomorrow.
           "land-gate": LAND_LOCK_TTL_SECONDS,
           "land-queue": LAND_QUEUE_TTL_SECONDS,
           # WI-0293, and this row is the one with the widest gap between its own TTL and
           # the default it would otherwise inherit: 120 SECONDS against the claim's 8
           # HOURS. A heartbeat that re-stamped a trunk lock with a claim's lifetime would
           # convert the shortest-lived record in the store into the longest, and because
           # every writer of the trunk waits on this one record, the blast radius is every
           # land AND every `poga work` write in the repo until tomorrow. The guard that
           # caught the omission is right that it would have been silent.
           "trunk-lock": TRUNK_LOCK_TTL_SECONDS}
    n = 0
    # WI-0298: the heartbeat's filter WAS `rec["session_id"] == ident`, and that is the
    # line that wedged the gate. Inside a lane `ident` is the lane branch, so this matched
    # every record any session had ever left in that lane and renewed all of them —
    # including a dead holder's grip on the land gate, forever. It now asks the same
    # question renewal asks everywhere else (`_coord_mine_for_refresh`): whose journal is
    # this? `_coord_refresh` re-checks, so this is a cheap pre-filter and not the gate.
    # The ambient journal, ALWAYS — even when the caller named an identity. `identity`
    # says which lane's records to look at; the journal says which session may renew one,
    # and those are different questions (that they were ever the same key is the defect).
    journal = _coord_my_journal()
    try:
        for kind in kinds:
            for name, rec in _coord_list(kind, include_expired=True).items():
                if _coord_mine_for_refresh(rec, ident, journal) and \
                        _coord_refresh(kind, name, ident, ttl.get(kind, CLAIM_TTL_SECONDS)):
                    n += 1
    except Exception:
        pass
    return n


def _coord_holder_is_dead(rec: dict, liveness_proof: bool = False) -> bool:
    """Is the lane holding this coordination record PROVABLY gone? (WI-0164.)

    Two proofs, in increasing strength and decreasing certainty:

      1. **Its branch is gone.** A lane's branch is deleted only when that lane lands or is
         torn down, so an absent `refs/heads/<identity>` is proof the holder is finished.
         Always applied.
      2. **Its branch exists but its worktree holds no live session** — only when
         `liveness_proof`. This is the case the branch test alone cannot see, and it is the
         one WI-0164 hit: a lane died with UNMERGED work, so its branch survived by design
         and its number reservation outlived it holding the number hostage. *"poga-2 could
         not be torn down while unmerged, which is the circularity"* — the reservation
         blocked the land of its own recovered commits, and the only ways out were
         renumbering items that had been correctly drawn or hand-editing json under
         `.git/`.

    PROOF 2 IS OPT-IN, and that is the whole design. It rests on heartbeat evidence, which
    is strong for a lane that has been running and weak for one that has just started, so
    it is spent only where a false positive is cheap — see `COORD_ALLOC_KINDS`.

    `_tree_has_live_session` is reused rather than reimplemented (P16, and WI-0140 is open
    precisely because two liveness verdicts already disagree — a third would make it
    worse). It errs toward **live** on any read failure, which is the safe direction here
    too: a record we cannot prove dead stays held, and the TTL remains the backstop.

    Scoped to `worktree-` identities ONLY. A non-lane identity is a Claude session id, and
    an absent session id is not evidence of anything."""
    ident = (rec.get("session_id") or "").strip()
    if not ident.startswith("worktree-"):
        return False
    try:
        if not _ref_exists(f"refs/heads/{ident}"):
            return True                       # proof 1: torn down
        if not liveness_proof:
            return False
        lane = ident[len("worktree-"):]
        tree = _shared_work_root() / ".claude" / "worktrees" / lane
        if not tree.is_dir():
            return True                       # branch parked, worktree already reaped
        return not _tree_has_live_session(tree)
    except Exception:
        return False                          # cannot tell is NOT dead


def _coord_release_dead_lanes(kinds: tuple[str, ...] = LANE_EXIT_KINDS) -> list[tuple[str, str]]:
    """Release every record held by a lane branch that NO LONGER EXISTS (WI-0078).

    Claim release was wired to exactly ONE teardown route — `cmd_worktree_remove`, and
    only on the branch delete succeeding. Every other route left the holds behind: the
    reaper (`_reap_lane` frees the worktree and deletes the branch itself), and manual
    teardown, which is the DOCUMENTED route whenever a live sibling lane must be preserved
    (`poga lanes --clean` and `reap-lanes` would sweep it). A member tore a lane down properly on
    2026-08-04 and its two claims outlived it by a week.

    So this reconciles on the FACT rather than on the route: a lane's branch is deleted
    only when that lane lands or is torn down, so `refs/heads/<identity>` being gone is
    proof the holder is gone — no age heuristic, no liveness guess, and it cannot be
    bypassed by inventing a fourth teardown path
    ([`add-structural-guard-on-recurrence`](habits/master.md#add-structural-guard-on-recurrence):
    the third route leaking was the signal that wiring routes one at a time is the wrong
    shape).

    Scoped to `worktree-` identities ONLY. A non-lane identity is a Claude session id, and
    an absent session id is not evidence of anything — that is exactly the
    `declare-what-a-check-assumes` collapse, so those are left to the TTL.

    Returns [(kind, name)] released, so a caller can report what it cleared rather than
    doing it silently. Never raises.

    WI-0312 ROUTED THIS THROUGH THE ONE EXIT rather than leaving it a second release loop
    beside it. What is genuinely this sweep's own is the DEATH PROOF, not the ownership
    rule — so the proof is composed on top as a `select` and `_lane_exit_owns` stays the
    single answer to "whose record is this?". The two loops had already begun to drift:
    this one matched on `session_id` alone and so could never see a record a lane took
    through the main-anchored front door (WI-0123), while the exit could.

    No epoch is passed, and that is correct here rather than an omission: this sweep is not
    a stale retry of some session's own cleanup — it re-reads `refs/heads/<identity>` at the
    moment it runs, so a lane that has been REUSED reads as alive and is skipped by the
    proof itself, before ownership is ever consulted."""
    freed: list[tuple[str, str]] = []
    try:
        # WI-0164: was `_ref_exists` inline. A parked branch kept its holder looking alive
        # forever, so the one sweep that could have freed it never did. The predicate now
        # proves death two ways and still refuses to guess.
        def _dead(kind: str, _name: str, rec: dict) -> bool:
            # A `lane-alloc` record is matched by its NAME, not by its ownership key —
            # the launcher wrote it before any lane branch existed, so its `session_id`
            # is `app` and asking the proof about it returns "not a lane, cannot tell"
            # (`_coord_holder_is_dead`'s `worktree-` scope). The death question here is
            # about the LANE that record names, and the lane IS `ident`. Asking it that
            # way is what lets the reaper free the reservation of a lane that crashed
            # without ever reaching `end` — which nothing else can reach, because the
            # only other release is anchored on the close that never happened (WI-0249).
            subject = rec if (rec.get("session_id") or "").startswith("worktree-") \
                else {"session_id": ident}
            # …but NOT with the stronger proof, which `lane-alloc` inherits from
            # `COORD_ALLOC_KINDS` and must not spend. That proof frees a record whose
            # branch still exists on the strength of no live session in the worktree, and
            # WI-0164 allows it for NUMBER reservations on an explicit cost argument:
            # freeing a number no live lane is using costs nothing. A LANE reservation
            # fails that argument — it is what `_dispatch_live_lane_count` counts, so
            # freeing one under a lane that is merely between heartbeats under-reports the
            # cap and lets the next wave over-spawn into an occupied lane. Same evidence,
            # different cost, so a different threshold: the branch must be gone.
            strong = kind in COORD_ALLOC_KINDS and kind != LANE_ALLOC_KIND
            return _coord_holder_is_dead(subject, strong)

        for ident in sorted(_dead_lane_identities(kinds)):
            freed += _lane_exit_release(ident, kinds=kinds, reason="teardown",
                                        select=_dead)
    except Exception:
        pass
    return freed


def _dead_lane_identities(kinds: tuple[str, ...] = LANE_EXIT_KINDS) -> set[str]:
    """Every `worktree-` identity that still holds a record under `kinds`. The candidate
    set the dead-lane sweep walks — narrowing it to the provably-dead ones is
    `_coord_holder_is_dead`'s job, applied per record because the strength of proof it is
    allowed to spend differs by kind (`COORD_ALLOC_KINDS`).

    A `lane-alloc` record contributes its NAME rather than its ownership key, because that
    is where its lane is written: the launcher drew it before the branch existed, so its
    `session_id` is `app` and the lane appears nowhere else on the record. A lane that
    crashed holding nothing but its reservation would otherwise never become a candidate at
    all. Never raises."""
    out: set[str] = set()
    try:
        for kind in kinds:
            for name, rec in _coord_list(kind, include_expired=True).items():
                ident = (rec.get("session_id") or "").strip()
                if ident.startswith("worktree-"):
                    out.add(ident)
                elif kind == LANE_ALLOC_KIND and name:
                    out.add(f"worktree-{name}")
    except Exception:
        pass
    return out


class LeaseHeld(RuntimeError):
    """Raised by the `lease()` context manager when a live OTHER session holds the lease —
    the caller aborts rather than racing a single-writer resource."""
    def __init__(self, name: str, holder: str, expires: str):
        self.name, self.holder, self.expires = name, holder, expires
        super().__init__(f"lease '{name}' held by {holder} (expires {expires})")


def _lease_try(name: str, ttl: int = LEASE_TTL_SECONDS) -> tuple[bool, dict]:
    """Acquire the named single-writer lease. (True, our record) on success; (False, the
    holder record) if a live OTHER session holds it. Fail-open like all coordination: no
    shared dir → (True, {}), the operation proceeds unguarded (isolation still holds)."""
    return _coord_try_acquire("leases", name, _coord_identity(), ttl)


def _lease_release(name: str, force: bool = False) -> bool:
    return _coord_release("leases", name, _coord_identity(), force=force)


@contextlib.contextmanager
def lease(name: str, ttl: int = LEASE_TTL_SECONDS):
    """Hold the named lease for the block; release on exit (even on exception). Raises
    LeaseHeld if a live other session holds it. Usage in a fleet-mutating script:

        import session
        with session.lease("push-substrate"):
            ...push to every member repo...
    """
    ok, holder = _lease_try(name, ttl)
    if not ok:
        raise LeaseHeld(name, holder.get("branch") or holder.get("session_id", "?"),
                        str(holder.get("expires_iso", "?")))
    try:
        yield
    finally:
        _lease_release(name)


def cmd_lease(args: argparse.Namespace) -> None:
    """C5: acquire a named single-writer lease (exit 0 acquired / 1 held by a sibling)."""
    ok, holder = _lease_try(args.name, args.ttl or LEASE_TTL_SECONDS)
    if ok:
        print(f"lease '{args.name}' acquired as {_coord_identity()}")
        sys.exit(0)
    who = holder.get("branch") or holder.get("session_id", "?")
    print(f"REFUSED: lease '{args.name}' held by {who} (expires {holder.get('expires_iso', '?')}).")
    sys.exit(1)


def cmd_unlease(args: argparse.Namespace) -> None:
    """C5: release a named lease this lane holds (or --force to override the holder)."""
    ok = _lease_release(args.name, force=args.force)
    print(f"lease '{args.name}' released" if ok
          else f"unlease: '{args.name}' not held by you (use --force to override).")
    sys.exit(0 if ok else 1)


def _land_queue_position(identity: str, enqueued_at: float) -> tuple[int, int]:
    """This lane's 1-based place in line, and the number of lanes in it.

    Order is enqueue time, ties broken by identity, so every lane computes the SAME order
    from the same records — a queue whose members disagree about who is first is not a
    queue, it is a race with extra steps. `_coord_list` already drops expired tickets, so
    a lane that died waiting stops holding up the line within its ticket's TTL rather than
    forever. Our own ticket may be missing from the listing (the store went away
    mid-wait); the `max` keeps the reported length from contradicting the position."""
    live = _coord_list(LAND_QUEUE_KIND)
    ahead = 0
    for name, rec in live.items():
        if name == identity:
            continue
        try:
            t = float(rec.get("enqueued_at", 0.0))
        except (TypeError, ValueError):
            continue                     # a ticket with no readable enqueue time cannot
        if (t, name) < (enqueued_at, identity):   # be ordered; it waits behind us
            ahead += 1
    return ahead + 1, max(len(live), ahead + 1)


