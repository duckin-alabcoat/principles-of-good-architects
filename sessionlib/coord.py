def _fmt_wait(seconds: float) -> str:
    """A wait, in the unit a human reading it would use. Minutes alone reports every
    genuine sub-minute wait as `0m`, which reads as a bug in the reporter rather than as
    a short wait — and this line exists precisely so the operator trusts what it says."""
    return f"{seconds:.0f}s" if seconds < 120 else f"{seconds / 60:.0f}m"


def _lane_exit_epoch(journals: tuple[str, ...] = ()) -> float | None:
    """When the occupancy this exit is cleaning up ENDED — the latest `ended` stamp across
    `journals`, or across this session's own journal when none are named. None when no such
    stamp can be read (WI-0312).

    THE END, NOT THE START, and the difference is the whole guard. A lane's records are
    written throughout its session, so an epoch at `started` would refuse to release the
    lane's own claims and attention record — it would fix stealing by leaking. `ended` is
    the one instant that separates *everything this session could possibly have written*
    from *everything a successor in the same lane can have written*, which is exactly the
    line the reuse hazard needs drawn.

    Read from the JOURNAL rather than from `time.time()` at the moment of the exit, because
    the whole point is to be right about a cleanup that runs late: a retry stamping itself
    `now` would carry a clock newer than the session that displaced it and would sweep that
    session's records — the failure this exists to prevent. The journal is tracked and
    lands, so the stamp is still readable long after the lane's worktree is gone.

    None is the honest answer for a session that has not closed, and it disables the guard
    rather than defaulting it: an OPEN session has no successor in its lane by
    construction, so there is nothing for the guard to protect
    ([`declare-what-a-check-assumes`](habits/master.md#declare-what-a-check-assumes)).
    Never raises."""
    stamps: list[float] = []
    try:
        for fm in _journal_frontmatter_by_ids(journals) if journals else _own_frontmatter():
            ended = (fm.get("ended") or "").strip()
            if ended:
                with contextlib.suppress(Exception):
                    stamps.append(_coord_epoch(ended))
    except Exception:
        return None
    return max(stamps) if stamps else None


def _own_frontmatter() -> list[dict]:
    """This session's own journal frontmatter, as a 0-or-1 list so `_lane_exit_epoch` can
    treat both of its sources the same way. Never raises."""
    try:
        found = _find_holder_journal()
        return [found[1]] if found is not None else []
    except Exception:
        return []


def _journal_frontmatter_by_ids(journals: tuple[str, ...]) -> list[dict]:
    """Frontmatter of each journal named by `session-id`, wherever its checkout is.

    The teardown route needs this and cannot use `_find_holder_journal`: the
    `WorktreeRemove` hook runs in the MAIN checkout's own session, so "this session's
    journal" there is the hook's, not the lane's. The lane's journal ids are what teardown
    already resolved from the sidecar before deleting the branch. Never raises."""
    want = {j for j in journals if j}
    out: list[dict] = []
    if not want:
        return out
    try:
        for d in _holder_journal_dirs():
            for _p, fm in _journals_in(d):
                if (fm.get("session-id") or "").strip() in want:
                    out.append(fm)
    except Exception:
        pass
    return out


def _rec_created_after(rec: dict, epoch: float | None) -> bool:
    """Was this record written AFTER `epoch`? False whenever that cannot be established —
    an unknowable timestamp is not evidence of anything
    ([`declare-what-a-check-assumes`](habits/master.md#declare-what-a-check-assumes))."""
    if epoch is None:
        return False
    created = (rec.get("created_at") or "").strip()
    if not created:
        return False
    try:
        return _coord_epoch(created) > epoch
    except Exception:
        return False


def _lane_exit_owns(kind: str, name: str, rec: dict, identity: str,
                    journals: tuple[str, ...], epoch: float | None) -> bool:
    """Is `<kind>/<name>` THIS EXIT'S to free? The one ownership rule (WI-0312).

    Three arms, in decreasing certainty:

      1. **The journal.** `rec.journal` in `journals` is durable and unambiguous — it is
         one SESSION, and it finds the records a lane took through the main-anchored front
         door, which carry `branch: main` and main's ownership key and match nothing else
         (WI-0123). Tried first, and it can answer for any kind.
      2. **The address**, for the two kinds that are keyed by WHERE rather than by WHO.
         A `lane-alloc` record is written by the LAUNCHER, before any journal exists, so it
         carries `session_id: "app"` and `journal: ""` (measured on the live store,
         2026-09-04) and its lane appears nowhere but its NAME. An `attention` record is
         named for the coordination identity and carries the Claude session id as its key,
         so its ownership key names the session, not the lane. For both, the record's name
         IS the address and the address is what owns it.
      3. **The ownership key**, `rec.session_id == identity`, for every other kind.

    2 AND 3 ARE EXCLUSIVE, not ordered fallbacks, and that is load-bearing. For an
    address-keyed kind the address is the ONLY answer — falling through to the ownership
    key would let `worktree-poga-1`'s exit free `lane-alloc/poga-7` on the strength of a
    `session_id` that names the holder rather than the lane, which is a different lane's
    reservation taken by a name that never matched it. Both are subject to the epoch guard
    below; arm 1 is not.

    THE EPOCH GUARD is the WI-0312 half, and it is one comparison pointing both ways. A
    lane branch is a LOCATION, reused by every session that ever runs in that lane;
    `_coord_mine_for_refresh` already learned this on the renewal side, where over-matching
    made a record immortal. On the RELEASE side the same confusion costs the opposite
    thing: a delayed retry from a session that finished in poga-20 would free the records
    of the session sitting in poga-20 now — a live claim released out from under its
    holder. So the two arms that key on a location — the address and the ownership key —
    additionally require that the record predates the END of this exit's occupancy
    (`_lane_exit_epoch`):

      - everything this session itself wrote — before its start, like the reservation, or
        during it, like a claim — predates its close, so it is still swept and the leak
        WI-0078 filed stays closed;
      - a record written by a LATER session reusing this lane postdates that close, so it
        is left alone however exactly the lane name matches.

    Arm 1 is deliberately NOT epoch-guarded: a journal id is unique to one session, so a
    record naming ours is ours whenever it was written.

    When the epoch cannot be resolved the guard does not fire, and that is the declared
    assumption rather than an oversight. There are exactly two such cases and neither can
    be racing an occupant: an OPEN session, which by construction has no successor in its
    own lane; and the reaper and rollback, which prove the lane GONE at the moment they run
    (`_coord_holder_is_dead`, `git branch -D`).
    """
    if rec.get("journal") and rec.get("journal") in journals:
        return True
    address = _lane_exit_address(kind, identity)
    if address is not None:
        return name == address and not _rec_created_after(rec, epoch)
    if identity and rec.get("session_id") == identity:
        return not _rec_created_after(rec, epoch)
    return False


def _lane_exit_address(kind: str, identity: str) -> str | None:
    """The record NAME that `identity` addresses under `kind`, for the kinds keyed by
    where rather than by who — or None for every other kind, which is answered by the
    ownership key instead. See `_lane_exit_owns`'s address arm.

    Named once here rather than spelled out at the two release sites, for the reason
    `LANE_EXIT_KINDS` is named once: a kind whose address rule lives at its call site is a
    kind the next sweep will get wrong."""
    if kind == LANE_ALLOC_KIND:
        lane = identity.removeprefix("worktree-") if identity.startswith("worktree-") else ""
        return lane or None
    if kind == ATTENTION_KIND:
        return _attention_key(identity) if identity else None
    return None


def _session_records(identity: str, journals: tuple[str, ...] = (),
                     kinds: tuple[str, ...] = LANE_EXIT_KINDS,
                     select=None, epoch: float | None = None) -> list[tuple[str, str]]:
    """Every coordination record still held by `identity` or by one of `journals`, as
    [(kind, name)]. The RECEIPT a lane exit is checked against (WI-0298).

    Separate from the release itself on purpose: `a-close-is-the-banner-not-the-sentence`
    — the only valid receipt that a teardown ran is the state its own code leaves behind,
    never the sentence it printed. A release that returns a count is a self-report; this
    re-reads the store and answers "is anything of this session's still in there?".

    `select(kind, name, rec)` is an EXTRA condition composed on top of ownership, never a
    replacement for it (WI-0312) — it is how the reaper adds its own death proof without
    owning a second copy of the ownership rule. `epoch` is this exit's own occupancy
    start; see `_lane_exit_owns`."""
    left: list[tuple[str, str]] = []
    try:
        for kind in kinds:
            for name, rec in _coord_list(kind, include_expired=True).items():
                if not _lane_exit_owns(kind, name, rec, identity, journals, epoch):
                    continue
                if select is not None and not select(kind, name, rec):
                    continue
                left.append((kind, name))
    except Exception:
        pass
    return left


def _lane_exit_release(identity: str, journals: tuple[str, ...] = (),
                       reason: str = "lane exit",
                       kinds: tuple[str, ...] = LANE_EXIT_KINDS,
                       select=None,
                       epoch: float | None = None) -> list[tuple[str, str]]:
    """THE ONE LANE EXIT (WI-0298 brief D6, wired by WI-0312). Free what this session holds
    — the gate record, its place in the queue, its drawn numbers, its lane reservation and
    its dispatch slot. Returns [(kind, name)] freed. Never raises.

    Close, land, teardown, reap, recovery and rollback all come through here. They used to
    each free their own subset: teardown released `COORD_KINDS`, the reaper released what
    the dead-lane sweep knew about, the close force-deleted the lane reservation by name,
    and NOBODY released the dispatch slot, so a landed lane's freed capacity stayed
    invisible and the next wave under-spawned. Wiring the routes one at a time is what left
    three of them leaking last time (WI-0078); one exit that every route calls cannot be
    bypassed by inventing a fourth route.

    WHAT `kinds` IS FOR, because "one exit" is not "everything at every moment". The routes
    happen at different points in one lifecycle and free different things there: a close
    lets go of the attention record and the lane reservation while the worktree still
    stands and a land may still be running, and freeing the land gate at that moment would
    take the lock out from under the land it is protecting. So the STAGE is a parameter and
    the ownership rule is not. What the item's acceptance is about — three paths drifting
    on *whose record this is* — is exactly what a shared `kinds` could never have fixed and
    a shared `_lane_exit_owns` does.

    IDEMPOTENT AND RETRYABLE, both required rather than incidental. `_coord_release`
    returns False for a record that is already gone, so a second run over the same lane
    frees nothing and reports nothing — a repeat is a no-op, not a double-release. And the
    try sits around ONE RECORD rather than around the loop: a single unreadable or
    undeletable record used to abort the whole sweep and leave everything after it held,
    which made a partial failure indistinguishable from a total one and left nothing for a
    retry to make progress on. Now each record fails alone, the rest are freed, and
    `_lane_exit_verify` names the survivors."""
    freed: list[tuple[str, str]] = []
    for kind, name in _session_records(identity, journals, kinds=kinds, select=select,
                                       epoch=epoch):
        try:
            if _coord_release(kind, name, identity, force=True, reason=reason):
                freed.append((kind, name))
        except Exception:
            continue                 # one record's failure is not the sweep's failure
    return freed


def _lane_exit_verify(identity: str, journals: tuple[str, ...] = (),
                      reason: str = "lane exit",
                      kinds: tuple[str, ...] = LANE_EXIT_KINDS,
                      select=None,
                      epoch: float | None = None) -> tuple[bool, list[tuple[str, str]]]:
    """Run the lane exit and then PROVE the store is empty of this session's records.

    (True, []) when nothing of this session's is left; (False, leftovers) otherwise, so a
    caller reports what survived by name rather than announcing a clean teardown it never
    checked. This is the half the 2026-09-06 incident was missing: the session that had
    closed believed it had closed, and its gate record was still there most of an hour later.

    The re-read asks the SAME question the release asked — same kinds, same select, same
    epoch — because a verify scoped differently from the release it checks reports on a
    set nobody tried to free."""
    _lane_exit_release(identity, journals, reason=reason, kinds=kinds, select=select,
                       epoch=epoch)
    left = _session_records(identity, journals, kinds=kinds, select=select, epoch=epoch)
    return (not left), left


def _lane_exit_report(reason: str = "lane exit") -> list[str]:
    """Run THIS session's own verified lane exit and say what it did, as operator lines.

    The close's call into the one exit (WI-0312). It resolves the three things the exit
    needs — the ownership key, this session's journal, and the epoch its occupancy ended —
    from the session itself, so the two callers that end a session do not each assemble
    them and drift.

    IT WRITES NOTHING BUT COORDINATION RECORDS. The journal is already closed when this
    runs and stays closed: cleanup frees holds, and a cleanup that could touch the record
    of the close could fabricate one. So there is no path from here to `finalize_journal`,
    to a sidecar marker, or to a delivery result — a failure below prints and returns, and
    the close receipt written before it stands either way.

    NEVER AGAINST A FIXTURE (WI-0035), for the reason spelled out at
    `_release_lane_reservation`: a test that patches `JOURNAL_DIR` while leaving `ROOT` on
    the live checkout would resolve the real machine's lane and free its live records.

    Never raises — a coordination write must not turn a completed close into a failed
    one."""
    try:
        if _running_against_fixture():
            return []
        identity = _coord_identity()
        found = _find_holder_journal()
        journals = tuple(j for j in ((found[1].get("session-id") or "").strip(),) if j) \
            if found is not None else ()
        ok, left = _lane_exit_verify(identity, journals=journals, reason=reason,
                                     kinds=LANE_EXIT_CLOSE_KINDS,
                                     epoch=_lane_exit_epoch(journals))
        if ok:
            return []
        names = ", ".join(f"{k}/{n}" for k, n in left)
        return [f"lane exit: INCOMPLETE — these coordination records survived it: {names}. "
                f"Nothing is lost and nothing is stuck: the exit is idempotent, so the "
                f"teardown and the reaper free them on their own passes, and "
                f"`python3 session.py coord` lists them until they do."]
    except Exception as exc:                        # pragma: no cover - defensive
        return [f"lane exit: skipped ({type(exc).__name__}: {exc}) — the close stands; "
                f"the teardown and the reaper free these records on their own passes."]


class LandGateLock:
    """What `land_gate_lock()` yields: whether the land is serialized, and the handle a
    long land uses to say it is still alive.

    `serialized` False is never an error — it is a fail-open path, already reported to the
    operator by the context manager or by the reserve. Callers do not branch on it; it is
    here so a test can assert which path was taken, and `reason` names which one.

    WI-0346: it is now also LOAD-BEARING rather than only diagnostic. `refresh()` and the
    heartbeat key on it, and so does the release on the way out — so `serialized` must
    mean *we verifiably hold the record*, never *we tried*."""

    def __init__(self, serialized: bool, identity: str, waited: float,
                 position: int, holder: dict, reason: str):
        self.serialized = serialized
        self.identity = identity
        self.waited = waited
        self.position = position
        self.holder = holder
        self.reason = reason
        # WI-0298: the timer thread renewing this hold, and the switch that stops it.
        # Exposed so a test can assert the thread dies with the block — a refresher that
        # outlives its lock renews a record the process no longer holds, which is the
        # immortal-record failure this item exists to remove, reintroduced from inside.
        self.heartbeat_thread: _threading.Thread | None = None
        self.heartbeat_stop = _threading.Event()

    def refresh(self) -> bool:
        """Keep the hold alive across a long land. `session.py merge` blocks the shell, so
        no session heartbeat fires while a land runs — the land has to do this itself."""
        return _land_gate_refresh(self.identity) if self.serialized else False

    def _beat(self, every: float) -> None:
        """WI-0298 — renew from INSIDE the landing process, for as long as it lives.

        This is what makes the lease a live-holder lease rather than a clock. The TTL used
        to have to cover the slowest honest land, because nothing renewed it; now it only
        has to cover a few missed beats, so a lapsed record means the holder stopped
        breathing. A daemon thread deliberately: if the process dies, the renewals stop
        with it, which is precisely the signal a waiter needs."""
        while not self.heartbeat_stop.wait(every):
            if not _land_gate_refresh(self.identity):
                return          # no longer ours — stop, never re-take

    def start_heartbeat(self, every: float) -> None:
        if not self.serialized or not every or every <= 0:
            return
        self.heartbeat_thread = _threading.Thread(
            target=self._beat, args=(every,), name="land-gate-heartbeat", daemon=True)
        self.heartbeat_thread.start()

    def stop_heartbeat(self) -> None:
        self.heartbeat_stop.set()
        if self.heartbeat_thread is not None:
            self.heartbeat_thread.join(timeout=5)


@contextlib.contextmanager
def land_gate_lock(emit=print, poll: float = LAND_WAIT_POLL_SECONDS,
                   max_wait: float = LAND_WAIT_MAX_SECONDS,
                   report_every: float = LAND_WAIT_REPORT_SECONDS,
                   sleep=time.sleep,
                   heartbeat: float = LAND_LOCK_HEARTBEAT_SECONDS):
    """Hold the machine's land gate for the block; release it on the way out, always.

    Waits its turn and SAYS SO WHILE WAITING — position in line, who holds the gate, how
    long it has been waiting. An unexplained wait is indistinguishable from a stall on
    every surface we have, and this one can legitimately run to tens of minutes: a lane
    that reports "3rd in line, 6m" is visibly working, while the same lane silent is a
    hang somebody kills."""
    global _LAND_GATE_DEPTH
    identity = _coord_identity()
    started = time.time()
    # RE-ENTRANT WITHIN ONE PROCESS, and this is not a nicety. `_land_worktree_lane`'s
    # push-rejected path calls `_integrate_trunk_with_remote`, which runs its own gate and
    # CAS — from INSIDE this lock. A non-reentrant exclusive-create would have that lane
    # queue behind itself and sit out the full 90-minute cap before proceeding, turning a
    # successful land into an hour-and-a-half hang. Keyed on a process-local counter, not
    # on holder identity, so it cannot be confused with a sibling lane the way an
    # identity check can (see the acquire).
    if _LAND_GATE_DEPTH > 0:
        yield LandGateLock(False, identity, 0.0, 1, {}, "reentrant")
        return
    # Fail-open path 1: no coordination store at all. Nothing can be serialized, and
    # refusing to land would be the worse answer — worktree isolation still holds, so the
    # land is correct, just unprotected from a sibling's.
    if _coord_dir(LAND_QUEUE_KIND, create=True) is None:
        emit("land-gate: no coordination store — landing UNSERIALIZED (fail-open). "
             "Concurrent lands will contend as they did before WI-0267.")
        _LAND_GATE_DEPTH += 1
        try:
            yield LandGateLock(False, identity, 0.0, 1, {}, "no-store")
        finally:
            _LAND_GATE_DEPTH -= 1
        return
    _LAND_GATE_DEPTH += 1
    ticket_taken = False
    serialized = False
    holder: dict = {}
    position = 1
    reason = ""
    try:
        # Take a ticket BEFORE the first attempt on the gate, so our place in line is
        # dated from when we started waiting rather than from when we first lost.
        ticket_taken, ticket = _coord_try_acquire(
            LAND_QUEUE_KIND, identity, identity, LAND_QUEUE_TTL_SECONDS,
            enqueued_at=started, purpose="land")
        next_report = report_every
        while True:
            position, total = _land_queue_position(identity, started)
            if position == 1:
                # Only the head of the line touches the gate. FIFO is not cosmetic here:
                # a free-for-all retry lets a lane that arrived last win repeatedly, and
                # the lane it starves is the one whose wait is already being reported to
                # a human as a position in a queue.
                serialized, holder, failopen = _land_gate_reserve(identity, emit=emit)
                if serialized:
                    reason = "acquired"
                    break
                if failopen:
                    # WI-0346. The reserve took nothing AND there is no holder to wait
                    # for — a broken store does not become a working one by queueing, and
                    # the cap below is 90 minutes. The reserve has already said why, so
                    # the only thing left to do is carry its answer out honestly:
                    # unserialized, named, and holding no record to release.
                    holder = {}
                    reason = failopen
                    break
            waited = time.time() - started
            # The position report comes BEFORE the cap check, deliberately: a lane that is
            # about to give up should still say where it was in line and who was ahead of
            # it. That is the diagnostic for WHY it gave up, and it is worth more than the
            # give-up line alone.
            if waited >= next_report:
                current = holder or _land_gate_holder()
                who = _coord_short_holder(current) if current else ""
                emit(f"land-gate: queued — position {position} of {total}, waiting "
                     f"{_fmt_wait(waited)}"
                     + (f"; gate held by {who}" if who else "")
                     + ". One land at a time (WI-0267) — this is a queue, not a stall.")
                next_report = waited + report_every
            # Fail-open path 3: alive but wedged. Nothing above can detect a holder that
            # is genuinely running and simply never finishing, so the cap is the backstop.
            if waited >= max_wait:
                reason = "cap"
                emit(f"land-gate: waited {_fmt_wait(waited)} and never got the gate — "
                     f"landing UNSERIALIZED rather than not landing at all. This gate "
                     f"fails open on purpose (WI-0267): expect the slow contended land "
                     f"it exists to prevent, and check `python3 session.py coord` "
                     f"for a stuck holder.")
                break
            # Our ticket must outlive a long wait; only a DEAD waiter's may lapse.
            _coord_refresh(LAND_QUEUE_KIND, identity, identity, LAND_QUEUE_TTL_SECONDS)
            sleep(poll)
        waited_total = time.time() - started
        if serialized and waited_total >= report_every:
            emit(f"land-gate: acquired after {_fmt_wait(waited_total)} — gating now.")
        gate = LandGateLock(serialized, identity, waited_total, position, holder, reason)
        # WI-0298: start renewing BEFORE the block runs, and stop in the same `finally`
        # that releases. A land is the one operation long enough to outlive its own TTL,
        # and it is also the one during which nothing else in this process is running to
        # renew for it.
        gate.start_heartbeat(heartbeat)
        try:
            yield gate
        finally:
            gate.stop_heartbeat()
    finally:
        _LAND_GATE_DEPTH -= 1
        # WI-0346 — free the record we WROTE, not whatever is at that path. The previous
        # line released with `force=True` under a comment arguing `serialized` proved the
        # record was ours; it proved only that a reserve had once returned True, which
        # the fail-open paths also did having written nothing, and which says nothing
        # about a lapsed record another lane has since legitimately reclaimed. Both cases
        # unlinked the single shared gate out from under a live land.
        #
        # `_coord_release_exact` is narrower than `force` AND narrower than the ownership
        # check the old comment rejected — it never matches the ambient journal siblings
        # share, because it matches the whole record identity. The ticket goes through it
        # too: its name is the LANE, which every session that ever runs there shares, so
        # "held by this name" was never the same question as "written by us".
        if serialized:
            _coord_release_exact(LAND_LOCK_KIND, LAND_LOCK_NAME, holder,
                                 reason="land complete", emit=emit)
        if ticket_taken:
            _coord_release_exact(LAND_QUEUE_KIND, identity, ticket,
                                 reason="land complete", emit=emit)


def _trunk_lock_reserve(identity: str) -> tuple[bool, dict, str]:
    """Take the trunk lock, exclusively. Three answers, the same shape as
    `_land_gate_reserve` (WI-0346):

      (True,  our record,   "")       - the lock is ours;
      (False, the holder's, "")       - a live other writer has it; RETRY;
      (False, {},           reason)   - fail-open: nothing was reserved and nobody holds
                                        it, so stop retrying and move the ref unlocked.

    Exclusive create or lose, modelled on `_land_gate_reserve` - see the section comment
    above for why reclaim-if-mine would be actively wrong for this particular lock. The
    only reclaim permitted is of an EXPIRED record, and because that write is not itself
    exclusive it is re-read and arbitrated, so two contenders that both judge the corpse
    theirs cannot both proceed.

    It inherited the gate's defect along with its shape: the fs-error path answered True
    having written nothing, and `trunk_lock`'s `finally` then force-released the record
    of whichever writer really held it - on the lock that exists to keep two processes
    off `refs/heads/<trunk>`. Fixed here and at the release together, because neither
    half is sufficient: a truthful reserve still cannot see a reclaim that happens after
    it returns ([`retire-the-class-not-the-instance`])."""
    d = _coord_dir(TRUNK_LOCK_KIND, create=True)
    if d is None:
        return False, {}, "no-store"     # no shared dir -> fail-open, as everywhere else
    path = d / f"{TRUNK_LOCK_NAME}.json"
    rec = _coord_record(identity, TRUNK_LOCK_TTL_SECONDS, name=TRUNK_LOCK_NAME,
                        kind=TRUNK_LOCK_KIND, acquired_at=time.time())
    payload = json.dumps(rec, ensure_ascii=False, indent=2) + "\n"
    try:
        fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(payload)
        return True, rec, ""
    except FileExistsError:
        pass
    except Exception:
        return False, {}, "fs-error"     # unexpected fs error -> fail-open
    holder = _coord_read(path)
    if holder is not None and not _coord_expired(holder):
        return False, holder, ""
    try:
        atomic_write(path, payload)
    except Exception:
        return False, holder or {}, ""
    back = _coord_read(path)
    won = bool(back) and back.get("created_at") == rec.get("created_at") \
        and back.get("session_id") == rec.get("session_id")
    return (True, rec, "") if won else (False, back or {}, "")


@contextlib.contextmanager
def trunk_lock(emit=print, poll: float = TRUNK_LOCK_POLL_SECONDS,
               max_wait: float = TRUNK_LOCK_MAX_WAIT_SECONDS, sleep=time.sleep):
    """Hold the trunk ref against every other writer of it, for as long as it takes to
    move it and no longer.

    Yields True if the hold is real, False if we are proceeding unlocked (and said why).
    Callers do not branch on it - a ref update is correct either way, just unprotected in
    the second case - but the tests do, and so does the receipt.

    NOT a queue. The land gate takes dated tickets because its holds run to minutes and a
    silent multi-minute wait is indistinguishable from a hang; here every hold is a commit,
    so the fair-ordering machinery would cost more than the thing it orders. First to the
    `O_EXCL` wins, and nobody waits long enough to be starved by it."""
    global _TRUNK_LOCK_DEPTH
    # Re-entrant per PROCESS, keyed on a counter and never on holder identity. A land
    # holds this around its swap; if any step inside that ever reaches a store write, a
    # non-reentrant lock would have the process deadlock against itself for the full cap.
    # Identity would NOT do here: a lane that runs `session.py wi-new` directly shares its
    # session id AND its journal with its own land, so an identity check cannot tell
    # "myself, nested" from "my sibling, racing".
    if _TRUNK_LOCK_DEPTH > 0:
        yield True
        return
    identity = _coord_identity()
    if _coord_dir(TRUNK_LOCK_KIND, create=True) is None:
        _TRUNK_LOCK_DEPTH += 1
        try:
            yield False
        finally:
            _TRUNK_LOCK_DEPTH -= 1
        return
    started = time.time()
    held, holder, failopen = _trunk_lock_reserve(identity)
    while not held and not failopen and (time.time() - started) < max_wait:
        sleep(poll)
        held, holder, failopen = _trunk_lock_reserve(identity)
    if failopen:
        # WI-0346: nothing was reserved and nobody holds it. Retrying a broken store for
        # the full cap buys nothing; the ref move is correct either way, just unprotected.
        holder = {}
        emit(f"trunk-lock: could not take the lock ({failopen}) - moving the trunk "
             f"UNLOCKED (fail-open). `python3 session.py coord` shows the store's state.")
    elif not held:
        emit(f"trunk-lock: waited {_fmt_wait(time.time() - started)} for "
             f"{_coord_short_holder(holder)} and gave up — moving the trunk UNLOCKED "
             f"(fail-open). `python3 session.py coord` shows the holder.")
    _TRUNK_LOCK_DEPTH += 1
    try:
        yield bool(held)
    finally:
        _TRUNK_LOCK_DEPTH -= 1
        if held:
            # WI-0346, and the same correction as the land gate's: `held` proves a reserve
            # returned True, not that the record at that path is still the one we wrote.
            # `_coord_release_exact` asks the second question, which is the one the unlink
            # actually depends on.
            _coord_release_exact(TRUNK_LOCK_KIND, TRUNK_LOCK_NAME, holder,
                                 reason="trunk write complete", emit=emit)


def _release_committed_numbers(paths: list[str],
                               reason: str = "committed") -> list[str]:
    """Free the number reservation of every store file in `paths` that is now COMMITTED
    (WI-0237). Returns the `<namespace>/<name>` of each record actually released.

    THE RESERVATION HAS DONE ITS JOB THE MOMENT THE FILE IS COMMITTED, and holding it
    past that point protects nothing while costing a great deal. `_counter_reserve_next`
    draws `max(landed files, sibling lane tips, trunk, held reservations) + 1`, so a
    committed file's number is already counted by the file scans whether or not a
    reservation also names it — the ticket is redundant from the commit onward, and the
    number can never be re-issued.

    WHAT IT COSTS TO KEEP. `poga work` anchors on the MAIN checkout by design (ADR-0073 —
    it is what keeps an item filed in a lane from being stranded), so the reservation it
    draws is tagged `branch: main` with the Claude session id as its ownership key. Every
    release path is lane-shaped: teardown frees what a LANE branch holds, and
    `_coord_release_dead_lanes` frees records whose lane branch is gone. A record tagged
    `main` is held by a branch that never disappears, by a session that ends, and no path
    frees it — so it sat out its full 8h TTL. Session ~185 filed fourteen items from a
    lane and was then refused its own land by its own fourteen tickets, one per item, and
    the trunk stayed blocked for the rest of the working day by the session's own
    successful work. Twelve such records were still in the live store when this was
    written, every one of them for a number already committed on the trunk.

    `force=True` IS THE POINT, not a shortcut past the ownership check. The commit is
    strictly better evidence than the ownership key: it proves the number is spent,
    whoever drew it. And the records that most need freeing are exactly the ones that
    read as somebody else's — the ownership key degrades to the checkout (`_coord_mine`),
    and a session whose journal has closed can no longer match its own record at all.
    `_coord_release` leaves a tombstone (WI-0074), so each release is auditable after the
    fact rather than a silent unlink.

    Never raises: a store write that succeeded must not be turned into an error by a
    coordination record that could not be tidied."""
    freed: list[str] = []
    try:
        counters = list(_counters().values())
        ident = _coord_identity()
    except Exception:
        return freed
    for path in paths:
        for c in counters:
            try:
                n = _counter_num_in_path(c, path)
            except Exception:
                continue
            if n is None:
                continue
            key = f"{c.namespace}/{n:04d}"
            if key in freed:
                break                     # a rename names one number twice
            try:
                if _coord_release(c.namespace, f"{n:04d}", ident, force=True,
                                  reason=reason):
                    freed.append(key)
            except Exception:
                pass
            break
    return freed


def _counter_alloc_holds(c: _Counter) -> dict[str, dict]:
    """Reservation records that still HOLD their number (R5b). Live-by-TTL records, PLUS
    TTL-expired records whose holder lane branch still exists: the reserved file is
    lane-local until land, so the old release condition — 'once the file exists the file
    scan accounts for it' — is false under lanes. Expiry alone must not free a number a
    living lane drew; the TTL frees a number only once its lane branch is gone (the
    orphan backstop)."""
    out: dict[str, dict] = {}
    for name, rec in _coord_list(c.namespace, include_expired=True).items():
        if not _coord_expired(rec):
            out[name] = rec
        else:
            br = rec.get("branch", "")
            if br and _ref_exists(f"refs/heads/{br}"):
                out[name] = rec
    return out


def _adr_alloc_holds() -> dict[str, dict]:
    """adr-alloc records that still HOLD their number (R5b)."""
    return _counter_alloc_holds(_counter("adr"))


def _wi_alloc_holds() -> dict[str, dict]:
    """wi-alloc records that still HOLD their number (R5b)."""
    return _counter_alloc_holds(_counter("wi"))


# ── WI-0402: the release verbs that write shared state belong to the MAIN checkout ──
#
# THE GAP. A release cut could only ever run from a session standing in the main
# checkout, and three independent things said so: `_rel_tag_preflight` refuses on its
# FIRST check unless `symbolic-ref HEAD` is the trunk; `_rel_tag_git` runs `git -C ROOT`
# and ROOT for a lane IS the lane, so the preflight asks the wrong tree by construction
# rather than by configuration; and the Claude Code RUNTIME's own worktree isolation
# guard — not `check-bash`, which has no such rule — refuses a lane's git operations
# against the shared checkout outright. Every session is a lane now
# (ADR-0070), so the cut ended in "and then a person opens the right kind of session" —
# the errand this substrate exists to delete.
#
# WHY A FRONT DOOR, AND NOT AN ANCHORED `_rel_tag_git`. Pointing the cut's git calls at
# the main checkout is the smaller change and the wrong one, for the reason
# `_refuse_lane_store_write` already writes down: EVERY worktree carries its own
# `session.py`, and a lane's copy is whatever it was cut with, so a redirect lets a
# possibly-weeks-old harness drive today's real release. That hazard is strictly worse
# here than it is for the store, because a cut PUSHES A TAG and a tag starts an
# unattended deploy (ADR-0103).
#
# It is also not sufficient, which settles it. The cut touches four things and only one
# of them is git-in-a-subprocess: `_rel_dir()` is ROOT-relative, so the record would
# still be written into the lane and committed to the lane's branch; `_rel_harvest()`
# would read the lane's TRACKED, FROZEN copy of `work-items/`; the `version:` stamps
# would land in that same copy; and `_rel_publish_tag` — comparing the lane's file
# against `git -C <main> show HEAD:<spec>` — would then refuse with "release record was
# not committed; tag not created". Anchoring one of the four converts three honest
# refusals into one confusing one.
#
# So the door is `poga release cut`: `require_repo` anchors it on the main checkout and
# it execs MAIN's harness there, which is the identical shape `poga work` and `poga ops`
# have used since WI-0125. This refusal shuts the back door behind that door, because a
# front door only helps if the back door is shut
# ([`add-structural-guard-on-recurrence`]) — `session.py` is on disk in every lane and
# its `--help` advertises `release-cut`.
#
# THE READERS ARE DELIBERATELY NOT IN HERE. `release-list` and `release-candidates`
# write nothing and strand nothing; refusing them would make a lane unable to so much as
# look at the release history, which is the shape of a guard that fires on correct code
# and gets deleted. Same carve-out reasoning as `wi-stale`'s, and pinned by a test so a
# later "consistency" pass cannot quietly fold them in.
LANE_ANCHORED_RELEASE_VERBS = frozenset({"release-cut", "release-declare"})


def _refuse_lane_release_write(verb: str, argv: list[str] | None = None) -> None:
    """Refuse a release verb issued from a linked worktree, naming the front door.

    THREE OUTCOMES, never two, for the reason its sibling `_refuse_lane_store_write`
    spells out: git can say this is the main checkout (proceed silently), or that it is a
    linked worktree (refuse), or it can fail to answer — and the third borrows neither
    sentence, because a guard that cannot tell and stays quiet is indistinguishable from
    one that checked and approved.

    `_main_checkout(at=ROOT)` asks the question OF THE TREE THIS HARNESS LIVES IN, never
    of the process cwd: a cwd-relative answer is about a different repo entirely, and
    would declare a test's temp repo a lane of the federation.
    """
    if verb not in LANE_ANCHORED_RELEASE_VERBS:
        return
    main = _main_checkout(at=ROOT)
    door = f"poga release {verb[len('release-'):]}"
    if main is None:
        print(f"{verb}: CANNOT TELL whether {ROOT} is the main checkout or a lane, so the "
              f"wrong-checkout check did not run. If this is a lane, the record you are "
              f"about to write lands in a copy of `{RELEASES_DIRNAME}/` no other checkout "
              f"reads, and the tag would be cut against this lane's HEAD — use `{door}`, "
              f"which anchors on the main checkout.", file=sys.stderr)
        return
    if main == ROOT.resolve():
        return
    rest = argv if argv is not None else (sys.argv[2:] if sys.argv[1:2] == [verb] else [])
    line = " ".join([door] + [shlex.quote(a) for a in rest])
    # Exit 4 is `LANE_STORE_REFUSAL_EXIT`'s meaning exactly — the request is well-formed
    # and answerable, it is addressed to the wrong checkout — so it is reused rather than
    # given a second number a caller would have to learn separately.
    print(f"{verb}: REFUSING to cut or declare a release from a lane — {ROOT} is a linked "
          f"worktree. Its `{RELEASES_DIRNAME}/` and `{WI_DIRNAME}/` are a TRACKED COPY "
          f"frozen at this lane's base commit, so the harvest would read a store that "
          f"stopped moving when this lane was cut, the record and the `version:` stamps "
          f"would be written where nothing else reads them, and the tag — which starts an "
          f"unattended deploy — would be cut against this lane's HEAD rather than the "
          f"trunk.\n"
          f"          The front door anchors on the main checkout and works from right "
          f"here, inside this lane. Run:\n\n"
          f"              {line}\n\n"
          f"          It runs the MAIN checkout's harness, against the main checkout, and "
          f"every refusal this verb already makes still applies there: a dirty trunk, an "
          f"unpushed trunk, an existing tag and an unlabelled item all still stop the cut. "
          f"The main checkout is {main}. Nothing was written.",
          file=sys.stderr)
    sys.exit(LANE_STORE_REFUSAL_EXIT)


def cmd_release_declare(args: argparse.Namespace) -> None:
    """Declare a MAJOR up front: its theme, its ruled-in items, and its ship target.

    This is the only way a major comes into existence (ADR-0081 D1) — there is no code
    path that computes one. Writing it before the work is the point: the manifest is a
    promise made outward, so it has to exist while the work is still changeable.
    """
    version = args.version.strip()
    if not SEMVER_RE.match(version):
        print(f"release-declare: '{version}' is not a semver like 7.0.0.")
        sys.exit(2)
    cur = _rel_current()
    if cur and _rel_parse_version(version) <= cur:
        print(f"release-declare: {version} is not ahead of the current "
              f"{'.'.join(str(x) for x in cur)}.")
        sys.exit(2)
    path = _rel_manifest_path(version)
    if path.exists():
        # Frozen once declared (WI-0044). Amendments are a deliberate, LOUD act — the
        # enemy is silent drift, not change — so they never happen by re-running a
        # command that looks like it just writes a file.
        print(f"release-declare: {path.name} already exists and a manifest is FROZEN "
              f"once declared. Amend it in place with an appended, dated reason.")
        sys.exit(2)
    ids = [x.strip() for x in (args.items or "").split(",") if x.strip()]
    known = {it["id"] for it in _wi_parse()}
    unknown = [i for i in ids if i not in known]
    if unknown:
        # WI-0239. The refusal is the safe direction and stays — a manifest is frozen
        # once declared, so ruling in an id this tree cannot read is not something to
        # wave through. What was wrong was the diagnosis: a milestone whose items were
        # minted on open lanes was told they did not exist, when the remedy is to land
        # the lanes and re-declare.
        cause = _wi_absent_cause(unknown)
        print(f"release-declare: not in this tree's store: {', '.join(unknown)}")
        for i in unknown:
            print(f"  {i} — " + (cause.get(i) or "no ref carries it and no live draw "
                                 "holds the number."))
        sys.exit(2)
    if not args.theme.strip():
        print("release-declare: a major needs a theme sentence — an agent-written "
              "'various improvements' is a version with no promise in it.")
        sys.exit(2)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# {_rel_project()} {version} — declaration manifest",
        "",
        "**DECLARED, not shipped.** This is a promise made outward: a closed set, frozen "
        "once declared. Anything not ruled in here is out. Amendments are allowed but "
        "must be LOUD — appended below with a date and a reason, never edited away. "
        "This is *not* a freeze on other work: off-manifest items keep shipping as minors "
        "alongside it.",
        "",
        "Item ids are REFERENCES into the work-item store, never restated descriptions — "
        "this is a view over the store, not a second backlog "
        "([`single-source-and-deliver`](habits/master.md#single-source-and-deliver)).",
        "",
        f"- version: {version}",
        f"- theme: {args.theme.strip()}",
        f"- target: {args.target.strip() if args.target else ''}",
        f"- declared: {_today()}",
        f"- items: {', '.join(ids)}",
        "",
        "## Definition of done",
        "",
        (args.done.strip() if getattr(args, "done", "") else
         "_Not stated. Fill this in — a manifest with no definition of done cannot be "
         "checked, only felt._"),
        "",
        "## Amendments",
        "",
        "_None yet. Append dated entries here; do not edit the fields above._",
        "",
    ]
    atomic_write(path, "\n".join(lines))
    print(f"declared {version} — {args.theme.strip()}")
    print(f"  {len(ids)} item(s) ruled in; target {args.target or '(none)'}")
    print(f"  {path}")


def _rel_tag_refuse(reason: str) -> None:
    print(f"release-cut: {' '.join(reason.split())}", file=sys.stderr)
    sys.exit(2)


def _rel_tag_git(*args: str):
    try:
        return subprocess.run(["git", "-C", str(ROOT), *args], text=True,
                              capture_output=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        _rel_tag_refuse(f"git {args[0]} could not complete: {exc}")


def _rel_tag_preflight(version: str) -> str:
    """Only a clean, published trunk may become a deployable release."""
    trunk = CFG.get("trunk", "main")
    branch = _rel_tag_git("symbolic-ref", "--quiet", "--short", "HEAD")
    if branch.returncode or branch.stdout.strip() != trunk:
        _rel_tag_refuse(f"run on landed {trunk} before cutting a tag")
    head = _rel_tag_git("rev-parse", "HEAD")
    remote = _rel_tag_git("ls-remote", "origin", f"refs/heads/{trunk}",
                          f"refs/tags/v{version}")
    if remote.returncode:
        _rel_tag_refuse("cannot verify origin before cutting a tag")
    refs = dict((line.split()[1], line.split()[0])
                for line in remote.stdout.splitlines() if len(line.split()) == 2)
    if head.returncode or refs.get(f"refs/heads/{trunk}") != head.stdout.strip():
        _rel_tag_refuse(f"{trunk} is not pushed and confirmed at origin")
    tag = f"v{version}"
    local = _rel_tag_git("show-ref", "--verify", "--quiet", f"refs/tags/{tag}")
    if local.returncode == 0 or f"refs/tags/{tag}" in refs:
        _rel_tag_refuse(f"tag {tag} already exists")
    if local.returncode != 1:
        _rel_tag_refuse(f"cannot verify whether tag {tag} exists")
    dirty = _rel_tag_git("status", "--porcelain", "--untracked-files=no")
    if dirty.returncode or dirty.stdout.strip():
        _rel_tag_refuse("tracked changes must be landed before cutting a tag")
    return trunk


def _rel_publish_tag(path: Path, version: str, trunk: str) -> None:
    """Publish record and tag atomically; never stamp items on a refused push."""
    spec = str(path.relative_to(ROOT))
    head = _rel_tag_git("rev-parse", "HEAD")
    record = _rel_tag_git("show", f"HEAD:{spec}")
    if head.returncode or record.returncode or record.stdout != path.read_text():
        _rel_tag_refuse("release record was not committed; tag not created")
    commit = head.stdout.strip()
    tag = f"v{version}"
    made = _rel_tag_git("tag", "-a", tag, commit, "-m", f"{_rel_project()} {version}")
    if made.returncode:
        _rel_tag_refuse(f"could not create tag {tag}: {made.stderr.strip()}")
    pushed = _rel_tag_git("push", "--atomic", "origin",
                          f"{commit}:refs/heads/{trunk}", f"refs/tags/{tag}")
    if pushed.returncode:
        _rel_tag_refuse(f"origin rejected release {tag}; local record and tag retained, items unstamped: {pushed.stderr.strip()}")
    remote = _rel_tag_git("ls-remote", "origin", f"refs/tags/{tag}^{{}}")
    if remote.returncode or remote.stdout.split()[:1] != [commit]:
        _rel_tag_refuse(f"could not confirm tag {tag} at origin; items unstamped")
    print(f"published {tag} — {commit}, pushed and confirmed")


def _rel_advance_devbox_mail(version: str) -> None:
    """Devbox's half of a federation deploy (WI-0428): the Runner's runner takes the tag
    unattended, and devbox's mail worker had nothing that ever did. Only the federation
    ships `deploy/devbox_mail.py`; a machine with no worker installed says so and is
    skipped. Never fatal — the tag is already published, and a refusal is printed whole."""
    script = ROOT / "deploy" / "devbox_mail.py"
    if not script.is_file():
        return
    try:
        ran = subprocess.run([sys.executable, str(script), "advance", "--tag", f"v{version}"],
                             capture_output=True, text=True, timeout=600)
    except (OSError, subprocess.TimeoutExpired) as exc:
        print(f"  devbox mail worker NOT advanced: {exc}")
        return
    if ran.returncode == 0:
        print(f"  devbox mail worker advanced: {ran.stdout.strip()}")
    else:
        print(f"  devbox mail worker NOT advanced: {ran.stderr.strip()}")


def cmd_release_cut(args: argparse.Namespace) -> None:
    """Harvest everything that landed into an immutable release record.

    The set never gates this (ADR-0078 D1): whatever is closed and unstamped ships, and
    whatever isn't is named as slipped rather than holding the cut.
    """
    shipped = _rel_harvest()
    if not shipped:
        print("release-cut: nothing to release — no closed item is missing a version.")
        sys.exit(1)
    bump, unlabelled = _wi_derive_bump(shipped)
    if bump is None:
        print("release-cut: refusing to compute a bump — these shipped items carry no "
              "impact label:")
        for wid in unlabelled:
            print(f"  - {wid}  (`wi-status {wid} --impact fix|feature`)")
        sys.exit(1)

    manifest = _rel_declared_major()
    override_reason = (getattr(args, "reason", "") or "").strip()
    source = "derived"
    ids = sorted(it["id"] for it in shipped)
    # ADR-0084 D1: the major is not a flag, it is a COUNT. `--ship-major` is gone — a
    # milestone shippable on demand could be declared complete while incomplete, which is
    # the one thing "declared, not derived" exists to prevent.
    promise = _rel_promise_state(manifest, set(ids)) if manifest else None
    ship_major = bool(promise and promise["complete"])
    if manifest and not ship_major:
        # A DECLARED MAJOR DOES NOT CAPTURE ORDINARY WORK.
        #
        # This used to read `if manifest:` and unconditionally became the declared major.
        # "Declared, not derived" (ADR-0081 D1) is about how a major's number is CHOSEN —
        # by a human naming a milestone — not about which harvest ships it, and collapsing
        # the two had three consequences, all wrong:
        #   1. every finished item became part of the major whether or not it had anything
        #      to do with the milestone, consuming the major's number on unrelated work
        #      while the milestone's OWN items were reported as slipped;
        #   2. minor and patch froze for the entire declaration window — features and
        #      fixes could not be numbered at all until the whole major shipped, which for
        #      a milestone with a two-week target means two weeks of unnumbered releases;
        #   3. `--override-bump` sat in the `elif`, so the documented escape hatch was
        #      unreachable exactly when a manifest existed — and it was ignored SILENTLY,
        #      with no warning that the flag had been discarded.
        # operator caught it by asking the obvious question this code answered wrongly:
        # wouldn't finished work bump the minor? It should, and now it does. ADR-0084
        # finished the thought: the major arrives when the promise is KEPT, so this note
        # reports the remaining count rather than naming a flag.
        n_out = len(promise["outstanding"])
        print(f"note:    {manifest['version']} is declared and not yet shipped — "
              f"{n_out} of {len(manifest['items'])} ruled-in item(s) still outstanding, "
              f"so this harvest is numbered normally.")
        if promise.get("absent"):
            # WI-0239: name the ones that are not merely unfinished but not HERE. Without
            # this the operator reads "3 outstanding" and goes looking for work that is
            # already done on a lane nobody landed.
            for w, cause in sorted(promise["absent"].items()):
                print(f"         {w} is not in this tree's store. {cause}")
        if promise["cancelled"]:
            # A superseded item can never ship, so it would stall the major forever. Say
            # so by name with the way out, rather than letting the milestone quietly never
            # arrive ([`declare-what-a-check-assumes`]).
            print(f"         {', '.join(promise['cancelled'])} was superseded and cannot "
                  f"ship — amend the manifest to drop it (ADR-0084 D5) or the milestone "
                  f"can never complete.")
    if manifest and ship_major:
        version, bump, source = manifest["version"], "major", "promise complete"
    elif getattr(args, "override_bump", None):
        if args.override_bump == "major":
            # argparse already restricts the CLI to minor|patch; this is the same rule
            # enforced where it actually matters. If an override could mint a major,
            # "declared, not derived" (ADR-0081 D1) would hold only by politeness — and
            # the CLI is not the only caller (`poga`, a future release script, a test).
            print("release-cut: a major cannot be overridden into existence. Declare the "
                  "milestone with `release-declare <version> --theme …` (ADR-0081).")
            sys.exit(2)
        if not override_reason:
            print("release-cut: --override-bump requires --reason. An override with no "
                  "written reason is indistinguishable from a mistake.")
            sys.exit(2)
        bump, source = args.override_bump, "overridden"
        cur = _rel_current() or (0, 0, 0)
        version = _rel_apply_bump(cur, bump)
    else:
        cur = _rel_current()
        if cur is None:
            print("release-cut: no prior release record, so there is no version to bump "
                  "from. Seed one first (see releases/README.md).")
            sys.exit(1)
        version = _rel_apply_bump(cur, bump)

    # THE MANIFEST THIS RECORD IS SHIPPING — None on an ordinary harvest even while a
    # major is outstanding. `manifest` alone answers "is a major declared?", which is a
    # different question from "is this record that major?", and every place that confused
    # the two produced a record claiming someone else's promise. The first real run of
    # this command stamped 6.1.0 with 7.0.0's theme and target for exactly that reason.
    shipping = manifest if ship_major else None
    # WI-0065 — the two halves operator asked for on reading 6.1.0's record: a ONE-LINER that
    # answers "what's new?" at a glance, and a five-second read of the contents. `summary`
    # is the first; `titles`, rendered beside every id below, is the second. Both are
    # derived here, once, from the harvest already in hand — the store is read for titles a
    # single time rather than per bullet, and nothing is written back to it.
    summary = _rel_summary(shipped)
    titles = _rel_titles()
    migrations = sorted(it["id"] for it in shipped if it.get("migration") == "yes")
    # ADR-0084 D4 — the ruled-in items that went out EARLIER, with the number each got.
    # This is what stops D2 (nothing waits) from silently shrinking every milestone: the
    # major's own harvest can only hold whatever was unstamped on the day it completed,
    # so without this section a nine-item promise ships a record listing two.
    prior = sorted(promise["prior"]) if shipping else []
    # D6 — a major can no longer ship with anything outstanding, so `slipped` is
    # structurally empty here. Kept because the SHAPE of the record is a published
    # contract, and because a dropped item now shows as a manifest amendment, which is a
    # stronger receipt than a bare line ([ADR-0078](adr/0078-…) D5 relocated, not dropped).
    slipped = list(promise["outstanding"]) if shipping else []

    if getattr(args, "dry_run", False):
        print(f"would cut {version} ({bump}, {source}) — {len(ids)} item(s)"
              + (f", {len(prior)} already shipped earlier" if prior else "")
              + (f", {len(slipped)} slipped" if slipped else "")
              + (f", {len(migrations)} needing migration" if migrations else ""))
        print(f"  {summary}")
        return

    path = _rel_dir() / f"{version}.md"
    if path.exists():
        print(f"release-cut: {path.name} already exists — a release record is immutable.")
        sys.exit(2)
    trunk = None if getattr(args, "no_tag", False) else _rel_tag_preflight(version)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        f"# {_rel_project()} {version}",
        "",
        f"- version: {version}",
        f"- bump: {bump} ({source})",
        f"- shipped: {_today()}",
        # FIXED POSITION, directly under `shipped:`, on a major as well as a minor. A
        # major also carries a `theme:` below — the two are different claims and both
        # belong: the theme is the promise a human made up front, the summary is what the
        # harvest actually turned out to contain, and a milestone that shipped something
        # other than what it promised is exactly the case worth being able to see.
        f"- summary: {summary}",
    ]
    if shipping:
        # D7: the ORIGINAL target sits beside the actual date, permanently. A target that
        # can be quietly moved as it approaches creates no pressure at all — every version
        # then ships "on time" by retroactive redefinition.
        lines.append(f"- target (original): {shipping['target'] or '(none declared)'}")
        lines.append(f"- theme: {shipping['theme']}")
    if override_reason:
        lines.append(f"- override reason: {override_reason}")
    lines += ["", "## Shipped", ""]
    lines += [f"- {_rel_titled(i, titles)}" for i in ids]
    if shipping:
        # ADR-0084 D4. Printed even when empty, so a reader of a major always sees the
        # full promise accounted for rather than having to infer that silence means none.
        lines += ["", "## Previously shipped in this promise", ""]
        lines += ([f"- {i} — {v}{_rel_title_suffix(i, titles)}" for i, v in prior]
                  or ["_None — every ruled-in item shipped in this release._"])
    # D5: what SLIPPED, not only what shipped. A record listing only the eight of ten that
    # landed is literally true and quietly false — it rewrites the plan to match the
    # outcome, so "we hit the plan" becomes true by omission at every release.
    lines += ["", "## Slipped", ""]
    lines += ([f"- {_rel_titled(i, titles)} — returned to backlog, re-derived for a "
               f"future set" for i in slipped]
              or ["_Nothing declared for this release was left out._"
                  if shipping else
                  "_No declared set — a minor is harvested, so there was nothing to slip._"])
    lines += ["", "## Migration required", ""]
    lines += ([f"- {_rel_titled(i, titles)}" for i in migrations]
              or ["_None — no member has to edit its own files for this release._"])
    lines += [""]
    atomic_write(path, "\n".join(lines))

    # COMMIT THE RECORD BEFORE STAMPING, not after and not never.
    #
    # Every item write below auto-commits itself (`_wi_autocommit`), so the 7.0.0 cut
    # produced 26 commits and left its OWN artifact untracked. That is the worst of the
    # three possible half-states: the stamps say `version: 7.0.0` on 26 items while the
    # record that defines 7.0.0 exists only as an uncommitted file, and `_rel_current`
    # reads the highest record ON DISK — so the version looked cut to this process and
    # would have vanished with the lane. Nothing about the failure is visible from either
    # side; the items look released and the release looks absent.
    #
    # Committing first inverts which half survives an interruption. A record with
    # unstamped items is self-announcing (the next `release-cut` refuses on an existing
    # record, and the items are still visibly unstamped) and re-runnable by hand. Stamps
    # with no record are neither.
    _rel_commit_record(path, version)
    if trunk is not None:
        _rel_publish_tag(path, version, trunk)

    for it in shipped:
        it["version"] = version
        _wi_write_item(it)

    print(f"cut {version} ({bump}, {source}) — {len(ids)} item(s) stamped")
    print(f"  {summary}")
    if shipping:
        print(f"  PROMISE COMPLETE — all {len(manifest['items'])} ruled-in item(s) "
              f"accounted for ({len(ids)} here, {len(prior)} earlier).")
    if slipped:
        print(f"  {len(slipped)} slipped: {', '.join(slipped)}")
    if migrations:
        print(f"  MIGRATION REQUIRED for {len(migrations)}: {', '.join(migrations)}")
    print(f"  {path}")
    if trunk is not None:
        _rel_advance_devbox_mail(version)
    if manifest:
        print("  next: the capability discussion for the following version is now OWED "
              "(ADR-0078 D6).")


def cmd_release_list(args: argparse.Namespace) -> None:
    """Every shipped release, plus any declared-but-unshipped major and its slippage.

    WI-0303 (b) added the second half. A declared set rots by slippage, and ADR-0084 D1
    closed every OTHER way a milestone can shrink — so the one remaining failure is an
    item nobody drops and nobody finishes, which leaves the promise formally intact and
    indefinitely unmet.

    It rides THIS verb rather than a new one, and rides the `--status` line it already
    prints at startup, because that is the only placement that satisfies the item's own
    acceptance: the nagging has to come from the machine rather than from anyone's
    memory, and an on-demand verb nags nobody. `_rel_stale_report` is file reads only,
    which is what makes that legal on the startup path — the check is built
    the way it is *in order to* be allowed here.

    `--status` gets one clause; the full verb gets the report. Nothing is ever dropped:
    the remedy is an amendment (ADR-0084 D5), which is a written act with a reason in it.
    """
    recs = _rel_records()
    cur = _rel_current()
    stale_days = getattr(args, "stale_days", None) or REL_STALE_DAYS
    if getattr(args, "status", False):
        man = _rel_declared_major()
        if not recs and not man:
            return
        bits = [f"version {'.'.join(str(x) for x in cur)}"] if cur else ["no releases yet"]
        if man:
            bits.append(f"{man['version']} declared ({man['theme'][:40]})")
            # Fail-open, like every other startup line: a banner that can raise is a
            # banner that can take the whole session start down with it.
            try:
                rep = _rel_stale_report(man, stale_days=stale_days)
                bits.append(_rel_stale_status_clause(rep))
            except Exception:
                bits.append("slippage unreadable")
        print("Releases: " + " · ".join(bits))
        return
    if not recs:
        print("No release records yet.")
    for v, p in recs:
        print(f"  {'.'.join(str(x) for x in v):<10} {p.name}")
    man = _rel_declared_major()
    if not man:
        return
    print(f"  {man['version']:<10} DECLARED, not shipped — {man['theme']}")
    print(f"             target {man['target'] or '(none)'}; "
          f"{len(man['items'])} item(s) ruled in")
    try:
        rep = _rel_stale_report(man, stale_days=stale_days)
    except Exception as e:                                        # fail open, always
        print(f"\n  slippage: could not read the ruled-in items ({type(e).__name__}) — "
              f"the list above stands; nothing below it was measured.")
        return
    print("")
    for line in _rel_stale_lines(rep):
        print(line)


def _rel_stale_status_clause(rep: dict) -> str:
    """The startup line's slippage clause — the shortest true sentence about the report.

    It names a number in EVERY case, including the quiet one, because this flag is
    measured to be quiet (see `REL_STALE_DAYS`) and a clause that appears only on a
    finding would be indistinguishable from a clause that is broken.
    """
    rows = rep["rows"]
    if not rows:
        return "promise complete"
    stuck = [r for r in rows if r["state"] == "cancelled"]
    stale = [r for r in rows if r["state"] == "stale"]
    if stuck:
        return (f"{len(stuck)} ruled-in item(s) SUPERSEDED — "
                f"{rep['version']} cannot complete")
    if stale:
        return (f"{len(stale)} of {len(rows)} outstanding idle "
                f"{rep['stale_days']}d+")
    oldest = (f"oldest {rep['oldest']}d" if rep["oldest"] is not None
              else "no dated movement")
    return f"{len(rows)} outstanding, {oldest}"


def cmd_release_candidates(args: argparse.Namespace) -> None:
    """WI-0303 (a): the delegable half of declaring a major — the candidate harvest.

    THE DIVISION OF LABOUR THIS IMPLEMENTS, from the source brief §4: agents propose and
    track; operator names and ratifies. Every agent here has read the whole work-item store
    and operator has not, so drafting the slate is the delegable half and it turns his sitting
    from recall into judgment.

    WHAT IT DELIBERATELY DOES NOT PRODUCE, and this is the load-bearing half. No theme
    sentence and no in/out ruling. The item's own words: *an agent-written theme produces
    majors called "various improvements" — a version with no promise in it; if operator is
    rubber-stamping proposed themes, majors have stopped meaning anything.*

    The item's acceptance paragraph reads both ways on this — it lists "a proposed theme
    per grouping" among the slate's contents and then says the theme sentence is
    explicitly not produced by the harvest. Resolved toward the second, on the argument
    the item gives for it rather than on the sentence that contradicts it: a printed
    candidate sentence is the exact mechanism by which rubber-stamping happens, and it
    cannot be un-read once it is on the page. What the slate prints instead is the
    EVIDENCE a theme would be written from — which items cluster, what they already share,
    what each cluster costs and what it waits on — plus a blank line for the sentence. The
    grouping's label is the `group:` field, which a human already authored when filing the
    item; that is a filing label and not a promise, and the difference is the whole point.

    COST IS NOT ESTIMATED. The store has no effort field, so any number here would be
    invented ([`no-fabricated-data`](habits/master.md#no-fabricated-data)). Three measured
    proxies are printed in its place and named as proxies: how many items a cluster holds,
    how many of them cannot start yet, and how many of their blockers point outside it.

    Prints by default and writes only with `--out`. A slate is a VIEW over the store that
    is stale the moment an item moves, and the manifest itself is described in its own
    preamble as a view rather than a second backlog; persisting a dated copy on every run
    would mint exactly the second list both of those rules exist to prevent. `--out` is
    there for the ruling session, where a frozen artifact is the point.
    """
    today = getattr(args, "today", "") or datetime.now(timezone.utc).date().isoformat()
    lines = _rel_candidate_lines(today=today,
                                 sections=getattr(args, "sections", None) or 0)
    out = getattr(args, "out", "") or ""
    if out:
        path = Path(out)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic_write(path, "\n".join(lines) + "\n")
        except Exception as e:
            print(f"release-candidates: could not write {out} ({type(e).__name__}) — "
                  f"printing instead so the work is not lost.")
            for line in lines:
                print(line)
            sys.exit(1)
        print(f"Wrote the candidate slate to {path} ({len(lines)} lines). "
              f"It is a snapshot of the store as of {today}, not a second backlog.")
        return
    for line in lines:
        print(line)


def _rel_candidate_lines(today: str = "", sections: int = 0) -> list[str]:
    """The candidate slate as text. Separated from the printer so `--out`, stdout and the
    tests all read one computation.

    `sections` caps how many clusters are printed in full (0 = all). P19: the store is
    367 files today and a slate is read in one sitting, so an unbounded list is a list
    nobody finishes — but a cap silently reached is indistinguishable from a short store,
    so reaching it is announced.
    """
    today = today or datetime.now(timezone.utc).date().isoformat()
    # ONE parse, two views. `by_id` must carry the TERMINAL items too — it is what
    # `_rel_live_blockers` resolves a `blocked-by` edge against, and a blocker that has
    # since closed is exactly the case it exists to answer. Parsing twice to get the two
    # sets read the whole 367-file store twice for no gain.
    everything = _wi_parse()
    by_id = {it["id"]: it for it in everything}
    items = [it for it in everything if it.get("status") not in WI_TERMINAL]
    man = _rel_declared_major()
    ruled_in = set(man["items"]) if man else set()
    live = [it for it in items if it["id"] not in ruled_in]

    out = [f"# Candidate slate for the next major — {_rel_project()}, {today}",
           "",
           f"Drawn from {len(items)} live work item(s) in {WI_DIRNAME}/. Every id below "
           f"points at its own file; nothing here restates an item's description, so this "
           f"is a view over the store rather than a second backlog.",
           ""]
    if man:
        out += [f"{man['version']} IS ALREADY DECLARED and its {len(ruled_in)} ruled-in "
                f"item(s) are excluded below — this slate is for the version AFTER it.",
                ""]
    out += ["## What this does not decide",
            "",
            "No theme sentence and no in/out ruling. Those are yours, permanently. A "
            "machine-written theme is how a major becomes 'various improvements', and a "
            "proposed sentence cannot be un-read once it is on the page — so each cluster "
            "below carries the EVIDENCE a theme would be written from and a blank line to "
            "write it on. The cluster headings are `group:` fields somebody already typed "
            "when filing the item; a filing label is not a promise.",
            "",
            "Cost is not estimated either. The store carries no effort field, so a number "
            "here would be invented. What is printed is three measured proxies, named as "
            "proxies: the cluster's size, how much of it cannot start yet, and how many of "
            "its blockers point outside it.",
            ""]

    forcing = [it for it in live if (it.get("migration") or "").strip() == "yes"]
    out += ["## Migration-forcing, not yet shipped", ""]
    if forcing:
        out += [f"{len(forcing)} item(s) carry `migration: yes` — shipping them makes "
                f"other members edit their own files. This is the closest live signal to "
                f"the brief's 'deferred breaking items': ADR-0081 D5 RETIRED "
                f"`impact: breaking` and split it into `impact` (size) plus `migration` "
                f"(does it force edits elsewhere). The label feeds no version number and "
                f"gates nothing, so it is surfaced here as a candidate signal and never "
                f"read as a trigger.",
                ""]
        out += [f"- {_rel_candidate_row(it, by_id)}" for it in forcing]
    else:
        out += ["None. No live item carries `migration: yes`, so nothing is queued that "
                "can only travel in a major on those grounds.",
                "",
                "Worth reading as a measured zero rather than as an omission: the brief's "
                "original trigger — escalate when N `breaking` items are waiting — was "
                "DROPPED in the session ~241 ruling for precisely this reason, and the "
                "line above is that ruling's evidence, re-measured on the day you read it."]
    out += [""]

    groups: dict[str, list[dict]] = {}
    for it in live:
        groups.setdefault((it.get("group") or "").strip(), []).append(it)
    named = sorted(((g, v) for g, v in groups.items() if g),
                   key=lambda kv: (-len(kv[1]), kv[0]))
    shown = named[:sections] if sections else named
    out += [f"## Clusters — {len(named)} group(s), largest first", ""]
    for g, its in shown:
        out += _rel_cluster_lines(g, its, by_id)
    if len(shown) < len(named):
        rest = named[len(shown):]
        # The NAMES are capped too, and saying so costs one clause. A header that counts
        # ten and then lists eight is the same defect this whole block exists to avoid,
        # one level down — an announced bound whose own announcement is silently bounded.
        names = ", ".join(f"{g} ({len(v)})" for g, v in rest[:8])
        more = f", and {len(rest) - 8} more not named here" if len(rest) > 8 else ""
        out += [f"NOT SHOWN ({len(rest)}): the per-run cap is {sections} cluster(s) and "
                f"there are {len(named)}, so the tail was not laid out. Nothing above is "
                f"a statement about it — {names}{more}.",
                ""]
    loose = sorted(groups.get("", []), key=lambda it: it["id"])
    out += [f"## Ungrouped — {len(loose)} item(s)", ""]
    if loose:
        out += ["No `group:` field, so these cluster with nothing and are listed for "
                "completeness. An item that belongs in a grouping above is a `wi-edit "
                "--group` away from joining it; that is an authoring act, not this "
                "report's to perform.",
                ""]
        out += [f"- {_rel_candidate_row(it, by_id)}" for it in loose]
    else:
        out += ["None — every live item carries a group."]
    out += ["",
            "## Ruling",
            "",
            "Each cluster above is in, out, or on the cut line. Write the theme for "
            "whatever you rule in, then declare it:",
            "",
            f"    python3 session.py release-declare <version> --theme \"<yours>\" "
            f"--items WI-…,WI-… --target YYYY-MM-DD --done \"<what makes it finished>\"",
            "",
            "The manifest is frozen once written; dropping an item afterwards is an "
            "amendment with a written reason, never a flag (ADR-0084 D5)."]
    return out


def _rel_cluster_lines(group: str, its: list[dict], by_id: dict) -> list[str]:
    """One cluster: its measured proxies, its blank theme line, and its items."""
    # A TRUE PARTITION, and it has to be: the first cut counted `held` separately from
    # `blocked`, so a cluster of three printed "ready 1, blocked 1, held 2" — four states
    # for three items. Three numbers on one line read as a breakdown whether or not they
    # were built as one, and a breakdown that does not sum is worse than no breakdown,
    # because the reader corrects it by guessing which number is wrong.
    blocked = [it for it in its if _rel_live_blockers(it, by_id)]
    held = [it for it in its if it not in blocked and it.get("status") == "held"]
    ready = [it for it in its if it not in blocked and it not in held]
    inside = {it["id"] for it in its}
    outward = sorted({b for it in its for b in _rel_live_blockers(it, by_id)
                      if b not in inside})
    feat = len([it for it in its if it.get("impact") == "feature"])
    fix = len([it for it in its if it.get("impact") == "fix"])
    unlabelled = [it["id"] for it in its if it.get("impact") not in WI_IMPACTS]
    out = [f"### {group} — {len(its)} item(s)", ""]
    out += [f"- size: {len(its)} = ready {len(ready)} + blocked {len(blocked)} + "
            f"held {len(held)}",
            f"- impact: {feat} feature, {fix} fix"
            + (f", {len(unlabelled)} UNLABELLED ({', '.join(unlabelled[:4])}) — an "
               f"unlabelled item refuses the whole bump computation at the cut"
               if unlabelled else ""),
            f"- blockers outside this cluster: "
            + (", ".join(outward) if outward else "none — it can be ruled in whole")]
    out += ["", "theme: ______________________________________________  (yours)", ""]
    out += [f"- {_rel_candidate_row(it, by_id)}" for it in sorted(its,
                                                                 key=lambda i: i["id"])]
    out += [""]
    return out


def _rel_live_blockers(item: dict, by_id: dict) -> list[str]:
    """The item's `blocked-by` ids that are NOT terminal — resolved against the store at
    read time rather than trusted from the field, the way `wi-list` and `wi-show` do it.
    A blocker that has since closed does not block, and reporting it as one would inflate
    every cluster's cost with work that is already done."""
    out = []
    for b in item.get("blocked_by") or []:
        other = by_id.get(b)
        if other is None or other.get("status") not in WI_TERMINAL:
            out.append(b)
    return out


def _rel_candidate_row(it: dict, by_id: dict) -> str:
    """One item's line on the slate: id, title, size label, and what it waits on."""
    bits = [_rel_titled(it["id"], {it["id"]: it.get("title") or ""})]
    bits.append(f"[{it.get('impact') or 'UNLABELLED'}]")
    if (it.get("migration") or "").strip() == "yes":
        bits.append("[migration]")
    if it.get("status") == "held":
        bits.append("[held]")
    blockers = _rel_live_blockers(it, by_id)
    if blockers:
        bits.append("waits on " + ", ".join(blockers))
    return "  ".join(bits)


def _unlock_if_owner_is_dead(path: str) -> bool:
    """Release a worktree lock whose owning process no longer exists.

    Claude Code locks a `--worktree` lane for the life of its session, with a reason that
    NAMES THE OWNER — `claude session poga-2 (pid 12345 start Thu Jan 1 12:00:00 2026)`.
    The lock is not ours and neither is the crash: when that session dies without
    unlocking, the lane becomes permanently unremovable, and every sweep we own fails
    against it with `cannot remove a locked working tree`. One member carried one for two
    days behind a pid that had been gone the whole time.

    The pid in the reason is what makes this safe rather than a guess: a lock naming a
    process that does not exist cannot be protecting a session, and `os.kill(pid, 0)` is
    the same liveness evidence the stranded-process reaper already trusts. Anything
    else — a live pid, a reason with no pid in it, an unreadable worktree list — leaves
    the lock exactly where it is. Unknown is never "safe to unlock"."""
    try:
        r = sh(["git", "-C", str(ROOT), "worktree", "list", "--porcelain"], check=False)
        if r.returncode != 0:
            return False
        target, reason = str(Path(path).resolve()), None
        cur = None
        for ln in (r.stdout or "").splitlines():
            if ln.startswith("worktree "):
                cur = str(Path(ln[len("worktree "):].strip()).resolve())
            elif ln.startswith("locked") and cur == target:
                reason = ln[len("locked"):].strip()
                break
        if reason is None:
            return False                        # not locked, or not this worktree
        m = _LOCK_PID_RE.search(reason)
        if not m:
            print(f"note: {Path(path).name} is locked by a reason naming no pid — left "
                  f"alone: {reason[:80]}", file=sys.stderr)
            return False
        pid = int(m.group(1))
        if _pid_alive(pid):
            print(f"note: {Path(path).name} is locked by LIVE pid {pid} — left alone.",
                  file=sys.stderr)
            return False
        u = sh(["git", "-C", str(ROOT), "worktree", "unlock", str(path)], check=False)
        if u.returncode == 0:
            print(f"unlocked: {Path(path).name} — lock owner pid {pid} is gone.")
            return True
        return False
    except Exception:
        return False


def _preflight_guided_blocked(results: list[_PreflightResult]) -> str:
    """Why the guided step must not run right now, or "" if it may.

    THE STRANDED-FLOW INTERLOCK IS NOT A DETAIL. Wall 4 of ADR-0096 was a second auth
    flow opened while one was already live. A repair that starts another auth flow on a
    machine that already has one is the original defect wearing a fix's clothes."""
    for r in results:
        if r.name == "stranded-runtimes" and r.verdict == PREFLIGHT_FAIL:
            return ("an interactive auth flow is already running on this machine; "
                    "starting a second one is ADR-0096's wall 4")
    try:
        if not (sys.stdin.isatty() and sys.stdout.isatty()):
            return "there is no terminal here to answer the dialog"
    except Exception:
        return "this process has no usable terminal"
    return ""


def _canon_block() -> str:
    """The generated canon digest (CANON.md), or '' if absent/unreadable. Read-only;
    never blocks the start ritual — injecting the universal set is best-effort delivery.

    The digest is delivered with this system's picker setting already applied (see
    `_resolve_picker_policy`), so the instructions and the check-question hook agree."""
    try:
        canon = CANON_PATH.read_text(encoding="utf-8").strip()
    except Exception:
        return ""
    try:
        return _resolve_picker_policy(canon)
    except Exception:
        return canon


# The canon's P17 lines as `distill.py` writes them, keyed by the bold lead that starts
# each line. With `interaction.pickers: allow` they are replaced whole at delivery time.
_P17_ALLOW_LINES = {
    "- **P17 `ask-in-prose-not-pickers`**":
        "- **P17 `ask-in-prose-not-pickers`** — This system set `interaction.pickers: "
        "allow`, so a picker is permitted. Picker or prose, lay out each option with its "
        "pros and cons, give a reasoned recommendation, leave room for an answer outside "
        "the options (including rejecting the question's premise), then confirm.",
    "- **`structured-decision-presentation`** (P17)":
        "- **`structured-decision-presentation`** (P17) — For decisions with real "
        "trade-offs: each option's pros and cons, then an explicit recommendation with "
        "reasoning. A picker is permitted here (`interaction.pickers: allow`), but the "
        "reasoning stays in the conversation. Yes/no confirmations are fine.",
}


def _resolve_picker_policy(canon: str) -> str:
    """The canon as this system's picker setting reads it. Consultant brief 2026-09-28.

    CANON.md is generated and shared, and it states P17's default: never a picker. A
    system that set `"interaction": {"pickers": "allow"}` has the check-question hook
    stand down, and the instructions must say the same, or a compliant agent still
    avoids the UI the user opted into. So with `allow`, the two P17 lines are swapped
    for wording that permits a picker and keeps the rest of P17: explain the options,
    recommend, leave room to reject the premise. With the default, the canon is returned
    unchanged. `pickers_allowed` fails closed, so a broken config keeps the ban here too."""
    if not pickers_allowed():
        return canon
    lines = canon.split("\n")
    for i, line in enumerate(lines):
        for lead, replacement in _P17_ALLOW_LINES.items():
            if line.startswith(lead):
                lines[i] = replacement
    return "\n".join(lines)


