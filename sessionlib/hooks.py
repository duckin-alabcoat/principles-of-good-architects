def cmd_announce(args: argparse.Namespace) -> None:
    """Print the staged session banner to plain stdout, then consume it.

    Wired as a second SessionStart 'startup' hook alongside `start`. This is the
    deterministic USER-VISIBLE post of the start stamp (and any orphan we just
    auto-closed): `start`'s own systemMessage channel is upstream-broken
    (#9090/#50542) and its additionalContext is model-only, so the banner rides
    the one SessionStart channel that renders to the user — plain stdout.

    SessionStart hooks run in PARALLEL with no ordering guarantee, so this hook
    cannot assume `start` has already staged the banner. It POLLS for THIS
    session's per-session file (keyed by the shared stdin session_id), which
    `start` writes at every exit — the real banner on the normal path, an empty
    sentinel on the early-return paths. An empty file means "nothing to announce"
    (resolves the poll at once); a non-empty file is printed. Bounded wait,
    fail-open (a banner miss must never hang or break startup). Consumes (unlinks)
    the file so a re-run prints nothing."""
    try:
        session_id = _read_hook_stdin().get("session_id")
        path = _banner_file(session_id)
        deadline = time.monotonic() + ANNOUNCE_WAIT_S
        while True:
            if path.is_file():
                sys.stdout.write(path.read_text(encoding="utf-8"))
                path.unlink(missing_ok=True)
                return
            if time.monotonic() >= deadline:
                return
            time.sleep(ANNOUNCE_POLL_S)
    except Exception:
        pass


def cmd_runtime_resolve(args: argparse.Namespace) -> None:
    """Resolve a runtime for poga, or REFUSE BY NAME (ADR-0082 D3/D4).

    poga owns the exec; it does not own the table. On success this prints
    shell-readable KEY=VALUE lines for poga to consume. On failure it names the
    specific problem and exits nonzero — BEFORE poga allocates a lane, so a missing
    binary can never surface as a raw `no such file or directory` from inside `exec`
    after a worktree and a branch have already been created.

    Three distinct failures, three distinct exit codes, because 'unknown runtime',
    'no command configured' and 'command not installed here' need different fixes and
    folding them together is `declare-what-a-check-assumes` all over again:
      2  unknown id/alias
      3  known runtime, no launch command configured yet  (no shipped row today)
      4  command configured but not found on PATH         (a runtime not installed here)
    """
    if getattr(args, "list", False):
        print("runtimes (ADR-0082 D2 roster):")
        print(_runtime_roster())
        return

    key = (getattr(args, "runtime", None) or RUNTIME_DEFAULT)
    row = _runtime_row(key)
    if row is None:
        print(f"runtime-resolve: '{key}' is not a known runtime.\n"
              f"declared runtimes:\n{_runtime_roster()}", file=sys.stderr)
        sys.exit(2)

    if not row["command"]:
        print(f"runtime-resolve: runtime '{row['id']}' has no launch command "
              f"configured — add one to the RUNTIMES registry in session.py "
              f"before launching a lane with it.", file=sys.stderr)
        sys.exit(3)

    resolved = shutil.which(row["command"])
    if not resolved:
        print(f"runtime-resolve: runtime '{row['id']}' needs '{row['command']}', "
              f"which is not on PATH on this machine. Install it, or symlink it onto "
              f"PATH (e.g. ln -s <path-to-{row['command']}> ~/.local/bin/{row['command']}).",
              file=sys.stderr)
        sys.exit(4)

    print(f"POGA_RUNTIME_ID={row['id']}")
    print(f"POGA_RUNTIME_COMMAND={resolved}")
    print(f"POGA_RUNTIME_WORKTREE_FLAG={row['worktree_flag'] or ''}")
    print(f"POGA_RUNTIME_GUARDS={row['guards']}")
    print(f"POGA_RUNTIME_ARGV_SHAPE={row.get('argv_shape') or 'positional'}")
    print(f"POGA_RUNTIME_PROMPT_SHAPE={row.get('prompt_shape') or row.get('argv_shape') or 'positional'}")



def _close_summary_lines(journal_text: str) -> list[str]:
    """What this session leaves behind, rendered for the terminal it is closing (WI-0399).

    THE SECTION, NOT A RESTATEMENT OF IT. `### State at close` is what the Architect
    actually wrote about where things stand, and it is also exactly what the board
    renders -- one section, read by one function (`close_summary`), so the terminal and
    the board can never describe different closes.

    Silent when the section is empty, which is a real and honest answer: a session that
    wrote nothing there leaves nothing to print, and inventing a line would be
    ([`no-fabricated-data`](habits/master.md#no-fabricated-data)) on the one surface that
    is read as a receipt."""
    body = close_summary(journal_text)
    if not body:
        return []
    out = ["", "state at close:"]
    out += [f"  {ln}" if ln.strip() else "" for ln in body.splitlines()]
    return out


def cmd_end(args: argparse.Namespace) -> None:
    """Close this session's journal, recompile the views, and land its work.

    The journal is closed and the end banner printed BEFORE the land runs: the
    session is over either way, and a land that fails must not leave the record
    open.

    Exit codes are `integrate`'s three, because one land vocabulary beats two: **0**
    landed (or there was nothing to land), **1** refused with the trunk untouched, **2**
    the trunk kept moving. Nonzero only on failure — a success returns normally rather
    than raising `SystemExit(0)` (WI-0263).
    """
    if CFG is None:
        raise SystemExit(f"session.py: {CONFIG_PATH.name} missing or invalid — cannot end.")

    # WI-0340. THE REFUSALS BELOW NAME THE VERB THE OPERATOR RAN, not the function they
    # are raised from. `merge`'s closing half IS this function (P16, `_merge_close_args`),
    # so a hardcoded "session.py end" here is wrong for every closing `merge` — and it was
    # wrong in exactly the way the measured defect was diagnosed through: the lane read a
    # refusal naming a verb it had not run and a flag that verb did not take, and reached
    # its land by elimination. `end` is the default because every other caller IS `end`:
    # only the one translation point sets it.
    verb = getattr(args, "verb", None) or "end"

    # ADR-0055: if this session lazy-started and somehow reaches `end` before any
    # heartbeat consumed the marker, materialize the journal now so there is one
    # to close. Idempotent no-op otherwise.
    _complete_lazy_start(_claude_session_id())

    # ADR-0051 C2: close THIS session's journal (own-journal-only), then recompile the
    # generated handoff/STATUS views. No session edits the shared handoff any more.
    jpath, how = resolve_end_journal(getattr(args, "session_id", None))
    if jpath is None:
        raise SystemExit(f"session.py {verb}: {how}.")
    # WI-0332: the journal has to BE a journal before any of this proceeds. Refusing here
    # rather than only at `finalize_journal` buys the earliest possible stop — before the
    # attention record is cleared, before the work-item harvest, before the banner — so a
    # refused close leaves the session exactly as it found it. `--session-id` is the
    # resolver that reaches a clobbered journal at all: the other two filter on
    # `session-id` and cannot see one, which is a second face of the same defect and is
    # why `unreadable_journals` reports at every compile rather than only here.
    fm, _body = require_journal_frontmatter(jpath, jpath.read_text(encoding="utf-8"))
    if fm.get("ended"):
        raise SystemExit(
            f"session.py {verb}: journal {fm.get('session-id')} already closed at "
            f"{fm['ended']}.")

    # ADR-0101: a session that is ending is not waiting on anyone. Left behind, the record
    # would age into a permanent "waiting on you" for a lane that no longer exists — the
    # ghost shape this whole design exists to avoid, reintroduced by its own mechanism.
    # Moved BELOW both journal refusals (WI-0332): a close that refuses is not a session
    # that ended, and clearing its attention record would publish the opposite. It sits
    # under the already-closed check too, not just the frontmatter one — both are the same
    # kind of "this is not a close" and splitting them would leave half the hole open.
    _attention_clear()

    version = role_doc_version()
    machine = detect_machine()
    end_stamp = now_stamp()
    start_dt = _parse_iso(fm.get("started", ""))
    dur = format_duration(start_dt, datetime.now(CFG["tz"])) if start_dt else "?"
    ordinal = compiled_ordinal(fm.get("session-id", ""))   # the derived 'Session N'
    ordinal = _guard_close_ordinal(ordinal, fm)
    # R4b (the session-90 five-way collision): a lane's ordinal is computed from the
    # lane-LOCAL journal set, so siblings cut from one base all derive the same number
    # — five lanes each committed "close session 90". A lane therefore never asserts
    # a final ordinal: its derived close-commit message carries the session-id (unique
    # by construction) and its banners show ~N; the trunk compile assigns the real
    # number at land (`compiled_ordinal` over the landed union).
    on_lane = _on_worktree_lane()

    # Interactive-close guard (P15 / add-structural-guard-on-recurrence; consultant
    # brief 2026-07-26-consultant-unprompted-mid-session-closeouts). `end` IS the
    # session-end ritual — it follows the user AGREEING to close, never the agent's own
    # judgment that its task list is done (session 98 closed itself off the back of "yes
    # build that", a task, not a close). The Architect asks in one line and passes back
    # what the user actually said; there is deliberately no list of accepted phrases,
    # because any such list is wrong the moment the user says something not on it. Not
    # tamper-proof — an agent could fabricate the quote — but a fabrication sits in an
    # auditable frontmatter field, exactly what the ADR-0053 miner is built to catch
    # (see finalize_journal).
    #
    # ADR-0113 REDRAWS THE EXEMPTION (WI-0249 (a), closing WI-0144). It used to be
    # `not on_lane` — the line was WHERE `end` ran, and ADR-0104 D5 said so and named it
    # as the hole it was leaving open. It is now WHAT AUTHORIZED THE CLOSE: a dispatched
    # session is exempt because its dispatch is the authorization, and a hand-opened lane
    # asks like every other hand-opened session. `on_lane` leaves this condition entirely.
    # D5's reasoning for the old line — that gating a lane would strand its work — was
    # true when `end` was a lane's only way to reach the trunk and is not true now:
    # `merge` lands a package and leaves the session open (WI-0144), so a refused close
    # costs a question, not a strand.
    # WI-0331 adds the SECOND non-human authorization. ADR-0113 redrew this line on what
    # authorized the close and found one: a dispatch. An unattended runner (ADR-0050's
    # adoption path) is the other — it spawns a headless session in a member repo with
    # nobody attached, and before this it could not close at all, leaving `--confirm`
    # with an invented quote as the only way past a gate that exists to record that a
    # human agreed. The two stay SEPARATE resolvers with separate citations so the record
    # never says "dispatch" about a thing that was not one.
    dispatch_confirm = _dispatched_close_authorization()
    unattended_confirm = _unattended_close_authorization()
    # Precedence is evidence quality: a human's own sentence beats a record of the
    # instruction that produced it, and a dispatch (a named item, a queue, a lane) is a
    # stronger authorization than "a machine started me", so the weakest stands last.
    confirm = ((getattr(args, "confirm", None) or "").strip()
               or dispatch_confirm or unattended_confirm)
    if not confirm:
        raise SystemExit(
            f"session.py {verb}: refused — pass --confirm \"<what the user said>\". You do "
            "not close a session on your own judgment: ask the user in one line ('Close "
            "out the session?') and run this only once they agree, passing their reply "
            "verbatim. Finishing your task list, a brief, or the board is NOT a close. A "
            "bare W needs no ask — pass --confirm \"W\". THIS REFUSES IN A LANE TOO "
            "(ADR-0113, superseding ADR-0104 D5): the exemption follows what authorized "
            "the close, not where `end` runs. Nothing is stranded by it — `session.py "
            "merge --continue` lands your work and leaves the session open, so a refused "
            "close costs a question, not your work. (A bare `merge` is a close too since "
            "WI-0288 R2, and is refused here on the same terms.) A DISPATCHED lane "
            "needs no --confirm: its dispatch is its authorization, cited into "
            "close-confirm. AN UNATTENDED RUN needs no --confirm either: its runner "
            "sets POGA_UNATTENDED_RUN and writes the run record this resolves against "
            "(WI-0331). IF YOU ARE AN UNATTENDED SESSION AND THAT IS ABSENT, DO NOT "
            "INVENT A --confirm VALUE — that field records that a HUMAN agreed, and a "
            "fabricated one corrupts the only evidence anybody has. Leave the session "
            "open and say the runner did not mark it.")

    # WI-0340. Placed HERE on purpose: after the authorization is resolved, so the guard
    # can tell a dispatched close from a human one, and before anything at all is written,
    # so a refusal leaves the session exactly as it found it — the ordering WI-0332 argues
    # for one refusal further up. `--dry-run` is deliberately downstream of this too: a
    # dry run that reports a close which would in fact be refused is a lie about the very
    # thing it exists to preview. `_body` is the frontmatter parse's second half, read
    # here for the first time.
    if dispatch_confirm and not (getattr(args, "confirm", None) or "").strip():
        _refuse_a_dispatched_close_the_record_contradicts(jpath, fm, _body, verb)

    derived_msg = (f"docs(handoff): close {fm.get('session-id', '')}" if on_lane
                   else f"docs(handoff): close session {ordinal}") + (
                   f" — {args.title}" if args.title else "")
    banner_tail = LANE_ORDINAL_NOTE if on_lane else None

    if args.dry_run:
        print("--- session end (dry-run, nothing written) ---")
        # WI-0401: the dry run shows the disposition block too. A session checking
        # whether it can close is exactly the one that needs to see which clause of its
        # goal it has not accounted for, and seeing it here costs nothing and writes
        # nothing.
        for line in goal_block_for_session(fm.get("session-id", "")):
            print(line)
        print(_fmt_banner("end", _display_ordinal(ordinal, settled=not on_lane),
                          version, machine, end_stamp, dur, tail=banner_tail))
        print(f"journal: {jpath.name} ({how}); duration: {dur}")
        return

    # 1. Finalize the journal: ended + duration + final title (frontmatter surgery, P15),
    #    and harvest the work items this session held (ADR-0093 D1) — here, because the
    #    claims are still in the coordination store and land teardown is about to free
    #    them. Harvested BEFORE the stamp so a store that cannot be read leaves the field
    #    absent rather than empty.
    # `confirm` is the user's own words where they gave them and the resolved dispatch
    # citation otherwise (ADR-0113) — an explicit --confirm always wins, because a human's
    # sentence is better evidence than a record of the instruction that produced them.
    # Either way the field is never empty on a close that happened, which is what makes
    # "what authorized this?" answerable from the journal alone (ADR-0112 D9).
    # WI-0278: fold this session's escalation ledger into the body FIRST, so the close
    # stamp lands on the text that carries it and the journal reaches disk once. The
    # ledger was written across the session by the Notification hook and by every clear;
    # this is the moment it becomes the durable, TRACKED record -- the sidecar it comes
    # from is gitignored per-machine residue that the janitor drops on its own schedule.
    #
    # ORDER MATTERS AND IT IS THE ONE ORDER THAT WORKS. `_attention_clear()` ran above
    # (line ~655), so a question still open when `end` was called has ALREADY had its
    # clear line appended by the time this reads -- which is correct, and is why the
    # rendered wait for that last question is measured to the close rather than left
    # blank. Both refusals are above that clear, so a close that refuses folds nothing.
    folded = fold_midsession_escalations(jpath.read_text(encoding="utf-8"),
                                         fm.get("session-id", ""))
    # WI-0401: and the goal disposition beside it, on exactly the same terms — a machine
    # written section, folded at the same moment, for the same reason. The block `end`
    # prints goes to a terminal, and a dispatched lane's terminal is a detached pane; the
    # journal is where "why did this session close with that clause unmet?" is answered
    # later, from the trunk.
    folded = fold_goal_disposition(folded, fm.get("session-id", ""))
    closed = finalize_journal(folded, _now_iso(), dur,
                              title=args.title or None,
                              confirm=confirm or None,
                              work_items=_harvest_session_work_items(
                                  fm.get("session-id", "")),
                              path=jpath)
    atomic_write(jpath, closed)

    # 1a. WI-0399 — PUBLISH THE CLOSE, and publish it HERE, which is the whole race this
    #     pairing can lose. The summary has to be durable before the process can go away:
    #     this session is about to land, print, and then (WI-0399's other half) terminate
    #     its own runtime, and a record written on the way out would be lost to a fast
    #     exit or to the SIGKILL escalation. So it is written the instant the journal is
    #     stamped -- before the land, before the banner, before anything starts signalling
    #     -- and the board can be read after the process is gone, which is the property
    #     the item asks to be shown rather than asserted.
    #
    #     `landed=None` on purpose: nothing has tried to land yet, and a boolean here
    #     would have to guess. The land re-publishes with the real answer below.
    _close_fm, _ = parse_journal(closed)
    _session_close_publish(closed, _close_fm, landed=None)

    from sessionlib.registry_state import record_end as record_registry_end
    try:
        if not _running_against_fixture():
            record_registry_end(ROOT, _shared_work_root(), fm.get("session-id", ""))
    except (OSError, UnicodeError) as exc:
        print(f"registries: baseline write failed — {exc}", file=sys.stderr)

    # R2b (the poga-5 close-honesty gap): the end banner is the only valid receipt of a
    # close — a close claim without it is false. This marker makes "did `end` actually
    # run?" a file-existence test, distinct from the SessionEnd hook's `.ended` marker
    # (which fires on any app quit, ritual or not — exactly what masked poga-5's false
    # close). Keyed by the durable session-id; minable like the guard-firing log.
    _sidecar_write(fm.get("session-id", ""), "end-ran",
                   {"ts": _now_iso(), "claude_session_id": _claude_session_id() or "",
                    "title": args.title or fm.get("title", "")})

    # 1b. WI-0249: a closed journal lets go of the lane's reservation. Anchored HERE, on
    #     the close itself, rather than on the land — a close that never lands (`--no-merge`,
    #     a failed gate) has still ended the session that held the lane, and a reservation
    #     outliving its session is the whole defect. Safe to release while the worktree
    #     stands; see `_release_lane_reservation`.
    freed = _release_lane_reservation(f"journal {fm.get('session-id', '')} closed")
    if freed:
        print(f"released: lane reservation '{freed}' — it no longer counts against the "
              f"dispatch cap.")

    # 1c. WI-0401 — THE GOAL DISPOSITION BLOCK, and its position is the argument. A Stop
    #     hook re-reads the session's goal every time it tries to stop; two recorded
    #     sessions could not answer for a clause that had been taken away mid-session and
    #     so could not leave, one of them for 34 turns after its journal was already
    #     closed. The evaluator was not wrong — it had nothing to read. This prints what
    #     it needed: every clause of the goal with what became of it, and the instruction
    #     QUOTED for any clause that was mooted or blocked.
    #
    #     Printed ABOVE the end banner, because the banner is the close receipt and the
    #     disposition is the reason the close is legitimate; a reader scanning up from
    #     the banner finds it immediately. Silent when the session has no goal, which is
    #     nearly every session. It never refuses and never raises: a block that could
    #     stop a close would be the defect wearing the fix's clothes.
    for line in goal_block_for_session(fm.get("session-id", "")):
        print(line)

    # 2. The end banner — the visible bookend to the start banner. `end` runs as an
    #    Architect Bash command, so this stdout is shown to the user directly. Printed
    #    before the land flow: the session IS closed regardless of the merge outcome.
    print(_fmt_banner("end", _display_ordinal(ordinal, settled=not on_lane),
                      version, machine, end_stamp, dur, tail=banner_tail))

    focus = getattr(args, "focus", None)
    blocked = getattr(args, "blocked", None)

    # Commit message: --commit VALUE overrides; bare --commit (const "") derives the
    # default (session-id form on a lane — R4b). Omit --commit entirely -> no commit /
    # no land.
    commit_msg = args.commit
    if commit_msg == "":
        commit_msg = derived_msg

    # ADR-0056 D3: on a session branch, commit the closed journal + work to the BRANCH
    # (never compile the views here — D2), then land through the gate. On the trunk
    # directly (branching off, or a pre-Phase-2 session like the one that ships this),
    # degrade to the Phase-1 path: compile + stamp + commit + push to the trunk.
    # ADR-0058 D2: this session lands its own work, alone, now. It never waits on a
    # sibling — waiting is what froze the trunk (and the compiled views with it). A
    # live sibling matters only for ATTRIBUTION: their in-flight files are excluded
    # from what this close commits.
    # WI-0035: everything below this line runs git against ROOT. The journal surgery
    # above is fixture-safe (it writes wherever JOURNAL_DIR points); git is not.
    if commit_msg or on_lane:
        _refuse_git_on_fixture("end")

    csid = _claude_session_id()
    siblings = _live_sibling_csids(csid)

    # ADR-0060 D2: a terminal worktree lane lands by plumbing — it is alone in its own
    # worktree + branch, so it ff-advances the trunk to its tip with no attribution and
    # no shared-tree machinery. Checked first: a lane is never a shared-tree close.
    if on_lane:
        # A lane always commits its own tree; an omitted --commit still lands the closed
        # journal. Derive the default message either way (there is always work to close).
        if not commit_msg:
            commit_msg = derived_msg
        if getattr(args, "no_merge", False):
            sh(SWEEP_ADD)
            if _has_staged_changes():
                sh(["git", "commit", "-m", commit_msg], check=False)
            print(f"--no-merge: journal closed + committed on '{_current_branch()}'. Land "
                  f"later with `session.py merge --continue`.")
            return
        landed = _land_worktree_lane(focus, blocked, version, commit_msg=commit_msg,
                                     push=args.push,
                                     resolve=getattr(args, "resolve", "generated"),
                                     renumber=not getattr(args, "no_renumber", False))
        # WI-0312: THE LANE EXIT, on the close — the route the WI-0298 docstring named and
        # nothing ever called. It ran only from `cmd_worktree_remove`, which fires when
        # Claude removes the worktree and only when `git branch -d` then succeeds, so a
        # landed lane went on holding its claims, its leases and its attention record until
        # an unrelated hook happened to fire — and, when the lane was torn down by hand or
        # reaped instead, until a sweep that matched on the branch key alone and could not
        # see a record taken through the front door at all. Here the release is anchored on
        # the fact it represents: this session is over and its work is on the trunk.
        #
        # `LANE_EXIT_CLOSE_KINDS`, not the full set — see the tuple for why the spawn slot
        # is the one thing a close must NOT take back.
        #
        # AFTER the land and after the push, never before: everything above still needs the
        # records this frees. Teardown runs the same exit again minutes later and that is
        # by design — a repeat is a no-op, not a double-release — which is also what makes
        # a partial failure here simply retryable.
        #
        # ONLY ON A SUCCESSFUL LAND, and that condition is the same one teardown has always
        # applied by proxy: `cmd_worktree_remove` releases only when `git branch -d`
        # succeeds, i.e. only when the work reached the trunk. A blocked land leaves real
        # work on the branch for `poga resume` to finish, and freeing this session's claims
        # over it would show the item unheld on every board while its commits sit in a lane
        # — which is worse than holding them, because the next reader has no way to see
        # that anyone is mid-flight on it. The session is over either way; the HOLDS are
        # about the work, and the work is not.
        if landed:
            for line in _lane_exit_report(f"journal {fm.get('session-id', '')} closed"):
                print(line)
        # WI-0249: a DISPATCHED lane now ends its own process here. `end` used to close the
        # record and leave the runtime running, so the lane finished on every surface that
        # reads files and on none that reads processes. Last, and only on a successful land
        # — see `_dispatch_close_runtime`. The journal's own claude-session-id is passed so
        # the call can prove the record it just closed belongs to THIS runtime.
        _dispatch_close_runtime(bool(landed),
                                (fm.get("claude-session-id") or "").strip())
        # WI-0399 — the same close for a session a PERSON opened. Re-publish first, so the
        # board's record carries the land outcome it could not know when the journal was
        # stamped; then print what this session leaves behind; then end the runtime.
        #
        # ORDER IS THE POINT. The record is durable before the print, and the print is on
        # the terminal before anything is signalled, so neither surface can lose the
        # summary to the exit. `_attended_close_runtime` is a no-op for a dispatched lane
        # (the call above already handled it) and for any session `poga` did not launch.
        _session_close_publish(closed, _close_fm, landed=bool(landed))
        for line in _close_summary_lines(closed):
            print(line)
        _attended_close_runtime(bool(landed),
                                (fm.get("session-id") or "").strip())
        _exit_on_failed_land(landed)
        return

    # A legacy session branch (ADR-0056) still lands the old way: it carries real
    # commits that a candidate rebuild would duplicate. Branch cutting is off by
    # default now, so this path drains as sessions turn over.
    if _on_session_branch():
        branch = _current_branch()
        if not commit_msg:
            print(f"note:    journal closed on '{branch}' but --commit omitted — nothing "
                  f"committed or landed. Commit + `session.py merge --continue` to land.")
            return
        sh(SWEEP_ADD)
        if _has_staged_changes():
            sh(["git", "commit", "-m", commit_msg])
            print(f"committed: {commit_msg}  (on {branch})")
        if getattr(args, "no_merge", False):
            print(f"--no-merge: journal closed and committed on '{branch}'. Land later "
                  f"with `session.py merge --continue`.")
            return
        _exit_on_failed_land(
            _land_branch(focus, blocked, version, push=args.push,
                         renumber=not getattr(args, "no_renumber", False)))
        return

    # Regenerate the compiled views BEFORE attributing, so they ride in this session's
    # own commit rather than a second one — and so the gate sees them (a stale
    # CANON.md/STANDARD.md must not land). Runs even when nothing is committed: the
    # local view should reflect the closed journal either way.
    run_compile(CFG["tz"])
    # WI-0372: this call site DISCARDED the reason, so a close that stamped nothing said
    # nothing — the same wrong-answer-shaped-like-a-right-one one layer out from the
    # function itself. `cmd_stamp_status` has printed it since WI-0114; the close paths
    # that call the function directly print it in the same words.
    if (why := _stamp_status(version, focus, blocked)):
        print(f"status:  NOT stamped — {why}. Nothing was written; any freshness signal "
              f"read from it is stale, not current.")
    if not commit_msg:
        print("note:    journal closed but --commit omitted — nothing committed or "
              "landed. `session.py merge --continue` to land.")
        return
    paths, exact, swept = _attributed_paths(csid, siblings)
    if siblings:
        # ADR-0059 D4/D5 — tell the truth about shared-tree mode and steer to poga.
        print(f"note:    {len(siblings)} concurrent session(s) live in THIS working tree — "
              f"shared-tree mode. Committing ONLY this session's own attributed files (no "
              f"blend, sibling files untouched). For parallel work, run `poga` — each lane "
              f"gets its own isolated worktree (ADR-0060).")
    print(f"attributed: {exact} edited + {swept} swept"
          + (f"; {len(siblings)} live sibling(s) left untouched" if siblings else ""))
    if getattr(args, "no_merge", False):
        print("--no-merge: journal closed; nothing landed. `session.py merge --continue` to land.")
        return
    _exit_on_failed_land(_land_candidate(paths, commit_msg, push=args.push))


def cmd_heartbeat(_args: argparse.Namespace) -> None:
    """Stop + all-tools PreToolUse hook: refresh this session's `.live` heartbeat.
    Stop fires only BETWEEN turns; the PreToolUse binding fires on every tool call,
    so the beat stays fresh DURING a long working turn (ADR-0054 — the session-74
    false-reap fix). Hot path: must be fast and FAIL-OPEN, and writes are throttled
    to one per HEARTBEAT_MIN_INTERVAL_SEC (the read is the cheap part; the write
    hits the shared volume). The crash + live-elsewhere detector for orphan triage.
    Reads the hook JSON (session_id) on stdin."""
    if CFG is None:
        sys.exit(0)
    hook = _read_hook_stdin()
    sid = hook.get("session_id")
    if not sid:
        sys.exit(0)
    # ADR-0101: a tool call is proof this session is no longer blocked on the user, so its
    # waiting record retires here. Before the throttle, because the FIRST beat after an
    # answer is exactly the one that must clear it — a throttled-away clear would leave a
    # lane reading "waiting on you" while it works.
    _attention_clear()
    # ADR-0055: the first beat of a lazily-started session materializes the
    # deferred start work (journal, compile, reap, push). Runs BEFORE the
    # throttle — a fresh .live from `start` must not skip it.
    _complete_lazy_start(sid)
    # ADR-0089 D2: a resumed lane's checkpoint dissolves at the first beat, restoring the
    # working tree exactly as the operator left it. Before the throttle, because the
    # dissolve must happen on the FIRST beat of the resumed session and a fresh `.live`
    # from `start` would otherwise skip it — the same reason `_complete_lazy_start` sits
    # above the throttle. Cheap: one `git log -1` on the common path, and it returns False
    # immediately off a lane.
    with contextlib.suppress(Exception):
        _dissolve_lane_checkpoint()
    # ADR-0057 D1: attribute the file this call is about to write to this session.
    # Runs BEFORE the throttle — attribution must not be sampled, or a session's
    # edits inside a throttle window would go unrecorded and be swept by a sibling.
    _record_touch(sid, hook.get("tool_name", ""), hook.get("tool_input") or {})
    # WI-0288 R2 (2): count the turn and, once the dispatch's budget is spent, say so at
    # the turn boundary. ABOVE THE THROTTLE deliberately — the throttle samples beats by
    # wall clock, and a budget that skipped counts because two turns fell inside one
    # throttle window would not be a budget. Both calls are no-ops outside a dispatched
    # lane and both swallow their own errors, so the hot path stays fail-open.
    with contextlib.suppress(Exception):
        _turn_budget_count(sid, hook.get("hook_event_name", ""))
        notice = _turn_budget_notice(sid)
        # THE CHANNEL IS THE DECISION, NOT stderr. A `Stop` hook that exits 0 and prints
        # feeds the transcript, not the model — the notice would be written and never
        # read, a gate that has never run in the configuration it gates. `decision:
        # block` is the one Stop channel whose `reason` reaches the model, and blocking
        # the stop is also the right ACT here: the lane gets the turn in which to land
        # and close rather than being cut off holding unlanded work.
        #
        # `stop_hook_active` IS THE LOOP GUARD. It is set when this stop was already
        # blocked by a hook once, so re-blocking on it would hold the lane open forever
        # — burning exactly the tokens the budget exists to stop, which is the one way
        # this feature could be worse than not having it. Told once; then let it stop
        # and leave the idle lane to the reaper, which is the pre-existing path for it.
        if notice and not hook.get("stop_hook_active"):
            print(json.dumps({"decision": "block", "reason": notice}))
            sys.exit(0)
    live = SESSION_STATE_DIR / f"{sid}.live"
    payload = {}
    try:
        if live.is_file():
            payload = json.loads(live.read_text(encoding="utf-8"))
    except Exception:
        payload = {}
    age_min = _iso_age_min(payload.get("last_beat"))
    if age_min is not None and age_min * 60 < HEARTBEAT_MIN_INTERVAL_SEC:
        sys.exit(0)                    # beat is fresh — skip the write (throttle)
    payload["last_beat"] = _now_iso()
    # WI-0102: mail that arrives MID-session. Deliberately after the throttle, so this runs
    # at most once per HEARTBEAT_MIN_INTERVAL_SEC rather than on every tool call, and it
    # costs a directory read (0.024 ms measured) now that `_shared_work_root` is memoized.
    # Fail-open like everything else on this path — a mailbox hiccup must never break the
    # beat the whole orphan model rests on.
    arrivals = []
    with contextlib.suppress(Exception):
        arrivals = _inbox_arrivals(payload)
    _sidecar_write(sid, "live", payload)
    _coord_refresh_identity()          # ADR-0051 C4/C5: keep this session's claims/leases alive
    if arrivals:
        # PreToolUse stdout is the one channel that reaches a session already in flight.
        # Using it as a mail notification is a deliberate choice, not a side effect: the
        # alternative considered was stating the latency instead of removing it, and the
        # decision was to remove it (the operator's ruling, session ~157/158).
        print(f"inbox:   {len(arrivals)} brief(s) arrived during this session — "
              f"{', '.join(arrivals)}. Startup swept the inbox once; these are newer. "
              f"Read them before relying on anything they may change.")
    sys.exit(0)


def cmd_record_end(_args: argparse.Namespace) -> None:
    """SessionEnd hook: write this session's `.ended` marker (timestamp only — the
    ~1.5s SessionEnd budget forbids git work; the NEXT start does any handoff
    surgery). SessionEnd fires on clean termination but NOT on crash/force-kill —
    that is exactly what lets the next start tell a clean exit (auto-close) from a
    crash (flag). Reads the hook JSON on stdin; fail-open."""
    if CFG is None:
        sys.exit(0)
    hook = _read_hook_stdin()
    sid = hook.get("session_id")
    if not sid:
        sys.exit(0)
    _sidecar_write(sid, "ended", {"ended": _now_iso(), "reason": hook.get("reason", "")})
    # ADR-0089 D1: a LANE that stops with uncommitted work checkpoints it onto its own
    # (private) branch. Deliberately after the `.ended` write — the marker is the
    # clean-vs-crash discriminator the whole orphan model rests on, so it must land even
    # if the git work below cannot. Lanes only: a dirty MAIN checkout at stop belongs to
    # the interactive-close guard, and committing there would write to a tree other
    # sessions share. `_checkpoint_lane_work` is fail-open and no-ops on a clean tree.
    with contextlib.suppress(Exception):
        if _on_worktree_lane():
            _checkpoint_lane_work(sid)
    sys.exit(0)


def _test_verdict(err: str, returncode: int) -> tuple[str, str]:
    """Classify a run into one of THREE states, never two — `declare-what-a-check-assumes`
    turned on our own harness. Returns (state, detail) where state is one of
    `passed` / `failed` / `did-not-report`.

    Anchored on `^Ran N tests in` as the did-it-report signal, then classified from the
    line AFTER it. Never `OK` on its own: bare `OK` both over-matches (a fixture line
    `OK — all 1 index(es)...` is not a verdict) and under-matches (a green run with skips
    prints `OK (skipped=2)`). Two ways to be wrong about the same string, and this
    codebase has been bitten by each."""
    runs = list(TEST_RAN_RE.finditer(err))
    if not runs:
        return "did-not-report", (
            "no `Ran N tests` line on stderr — the suite never reported. This is NOT "
            "a pass and NOT a failure; something stopped it before it could summarize."
        )
    # The suite's own summary is the last one — a fixture that itself shells out to a
    # nested runner would emit earlier ones, and those describe someone else's run.
    last = runs[-1]
    ran = int(last.group(1))
    after = err[last.end():].lstrip("\n")
    head = after.splitlines()[0].strip() if after.strip() else ""
    if TEST_OK_RE.match(head):
        state, detail = "passed", f"{ran} test(s), {head}"
    elif TEST_FAILED_RE.match(head):
        state, detail = "failed", f"{ran} test(s), {head}"
    else:
        return "did-not-report", (
            f"`Ran {ran} tests` found, but the line after it is {head!r} — neither "
            f"OK nor FAILED. The run summarized into something this verb does not "
            f"recognize; read the log rather than trusting a guess."
        )
    # The exit code and the summary are two independent witnesses. When they disagree,
    # the honest answer is that we cannot tell — collapsing a disagreement into either
    # verdict is precisely the confident-wrong-answer this whole item exists to stop.
    expected = 0 if state == "passed" else 1
    if returncode != expected:
        return "did-not-report", (
            f"{detail} — but the process exited {returncode}, and a {state} run should "
            f"exit {expected}. Two witnesses disagree; neither verdict is reportable."
        )
    return state, detail


class _PreflightResult:
    """One precondition's verdict. `remedy` is what to DO — printed only when the check
    is not OK, and phrased as the thing that fixes it rather than the thing that is
    wrong. A remedy operator has to translate into a command is half a remedy."""

    def __init__(self, name: str, verdict: str, detail: str, remedy: str = "",
                 *, applicable: bool = True) -> None:
        self.name = name
        self.verdict = verdict
        self.detail = detail
        self.remedy = remedy
        # WI-0468: False only for a check whose subject does not exist on this platform
        # (macOS quarantine on Linux). Such a row still prints SKIPPED, but it is not
        # "undetermined" — nothing is unknown about a flag the kernel cannot carry — so
        # it must not turn every Linux `poga preflight` into exit 2, CANNOT TELL.
        self.applicable = applicable

    def as_dict(self) -> dict:
        return {"check": self.name, "verdict": self.verdict,
                "detail": self.detail, "remedy": self.remedy}


PREFLIGHT_UNCHECKED = "UNCHECKED"


def _pf_runtime_quarantine() -> list[_PreflightResult]:
    """Read each registered binary's quarantine flag; removal is an operator decision.

    OFF macOS THERE IS NOTHING TO READ (WI-0468). `com.apple.quarantine` is Gatekeeper's
    attribute; no other kernel sets it, and Linux's `xattr` (when the python tool is even
    installed) answers a different question. One SKIPPED row says so — not a FAIL, and
    not an UNCHECKED per runtime that reads as "xattr is broken on this box"."""
    if sys.platform != "darwin":
        return [_PreflightResult(
            "runtime-quarantine", PREFLIGHT_SKIPPED,
            f"NOT checked — com.apple.quarantine is a macOS (Gatekeeper) attribute; this "
            f"platform ({sys.platform}) has no quarantine flag to read (WI-0468).",
            applicable=False)]
    results = []
    xattr = shutil.which("xattr")
    for runtime in RUNTIMES:
        command = runtime["command"]
        path = shutil.which(command)
        verdict = PREFLIGHT_UNCHECKED
        remedy = ""
        if path is None:
            detail = f"{command}: not installed or not resolvable on PATH."
        elif xattr is None:
            detail = f"{path}: xattr unavailable on PATH."
        else:
            try:
                probe = subprocess.run(
                    [xattr, "-p", "com.apple.quarantine", path],
                    capture_output=True, text=True, timeout=5)
            except (OSError, subprocess.TimeoutExpired) as exc:
                detail = f"{path}: quarantine check failed: {exc}"
            else:
                if probe.returncode == 0:
                    verdict = PREFLIGHT_FAIL
                    detail = f"{path}: com.apple.quarantine is set."
                    remedy = f"xattr -d com.apple.quarantine {shlex.quote(path)}"
                elif "No such xattr" in probe.stderr:
                    verdict = PREFLIGHT_OK
                    detail = f"{path}: com.apple.quarantine is not set."
                else:
                    detail = (f"{path}: xattr exited {probe.returncode}: "
                              f"{probe.stderr.strip() or 'no stderr'}")
        results.append(_PreflightResult("runtime-quarantine", verdict, detail, remedy))
    return results


def _pf_terminfo() -> _PreflightResult:
    """Wall 1. Does $TERM resolve to an installed entry, and does that entry carry the
    capabilities whose absence is silent rather than loud?"""
    term = os.environ.get("TERM", "").strip()
    if not term:
        return _PreflightResult(
            "terminfo", PREFLIGHT_UNKNOWN,
            "$TERM is unset, so there is no entry to resolve. Normal for a hook or a "
            "non-interactive run, and it says NOTHING about an interactive shell here.",
            "Re-run from the interactive terminal you actually intend to use.")
    try:
        r = subprocess.run(["infocmp", "-x", term], text=True, capture_output=True,
                           timeout=PREFLIGHT_PS_TIMEOUT)
    except FileNotFoundError:
        return _PreflightResult(
            "terminfo", PREFLIGHT_UNKNOWN,
            f"$TERM is '{term}' but `infocmp` is not installed, so the entry cannot be "
            f"read. Absence of the tool is not absence of the entry.",
            "Install ncurses (`brew install ncurses`) and re-run.")
    except subprocess.TimeoutExpired:
        return _PreflightResult("terminfo", PREFLIGHT_UNKNOWN,
                                f"`infocmp -x {term}` did not return in "
                                f"{PREFLIGHT_PS_TIMEOUT}s.", "Re-run.")
    if r.returncode != 0:
        return _PreflightResult(
            "terminfo", PREFLIGHT_FAIL,
            f"$TERM is '{term}' and this machine has no terminfo entry for it. Backspace "
            f"and width will misbehave SILENTLY — a truncated-looking paste is a render "
            f"artefact, not a truncated buffer.",
            f"On a machine that has the entry: `infocmp -x {term} > /tmp/{term}.ti`, "
            f"copy it here, then `tic -x /tmp/{term}.ti`.")
    missing = [c for c in PREFLIGHT_TERM_CAPS if f"{c}=" not in r.stdout]
    if missing:
        return _PreflightResult(
            "terminfo", PREFLIGHT_FAIL,
            f"$TERM '{term}' resolves, but its entry declares no "
            f"{', '.join(missing)} — the capability whose absence makes backspace do "
            f"nothing.",
            f"Re-install the entry from a machine whose `infocmp -x {term}` shows it.")
    return _PreflightResult("terminfo", PREFLIGHT_OK,
                            f"$TERM '{term}' resolves and declares "
                            f"{', '.join(PREFLIGHT_TERM_CAPS)}.")


def _pf_claude_json() -> tuple[dict | None, str]:
    """`~/.claude.json` parsed, or (None, why). Shared by the trust and onboarding checks
    so a missing file produces one honest reason in two places rather than two different
    guesses about the same absence."""
    p = Path.home() / ".claude.json"
    if not p.exists():
        return None, f"{p} does not exist (a machine where `claude` has never run)"
    try:
        return json.loads(p.read_text(encoding="utf-8")), ""
    except Exception as e:
        return None, f"{p} is unreadable or not valid JSON ({type(e).__name__})"


def _pf_workspace_trust() -> _PreflightResult:
    """Wall 2. `claude --worktree` refuses on an untrusted workspace, and poga's lane
    creation IS that call — so the refusal arrives as a failed launch.

    The path that must be trusted is the MAIN checkout, not this lane: poga cds to the
    repo root and asks the runtime to make the worktree from there. Checking the lane's
    own path would pass on a machine where the launch still cannot happen — a right
    answer to the wrong question."""
    data, why = _pf_claude_json()
    root = str(_shared_work_root())
    if data is None:
        return _PreflightResult(
            "workspace-trust", PREFLIGHT_UNKNOWN,
            f"cannot tell whether '{root}' is trusted — {why}.",
            f"Run `claude` once in {root} and accept the trust dialog.")
    projects = data.get("projects")
    if not isinstance(projects, dict):
        return _PreflightResult(
            "workspace-trust", PREFLIGHT_UNKNOWN,
            "~/.claude.json carries no `projects` map, so trust state here is "
            "unrecorded rather than known-absent.",
            f"Run `claude` once in {root} and accept the trust dialog.")
    entry = projects.get(root)
    if not isinstance(entry, dict):
        return _PreflightResult(
            "workspace-trust", PREFLIGHT_FAIL,
            f"'{root}' has no entry in ~/.claude.json, so the trust dialog has never "
            f"been accepted for it. `poga` will fail at lane creation with 'Workspace "
            f"trust not yet accepted'.",
            f"Run `claude` once in {root} and accept the trust dialog, then re-run.")
    if entry.get("hasTrustDialogAccepted") is not True:
        return _PreflightResult(
            "workspace-trust", PREFLIGHT_FAIL,
            f"'{root}' is known to ~/.claude.json but hasTrustDialogAccepted is not "
            f"true. Lane creation will refuse.",
            f"Run `claude` once in {root} and accept the trust dialog.")
    return _PreflightResult("workspace-trust", PREFLIGHT_OK, f"'{root}' is trusted.")


def _pf_onboarding() -> _PreflightResult:
    """Wall 3. An absent `hasCompletedOnboarding` runs the first-run wizard, and its
    login step opens a BROWSER — on a headless host that is a hang, not a prompt, and it
    happens even when auth is already live."""
    data, why = _pf_claude_json()
    if data is None:
        return _PreflightResult(
            "onboarding", PREFLIGHT_FAIL,
            f"the first-run wizard will run — {why}. On a headless host its login step "
            f"opens a browser that nobody can answer.",
            "Run `claude` once interactively on this machine and complete onboarding "
            "BEFORE launching a lane.")
    if data.get("hasCompletedOnboarding") is not True:
        return _PreflightResult(
            "onboarding", PREFLIGHT_FAIL,
            "~/.claude.json exists but hasCompletedOnboarding is not true, so the "
            "first-run wizard will run and try to open a browser.",
            "Run `claude` once interactively and complete onboarding.")
    n = len(data.get("projects") or {})
    return _PreflightResult("onboarding", PREFLIGHT_OK,
                            f"onboarding complete; {n} project(s) tracked.")


def _pf_auth() -> _PreflightResult:
    """Wall 3's other half. The distinction that matters is LIVE vs CREDENTIALS-PRESENT:
    devbox had a credential and still ran a login flow. So this asks the CLI for its own
    verdict rather than looking for a file — and a file check is exactly what would have
    passed while the wizard opened a browser.

    Reaches the network, which is why this verb is not on the startup path (startup pays no network cost) —
    and why it must not run under the land gate at all (ADR-0119 D4): a land's verdict
    cannot be allowed to depend on whether the operator happens to be logged in, still less
    on whether the network is up. UNKNOWN is the honest answer and one this result type
    already carries.

    The gate check comes FIRST, before the PATH lookup (WI-0432). Whether `claude` is on
    PATH is as much a property of the machine as whether it is logged in: the nightly
    LaunchDaemon's PATH lacks `~/.local/bin`, so this answered FAIL there and UNKNOWN in
    an interactive shell — one test, two verdicts, split by who launched the suite."""
    if _under_gate():
        return _PreflightResult(
            "auth", PREFLIGHT_UNKNOWN,
            "not asked under the land gate — a land cannot depend on this machine's "
            "login (ADR-0119 D4).", "Run `poga preflight` outside the gate.")
    if shutil.which("claude") is None:
        return _PreflightResult(
            "auth", PREFLIGHT_FAIL,
            "`claude` is not on PATH, so no lane can be launched at all.",
            "Install Claude Code on this machine.")
    try:
        r = subprocess.run(["claude", "auth", "status"], text=True, capture_output=True,
                           timeout=PREFLIGHT_AUTH_TIMEOUT)
    except subprocess.TimeoutExpired:
        return _PreflightResult(
            "auth", PREFLIGHT_UNKNOWN,
            f"`claude auth status` did not return in {PREFLIGHT_AUTH_TIMEOUT}s. That is "
            f"not a failed login — it is no answer, and the network is the likelier "
            f"cause.",
            "Re-run when the network is up.")
    except Exception as e:
        return _PreflightResult("auth", PREFLIGHT_UNKNOWN,
                                f"`claude auth status` could not run "
                                f"({type(e).__name__}).", "Re-run.")
    out = f"{r.stdout}\n{r.stderr}".strip()
    first = next((l.strip() for l in out.splitlines() if l.strip()),
                 f"no output (exit {r.returncode})")
    if r.returncode != 0:
        return _PreflightResult(
            "auth", PREFLIGHT_FAIL,
            f"`claude auth status` exited {r.returncode} — {first[:90]}",
            "Run `claude auth login` on THIS machine, interactively, and let it finish.")
    # PARSED, never substring-matched. `claude auth status` emits a JSON document whose
    # `loggedIn` is a real boolean, and the string "loggedin" appears in it either way —
    # so a substring test reports a logged-OUT machine as live. That is the exact class
    # of wrong-answer-shaped-like-a-right-one this whole verb exists to stop, and this
    # check shipped with it for one revision. If the output shape ever changes, the
    # branches below say CANNOT TELL rather than guessing from the text.
    try:
        doc = json.loads(r.stdout)
    except Exception:
        return _PreflightResult(
            "auth", PREFLIGHT_UNKNOWN,
            f"`claude auth status` exited 0 but did not emit the JSON this check reads "
            f"(got: {first[:70]}). Its output shape may have changed.",
            "Read `claude auth status` yourself, then update _pf_auth to the new shape.")
    if not isinstance(doc, dict) or not isinstance(doc.get("loggedIn"), bool):
        return _PreflightResult(
            "auth", PREFLIGHT_UNKNOWN,
            "`claude auth status` returned JSON carrying no boolean `loggedIn`, so this "
            "machine's login state is unstated rather than false.",
            "Read `claude auth status` yourself, then update _pf_auth to the new shape.")
    if not doc["loggedIn"]:
        return _PreflightResult(
            "auth", PREFLIGHT_FAIL,
            "`claude auth status` reports loggedIn: false. A credential on disk is not a "
            "live session — this is the state that makes the first-run wizard open a "
            "browser.",
            "Run `claude auth login` on THIS machine, interactively, and let it finish.")
    who = doc.get("email") or doc.get("orgName") or "account unnamed"
    sub = f", {doc['subscriptionType']}" if doc.get("subscriptionType") else ""
    return _PreflightResult(
        "auth", PREFLIGHT_OK,
        f"live — {who} via {doc.get('authMethod', 'unknown method')}{sub}.")


def _pf_data_root() -> _PreflightResult:
    """The gitignored half of the repo. A fresh CLONE has none of it — `users/`, the
    receipt-ritual inbox, `architect-learnings.md` are all gitignored — and every one of
    them reads as EMPTY rather than as missing. An empty inbox and an unreadable inbox
    look identical from outside, and only one of them is fine."""
    root = _shared_work_root()
    missing: list[str] = []
    checked: list[str] = []
    inbox_rel = (CFG or {}).get("inbox")
    if inbox_rel:
        checked.append(inbox_rel)
        if not (root / inbox_rel).is_dir():
            missing.append(f"{inbox_rel} (the receipt-ritual inbox — pending briefs "
                           f"CANNOT be seen, which is not the same as none pending)")
    profile_rel = (CFG or {}).get("user_profile")
    if profile_rel:
        checked.append(profile_rel)
        if not (root / profile_rel).is_file():
            missing.append(f"{profile_rel} (the bound user's profile — sessions open "
                           f"with no preferences applied)")
    if not checked:
        return _PreflightResult(
            "data-root", PREFLIGHT_UNKNOWN,
            "session.config.json declares neither `inbox` nor `user_profile`, so there "
            "is nothing to verify — and that is not evidence of a healthy data root.",
            "Declare the paths in session.config.json.")
    if missing:
        return _PreflightResult(
            "data-root", PREFLIGHT_FAIL,
            f"{len(missing)} gitignored path(s) absent under {root}: " + "; ".join(missing),
            "Copy the gitignored working state from the machine that has it "
            "(WI-0004 is the real fix — this is the symptom).")
    return _PreflightResult("data-root", PREFLIGHT_OK,
                            f"{len(checked)} declared path(s) present under {root}.")


def _pf_stranded_runtimes() -> _PreflightResult:
    """Wall 4. An interactive `claude auth login` survived its own TaskStop by half an
    hour, because killing a local client does not kill the remote process — and a
    second auth flow was open while operator started his own.

    Scope is deliberately NARROW: auth flows only. A general "runtime processes running"
    count would flag this very session and every sibling lane, and a check that fires on
    healthy state is a check people learn to ignore. What it cannot determine — whose
    session each live runtime belongs to — it says, rather than guessing.

    UNDER THE GATE it does not look (ADR-0119 D4). Stranded auth flows are a property of
    the operator's machine at this instant, and a commit cannot be gated on them."""
    try:
        r = subprocess.run(["ps", "-axo", "pid=,etime=,command="], text=True,
                           capture_output=True, timeout=PREFLIGHT_PS_TIMEOUT)
    except Exception as e:
        return _PreflightResult(
            "stranded-runtimes", PREFLIGHT_UNKNOWN,
            f"could not enumerate processes ({type(e).__name__}), so a stranded auth "
            f"flow would be invisible here.",
            "Check by hand: `ps -ax | grep 'auth login'`.")
    commands = {row["command"] for row in RUNTIMES if row.get("command")}
    flows: list[str] = []
    for line in r.stdout.splitlines():
        parts = line.strip().split(None, 2)
        if len(parts) < 3:
            continue
        pid, etime, cmd = parts
        low = cmd.lower()
        if "auth" not in low or "login" not in low:
            continue
        exe = Path(cmd.split()[0]).name
        if exe in commands:
            flows.append(f"pid {pid} (up {etime}): {cmd[:70]}")
    if flows:
        return _PreflightResult(
            "stranded-runtimes", PREFLIGHT_FAIL,
            f"{len(flows)} interactive auth flow(s) already running on this machine — a "
            f"second one will collide with them:\n"
            + "\n".join(f"           {'':<19} {f}" for f in flows),
            "Let the existing flow finish, or kill it by pid, before starting another.")
    return _PreflightResult(
        "stranded-runtimes", PREFLIGHT_OK,
        "no runtime auth flow is running. NOT checked: whether the runtime processes "
        "that ARE live belong to your sessions — ps cannot answer that.")


_SWAP_UNITS = {"K": 1024, "M": 1024 ** 2, "G": 1024 ** 3, "T": 1024 ** 4}
# WI-0468: where Linux publishes the two numbers macOS answers through `sysctl`. A name,
# not an inline literal, so a test can hand `_memory_sample` a recorded file.
_PROC_MEMINFO = "/proc/meminfo"


def _human_bytes(n: float) -> str:
    """Bytes as the operator reads them. Printing everything in GB renders the 189 MB
    daemon that is FINE as `0.2 GB`, and a number that looks like nothing is how a reader
    learns to stop reading the line."""
    if n >= 1024 ** 3:
        return f"{n / 1024 ** 3:.1f} GB"
    return f"{n / 1024 ** 2:.0f} MB"


def _meminfo_into(sample: dict, text: str) -> None:
    """WI-0468. Fill `phys_bytes` and `swap_used_bytes` from Linux's /proc/meminfo text.

    Swap IN USE is SwapTotal - SwapFree: the same quantity macOS's `vm.swapusage` reports
    as `used`, so the verdict's one threshold means the same thing on both kernels. Every
    field there is in kB (the kernel prints the literal unit, always `kB`, meaning KiB);
    the multiplier is 1024, and getting it wrong is the off-by-1024 that still looks
    plausible. A missing field is recorded as unreadable, never defaulted to 0 — a box
    with no swap configured prints `SwapTotal: 0 kB`, which IS a reading (zero in use)."""
    fields: dict = {}
    for line in text.splitlines():
        m = re.match(r"(\w+):\s+(\d+)\s*kB\s*$", line.strip())
        if m:
            fields[m.group(1)] = int(m.group(2)) * 1024
    if fields.get("MemTotal"):
        sample["phys_bytes"] = fields["MemTotal"]
    else:
        sample["unreadable"].append("/proc/meminfo: no MemTotal line")
    if "SwapTotal" in fields and "SwapFree" in fields:
        sample["swap_used_bytes"] = max(0, fields["SwapTotal"] - fields["SwapFree"])
    else:
        sample["unreadable"].append("/proc/meminfo: no SwapTotal/SwapFree lines")


def _memory_sample() -> dict:
    """This machine's memory state: physical size, swap in use, and every process's RSS
    and owning uid. Two local reads of the kernel's own counters, expected to cost on the order of
    10 ms for the pair.

    THE I/O IS SEPARATED FROM THE JUDGEMENT ON PURPOSE, and that is the half that makes
    this check testable at all. Everything that touches the machine is here; everything
    that decides is `_memory_pressure_verdict`, a pure function over the dict this
    returns. A recorded thrash can therefore be REPLAYED from its numbers —
    which matters, because that state cannot be manufactured on a live box without
    inflicting the very harm the check exists to prevent
    (`evidence-is-separated-from-state-by-construction`).

    UNDER THE GATE IT DOES NOT LOOK (ADR-0119 D4), same as `_pf_stranded_runtimes`: how
    much swap the operator's box is using this minute is not a property of the commit. The
    guard sits in the spawning function because that is where `tests/test_gate_snapshot.py`
    reads for it, and it costs no coverage here — the branches that matter are pinned
    against fabricated samples, not against a mocked `ps`."""
    sample: dict = {"phys_bytes": None, "swap_used_bytes": None, "procs": [],
                    "unreadable": []}
    if _under_gate():
        sample["unreadable"].append(
            "this suite is the land gate, which must not read this machine (ADR-0119 D4)")
        return sample
    # WHICH COUNTERS DEPENDS ON THE KERNEL (WI-0468). macOS answers `sysctl hw.memsize
    # vm.swapusage`; Linux has no such sysctl names and publishes the same two facts in
    # /proc/meminfo. Both land in the SAME sample shape, so the pure verdict below needs
    # no platform branch and a recorded Linux thrash replays exactly like a macOS one.
    # Any other kernel records WHY it was not read, which the verdict renders UNKNOWN —
    # never a zero that would read as "no swap in use".
    if sys.platform == "darwin":
        sample["counters"] = "sysctl"
        try:
            r = subprocess.run(["sysctl", "-n", "hw.memsize", "vm.swapusage"], text=True,
                               capture_output=True, timeout=PREFLIGHT_SYSCTL_TIMEOUT)
            lines = [ln.strip() for ln in r.stdout.splitlines() if ln.strip()]
            if r.returncode != 0 or len(lines) < 2:
                sample["unreadable"].append(f"sysctl exited {r.returncode}")
            else:
                if lines[0].isdigit():
                    sample["phys_bytes"] = int(lines[0])
                else:
                    sample["unreadable"].append(f"hw.memsize unparseable: {lines[0][:40]!r}")
                m = re.search(r"used\s*=\s*([0-9.]+)([KMGT])", lines[1])
                if m:
                    sample["swap_used_bytes"] = int(float(m.group(1))
                                                    * _SWAP_UNITS[m.group(2)])
                else:
                    sample["unreadable"].append(
                        f"vm.swapusage unparseable: {lines[1][:60]!r}")
        except Exception as e:
            sample["unreadable"].append(f"sysctl: {type(e).__name__}")
    elif sys.platform.startswith("linux"):
        sample["counters"] = "/proc/meminfo"
        try:
            meminfo = Path(_PROC_MEMINFO).read_text(encoding="utf-8")
        except Exception as e:
            sample["unreadable"].append(f"/proc/meminfo: {type(e).__name__}")
        else:
            _meminfo_into(sample, meminfo)
    else:
        sample["unreadable"].append(
            f"no memory counters known for platform {sys.platform!r} (macOS and Linux "
            f"only, WI-0468)")
    # ONE `ps` FOR BOTH KERNELS (WI-0468): BSD ps and Linux procps both take `-A`, `-o`
    # with `=` blank headers, and report `rss` in KiB. The difference is `comm` — a full
    # path on macOS, the bare (15-char-truncated) name on procps — and the verdict reads
    # only `Path(comm).name`, so both resolve to the same session command name.
    try:
        r = subprocess.run(["ps", "-Ao", "rss=,uid=,pid=,comm="], text=True,
                           capture_output=True, timeout=PREFLIGHT_PS_TIMEOUT)
        if r.returncode != 0:
            sample["unreadable"].append(f"ps exited {r.returncode}")
        for line in r.stdout.splitlines():
            parts = line.split(None, 3)
            if len(parts) < 4:
                continue
            rss, uid, pid, comm = parts
            if not (rss.isdigit() and uid.isdigit() and pid.isdigit()):
                continue
            sample["procs"].append({"rss_bytes": int(rss) * 1024, "uid": int(uid),
                                    "pid": int(pid), "comm": comm.strip()})
    except Exception as e:
        sample["unreadable"].append(f"ps: {type(e).__name__}")
    return sample


def _memory_pressure_verdict(sample: dict, *, uid: int,
                             runtimes: frozenset = frozenset()) -> _PreflightResult:
    """The judgement half — pure, so a thrashing machine is a test case, not a story.

    TWO CONDITIONS, EITHER ONE REFUSES (WI-0398):
      1. swap in use is at or above `SWAP_REFUSE_FRACTION` of physical memory;
      2. a process this user does not own holds more RSS than BOTH the largest live
         session on this machine AND `DAEMON_RSS_FLOOR_FRACTION` of physical memory.

    THE FLOOR IN (2) IS THE NEGATIVE CONTROL MADE STRUCTURAL. "More RSS than the session
    would" is the rule the finding asked for, but on an idle box with no session running
    every daemon wins that comparison and a 300 MB indexer would be refused. The floor is
    what keeps an ordinarily busy machine — several suites, real load, no runaway — passing, and
    one false refusal on that machine is how a guard in front of every launch gets deleted
    instead of trusted.

    IT NAMES THE OFFENDER AND ITS RSS, never "high memory pressure". A number the reader
    has to go interpret in Activity Monitor sends them back into the same lost hours the
    finding describes; `<daemon> (pid <n>) holds <size>` is a thing to act on.

    IT SAYS WHAT IT DID NOT LOOK AT. Load average is deliberately not a condition: the
    thrashing machine read very high, and so does a healthy machine running several
    real suites. That is the whole discrimination failure this check exists to fix."""
    phys = sample.get("phys_bytes")
    swap = sample.get("swap_used_bytes")
    procs = sample.get("procs") or []
    unreadable = list(sample.get("unreadable") or [])
    if not phys or swap is None or not procs:
        return _PreflightResult(
            "memory-pressure", PREFLIGHT_UNKNOWN,
            "could not read this machine's memory state ("
            + "; ".join(unreadable or ["no counters returned"])
            + "), so a thrashing machine would be invisible here.",
            "Read it by hand: "
            + ("`grep -E 'MemTotal|Swap' /proc/meminfo`"
               if sample.get("counters") == "/proc/meminfo" else "`sysctl vm.swapusage`")
            + " and `ps -Ao rss=,uid=,comm= | sort -rn | head`.")

    swap_limit = phys * SWAP_REFUSE_FRACTION
    floor = phys * DAEMON_RSS_FLOOR_FRACTION
    sessions = [p for p in procs
                if p["uid"] == uid and Path(p["comm"]).name in runtimes]
    biggest_session = max([p["rss_bytes"] for p in sessions], default=0)
    bar = max(biggest_session, floor)
    daemons = sorted((p for p in procs if p["uid"] != uid),
                     key=lambda p: p["rss_bytes"], reverse=True)
    offenders = [d for d in daemons if d["rss_bytes"] > bar]

    session_note = (f"the largest live session ({_human_bytes(biggest_session)})"
                    if biggest_session else "no live session")
    reasons: list = []
    if swap >= swap_limit:
        reasons.append(
            f"swap {_human_bytes(swap)} in use of {_human_bytes(phys)} physical "
            f"({swap / phys:.0%} — refuses at {SWAP_REFUSE_FRACTION:.0%})")
    for d in offenders[:3]:
        reasons.append(
            f"{Path(d['comm']).name} (pid {d['pid']}, uid {d['uid']}) holds "
            f"{_human_bytes(d['rss_bytes'])} RSS — more than {session_note} and more "
            f"than the {_human_bytes(floor)} floor")

    if reasons:
        if offenders:
            first = offenders[0]
            # The service manager is launchd on macOS and systemd (usually) on Linux;
            # the sample says which kernel it read, so the remedy names the right one.
            manager = ("systemd" if sample.get("counters") == "/proc/meminfo"
                       else "launchd")
            fix = (f"Restart {Path(first['comm']).name} — {manager} brings a system daemon "
                   f"straight back: `sudo kill {first['pid']}`. If it is not yours to "
                   f"kill, reboot.")
        else:
            fix = ("Quit what is holding the memory, or reboot. Nothing in this repo can "
                   "free it.")
        return _PreflightResult(
            "memory-pressure", PREFLIGHT_FAIL,
            "this machine is THRASHING, not busy: " + "; ".join(reasons)
            + ". Load average cannot tell those two apart, which is why this refuses "
              "instead of reporting.",
            f"{fix} Waiting does not clear it — a lane once waited hours and "
            f"never landed. Re-run `poga preflight` afterwards; to launch into it "
            f"anyway, {PREFLIGHT_BYPASS_ENV}=1 poga …")

    worst = daemons[0] if daemons else None
    worst_txt = (f"largest system process {Path(worst['comm']).name} "
                 f"{_human_bytes(worst['rss_bytes'])}" if worst
                 else "no process outside this user")
    largest_session = (f"largest live session {_human_bytes(biggest_session)}"
                       if biggest_session else "no live session running")
    return _PreflightResult(
        "memory-pressure", PREFLIGHT_OK,
        f"swap {_human_bytes(swap)} of {_human_bytes(phys)} physical "
        f"({swap / phys:.0%}); {worst_txt}, under the {_human_bytes(bar)} bar; "
        f"{largest_session}. NOT checked: load average — a busy machine and a thrashing "
        f"one read the same there (WI-0398).")


def _pf_memory_pressure() -> _PreflightResult:
    """WI-0398. Tell a thrashing machine from a busy one.

    A long-running system daemon can grow to a large share of RAM at well over 100% CPU,
    with swap near the size of physical memory and almost no free pages. Every gate then
    pages to disk, the load average reads very high with a handful of processes, and a
    lane can sit for hours unable to land. Without this check nothing tells the session
    its work queue is not the problem.

    IT IS IN THE LAUNCH-GATE SUBSET, which is the point of the item: a refusal only
    `poga preflight` can produce is a dashboard somebody has to think to open, and a
    session caught by a thrashing box has no reason to open it. Membership is earned on
    ADR-0096 D3's three tests — LOCAL (two reads of this kernel's own counters), INSTANT
    (10 ms for the pair, measured; auth is a network round trip with a 20 s timeout and
    the land gate is ~90 s), and LAUNCH-FATAL (a lane created on a thrashing box cannot
    land, which is what one lane's lost hours demonstrated).

    WHAT IT WILL NOT DO is refuse a busy machine. The thresholds were chosen between two
    real readings, recorded in `sessionlib/config.py` beside them, and the healthy one
    carries load ~8 with four live sessions."""
    if _under_gate():
        return _PreflightResult(
            "memory-pressure", PREFLIGHT_SKIPPED,
            "NOT checked — this suite is the land gate, which must not read this machine "
            "(ADR-0119 D4). How much swap the operator's box is using this minute is not "
            "a property of the commit being landed.")
    runtimes = frozenset(r["command"] for r in RUNTIMES if r.get("command"))
    return _memory_pressure_verdict(_memory_sample(), uid=os.getuid(),
                                    runtimes=runtimes)


# The LAUNCH GATE subset (ADR-0096). Three checks, chosen by one test: is it local,
# instant, and does its failure stop a lane from being usable?
#
#   terminfo         a file read. Failure = a session whose backspace does nothing and
#                    whose pastes render truncated — usable-looking and not usable.
#   workspace-trust  a file read. Failure = `claude --worktree` refuses outright.
#   onboarding       a file read. Failure = the first-run wizard opens a browser.
#
# AUTH AND THE GATE ARE DELIBERATELY OUT. Auth reaches the network and the land gate is
# ~90 seconds; putting either in front of every launch is precisely the startup cost operator
# vetoed. They stay behind the explicit verb, where someone standing a machine
# up pays for them once. This is a launch gate, not a health check — it refuses only what
# it can prove broken for free.
def _pf_residency() -> _PreflightResult:
    """ADR-0106 D6 — you may OPERATE here, you may not DEVELOP here.

    A machine that hosts a member's production process refuses to be developed on: no
    lanes, no dispatch, no resume. This is the operator's ruling that a production host is
    not a development machine, made structural instead of remembered — the same move
    ADR-0090 D3b names, where a rule held by discipline becomes a rule held by the
    substrate.

    WHAT IS **NOT** REFUSED, and the line is deliberate: a plain `session.py start`. A
    system whose production DATA lives on its production host can only
    be operated where its data is, and refusing every session there would make those
    records unreachable by their own Architect — the opposite of what D1's data axis
    exists to protect. Only the concurrency substrate used to BUILD is refused.

    IT FAILS OPEN ON UNDECLARED, and that is the load-bearing half. `session.py` ships
    byte-identical fleet-wide, so refusing on "no residency block" would block every
    launch on every member that has not yet declared — turning a missing DECLARATION into
    a missing CAPABILITY, which is ADR-0096 D6's argument unchanged.

    THE BYPASS ANNOUNCES ITSELF (ADR-0096 D7). It prints on stderr on the way past, so a
    bypassed launch can never be mistaken later for a compliant one."""
    if os.environ.get(RESIDENCY_BYPASS_ENV) == "1":
        print(f"poga: NOTE — {RESIDENCY_BYPASS_ENV}=1, developing on a declared "
              f"production host. This session is NOT compliant with ADR-0106 D6.",
              file=sys.stderr)
        return _PreflightResult(
            "residency", PREFLIGHT_OK,
            f"{RESIDENCY_BYPASS_ENV}=1 — the production-host refusal was bypassed, "
            f"deliberately and on the record.")

    machine = detect_machine()
    state, why = residency_state(CFG, machine)

    if state == RESIDENCY_UNDECLARED:
        return _PreflightResult(
            "residency", PREFLIGHT_UNKNOWN, why,
            'Add a `residency` block to session.config.json — {"process": "<machine '
            'label or null>", "data": "<machine label or null>"} (ADR-0106 D1).')
    if state == RESIDENCY_UNRESOLVABLE:
        return _PreflightResult(
            "residency", PREFLIGHT_UNKNOWN, why,
            "Add the missing row to `machine_map` in session.config.json (WI-0148) — a "
            "residency label only means something the map can resolve.")

    if is_production_host(CFG, machine):
        role, role_why = data_role_of(CFG, machine)
        return _PreflightResult(
            "residency", PREFLIGHT_FAIL,
            f"{machine} is this system's declared PRODUCTION process host, so it is not "
            f"a place to develop (ADR-0106 D6). Data role here: {role} — {role_why}.",
            f"Develop on devbox; ship here with `poga deploy <system>` (ADR-0103). "
            f"To OPERATE production data here, run a plain session — open the repo "
            f"without `poga` — which is allowed and is not refused. To develop here "
            f"anyway, {RESIDENCY_BYPASS_ENV}=1 poga … — which says so on the way past.")

    role, role_why = data_role_of(CFG, machine)
    return _PreflightResult("residency", PREFLIGHT_OK,
                            f"{why} Data role here: {role} — {role_why}.")


# The gate subset gains `residency` because it satisfies D3's membership test exactly as
# the other three do: LOCAL (a config read), INSTANT (no process, no network), and
# LAUNCH-FATAL (developing on a production host is the thing being prevented). Adding it
# here is also what gives `poga resume` the same refusal for free — resume creates no
# lane, but entering one on a production host is the identical mistake.
#
# `memory-pressure` joins on the same three tests (WI-0398). LOCAL: `sysctl` and `ps` read
# this kernel's own counters, nothing outside the box. INSTANT: on the order of 10 ms for
# the pair — three orders off auth's 20 s network timeout,
# which is the cost argument the two exclusions rest on and which this does not weaken.
# LAUNCH-FATAL: a lane created on a thrashing machine cannot land, and one once
# sat for hours proving it. Putting it ONLY behind `poga preflight` would have left it a
# dashboard, and the session that lost those hours had no reason to open a dashboard.
PREFLIGHT_GATE_CHECKS = (_pf_terminfo, _pf_workspace_trust, _pf_onboarding,
                         _pf_residency, _pf_memory_pressure)


class _PreflightRepair:
    """One check's repair declaration. `why` is load-bearing for REPAIR_NONE: it is what
    turns a handed-back remedy from a report into an explanation."""

    def __init__(self, kind: str, why: str, fn=None) -> None:
        self.kind = kind
        self.why = why
        self.fn = fn


def _repair_terminfo(_r: _PreflightResult) -> tuple[bool, str]:
    """Install the missing entry from a local database. Returns (attempted-and-believed,
    narration); the CALLER decides whether it worked by re-running the check."""
    term = os.environ.get("TERM", "").strip()
    if not term:
        return False, "$TERM is unset, so there is no entry to install"
    if shutil.which("infocmp") is None or shutil.which("tic") is None:
        return False, ("`infocmp`/`tic` are not installed, so no entry can be compiled "
                       "here (`brew install ncurses`)")
    dest = _terminfo_dest()
    tried: list[str] = []
    for db in _terminfo_source_dbs():
        try:
            got = subprocess.run(["infocmp", "-x", "-A", str(db), term],
                                 text=True, capture_output=True,
                                 timeout=PREFLIGHT_PS_TIMEOUT)
        except Exception:
            continue
        if got.returncode != 0 or not got.stdout.strip():
            continue
        # A SOURCE THAT LACKS THE CAPABILITY IS NOT A SOURCE. Installing an entry that
        # resolves but declares no `kbs` swaps one silently-broken terminal for another,
        # and the re-check would then have to catch our own bad install.
        missing = [c for c in PREFLIGHT_TERM_CAPS if f"{c}=" not in got.stdout]
        if missing:
            tried.append(f"{db} has '{term}' but it declares no {', '.join(missing)}")
            continue
        try:
            dest.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile("w", suffix=".ti", delete=False) as fh:
                fh.write(got.stdout)
                src_file = fh.name
            ran = subprocess.run(["tic", "-x", "-o", str(dest), src_file],
                                 text=True, capture_output=True,
                                 timeout=PREFLIGHT_PS_TIMEOUT)
        except Exception as e:
            tried.append(f"{db} could not be compiled ({type(e).__name__})")
            continue
        finally:
            try:
                os.unlink(src_file)
            except Exception:
                pass
        if ran.returncode != 0:
            tried.append(f"`tic` refused the entry from {db} "
                         f"({(ran.stderr or '').strip()[:80]})")
            continue
        return True, f"compiled '{term}' into {dest} from {db}"
    if tried:
        return False, ("no local terminfo database carries a usable '%s': %s"
                       % (term, "; ".join(tried)))
    return False, (f"no local terminfo database on this machine carries an entry for "
                   f"'{term}' — searched "
                   f"{len(_terminfo_source_dbs())} database(s)")


# EVERY CHECK DECLARES ITS CLASS (ADR-0109 D2). The split is 1 auto / 3 guided / 5 none,
# and it is written down rather than inferred so that a check added later must say which
# class it is in. `_preflight_repair` raises on a check missing from this table, because
# a repairable check nobody wired up reads as unrepairable forever.
PREFLIGHT_REPAIRS: dict[str, _PreflightRepair] = {
    "terminfo": _PreflightRepair(
        REPAIR_AUTO,
        "the entry is compiled from a local database; nothing outside this machine is "
        "needed", _repair_terminfo),
    "workspace-trust": _PreflightRepair(
        REPAIR_GUIDED,
        "trust is `claude`'s own state; writing ~/.claude.json behind it is forging "
        "another product's state file"),
    "onboarding": _PreflightRepair(
        REPAIR_GUIDED,
        "the first-run wizard is `claude`'s own interaction and only it can complete it"),
    "auth": _PreflightRepair(
        REPAIR_GUIDED,
        "a login is interactive by construction; a credential written by us is not a "
        "live session"),
    "data-root": _PreflightRepair(
        REPAIR_NONE,
        "copying the gitignored state from the machine that has it entrenches the "
        "two-writer problem session ~161 recorded; WI-0004 is the real fix"),
    "residency": _PreflightRepair(
        REPAIR_NONE,
        "declaring which machine is production is a decision, not a repair — a value "
        "invented here would be a fabricated declaration"),
    "stranded-runtimes": _PreflightRepair(
        REPAIR_NONE,
        "killing a live auth flow is destructive and this check cannot tell whose it is "
        "(P9); the flow may be the operator's own"),
    "runtime-quarantine": _PreflightRepair(
        REPAIR_NONE,
        "removing quarantine is a security decision; review the binary before running "
        "the reported command"),
    "memory-pressure": _PreflightRepair(
        REPAIR_NONE,
        "killing a system daemon or rebooting is the operator's call on the operator's "
        "machine (P9), and it is root's process besides — this check names it and stops"),
    "gate": _PreflightRepair(
        REPAIR_NONE,
        "a red land gate is failing code — fixing it is the work, not housekeeping"),
}


def _preflight_repair(results: list[_PreflightResult], *, allow_guided: bool,
                      checks_by_name: dict) -> tuple[list[_PreflightResult], list[str]]:
    """Repair what can be repaired, re-run each repaired check, and return the POST-REPAIR
    results plus the narration of what was done.

    THE RE-RUN IS THE RECEIPT (ADR-0109 D3). A repair that reports success is not
    evidence; the check returning OK afterwards is. So a repair whose command succeeded
    and whose check still fails is reported as a FAILED repair, which is the honest
    answer and the one that keeps `tic` exiting 0 on a bad entry from reading as green.
    """
    out = list(results)
    narration: list[str] = []

    # AN UNDECLARED CHECK IS A DEFECT, AND IT SAYS SO — but it does not crash the verb.
    # The completeness of PREFLIGHT_REPAIRS is enforced by the suite
    # (`test_every_check_the_verb_runs_declares_a_class`), which is where a structural
    # guard belongs: raising here would make a diagnostic tool die on the machine whose
    # diagnosis is being asked for, which is a worse failure than the one it guards. What
    # matters is that "nobody wired this up" never reads as "nothing can be done" —
    # so it is named as a substrate defect rather than skipped.
    for r in results:
        if r.name not in PREFLIGHT_REPAIRS and r.verdict == PREFLIGHT_FAIL:
            narration.append(f"{r.name}: no repair class is declared for this check — "
                             f"that is a substrate defect (ADR-0109 D2), not a finding "
                             f"about this machine")

    def _recheck(name: str) -> _PreflightResult | None:
        fn = checks_by_name.get(name)
        try:
            return fn() if fn else None
        except Exception:
            return None

    for i, r in enumerate(out):
        if r.verdict != PREFLIGHT_FAIL:
            continue
        spec = PREFLIGHT_REPAIRS.get(r.name)
        if spec is None or spec.kind != REPAIR_AUTO or spec.fn is None:
            continue
        ok, how = spec.fn(r)
        if not ok:
            narration.append(f"{r.name}: tried to repair and could not — {how}")
            continue
        fresh = _recheck(r.name)
        if fresh is not None and fresh.verdict == PREFLIGHT_OK:
            out[i] = fresh
            narration.append(f"{r.name}: repaired — {how}")
        else:
            still = fresh.detail if fresh is not None else "the check could not be re-run"
            narration.append(f"{r.name}: repair ran ({how}) but the check still does not "
                             f"pass — {still}")
            if fresh is not None:
                out[i] = fresh

    if not allow_guided:
        return out, narration
    guided_failed = [r for r in out if r.verdict == PREFLIGHT_FAIL
                     and _repair_kind(r.name) == REPAIR_GUIDED]
    if not guided_failed:
        return out, narration
    blocked = _preflight_guided_blocked(out)
    if blocked:
        narration.append(
            f"{', '.join(r.name for r in guided_failed)}: could not open the step here — "
            f"{blocked}")
        return out, narration
    ok, how = _repair_claude_first_run(out)
    if not ok:
        narration.append(f"{', '.join(r.name for r in guided_failed)}: tried to open the "
                         f"step and could not — {how}")
        return out, narration
    for i, r in enumerate(out):
        if r.verdict == PREFLIGHT_FAIL and _repair_kind(r.name) == REPAIR_GUIDED:
            fresh = _recheck(r.name)
            if fresh is not None:
                out[i] = fresh
    fixed = [r.name for r in out if r.verdict == PREFLIGHT_OK
             and any(g.name == r.name for g in guided_failed)]
    if fixed:
        narration.append(f"{', '.join(fixed)}: repaired — {how}")
    else:
        narration.append(f"guided step ran ({how}) but nothing in the guided class "
                         f"passes yet")
    return out, narration


