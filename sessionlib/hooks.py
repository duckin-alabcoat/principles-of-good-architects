    # evidence) surface as flown-not-landed; minus our own only when we just wrote it
    # eagerly (the lazy path hasn't materialized ours yet).
    others_open = max(0, len(_open_journal_paths())
                      - (1 if (not args.dry_run and not lazy) else 0))
    if others_open:
        out.append(f"prior:   {others_open} unclosed journal(s) — flown-not-landed "
                   f"(ADR-0051), rendered in-progress; no action")
    # R2a (the poga-5 close-honesty gap): an unlanded lane's journal exists only on its
    # branch, invisible to the journal reap above — report any that are present but
    # unstamped so a falsely-reported close is loud at the next start, not silent.
    try:
        for _lane in _scan_lanes():
            if _lane["status"] != "unmerged" or not _lane["branch"]:
                continue
            for _sid in _lane_unstamped_journals(_lane["branch"]):
                out.append(f"lane:    {_lane['name']} UNMERGED — journal {_sid} present "
                           f"but UNSTAMPED (`session.py end` never ran; a reported close "
                           f"was false). Close honestly from the lane, then land.")
    except Exception:
        pass
    stamp_note = ("(dry-run)" if args.dry_run else
                  "cloud container — start writes no tracked files (WI-0484); your work "
                  "comes back as a branch" if cloud else
                  ("deferred — journal + handoff materialize at your first tool call "
                   "(ADR-0055)" if lazy else "journal written; handoff compiled"))
    out.append(f"stamp:   {stamp_note}")
    out.append(f"journal:{' (dry-run)' if args.dry_run else ' none in a cloud container — put the narrative in your commits' if cloud else f' sessions/journal/{_did}.md — write your narrative here'}")
    # THREE states, never two. "Cannot see the inbox" and "the inbox is empty" used to
    # collapse to the same `(empty)` — so session 90 opened announcing an empty inbox
    # while two briefs sat pending, one of them time-boxed, because a poga lane simply
    # has no `proposed-edits/` (gitignored => not materialized in a worktree). Reporting
    # absence as emptiness is a fabricated fact
    # ([no-fabricated-data](habits/master.md#no-fabricated-data) / P18): say what is
    # actually known. `_link_shared_data` normally repairs this at the first heartbeat;
    # this line is the guard for when it can't. WI-0027: composed via `inbox_dirs()`, so
    # the path it reports is the one the engine acts on — not the lane's absent copy.
    out.append(_inbox_orientation_line())
    claims_line = _claims_orientation_line()
    if claims_line:
        out.append(f"claims:  {claims_line}")
    # ADR-0101: a sibling lane blocked on a question operator never saw. The window it is
    # waiting in may be one he scrolled past hours ago, and nothing else on this banner
    # distinguishes a lane waiting on him from a lane doing nothing — every other liveness
    # signal here answers "did the process move".
    with contextlib.suppress(Exception):
        for line in _attention_lines(exclude_self=True):
            out.append(line)
    # ADR-0089 D3: stranded lanes are reported by the repo that OWNS them, at start.
    # Until now the only surface that named an ended-but-unlanded lane was the standalone
    # `reap-lanes` — which nobody runs — so one member's stranded work was found on day 8 by
    # an external observer that happened to exist and happened to be pointed at the right
    # repo. A portfolio dashboard is a backstop, not a dependency of every member's safety.
    for line in _stranded_lane_lines():
        out.append(line)
    # WI-0141, the same argument one namespace over. A park ref outlives the refusal that
    # created it, and until now nothing ever said so — which is precisely the "a parked
    # branch nobody retires becomes the same stale signal" complaint the item opens with.
    # Costs no fetch (see `_retirable_park_lines`) and is silent when nothing is ready.
    with contextlib.suppress(Exception):
        for line in _retirable_park_lines():
            out.append(line)
    # WI-0180. `poga` fails OPEN when preflight cannot return a verdict, so a session can
    # open on a machine nothing checked. The note saying so goes to the operator's terminal
    # and scrolls away under the launch banner; the reason now lands on disk instead of
    # being deleted, and this is where it gets read — by the Architect whose session it is,
    # in the session it preceded.
    with contextlib.suppress(Exception):
        for line in _preflight_failure_lines(consume=not args.dry_run):
            out.append(line)
    # The same argument one level out: ADR-0089 covered the WORK a dead lane strands, but
    # nothing ever looked at the PROCESS that was running in it. Four were alive in deleted
    # lanes at session ~124, the oldest up 7d17h, and clearing them fell to operator by hand.
    # Reported here, killed only by the explicit verb — an unattended auto-kill at every
    # start is the wrong altitude for a signal this subtle (P9).
    with contextlib.suppress(Exception):
        for line in _stranded_process_lines():
            out.append(line)
    # WI-0089 one level up: a lane is structurally blind to the shared checkout it depends
    # on, so main's dirt was discovered only by tripping over it — a land that quietly
    # declines to sync, a refused substrate push, or a session-end from main committing it
    # verbatim. Silent when main is clean.
    with contextlib.suppress(Exception):
        for line in _main_checkout_lines():
            out.append(line)
    # WI-0023: the accumulated permission pile, once it is big enough to be worth a
    # review moment. Silent below the threshold and silent when there is no pile — the
    # only way a rare signal stays readable is by actually being rare.
    with contextlib.suppress(Exception):
        line = _permission_pile_line()
        if line:
            out.append(line)
    # WI-0131: say it out loud when the federation refreshed this member's substrate.
    with contextlib.suppress(Exception):
        line = _substrate_push_line()
        if line:
            out.append(line)
    # ADR-0073, ahead of the lifecycle-inversion wrapper landing: ship the PREP-step
    # work-item print as this SessionStart hook for now (the brief's own sequencing
    # note) — same module the eventual `poga` PREP step calls, one caller today.
    # Gated per-session on the board properly showing the items —
    # decided by a FILE READ (never HTTP here), fail-open in both directions. The full
    # snapshot is always rendered first because rendering is what pins the ordinal
    # mapping: `do 3` must resolve identically whichever view prints.
    try:
        wi_lines = _wi_render_snapshot_lines()
        if wi_lines and not wi_lines[0].startswith("Work items: (none"):
            board = None
            with contextlib.suppress(Exception):
                board, _ = _board_live()
            if board is not None:
                with contextlib.suppress(Exception):
                    wi_lines = _wi_short_lines(board)
            out.extend(wi_lines)
    except Exception:
        pass
    # WI-0328: name the interpreter this session runs on, every session.
    with contextlib.suppress(Exception):
        out.append(f"python:  {_interpreter_line()}")
    # WI-0333, and the WI-0328 line above is its precedent exactly: a fact the gate
    # already knows, said at START instead of at land. Unconditional, all three states —
    # a line that appeared only on a red trunk would be a line nobody could tell from a
    # line that failed to run, and the UNKNOWN case is the one a member with no nightly
    # most needs to see.
    with contextlib.suppress(Exception):
        out.append(trunk_suite_line())
    # WI-0349: what landing has been costing, on the one surface every session reads.
    # Same shape and same reasoning as the two lines above — a fact the harness already
    # measures, said where it does not have to be asked for.
    with contextlib.suppress(Exception):
        out.append(landing_line())
    canon = _canon_block()
    out.append(f"canon:   {'CANON.md injected as context' if canon else '(absent)'}")
    standard = _standard_block()
    out.append(f"standard:{' STANDARD.md injected as context' if standard else ' (absent)'}")
    # WI-0451: the `voice` settings, in one line. Never fails the start.
    with contextlib.suppress(Exception):
        out.append(voice_line())
    # The effective picker policy, stated once, beside the canon it governs.
    with contextlib.suppress(Exception):
        out.append(pickers_line())
    # ADR-0035 inject-don't-read: the prior session's entry + the user profile go
    # into context so steps 5-6 cost zero read-turns.
    injected, inj_labels = _inject_block(prior_block)
    # Report what was ASSEMBLED, part by part. The previous line printed
    # `prior-entry + user-profile` whenever anything was injected, so it could not
    # express the case where the profile was missing — which was every session on a
    # member whose profile is not in its own repo.
    # PREFIX match, not equality: the label carries truncation detail (WI-0066), and an
    # equality test would read a delivered-but-truncated profile as no profile at all —
    # then tell the Architect to declare a key it already declared.
    if any(lbl.startswith("user-profile") for lbl in inj_labels):
        profile_note = ""
    else:
        declared = (CFG or {}).get("user_profile")
        if isinstance(declared, str) and declared.strip():
            # Declared but unreadable (or `_shared_work_root()` couldn't be resolved) —
            # name the path that failed rather than telling the Architect to declare
            # something it already declared. Reported by a member Architect.
            try:
                resolved = (_shared_work_root() / declared.strip()).resolve()
            except Exception:
                resolved = declared.strip()
            profile_note = f"  [user profile declared but unreadable: {resolved}]"
        else:
            profile_note = "  [no user profile — declare `user_profile` in session.config.json]"
    out.append(f"injected: {' + '.join(inj_labels) if inj_labels else '(none)'}" + profile_note)
    from sessionlib.registry_state import orientation as registry_orientation
    out.append(registry_orientation(ROOT, _shared_work_root(), dry_run=args.dry_run))
    announce = (f"Session {_display_ordinal(n)} start: {CFG['architect_name']} v{version} · {machine} · "
                f"{stamp} · {_session_surface()[1]}")
    out.append(f"announce: {announce}")
    # WI-0390: the brief goes in the ORIENTATION, not the argv. Placed last in the block
    # and ahead of the canon/standard injection below, because that is the reading order
    # the lane needs: orient, read the assignment, then read the set it must apply to it.
    # Inside `out` rather than appended to `context` so `--dry-run` shows it — a delivery
    # channel you cannot see without spawning a real lane is how this defect survived.
    if dispatch_brief:
        out += ["", dispatch_brief]

    if args.dry_run:
        print("--- session start (dry-run, nothing written) ---")
        print("\n".join(out))
        return
    # Emit pure JSON: sessionTitle sets the picker label, additionalContext carries
    # the orientation + CANON + STANDARD + the injected prior-entry/profile. Any
    # stray print here would corrupt the parse.
    context = "\n".join(out)
    for extra in (canon, standard, injected):
        if extra:
            context += "\n\n" + extra
    if getattr(args, "prep", False):
        # ADR-0082 D5. There is no hook to emit JSON to on this path — the wrapper is
        # about to launch a runtime that may have no injection channel at all — so the
        # payload is WRITTEN and its path is the only thing on stdout, for the wrapper to
        # name in the opening prompt. Keeping the path off bash's hands (rather than
        # hardcoding it there too) keeps one owner for where this file lives (P16). The
        # human-facing note goes to stderr so stdout stays a single machine-readable line.
        rel = _write_session_context(context)
        # WI-0391: the single place that satisfies the prep contract. Set AFTER the write,
        # so a write that raises leaves the flag false and the wrapper refuses rather than
        # reporting a payload nobody produced.
        global _PREP_PAYLOAD_WRITTEN
        _PREP_PAYLOAD_WRITTEN = True
        print(f"poga: session context written to {rel} — the opening prompt will name it.",
              file=sys.stderr)
        print(rel)
        return
    # WI-0152: the durable id is what makes this name unique; the ordinal alone
    # does not, and two sessions on this machine have already proved it.
    _emit_start(structural_name(n, machine, stamp, _did), context, announce)


