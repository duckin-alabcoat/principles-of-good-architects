def _cli_parser() -> argparse.ArgumentParser:
    """The whole `session.py` argument parser: every command family, then `--grant` on
    every verb."""
    ap = argparse.ArgumentParser(description="Federation session-ritual harness.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    for register in CLI_FAMILIES:
        register(sub)

    # WI-0280 / ADR-0112 D9. Declared on EVERY verb, in one loop, rather than on the
    # handful that reach an authorized commit today. Two reasons, and the second is the
    # one that decides it. (a) The flag is inert where it is unused: a verb that makes no
    # commit reads `cited_grant()` nowhere, so carrying it costs a line of help text.
    # (b) A hand-kept list of authorized verbs is the shape this file has already been
    # burned by — `_store_autocommit` exists as a single hook point precisely so that "a
    # verb added tomorrow cannot forget a step that is not its to remember", and a verb
    # list here would reintroduce the forgetting one level up. `add_subparsers` hands back
    # its parsers in `.choices`; dedupe by identity because an alias maps two names to one
    # parser and argparse raises on a repeated option.
    _seen = set()
    for _p in sub.choices.values():
        if id(_p) in _seen:
            continue
        _seen.add(id(_p))
        _p.add_argument(
            "--grant", metavar="G-XXXXXX", default="",
            help="ADR-0112 D9: cite a grant minted by `poga authorize`. When it RESOLVES "
                 "for this act, any commit this verb makes carries an "
                 f"`{GRANT_TRAILER_KEY}: G-XXXXXX` trailer, so what authorized the write "
                 "is answerable from tracked history after the coordination store is "
                 "gone. A grant that does not resolve writes NO trailer and says why on "
                 "stderr — an unbacked provenance line is worse than none.")
    return ap


def main() -> None:
    ap = _cli_parser()
    args = ap.parse_args()
    # WI-0193. FIRST, because a refusal must not buy a network fetch: `_report_checkout_
    # staleness` below can pay a real `git fetch` (0.81 s measured, up to the timeout with
    # the network down) to warn about a store this call is not going to touch anyway.
    #
    # The same choke point as the staleness report, for the same WI-0222 reason and with
    # the same coverage: `python3 session.py ops-new` run straight from a lane is precisely
    # the invocation `poga` never sees, and it is the one that filed OPS-0006 into a store
    # nothing reads. Placing it per-verb would have left the next store verb uncovered.
    _refuse_lane_store_write(getattr(args, "cmd", ""))
    # WI-0402, and here rather than inside `cmd_release_cut` for the same reason its
    # sibling above is here: `python3 session.py release-cut` typed straight from a lane
    # is precisely the invocation `poga` never sees, and it is the one that would cut a
    # tag against a lane's HEAD. Placing it per-verb would leave the next release verb
    # uncovered. In-process callers (the suite calls `cmd_release_cut` directly) do not
    # pass through here, so the fixtures that drive a cut against their own temp repo are
    # untouched — which is correct: they are not a lane of anything.
    _refuse_lane_release_write(getattr(args, "cmd", ""))
    # WI-0222. THE choke point: every verb that reaches session.py passes through here, so
    # the report costs one placement rather than one per verb — including a bare
    # `python3 session.py wi-list` run straight from a lane, which `poga` never sees at
    # all. Before `args.func`, so the warning precedes the output it is a warning about.
    _report_checkout_staleness(getattr(args, "cmd", ""))
    # WI-0280. The same choke point carries ADR-0112 D9's grant citation, for the same
    # one-placement reason: `--grant` is declared on every verb by the loop above, and read
    # at the single hook point every authorized commit passes through
    # (`_grant_trailer_args`).
    #
    # SET UNCONDITIONALLY, INCLUDING TO "". That is the property that makes a module-level
    # citation honest where the `POGA_GRANT` variable it replaces was not: a second verb
    # cannot inherit the first one's grant, because every invocation writes the slot before
    # it runs anything. Nothing ever cleared the environment variable, which is the whole
    # complaint against it. `test_grants.py::TheTrailerTakesNoAmbientInputTest` pins it.
    #
    # `getattr` rather than `args.grant` because this is not the only way a namespace
    # reaches here — a test builds one directly, and a caller that constructs its own
    # parser would otherwise crash the choke point rather than simply cite nothing.
    cite_grant(getattr(args, "grant", "") or "")
    args.func(args)
