_PREP_PAYLOAD_WRITTEN = False


def _supersede_journal(p: Path, new_session_id: str) -> str | None:
    """WI-0391: close an open journal this lane is about to take over, and point it at the
    session taking over. Returns a one-line note for the orientation, or None if there was
    nothing to do. Never raises — a start must not fail because a foreign record was odd.

    WHAT IT CLAIMS, precisely, because a machine close that overstates is worse than none:
    the reason label says a new session opened in this lane, which is a fact this code
    observed, and NOT that the other session is dead, which nobody proved. That is the same
    structural-evidence footing as `lane-torn-down`.

    THE BODY IS NEVER TOUCHED. Only the frontmatter is stamped. The behaviour this replaces
    ADOPTED the journal and appended a second session's narrative to it — which is how a
    Codex lane came to write its orientation into session ~369's file on 2026-09-18 — so
    the comparison for "is this too destructive" is not against leaving the file alone, it
    is against writing a stranger's session into it.

    Re-reads and re-checks `ended` rather than trusting the caller's earlier scan: the reap
    and the janitor both run between that scan and this call, and either may have closed it
    already. Closing a closed journal would move its `ended` stamp backwards onto a later
    clock, which is a fabricated end time."""
    try:
        if not p.is_file():
            return None
        text = p.read_text(encoding="utf-8")
        fm, _ = parse_journal(text)
        if not fm or fm.get("ended", "").strip():
            return None                      # already closed by the reaper or the janitor
        start_dt = _parse_iso(fm.get("started", ""))
        end_dt = datetime.now(CFG["tz"])
        dur = format_duration(start_dt, end_dt) if start_dt else "?"
        stub = (fm.get("title") or "").strip() in ("", JOURNAL_STUB_TITLE)
        atomic_write(p, finalize_journal(
            text, end_dt.isoformat(), dur,
            title=machine_close_title("lane-reassigned") if stub else None,
            closed_by=f"start ({MACHINE_CLOSE_REASONS['lane-reassigned']})",
            superseded_by=new_session_id, path=p))
        return (f"superseded: {p.name} was open in this lane and belongs to another "
                f"session — closed as dropped, pointed at {new_session_id}. Its narrative "
                "is untouched; this session writes its own journal.")
    except Exception:
        return None


def _refuse_prep_early_return(args: argparse.Namespace, because: str) -> None:
    """WI-0391: the per-site half of the prep contract — an early return CONSULTS `--prep`
    rather than firing blind.

    The wrapper in `cmd_start` already turns any payload-less `--prep` run into a non-zero
    exit, so this is not what makes the contract hold. What it adds is the one thing a
    generic guard cannot: WHICH return fired and why, at the moment it fires. The failure
    this whole item is about was diagnosed from four bytes of the wrong path appearing in
    an unrelated stderr note, hours later, in another process — the cost of the diagnosis
    was the whole of the cost. Both sites are named because the operator's ruling names both: the
    early returns consult `--prep` either way, so that neither can be the one nobody
    checked.

    Not reachable on today's launch path (a `--prep` run carries no session id and both
    sites require one), and deliberately built anyway: the ruling closes the door, not the
    one hole found behind it."""
    if getattr(args, "prep", False) and not getattr(args, "dry_run", False):
        raise SystemExit(
            f"session.py start --prep: refusing the idempotent early return — {because}. "
            "A prep run must produce a session context payload or fail; returning 0 here "
            "would launch a lane with no canon and no way to tell (WI-0391). Nothing was "
            "written.")


def cmd_start(args: argparse.Namespace) -> None:
    """The session-start ritual, plus the `--prep` contract that wraps it.

    THE CONTRACT: a `--prep` run either writes the session-context payload and prints its
    path as the only line on stdout, or it exits non-zero. It never exits 0 having written
    nothing. That is not a stylistic preference — it is WI-0391's whole subject. `cmd_start`
    had two early returns that fired before the payload was composed, and one of them was
    reachable on every `--prep` launch on a machine carrying any open journal from today
    (five such journals on main the day this was built). The lane then launched with no
    canon at all, exit 0, nothing on stderr the model could see, and the only symptom was a
    pointer instruction naming a file that did not exist.

    WHY A RUNTIME GUARD AND NOT A CODE REVIEW RULE. The defect is not that someone wrote a
    bad early return; it is that an early return is the natural way to write "nothing to do
    here", and the cost of one lands in a different process an hour later. This is the
    [`add-structural-guard-on-recurrence`](habits/master.md#add-structural-guard-on-recurrence)
    shape, and it deliberately fails CLOSED: what sits on the other side of this guard is a
    lane running without its principles while reporting success, which is exactly the loss
    the guard exists to prevent, so letting it through is the unsafe direction. A prep that
    cannot produce a payload must say so where the wrapper can act on it — WI-0389's
    consumer boundary already degrades a refused prep to a clean pointer rather than
    splicing whatever it got into an instruction.

    `--dry-run` is outside the contract: it writes nothing by definition and says so.

    `__wrapped__` is set below, and it is load-bearing rather than decoration. Three
    existing guards assert the start's wiring by reading `inspect.getsource(cmd_start)` —
    that it emits the landing line, the trunk-suite verdict and the board view. Splitting
    the body out from under that name makes all three read a wrapper that mentions none of
    them and go quietly green on a start that had stopped emitting any of it: a guard that
    still passes while no longer looking. `inspect.getsourcelines` unwraps, so the pointer
    keeps those three asking the question they were written to ask, of the code that now
    answers it."""
    if not getattr(args, "prep", False) or getattr(args, "dry_run", False):
        _cmd_start(args)
        return
    global _PREP_PAYLOAD_WRITTEN
    _PREP_PAYLOAD_WRITTEN = False
    _cmd_start(args)
    if not _PREP_PAYLOAD_WRITTEN:
        raise SystemExit(
            "session.py start --prep: finished without writing a session context payload. "
            "Refusing to exit 0 with nothing on stdout — a lane launched on this would run "
            "with no canon and no way to tell (WI-0391). Nothing was written.")


def _cmd_start(args: argparse.Namespace) -> None:
    if CFG is None:
        raise SystemExit(f"session.py: {CONFIG_PATH.name} missing or invalid — cannot start.")
    handoff = CFG["handoff"]
    hook = _read_hook_stdin()
    session_id = hook.get("session_id")
    banner_path = _banner_file(session_id)   # this session's rendezvous file for `announce`

    # WI-0390: a dispatched lane's BRIEF now rides this orientation rather than the
    # runtime's argv, because `poga` reads a bare positional as the operator's own prompt
    # and refuses to splice canon into one — so every dispatched lane was running without
    # its principles, habits and rituals. Built once, here, and used twice below: the
    # receipt is written ABOUT this string, and this same string is appended to `out`.
    # Empty for a hand-launched session, which must get exactly the orientation it always
    # got.
    dispatch_brief = _dispatch_brief_block()

    # WI-0248: a dispatched lane reports, on the dispatch's own slot, whether it actually
    # received its brief. Deliberately BEFORE the two early returns below — a lane that
    # re-enters an already-open journal is still a lane whose briefing the dispatch needs
    # an answer about, and the measurement is idempotent (the brief is a pure function of
    # records that do not change under it).
    if not args.dry_run:
        _dispatch_write_receipt(dispatch_brief)

    machine = detect_machine()
    stamp = now_stamp()
    today = stamp.split(" ", 1)[0]

    # 1. Idempotency (ADR-0051 C1/C2): a re-run of the SAME session finds its OWN open
    #    journal — never allocate a second. The check is against the durable journal,
    #    not a shared-ledger entry (the handoff is a generated view now, and nothing
    #    is allocated at birth to contend over).
    mine = _my_open_journal(session_id, machine, today)
    # 1a. WI-0391: under `--prep` that idempotency check is not identifying THIS session.
    #     `_my_open_journal` keys on the claude-session-id, and a `--prep` run has none, so
    #     it takes its documented fallback — "an open journal on this machine started
    #     today" — and hands back whatever open journal the lane's tree happens to carry.
    #     That is ANOTHER session's record by construction, and the harness then adopted it:
    #     the launched lane wrote its narrative into a stranger's journal AND, because the
    #     early return below fires before the payload is composed, launched with no canon.
    #     Both were observed live on 2026-09-18.
    #
    #     the operator's ruling, 2026-09-18: a session launched into a lane holding another
    #     session's open journal CLOSES that journal as dropped, with a pointer, and OPENS
    #     ITS OWN. Closing it is the smaller act, not the larger one — the behaviour it
    #     replaces wrote foreign narrative into the body, and this leaves the body untouched.
    #
    #     Gated on `--prep` and NOT on `session_id is None` alone, because those are
    #     different situations wearing the same missing field: a hand `python3 session.py
    #     start` re-run also has no session id, and there the fallback is doing its real job
    #     (ADR-0051 C1/C2 counter contention — the same session, run twice). `--prep` is the
    #     wrapper about to launch a NEW runtime into this lane, which a re-run never is.
    superseded: Path | None = None
    supersede_note: str = ""
    if mine is not None and getattr(args, "prep", False) and not session_id:
        superseded, mine = mine, None
    if mine is not None:
        _refuse_prep_early_return(
            args, "this session's own journal is already open "
                  f"({mine.name}) and the start is idempotent")
        fm, _ = parse_journal(mine.read_text(encoding="utf-8"))
        if not args.dry_run:
            _stage_banner(banner_path, [])   # sentinel: nothing new to announce
        _emit_already_open(fm)
        from sessionlib.registry_state import orientation as registry_orientation
        print(registry_orientation(ROOT, _shared_work_root(), dry_run=args.dry_run))
        return
    # 1b. ADR-0082 D1 prep adoption: the wrapper may already have run the start ritual
    #     for this lane before launching us. Bind that journal to this runtime session
    #     instead of opening a second one. Deliberately NOT an early return — the
    #     orientation block and the canon/standard injection below still have to reach
    #     the runtime's context (D5: delivery degrades inject → point, never → nothing);
    #     what adoption skips is the ALLOCATION, not the delivery.
    adopted = _claim_prepped_journal(session_id) if session_id else None
    if adopted is None and session_id and _pending_marker(session_id).is_file():
        # ADR-0055: this session already lazy-started — the marker exists, the
        # journal just hasn't materialized yet (no beat so far). Same idempotent
        # no-op as the journal case above.
        _refuse_prep_early_return(
            args, "this session already lazy-started and its journal has not "
                  "materialized yet (ADR-0055)")
        if not args.dry_run:
            _stage_banner(banner_path, [])
        print("\n".join([
            "=== SESSION START (already open) ===",
            "stamp:   already lazy-started this session — do NOT re-run `session.py start`.",
            "note:    the journal materializes at your first tool call (ADR-0055); orient "
            "from the hook's original block.",
        ]))
        return

    # 2. git status — startup NEVER blocks on a dirty tree (the operator's ruling, session 50:
    #    handle whatever is there and start). Uncommitted files are in-flight work, left
    #    as-is; the session-end commit sweeps them.
    status = sh(["git", "status", "--porcelain"]).stdout
    dirty = [l for l in status.splitlines() if l.strip()]
    tree_clean = not dirty
    # WI-0484: a Claude cloud container writes nothing tracked at start, on either path,
    # and pushes nothing: its work comes back as a branch.
    cloud = _cloud_start_quiet()

    # 3. Remote sync — safe routine action (ADR-0035); deferred on a dirty tree (a
    #    ff-pull into uncommitted work can fail — not risked in the startup path).
    #    On the hook path (ADR-0055 lazy start) the PUSH half is deferred to first
    #    activity — fetch/diagnose/ff-pull still run so context is fresh.
    if tree_clean:
        pull_note, sync_extra = git_sync(args.dry_run, push=(session_id is None and not cloud))
    else:
        pull_note, sync_extra = ("deferred — uncommitted changes present; pull/push at session end", [])

    # 4. The prior session's entry to inject (ADR-0035 inject-don't-read) — the topmost
    #    of the CURRENTLY compiled handoff, captured before we fold ourselves in.
    prior_text = handoff.read_text(encoding="utf-8") if handoff.exists() else ""
    prior = topmost_entry(prior_text)
    prior_block = _entry_block(prior_text, prior) if prior else ""

    version = role_doc_version()
    # ADR-0082 D3: the registry row's id, supplied by the wrapper at prep. Absent (every
    # hook-path start, and any hand run) it is this binding's own runtime — which is what
    # every journal written before ADR-0082 already recorded, so the default is not a
    # guess, it is the pre-inversion behaviour preserved exactly.
    runtime_id = (getattr(args, "runtime", None) or CLAUDE_RUNTIME).strip() or CLAUDE_RUNTIME
    _did = durable_session_id(machine, datetime.now(CFG["tz"]))
    reaped: list[tuple[str, str]] = []
    # ADR-0055: the hook path defers; manual runs stay eager. An ADOPTED session is
    # neither — its journal already exists on disk, written eagerly by the wrapper, so
    # there is nothing to defer and nothing to allocate.
    lazy = session_id is not None and adopted is None
    if adopted is not None:
        _fm_adopted, _ = parse_journal(adopted.read_text(encoding="utf-8"))
        _did = _fm_adopted.get("session-id", _did) or _did

    if not args.dry_run:
        if adopted is not None:
            # The wrapper already froze, reaped, journalled, branched and compiled. All
            # that is owed here is the liveness marker the hook path would have written,
            # now that we finally know the runtime session id to key it by.
            _sidecar_write(session_id, "live", {
                "session_n": (compiled_ordinal(_did) or _next_ordinal()) - 1,
                "session_id": _did, "machine": machine,
                "started": _fm_adopted.get("started", _now_iso()), "last_beat": _now_iso(),
            })
            n = compiled_ordinal(_did) or _next_ordinal()
        elif lazy:
            # 5-8 DEFERRED (ADR-0055 lazy start): SessionStart does only read-only
            # work plus the liveness marker. The mutating start work — freeze, reap,
            # journal write, compile, deferred push — waits for the first heartbeat
            # (tool call or Stop), a signal a phantom preload (the desktop-app
            # pre-spawn: Start + End, never a turn) never produces. A phantom is
            # thereby a no-op by construction: no journal, no ordinal, no reap run.
            n = _next_ordinal()
            _sidecar_write(session_id, "live", {
                "session_n": n - 1, "session_id": _did, "machine": machine,
                "started": _now_iso(), "last_beat": _now_iso(),
            })
            _sidecar_write(session_id, "pending-start", {
                "session_id": _did, "ordinal": n, "machine": machine,
                "role_doc_version": f"v{version}", "base_commit": _base_commit(),
                "started": _now_iso(),
            })
        elif cloud:
            # WI-0484: a manual start in a Claude cloud container. The eager branch below
            # freezes, reaps, writes a journal and compiles the handoff and STATUS, all
            # tracked. The container's work comes back as a branch and the operator's own
            # machine owns that state, so here start only numbers itself.
            n = _next_ordinal()
        else:
            # 5. Fleet-migration safety (ADR-0051): if this member has a hand-written
            #    handoff and no archive yet, freeze it BEFORE we number ourselves — so
            #    the ordinal continues its real history (frozen_max + 1) rather than
            #    restarting at 1. Idempotent; a no-op once an archive exists.
            _migrate_freeze()
            # 6. Reap provably-dead journals (ADR-0051/ADR-0054): close a clean-exited
            #    prior session's journal at its exit marker, a crashed one past the
            #    grace; delete a phantom-class journal. Runs BEFORE we number ourselves
            #    so a reclaimed ordinal falls to this real session.
            reaped = _reap_dead_journals(session_id)
            # 6b. …and sweep what the reaper structurally cannot see: journals whose
            #     evidence no longer exists, and residue for sessions long over. Nearly
            #     free — the git probe fires only for a journal with NO sidecar at all.
            janitor_sweep(session_id)
            # 7. Emit this session's journal (own-journal-only, C2): the narrative
            #    exists before any close, so an abandoned session is a non-event.
            #    `ordinal` is ADVISORY (R4c): a start-time estimate kept only as
            #    `_guard_close_ordinal`'s floor — identity is the session-id, and the
            #    real number is assigned by the trunk compile.
            # ADR-0082 D1/D3: the runtime is whatever the wrapper resolved and passed in,
            # not a constant. Hardcoding it here would stamp a codex lane's journal as a
            # Claude session — WI-0060's "the record does not say what ran" defect
            # re-created from the other direction, and self-inflicted.
            write_start_journal(_did, {
                "session-id": _did, "ordinal": _next_ordinal(), "title": "(in progress)",
                "machine": machine, "runtime": runtime_id,
                "role-doc-version": f"v{version}", "base-commit": _base_commit(),
                "started": _now_iso(), "ended": "",
                "claude-session-id": session_id or "",
            })
            _sidecar_write(session_id, "live", {
                "session_n": _next_ordinal() - 1, "session_id": _did, "machine": machine,
                "started": _now_iso(), "last_beat": _now_iso(),
            })
            # 7b. WI-0391: this session now HAS its own journal, so the foreign one step 1a
            #     took off the idempotency path can be closed and pointed at it. Done here
            #     and not at step 1a because the pointer needs `_did`, and a close that
            #     names no successor is the half-record that made this defect invisible for
            #     as long as it was.
            if superseded is not None:
                note = _supersede_journal(superseded, _did)
                if note:
                    supersede_note = note
            # ADR-0056: isolate this session on its branch (the eager path already
            # pushed prior trunk commits via git_sync above).
            _cut_session_branch(_did)
            # 8. Regenerate the handoff + STATUS census (no-ops on the branch, D2).
            run_compile(CFG["tz"])
            n = compiled_ordinal(_did) or _next_ordinal()
            # 8b. ADR-0082 D1: when this start IS the wrapper's prep phase, leave the
            #     rendezvous so the runtime we are about to launch adopts this journal
            #     instead of opening its own. Written LAST — only a start that got all
            #     the way here has a journal worth adopting.
            if getattr(args, "prep", False):
                _write_prep_marker(_did, runtime_id)
        # 9. Stage the start banner for the `announce` hook (the user-visible post).
        #    A START-TIME ordinal is an estimate EVERYWHERE (see _display_ordinal) —
        #    shown as ~N, with the note naming what it is still waiting on. WI-0152: this
        #    used to attach the note only on a lane and print a bare N on the trunk, which
        #    asserted a number the trunk compile had not yet settled.
        _clear_stale_banners(keep=banner_path)
        _stage_banner(banner_path, [_fmt_banner(
            "start", _display_ordinal(n), version, machine, stamp,
            tail=LANE_ORDINAL_NOTE if _on_worktree_lane() else START_ORDINAL_NOTE)])
    else:
        n = _next_ordinal()

    # Orientation block — the Architect reads this to announce + summarize. The
    # FIRST lines are a hard directive against the opening-message-preempts-startup
    # failure. Injected every session, so it doesn't rely on the Architect having
    # internalized STANDARD.md (P15).
    out = [
        "=== SESSION START ===",
        "FIRST — before acting on the user's opening message: run the session-start",
        "steps below. That message is often only a session label (used to name the",
        "session in the picker), not a task. Announce, orient, summarize, THEN address",
        "it if it asked anything.",
        f"version: v{version}",
        f"machine: {machine}",
        f"time:    {stamp}",
        f"session: {_display_ordinal(n)} "
        f"({LANE_ORDINAL_NOTE if _on_worktree_lane() else START_ORDINAL_NOTE})",
        f"surface: {_session_surface()[0]}",
        f"sync:    {pull_note or '(skipped)'}",
    ]
    # ADR-0059 detect-and-refuse: another live session sharing THIS working tree is the
    # unsafe app-surface accident (two `claude` windows, one tree). Surface it loudly and
    # steer to `poga` (each lane gets its own isolated worktree). A poga lane is never
    # counted (its sidecar lives in its own worktree). Not raised for a lane/branch session.
    app_siblings = ([] if (_on_worktree_lane() or _on_session_branch())
                    else _live_same_tree_siblings(session_id))
    if app_siblings:
        out.append(
            f"REFUSE:  {len(app_siblings)} other live session(s) share THIS working tree "
            f"— unsafe shared-tree mode. Close this window and run concurrent work via "
            f"`poga` (each lane is its own isolated worktree). If you continue, your close "
            f"commits ONLY your own attributed files — never a sibling's, never a blend.")
    # A lane land declined to fast-forward this checkout because it held content of its
    # own (`_sync_main_checkout`). Say so at start: otherwise the tree just looks dirty in
    # a confusing way — the session-89 signature, where `git status` reads as a deliberate
    # revert of the landed work and the natural cleanup instincts are a coin-flip.
    stale_banner = SESSION_STATE_DIR / "stale-checkout.txt"
    try:
        if stale_banner.is_file():
            first = stale_banner.read_text(encoding="utf-8").strip().splitlines()
            out.append("STALE:   this checkout was left behind by a lane land — "
                       + (first[1] if len(first) > 1 else "see .session-state/stale-checkout.txt")
                       + f"; details in {stale_banner}")
    except Exception:
        pass
    if dirty:
        out.append(f"tree:    {len(dirty)} uncommitted file(s) — left as-is (swept at session end)")
    out.extend(sync_extra)
    if reaped:
        out.append("reaped:  " + ", ".join(f"{sid[:24]} {disp}" for sid, disp in reaped))
    # WI-0391. Beside `reaped:` because it is the same kind of fact — a journal this start
    # closed — and deliberately NOT folded into it: the reaper closes on proof of death,
    # this closes on a lane handover, and collapsing the two would let a handover read as
    # an observed end.
    if supersede_note:
        out.append(f"{supersede_note}")
