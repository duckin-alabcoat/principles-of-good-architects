def cmd_preflight(args: argparse.Namespace) -> None:
    """`preflight` (WI-0149) — check every precondition a fresh machine actually fails,
    against THIS machine, and report each one separately.

    Exit 0 = every check passed. Exit 1 = at least one FAILED. Exit 2 = nothing failed
    but at least one could not be determined. The three are distinct on purpose: an
    UNKNOWN collapsed into either neighbour is the shape that certifies a gap.

    `--gate` is a DIFFERENT contract, called by poga before it allocates a lane: only the
    instant local subset runs, and the exit code is binary — 0 may launch, 1 refuse. The
    three-way split is right for a report a human reads and wrong for a decision a script
    makes, so the two do not share one code.

    IT REPAIRS BY DEFAULT (ADR-0109 D1). WI-0150 proposed this as `--fix`, and an opt-in
    fix leaves the errand exactly where it was for everyone who does not know to type it.
    So the flag runs the other way: `--no-repair` is the cautious path, and the verdict
    printed is the POST-REPAIR state — the honest answer to "can this machine be worked
    in now", which is the question the verb is actually asked."""
    if getattr(args, "gate", False):
        _preflight_gate()
        return
    if getattr(args, "cloud_first_run", False):
        _cloud_first_run_stop()
        return
    # ADR-0119 D4. Two of these probe the operator's machine — `_pf_auth` asks the CLI
    # about its login (and the network), `_pf_stranded_runtimes` reads the process table —
    # and WI-0271 caught `VerbDefaultsTest` running both for real, during a land, by calling
    # this command.
    #
    # THE GUARD IS HERE AND NOT IN THE PROBES, which is where it went first. Both probes
    # have their own hermetic unit tests that mock `subprocess.run` and pin every branch
    # (`AuthCheckTest`, `StrandedRuntimeCheckTest`); a guard inside the probe sits ABOVE
    # that mock and breaks six tests that never touched the machine. The reach is this
    # command calling them for real, so this is where it is refused — the caller, not the
    # leaf. A guard that removes coverage without removing a reach is a bad trade twice.
    #
    # `_pf_memory_pressure` (WI-0398) is dropped here for the same reason, and ALSO
    # carries its own `_under_gate` guard — it is in the launch-gate subset, where this
    # command is not the caller, so the caller-side guard cannot be the only one. Dropping
    # it here as well keeps the report's row count and exit code under the gate exactly
    # what they were: a SKIPPED row would turn every gate-run report into CANNOT TELL.
    checks = (_pf_terminfo, _pf_workspace_trust, _pf_onboarding, _pf_auth,
              _pf_data_root, _pf_residency, _pf_stranded_runtimes,
              _pf_memory_pressure)
    if _under_gate():
        checks = tuple(c for c in checks
                       if c not in (_pf_auth, _pf_stranded_runtimes,
                                    _pf_memory_pressure))
        print("preflight: auth + stranded-runtimes + memory-pressure NOT checked — this "
              "suite is the land gate, which must not read this machine (ADR-0119 D4).")
    results = _preflight_cloud_rows([c() for c in checks])
    by_name = {r.name: fn for fn, r in zip(checks, results)}
    results.extend(_pf_runtime_quarantine())
    if getattr(args, "quick", False):
        results.append(_PreflightResult(
            "gate", PREFLIGHT_SKIPPED,
            "--quick: the land gate was not run. This is not a green gate.",
            "Re-run without --quick before trusting this machine to land work."))
    else:
        results.append(_pf_gate())

    narration: list[str] = []
    if not getattr(args, "no_repair", False):
        results, narration = _preflight_repair(
            results, allow_guided=True, checks_by_name=by_name)

    if getattr(args, "json", False):
        print(json.dumps({"machine": detect_machine(), "root": str(ROOT),
                          "repaired": narration,
                          "checks": [r.as_dict() for r in results]}, indent=2))
    else:
        print(f"preflight: {detect_machine()} · {ROOT}")
        for line in narration:
            print(f"  REPAIR   {line}")
        for r in results:
            print(f"  {r.verdict:<8} {r.name:<19} {r.detail}")
            if r.verdict != PREFLIGHT_OK and r.remedy:
                # A remedy handed back after a repair pass is an escalation, not a
                # finding — so it carries WHY the substrate could not do it itself.
                spec = PREFLIGHT_REPAIRS.get(r.name)
                if spec and spec.kind == REPAIR_NONE and r.verdict == PREFLIGHT_FAIL:
                    print(f"           {'':<19} (not repairable here: {spec.why})")
                print(f"           {'':<19} -> {r.remedy}")

    failed = [r for r in results if r.verdict == PREFLIGHT_FAIL]
    undetermined = [r for r in results if r.applicable
                    and r.verdict in (PREFLIGHT_UNKNOWN, PREFLIGHT_SKIPPED, PREFLIGHT_UNCHECKED)]
    if failed:
        print(f"preflight: NOT READY — {len(failed)} precondition(s) failed"
              + (f", {len(undetermined)} undetermined" if undetermined else "") + ".")
        raise SystemExit(1)
    if undetermined:
        print(f"preflight: CANNOT TELL — nothing failed, but {len(undetermined)} "
              f"check(s) could not be determined. That is not a ready machine; it is an "
              f"unverified one.")
        raise SystemExit(2)
    print(f"preflight: READY — all {len(results)} preconditions verified on "
          f"{detect_machine()}.")


def _interpreter_module():
    """The WI-0328 resolver, or None on a member that does not carry it yet.

    RETURNS None rather than raising, because `session.py` is shipped byte-identical to
    every member and `interpreter.py` reaches them on the next substrate push, not the
    same instant. A member one push behind must get a sentence, not a traceback for a
    file it never received."""
    import importlib
    if str(ROOT) not in sys.path:
        sys.path.append(str(ROOT))
    try:
        return importlib.import_module("interpreter")
    except Exception:
        return None


def _interpreter_line() -> str:
    """The session-start `python:` line — which interpreter this session is on, and
    whether that is the one the member pinned.

    The gate receipt has named the interpreter since WI-0320, but the gate runs at
    LAND: on 2026-09-10 that meant a wave of five lanes learned they had been built
    on the wrong Python only after every one of them had finished. Saying it at start
    costs one line and moves the discovery to before the work."""
    i = _interpreter_module()
    if i is None:
        return "python " + ".".join(map(str, sys.version_info[:3])) + " (" + \
               sys.executable + ") — no interpreter pin on this member"
    want, source, problem = i.resolve(ROOT)
    line = i.running_line()
    if problem:
        return line + " — " + problem
    if not want:
        return line + " — not pinned"
    if i.same(want, sys.executable, ROOT):
        return line + " — pinned by " + source
    return line + " — NOT the pinned " + want + " (from " + source + ")"


def cmd_interpreter(args: argparse.Namespace) -> None:
    """WI-0328: which Python the harness resolved, from where, and whether the pin is
    actually in force.

    A pin nobody can see is a pin nobody can trust, and the failure this item exists
    for is exactly a determinism that was believed rather than checked. Exits 1 when a
    value WAS declared and could not be used — a broken declaration should be a thing
    that fails, not a thing that quietly does nothing while the harness runs on
    whatever PATH found."""
    i = _interpreter_module()
    if i is None:
        print("running:  python %s (%s)"
              % (".".join(map(str, sys.version_info[:3])), sys.executable))
        print("pinned:   nothing — this member has no interpreter.py yet, so it runs on "
              "whatever started it. The next substrate push delivers it.")
        return
    for line in i.report(ROOT):
        print(line)
    if i.resolve(ROOT)[2]:
        sys.exit(1)


def cmd_show(args: argparse.Namespace) -> None:
    """WI-0324: print a BOUNDED view of a file, and say what was held back.

    The verb exists because a runtime whose shell output is capped cannot read a large
    file safely, and the recovery it reaches for — re-reading guessed ranges — costs more
    than the first read did. Measured on the Codex transcripts available: nearly all hit a
    truncated read inside their first ten tool calls, and about half re-read the same file
    several times afterwards.

    Exits 2 on a bad request (no such section, an ambiguous one, a malformed range)
    rather than printing something plausible. A caller that asked for the wrong thing
    should learn that, not receive a different thing that looks right."""
    try:
        print(render_show(args.path, section=args.section, byte_range=args.bytes,
                          sections=args.sections, budget=args.budget))
    except ValueError as exc:
        print(f"show: {exc}", file=sys.stderr)
        sys.exit(2)


def cmd_test(args: argparse.Namespace) -> None:
    """Run the suite the one honest way and print a verdict that can say "I don't know".

    WI-0139: three sessions (~129, ~134, ~148) reported this suite green off a reading
    that had never contained a verdict, against a memory that already prescribed the
    working form. The third time is the `add-structural-guard-on-recurrence` trigger —
    a self-correction promise is anti-evidence, so the fix is a verb that makes the
    honest form the default instead of something to remember.

    REFUSES OVER AN IN-PROGRESS MERGE (WI-0215, ADR-0119 D4). Running the suite in a
    checkout holding a `git merge --no-commit` destroyed `MERGE_HEAD` while leaving the
    resolved content staged — so the merge PARENTAGE was lost and the work was not, which
    is the worst arrangement of the two: the next `git commit` produces a single-parent
    commit that silently drops the second trunk from the ancestry, and `integrate` then
    calls the trunks diverged forever. It cost hand-surgery with `commit-tree -p -p`.

    The destroyer was never identified — the reflog held no commit, reset or abort, so
    something removed the file directly rather than issuing a git command, and a grep for
    `MERGE_HEAD` across the suite finds nothing. That is exactly why this is a refusal and
    not a repair: against an unidentified destroyer the honest move is to keep it away from
    the state it destroys, and the reconciliation that needs a long-lived merge is both the
    hardest operation to redo and the one where a lost second parent is least visible.

    Exit 2, never 1: this is DID NOT REPORT. A refusal that exited 1 would read as a
    failing suite, which is a different claim about the code and a false one.

    RUNS THE GATE'S SUITE BY DEFAULT (WI-0353). Until this item there were two
    definitions of "the suite" in one repo: this verb's serial `unittest discover`
    (~12 minutes) and the land gate's sharded `curate/run_suite.py` (~60s). The verb an
    Architect reaches for was therefore both the slow one and not the one that decides
    the land, which is the whole defect — a green here cost twelve minutes and still
    did not answer the question it was asked. The command is now READ FROM the gate's
    configured list (`_gate_suite_command`) rather than named again here, so the two
    are one definition and cannot be edited apart.

    `--serial` KEEPS THE UNITTEST ORDER, and the reason is load-bearing rather than a
    courtesy: the serial order is the ONLY detector of order-dependent test pollution.
    Session ~305 proved it — `tests/test_notes_file.py` replaced two functions on the
    shared `session` module and never restored them, the trunk went red, and the
    sharded gate never saw it because sharding changes test order. Three code lands
    succeeded on that red trunk. OPS-0009's nightly derive stays serial for exactly
    this reason, and a sharded PASS here says so in as many words.

    BOTH PRINT WHICH RUNNER RAN, on the `runner:` line and again inside the verdict.
    A green from the sharded runner and a green from the serial runner are different
    claims about the tree; a reader holding one of them and unable to say which has the
    same problem this item exists to fix."""
    git_dir = _git_dir()
    if git_dir is not None and (git_dir / "MERGE_HEAD").exists():
        print("test: DID NOT REPORT — this checkout has a merge in progress "
              f"({git_dir / 'MERGE_HEAD'} exists).")
        print("      Running the suite here destroyed MERGE_HEAD once and cost a "
              "hand-rebuilt merge commit (WI-0215); the second parent is lost silently.")
        print("      Finish or abort the merge, then run the suite.")
        sys.exit(2)
    logdir = ROOT / ".session-state"
    try:
        logdir.mkdir(exist_ok=True)
    except Exception:
        logdir = Path(tempfile.gettempdir())
    out_path = logdir / "test-stdout.log"
    err_path = logdir / "test-stderr.log"

    # WHICH SUITE — derived from the gate's own command list, never restated here
    # (WI-0353). The verb ran a serial `unittest discover` while the gate ran
    # `curate/run_suite.py` sharded, so the repo had TWO definitions of "the suite"
    # and the one an Architect reaches for was the ~12-minute one that does not decide
    # the land. `_gate_suite_command` reads `session.config.json` rather than naming a
    # runner, so the two cannot drift apart again by editing one of them.
    #
    # `_gate_argv` resolves `python3` to `sys.executable` (WI-0328) — this verb once
    # re-resolved the interpreter from PATH *inside an already-running interpreter*, so
    # `poga test` could report a verdict from a different Python than the one that
    # would gate the land, the exact split that parked a whole wave on 2026-09-10.
    suite_cmd = _gate_suite_command()
    serial_reason = ""
    if getattr(args, "serial", False):
        serial_reason = "you asked for it with --serial"
        suite_cmd = None
    elif getattr(args, "verbose", False):
        # -v names each test in discovery order. The sharded runner has no such order
        # to name — its workers each discover their own shard — so honouring -v means
        # running serially. Announced rather than silent: a runner swapped out from
        # under the reader is the defect this item exists to remove.
        serial_reason = "-v names each test in discovery order, which only the serial runner has"
        suite_cmd = None
    elif suite_cmd is None:
        serial_reason = ("this member's gate configures no sharded runner, so the "
                         "serial suite IS the gate's suite")
    elif not (ROOT / GATE_SUITE_RUNNER).exists():
        serial_reason = (f"the gate names {GATE_SUITE_RUNNER} and this checkout does "
                         f"not have that file")
        suite_cmd = None

    serial_is_gate_suite = False
    if suite_cmd is None:
        argv = [sys.executable, "-m", "unittest", "discover", "-s", "tests"]
        tag, runner = "serial", ("serial — `unittest discover -s tests`, one process, "
                                 "discovery order")
        # WI-0462: a serial run IS the gate's suite when the gate's only suite command
        # spawns exactly this argv — a member's default gate, and every new project's.
        # Compared BEFORE `-p`/`-v` are appended: `-v` changes the output, not the tests
        # run, and `-p` is refused separately below. Any other shape (a sharded gate run
        # with --serial, two suite commands, extra flags) answers a different question.
        try:
            land_suites = _land_suite_commands()
            serial_is_gate_suite = (len(land_suites) == 1
                                    and _gate_argv(land_suites[0]) == argv)
        except Exception:
            serial_is_gate_suite = False
        if getattr(args, "pattern", None):
            argv += ["-p", args.pattern]
        if getattr(args, "verbose", False):
            argv.append("-v")
    else:
        argv = _gate_argv(suite_cmd)
        tag, runner = "sharded", (f"sharded — `{_gate_command_key(suite_cmd)}`, "
                                  f"the command the land gate itself runs")
        if getattr(args, "pattern", None):
            argv += ["-p", args.pattern]
        if getattr(args, "jobs", None):
            argv += ["-j", str(args.jobs)]

    # ADR-0148 D2 (WI-0427): a FULL run of the gate's own suite files a verdict for this
    # lane's code tree, which is what lets the land run no suite. Only a full run of the
    # gate's suite qualifies — the sharded runner, or the serial runner where the gate's
    # suite IS that serial command (WI-0462: a new project has no sharded gate, so it
    # never filed one and every land re-ran its suite). A `-p` subset, or a serial run
    # standing in for a sharded gate, answers a different question and files nothing.
    # The tree is read before AND after, so a run that raced an edit files nothing.
    verdict_tree = None
    if (tag == "sharded" or serial_is_gate_suite) and not getattr(args, "pattern", None):
        verdict_tree = _code_tree(None)
    print(f"runner:  {runner}")
    if serial_reason:
        print(f"         serial because {serial_reason}.")
    if getattr(args, "jobs", None) and suite_cmd is None:
        print("         -j does nothing here: the serial runner has one process.")
    print(f"running: {' '.join(argv)}")
    print(f"  stdout -> {out_path}")
    print(f"  stderr -> {err_path}   (the verdict lives here)")
    try:
        with open(out_path, "w", encoding="utf-8") as out, \
             open(err_path, "w", encoding="utf-8") as err:
            # Separate file handles, never a pipe: the exit status is genuinely this
            # process's own, and neither stream can reorder into the other.
            #
            # CLOSED STDIN, like the gate's own run (WI-0168). Inheriting the session's
            # stdin hung a land for 33 minutes with no output and no timeout — a test
            # reached `_read_hook_stdin`, whose `sys.stdin.read()` waited on an EOF that
            # a harness socket never sends. This verb runs the same suite the gate runs
            # and has no more business reading the session's input than the gate does;
            # in a detached lane pane a wait for input is indistinguishable from work.
            # POGA_GATE=1 when this run can file a verdict: the gate's run is told it is
            # the gate (ADR-0119 D4), and a verdict standing in for it must be the same
            # run, machine-scoped probes held back identically.
            env = {**os.environ, GATE_ENV_VAR: "1"} if verdict_tree else None
            started = time.monotonic()
            rc = subprocess.run(argv, cwd=ROOT, stdout=out, stderr=err,
                                stdin=subprocess.DEVNULL, env=env).returncode
            elapsed = time.monotonic() - started
    except Exception as e:
        print(f"test: DID NOT REPORT [{tag}] — could not run the suite ({e}).")
        sys.exit(2)

    err_text = err_path.read_text(encoding="utf-8", errors="replace")
    state, detail = _test_verdict(err_text, rc)
    if verdict_tree and state in ("passed", "failed"):
        if _code_tree(None) == verdict_tree:
            record_verdict(verdict_tree, state == "passed", "poga-test", elapsed, detail)
            print(f"verdict: filed {state.upper()} for this tree ({verdict_tree[:12]}) — "
                  + ("a land of this tree runs no suite (ADR-0148)." if state == "passed"
                     else "a land of this tree re-runs the suite first."))
        else:
            print("verdict: NOT filed — files changed while the suite ran, so the run "
                  "verified neither tree.")

    if state == "passed":
        # THE VERDICT NAMES ITS RUNNER, because a green from each is a different claim
        # about the tree and a reader who cannot tell which one they hold has the
        # problem this item exists to fix. Session ~305 is the case: a test replaced two
        # functions on the shared `session` module and never restored them, the trunk
        # went red, and the SHARDED gate never saw it because sharding changes test
        # order. Three code lands succeeded on that red trunk.
        print(f"test: PASSED [{tag}] — {detail} (exit {rc}).")
        if tag == "sharded":
            print("      Sharding changes test order, so this is silent about "
                  "order-dependent pollution;")
            print("      `--serial` is the only run that detects it (session ~305). "
                  "The nightly derive runs serially.")
        return
    if state == "failed":
        print(f"test: FAILED [{tag}] — {detail} (exit {rc}).")
        # WI-0334 — the third copy of this scan, reduced to one source. The prefix list
        # was local and missing `UNEXPECTED SUCCESS:`, a RED flavour `run_suite` goes
        # out of its way to emit precisely because the verdict alone never says which
        # test; and the cap was silent, so twenty-one red tests and twenty red tests
        # printed the same twenty lines. The overflow is COUNTED now. The full output is
        # on disk here, so this was a misreport rather than a loss — which is the only
        # reason it ranks below the gate receipt, not a reason to leave it.
        named = [l for l in err_text.splitlines()
                 if l.startswith(GATE_IDENTITY_PREFIXES)]
        for line in named[:GATE_TEST_NAMED_CAP]:
            print(f"  {line}")
        if len(named) > GATE_TEST_NAMED_CAP:
            print(f"  \u2026 and {len(named) - GATE_TEST_NAMED_CAP} more — "
                  f"the full list is in the file below.")
        print(f"full failure output: {err_path}")
        sys.exit(1)
    print(f"test: DID NOT REPORT [{tag}] — {detail}")
    print(f"read the log; do not report this run as either outcome: {err_path}")
    sys.exit(2)


def cmd_resolve_orphan(args: argparse.Namespace) -> None:
    """Close a finished-but-unstamped session by writing its JOURNAL (WI-0170).

    Two defects made the pre-journal-era verb unable to do the thing it names, and both
    are fixed here:

    (a) It read only `topmost_entry(handoff)`, so any orphan that was not the newest
        entry was unreachable — it answered "topmost session N is already closed" and
        exited. `--session-id` addresses a specific journal; ids are stable, ordinals
        are not.

    (b) More serious: it wrote the synthesized End stamp into `session-handoff.md`,
        which `cmd_compile` REGENERATES from the journals at every `start` and `end`.
        The journal's `ended` stayed blank, so the stamp was erased at the next session
        boundary — the verb reported success and left nothing behind. That is ADR-0060
        D2's "generated views never ride a rebase" violated one level down: authored
        state written into a derived file. The write now goes to the journal (the
        source) and the views are recompiled from it.

    The end time is ARGUED, never defaulted. The old default was the session's own start
    time — a zero-duration close asserting, as data, that a session which demonstrably
    did hours of work took no time at all (`no-fabricated-data`). `--keep` therefore
    requires both `--end-at` and `--end-source`: the time, and the evidence it was read
    off (`capture-the-probe`). The provenance lands in the journal as `end-provenance`,
    so the record says the stamp was derived rather than observed — a reader can tell a
    reconstructed close from a real one, the same honesty `closed-by` buys against a
    machine close (`a-close-is-the-banner-not-the-sentence`)."""
    if CFG is None:
        raise SystemExit(f"session.py: {CONFIG_PATH.name} missing or invalid — cannot resolve.")

    if args.session_id:
        p = journal_path(args.session_id)
        if not p.exists():
            raise SystemExit(
                f"resolve-orphan: no journal for session-id '{args.session_id}'. "
                f"Ids are stable; ordinals are not — pass the id, not the number.")
        fm, _ = parse_journal(p.read_text(encoding="utf-8"))
        if not fm:
            raise SystemExit(f"resolve-orphan: {p.name} has no parseable frontmatter.")
        if (fm.get("ended") or "").strip():
            raise SystemExit(f"resolve-orphan: {args.session_id} is already closed "
                             f"(ended: {fm['ended']}).")
        holder = _find_holder_journal()
        if holder and holder[1].get("session-id") == args.session_id:
            raise SystemExit(
                "resolve-orphan: that is THIS session's own journal. A live session "
                "closes itself with `session.py end`; stamping it here would publish "
                "an end for a session still running.")
    else:
        candidates = _resolve_orphan_candidates()
        if not candidates:
            raise SystemExit("resolve-orphan: no open journal other than this session's "
                             "— nothing to resolve.")
        if len(candidates) > 1:
            listing = "\n".join(
                f"  {c.get('session-id')}  ordinal {c.get('ordinal') or '?'}  "
                f"started {c.get('started') or '?'}" for _, c in candidates)
            raise SystemExit(
                f"resolve-orphan: {len(candidates)} open journals — name one with "
                f"--session-id:\n{listing}")
        p, fm = candidates[0]

    sid = fm.get("session-id")
    started = _parse_iso(fm.get("started") or "")

    if args.bad:
        new_text = finalize_journal(
            p.read_text(encoding="utf-8"), ended=_now_iso(), duration="unknown",
            title=RESOLVE_BAD_TITLE, closed_by="resolve-orphan (bad)")
        action = f"{sid} marked corrupt and closed"
    else:  # --keep (default)
        if not args.end_at:
            raise SystemExit(
                "resolve-orphan: --keep needs --end-at 'YYYY-MM-DD HH:MM TZ'. The end "
                "time must be argued from evidence, not defaulted to the start time — a "
                "zero-duration close asserts as data that a session which did hours of "
                "work took none. Usual evidence: the session's last commit "
                "(`git log -1 --format=%ad --date=iso-local <sha>`), its last heartbeat, "
                "or its last authored file.")
        if not args.end_source:
            raise SystemExit(
                "resolve-orphan: --keep needs --end-source '<how the time was obtained>' "
                "— e.g. 'last commit ef0e7c4'. The stamp records that the time was "
                "DERIVED; without the probe the record would claim an observed end it "
                "never had (capture-the-probe / no-fabricated-data).")
        end_dt = parse_start_dt(args.end_at)
        if end_dt is None:
            raise SystemExit(f"resolve-orphan: --end-at '{args.end_at}' not parseable — "
                             "want 'YYYY-MM-DD HH:MM TZ' (e.g. '2026-07-02 21:48 UTC').")
        if started and end_dt < started:
            raise SystemExit(
                f"resolve-orphan: --end-at {args.end_at} is BEFORE {sid} started "
                f"({fm.get('started')}). Refusing — a negative duration is not a close.")
        duration = format_duration(started, end_dt) if started else "unknown"
        new_text = finalize_journal(
            p.read_text(encoding="utf-8"), ended=end_dt.isoformat(), duration=duration,
            closed_by="resolve-orphan")
        pfm, pbody = parse_journal(new_text)
        pfm["end-provenance"] = f"derived — {args.end_source}"
        new_text = _rerender_journal(pfm, pbody)
        action = (f"{sid} closed at {args.end_at} ({duration}) — end time derived from "
                  f"{args.end_source}")

    if args.dry_run:
        print(f"--- resolve-orphan (dry-run, nothing written) ---\n{action}")
        return
    atomic_write(p, new_text)
    run_compile(CFG["tz"])
    print(f"resolve-orphan: {action}.\n"
          f"                Journal written and views recompiled. Title it with "
          f"`session.py journal-title {sid} '<title>'`.")


def git_argv(segment: str) -> list[str] | None:
    """Tokens of a git invocation from the subcommand onward — wrapper prefixes
    (sudo/env/…), env-assignments, and git global options (`-C path`, `-c k=v`,
    `--git-dir …`) all stripped. `FOO=1 sudo git -C path push --force` ->
    ['push', '--force']. Returns [] for a bare `git`/`git -C path` with no
    subcommand, and None if the segment isn't a git invocation at all. This is
    the `-C`-aware normalization that lets the destructive-git guard classify a
    `git -C <other-repo> reset --hard` the prefix-anchored deny-list can't see."""
    try:
        toks = shlex.split(segment)
    except ValueError:
        toks = segment.split()
    k = 0
    while k < len(toks) and (_ENV_ASSIGN_RE.match(toks[k]) or toks[k] in _CMD_PREFIXES):
        k += 1
    if k >= len(toks) or os.path.basename(toks[k]) != "git":
        return None
    k += 1
    while k < len(toks) and toks[k].startswith("-"):
        # `--opt=value` carries its own arg; bare `-C`/`-c`/… consume the next.
        if toks[k] in _GIT_OPTS_WITH_ARG:
            k += 2
        else:
            k += 1
    return toks[k:] if k < len(toks) else []


def compound_guard_enabled() -> bool:
    """Is the RETIRED compound-bash deny switched back on for this system?

    Per [ADR-0087], the deny is OFF by default fleet-wide. Its motivation was a
    harness limitation — permission allow-strings cannot match a compound command, so
    every `&&`/`;` chain prompted, and one-op-per-call was what let the allow-list do
    its job. The harness's auto permission mode judges commands directly, so the
    discipline no longer buys the thing it was created to buy. The code stays live
    behind this switch (and under test) rather than rotting in git history: a system
    that still wants it sets `"compound_bash_guard": true` in `session.config.json`.

    Read INDEPENDENTLY of `_load_config` and defaulting to False on ANY error, so
    check-bash keeps its standing promise that the guard cannot break just because
    config is missing or malformed — `_load_config` returns None on any single bad
    field, and a flag read through it would make an unrelated typo silently re-enable
    or disable a policy. The destructive-git half never consults this at all."""
    try:
        raw = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
        return bool(raw.get("compound_bash_guard", False))
    except Exception:
        return False


def pickers_allowed() -> bool:
    """Has this system turned OFF the P17 picker guard? WI-0451.

    The one documented off switch is `"interaction": {"pickers": "allow"}` in the
    repo's `session.config.json` (CONFIG_PATH — the config of the checkout the hook
    runs in, so a lane worktree reads its own tracked copy). The guard stays ON by
    default for everyone, for P17's reason: a picker narrows the answer to the options
    the agent thought of, and the user loses the chance to say what it did not
    anticipate.

    FAILS CLOSED, the opposite of `compound_guard_enabled`, and on purpose: only the
    exact string "allow" turns the guard off. A missing file, unreadable JSON, a
    missing key, a non-dict block or any other value leaves the picker denied — a
    malformed config must never be the thing that silently lifts a ban. Read
    independently of `_load_config` for the same reason as the flag above."""
    try:
        raw = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
        block = raw.get("interaction")
        return isinstance(block, dict) and block.get("pickers") == "allow"
    except Exception:
        return False


# WI-0451: how the agent talks, as configuration. The defaults are the values the
# federation has always run with, so a config with no `voice` block behaves as before.
VOICE_DEFAULTS = {"terse": True, "emoji": False, "questions": "decide-and-record"}
VOICE_QUESTION_MODES = ("decide-and-record", "recommend-then-confirm")


def voice_settings() -> dict:
    """The `voice` block of session.config.json, field by field over VOICE_DEFAULTS.

    `terse` and `emoji` must be booleans; `questions` is `decide-and-record` (decide
    mechanics, record the call for later review, ask only about direction) or
    `recommend-then-confirm` (recommend, then wait for a yes). A field that is missing
    or has the wrong type or value falls back to its default ALONE — one typo must not
    reset the others. Never raises."""
    out = dict(VOICE_DEFAULTS)
    try:
        raw = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
        block = raw.get("voice")
    except Exception:
        return out
    if not isinstance(block, dict):
        return out
    for key in ("terse", "emoji"):
        if isinstance(block.get(key), bool):
            out[key] = block[key]
    if block.get("questions") in VOICE_QUESTION_MODES:
        out["questions"] = block["questions"]
    return out


def voice_line() -> str:
    """One orientation line naming the voice settings, so they reach the model at start."""
    v = voice_settings()
    return (f"voice:   {'terse' if v['terse'] else 'full-length'}, "
            f"{'emoji ok' if v['emoji'] else 'no emoji'}, questions: {v['questions']} "
            "(session.config.json `voice`)")


def pickers_line() -> str:
    """One orientation line naming the effective P17 picker policy for this system."""
    if pickers_allowed():
        return ("pickers: allowed (session.config.json interaction.pickers = allow); "
                "still explain the options and leave room to reject the premise")
    return ("pickers: denied, the P17 default; ask in prose "
            "(session.config.json interaction.pickers)")


def cmd_check_bash(_args: argparse.Namespace) -> None:
    """PreToolUse(Bash) hook: deny destructive git, a peer-pane relay and a
    false-green run (all always) and top-level compounds (only where re-enabled);
    auto-approve the safe git surface; leave everything else to the normal
    permission flow.

    Order matters, and [ADR-0087] FLIPPED it. The destructive-git check now runs
    FIRST and UNCONDITIONALLY — it used to sit behind the compound deny, which was
    fine while compounds were always denied upstream, but with that deny off by
    default a compound CONTAINING a destructive git op would otherwise sail through.
    (`destructive_git_violation` already iterates `top_level_segments`, so it covers
    compounds on its own; that is what makes the flip safe.) The compound deny is
    consulted only when `compound_guard_enabled()` says a system re-enabled it.

    THE THIRD UNCONDITIONAL DENY is `false_green_violation` (WI-0344): a run whose
    exit code is the verdict — a test suite, a land — with anything running after it
    in the same command, so the status that comes back belongs to the downstream
    command and a failing run reports exit 0. It sits with the other two rather than
    behind the ADR-0087 flag because its motivation was never prompt-matching
    either.

    Then safe-git auto-approve (allow), else no output (prompt). Fails open on any
    error — a guard that bricks the Bash tool is worse than one that occasionally
    misses. Emits the PreToolUse decision as pure JSON on stdout (the supported
    `hookSpecificOutput.permissionDecision` path: "deny" or "allow")."""
    try:
        payload = json.load(sys.stdin)
    except Exception:
        sys.exit(0)  # no/garbled input -> don't interfere
    if payload.get("tool_name") != "Bash":
        sys.exit(0)
    command = (payload.get("tool_input") or {}).get("command", "")
    if not isinstance(command, str) or not command.strip():
        sys.exit(0)
    try:
        # Destructive-git is motivation-independent and runs unconditionally; the
        # compound deny is opt-in per ADR-0087. Never let the flag read gate the
        # destructive check — a missing/garbled config must still deny `push --force`.
        reason = destructive_git_violation(command)
        # WI-0255: also unconditional, and for the same reason the destructive-git check
        # is — this guard's subject is not permission-prompt matching, it is a lane's
        # inability to tell a peer from its user. A repeat occurrence is what moves that
        # from discipline into code (`add-structural-guard-on-recurrence`).
        if not reason:
            reason = peer_injection_violation(command)
        # WI-0344: unconditional, on the same footing as the two above and for the
        # same reason — its subject is not permission-prompt matching either. It is
        # a run reporting a verdict it never produced, which is the one outcome the
        # work-item store exists to prevent asserting. Eight recorded occurrences
        # against an honest verb that has existed since WI-0139.
        if not reason:
            reason = false_green_violation(command)
        if not reason and compound_guard_enabled():
            reason = compound_violation(command)
    except Exception:
        sys.exit(0)  # parser bug must not block the user
    if reason:
        _log_guard_firing("check-bash", command)   # S2: one line per firing
        print(json.dumps({
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason": reason,
            }
        }))
        sys.exit(0)
    # No violation. Auto-APPROVE the recognized-safe git surface so `git -C <path> …`
    # stops prompting (no settings allow-string can match it — session 60). A hook
    # "allow" can't override a settings `deny`, and destructive git was already
    # screened above, so this only ever fast-paths safe git. Everything else falls
    # through (no output) to the normal permission flow — unchanged behavior.
    try:
        allow = safe_git_auto_allow(command)
    except Exception:
        sys.exit(0)  # parser bug must not block the user
    if allow:
        print(json.dumps({
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "allow",
                "permissionDecisionReason": allow,
            }
        }))
    sys.exit(0)


def cmd_check_question(_args: argparse.Namespace) -> None:
    """PreToolUse(AskUserQuestion) hook: deny the multiple-choice picker.

    P17 ask-in-prose-not-pickers (Accepted session 42) forbids AskUserQuestion /
    chip pickers for EVERY question to the user — ask in prose instead. This is the
    structural guard for that principle (add-structural-guard-on-recurrence under
    P15), the sibling of check-bash, built after a freshly-bootstrapped Architect
    asked operator a multiple-choice question despite the rule being in its profile. It
    does NOT touch the harness's own permission prompts — those are a separate flow
    and keep working. Fails open on any error — a guard must never brick the tool
    flow. Emits the PreToolUse deny as pure JSON on stdout.

    ON BY DEFAULT; one setting turns it off (WI-0451): `"interaction": {"pickers":
    "allow"}` in session.config.json. The CONFIG read fails closed — see
    `pickers_allowed` — so a broken config keeps the ban, while a broken hook payload
    still fails open as above."""
    try:
        payload = json.load(sys.stdin)
    except Exception:
        sys.exit(0)  # no/garbled input -> don't interfere
    if payload.get("tool_name") != "AskUserQuestion":
        sys.exit(0)
    if pickers_allowed():
        sys.exit(0)  # WI-0451: this system set interaction.pickers = "allow"
    reason = (
        "Blocked by P17 ask-in-prose-not-pickers: multiple-choice "
        "pickers (AskUserQuestion / chip UI) are disallowed for every question to the "
        "user, even when your recommendation is one of the options. Ask in PROSE "
        "instead — when there are real options, lay out each with its pros and cons, "
        "then give a reasoned recommendation and a plain confirm "
        '("I recommend X because …; OK to proceed?"). For a batch of low-stakes '
        'confirmations, a numbered list the user answers tersely ("1 yes, 2 no, 3 '
        'yes") is fine. NOTE: this does not affect harness permission prompts — those '
        "are a separate mechanism and still appear normally when a tool needs approval. "
        "To allow pickers in this repo, set \"interaction\": {\"pickers\": \"allow\"} "
        "in session.config.json."
    )
    _log_guard_firing("check-question", "AskUserQuestion")   # S2: one line per firing
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }))
    sys.exit(0)


def _grant_trailer_args(gid: str = "", verb: str = "", item: str = "",
                        lane: str = "") -> list:
    """ADR-0112 D9 — the `Authorized-By:` trailer, as extra `git commit` args.

    Returns `["-m", "Authorized-By: G-xxxx"]` when a grant is named AND resolves, and
    **an empty list otherwise**, so a commit made without a grant is argv-identical to
    what this harness produced before ADR-0112. That matters more than usual: `session.py`
    ships byte-identical to every member, and most of them never dispatch a lane.

    THE RESOLVE IS THE POINT, not decoration. A trailer is written only for a grant that
    actually authorizes the act — otherwise the audit trail would gain exactly the kind of
    unbacked provenance claim this ADR exists to remove, which would be worse than no
    trailer at all. A named-but-unresolvable grant prints its refusal and writes nothing.

    Why a receipt in the commit rather than only in the store: the coordination store is
    ephemeral by design (`<git-common-dir>/poga-coord`, untracked, cleared freely), so
    without this the answer to *what authorized this?* dies with it. One token in a
    message already being written makes the receipt DERIVED instead of stored — the same
    argument that puts a brief's edit-id in the CHANGELOG line.

    WI-0280 — THE ID COMES FROM THE COMMAND LINE, NEVER THE ENVIRONMENT. This used to fall
    through to `os.environ.get("POGA_GRANT")`. It no longer does, and
    `test_grants.py::TheTrailerTakesNoAmbientInputTest` fails if that is put back. The
    reasoning is recorded in full at `cited_grant` in `sessionlib/config.py`; the short
    form is that an exported variable authorizes a whole shell rather than an act. The
    fallback is now `cited_grant()` — `--grant` on the verb being run, set once at
    `main()`'s choke point."""
    gid = (gid or cited_grant()).strip()
    if not gid:
        return []
    state, sentence = resolve_grant(gid, verb=verb, item=item, lane=lane)
    if state != GRANT_GRANTED:
        print(f"grant:   NOT written to the commit trailer — {sentence}", file=sys.stderr)
        return []
    return ["-m", f"{GRANT_TRAILER_KEY}: {gid}"]


def _preflight_failure_dir(create: bool = False) -> Path | None:
    """`<git-common-dir>/poga-coord/preflight-failures` — the stderr of a preflight that
    could not deliver a verdict, parked by `poga`'s fail-open branch (WI-0180).

    NOT a COORD_KINDS member, for `_dispatch_dir`'s reason one step sharper: this record is
    written seconds before a lane opens and is FOR that lane's session, so a TTL reaper or a
    teardown release would sweep the evidence between the write and the only read of it."""
    common = _git_common_dir()
    if common is None:
        return None
    d = common / COORD_DIRNAME / PREFLIGHT_FAILURE_DIRNAME
    if create:
        try:
            d.mkdir(parents=True, exist_ok=True)
        except Exception:
            return None
    return d


def _preflight_failure_lines(consume: bool = True) -> list[str]:
    """Surface any preflight failure `poga` captured, at the start of the session it
    preceded — and move it aside once surfaced.

    WI-0180's second half, and the half that decides WHO does the diagnosing. The capture
    alone only moves the evidence from nowhere to a path nobody looks at; the operator
    would still be the one expected to notice a NOTE scroll past, remember it, and go
    reading. That is a person as an execution surface for a fact the machine already has
    ([ADR-0099](adr/0099-the-user-is-not-an-execution-surface.md)) — and it is the exact
    step that failed here, because the message is intermittent and scrolls past under a
    launch banner.

    Surfaced records move to `seen/` rather than being deleted: they are tiny, they only
    exist when the bug fired, and a second occurrence is the evidence that says whether
    the cause is the machine, the clock, or the checkout. `consume=False` for any caller
    that is not really opening a session (a dry run), so a rehearsal cannot mark evidence
    read that nobody read."""
    d = _preflight_failure_dir()
    if d is None or not d.is_dir():
        return []
    try:
        recs = sorted((f for f in d.glob("*.txt") if f.is_file()),
                      key=lambda f: f.name, reverse=True)
    except Exception:
        return []
    if not recs:
        return []
    lines = [f"preflight: {len(recs)} launch(es) could not verify preconditions — "
             f"`poga` captured the reason. READ IT; do not ask operator to reproduce it."]
    for f in recs[:3]:
        why = ""
        with contextlib.suppress(Exception):
            body = f.read_text(errors="replace").splitlines()
            head = next((l for l in body if l.startswith("# preflight ")), "")
            tail = [l for l in body[body.index("--- stderr ---") + 1:]
                    if l.strip()] if "--- stderr ---" in body else []
            why = f"{head[2:]} — {tail[-1][:120]}" if tail else head[2:]
        lines.append(f"preflight: {f} {('· ' + why) if why else ''}".rstrip())
    if len(recs) > 3:
        lines.append(f"preflight: (+{len(recs) - 3} older record(s) in {d})")
    if consume:
        seen = d / "seen"
        with contextlib.suppress(Exception):
            seen.mkdir(parents=True, exist_ok=True)
            for f in recs:
                with contextlib.suppress(Exception):
                    f.rename(seen / f.name)
    return lines


