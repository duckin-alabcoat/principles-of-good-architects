def _cli_land(sub) -> None:
    """Land (`merge`) and handoff rotation."""
    mp = sub.add_parser("merge", help="Land this branch/lane onto the trunk through the "
                                      "gate AND close the session — the shape of a "
                                      "session is open a lane, land one work item, and "
                                      "close. Pass --continue to land without closing "
                                      "(the retry / deferred-land path, and a genuine "
                                      "second package).")
    mp.add_argument("--continue", dest="keep_open", action="store_true",
                    help="WI-0288 R2: land WITHOUT closing, leaving the journal open — "
                         "the session keeps its id, ordinal, context and claims "
                         "(ADR-0056 D3). The retry path for a land blocked at the "
                         "rebase or the gate, the deferred land for an `end --no-merge`, "
                         "and the second work package, which is the exception you say "
                         "out loud rather than the default shape.")
    mp.add_argument("--title", help="Short title; set on the journal + shown as "
                                    "'Session N'. Ignored with --continue.")
    mp.add_argument("--session-id", help="Durable journal id to close, when the "
                    "CLAUDE_CODE_SESSION_ID env can't disambiguate (concurrent "
                    "sessions). WI-0340: `merge`'s closing half IS `end` "
                    "(`_merge_close_args`), and every other flag that close is made of "
                    "is already here — this one was forwarded but never declared, so "
                    "the refusal that names it sent the operator to a flag their verb "
                    "could not take. Grants nothing `end --session-id` did not already: "
                    "same handler, same journal resolution, same land. Ignored with "
                    "--continue, which closes nothing.")
    mp.add_argument("--confirm",
                    help="What the user said when they agreed to close, verbatim. "
                         "REQUIRED for the closing form on a hand-opened session, on "
                         "exactly the terms `end` requires it (ADR-0113): a closing "
                         "`merge` is a close, and gating one verb while leaving the "
                         "other open would make the guard one verb wide. A DISPATCHED "
                         "lane needs none — its dispatch is its authorization. Not "
                         "needed with --continue, which closes nothing.")
    mp.add_argument("--commit", default=None,
                    help="Commit message for any uncommitted branch work before landing.")
    # WI-0355. PUBLISHING IS PART OF LANDING, and the flag that used to gate it is now the
    # opt-out. `--push` was `store_true`, and dispatch briefs a lane with `merge --continue`
    # and no flag — so every dispatched lane landed locally and left the trunk owed to
    # whichever interactive session next noticed. Measured twice in session ~302: 6 unpushed
    # commits on local main at one point and 9 at another, all from lanes that had landed
    # cleanly hours earlier, found only by comparing to origin by hand. It also contradicted
    # ADR-0056 D3 step 5, which makes `git push` a step of the land, and the comment in
    # `_publication_is_stalled` that says "every land pushes".
    mp.add_argument("--no-push", dest="push", action="store_false",
                    help="Land locally and do NOT publish. The work goes on the trunk and "
                         "the push is reported as OWED; `session.py integrate` makes it "
                         "later. For a genuinely offline member.")
    # Accepted and ignored: it now names the default. Kept rather than removed because
    # STANDARD.md ships `merge --commit \"<message>\" --push` to every member in the fleet
    # and they do not all re-render on the same day — removing it would turn a stale doc
    # into a hard argparse error on the one verb a member cannot work without.
    mp.add_argument("--push", dest="push", action="store_true", help=argparse.SUPPRESS)
    mp.add_argument("--focus", help="STATUS.md focus line (judgment field).")
    mp.add_argument("--blocked", help="STATUS.md blocked field (e.g. 'false' or a reason).")
    mp.add_argument("--resolve", choices=RESOLVE_POLICIES, default="generated",
                    help="WI-0109: named policy for a rebase conflict. `generated` (default) takes the trunk side when the conflict is confined to this member's generated views — they are regenerated by this land's own recompile, so nothing durable is chosen away. `none` disables it. Anything outside the class always refuses, by name.")
    mp.add_argument("--no-renumber", action="store_true", help=NO_RENUMBER_HELP)
    mp.add_argument("--dry-run", action="store_true", help="Print only; write nothing.")
    mp.set_defaults(func=cmd_merge, push=True)

    rp = sub.add_parser(
        "rotate",
        help="Archive all but the newest --keep prose entries into session-handoff-archive/.",
    )
    rp.add_argument("--keep", type=int, default=ROTATE_KEEP_DEFAULT,
                    help=f"Prose entries to keep in the live handoff (default {ROTATE_KEEP_DEFAULT}).")
    rp.add_argument("--dry-run", action="store_true", help="Print only; write nothing.")
    rp.set_defaults(func=cmd_rotate)


