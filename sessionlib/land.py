# `_gate_command_prefixes`, `_gate_skip_plan`, `_classify_gate_neutral` and
# `_gate_unless_neutral` are deleted rather than left unreachable (ADR-0124's
# precedent). A diff is gate-neutral by the declared `BOOKKEEPING_PATHS`, made safe
# by curate/store_guard.py; `_gate_input_prefixes` above stays as the reader the
# nightly deriver's tests pin.


# ── ADR-0148: a land is a merge (WI-0427) ──────────────────────────────────────────
#
# The land verb checks, merges and pushes. It never runs the suite. Validation belongs
# to the lane and is bound to the lane's TREE (D2); a bookkeeping-only diff needs none
# (D3); a lane that loses a race to the trunk rebases and lands without re-validating
# (D4); and the trunk verifies itself after the merge, in the background (D5,
# sessionlib/trunkcheck.py). Measured before this change: validate was ~98% of every
# land's total, median 193 s even for a diff that touched only journals.
#
# WHY THE VERDICT IS KEYED ON THE "CODE TREE". A lane's `poga test` runs over its
# working tree; the land then commits the closed journal and the handoff on top. Keyed
# on the raw tree, that close commit would orphan every verdict the session earned.
# Keyed on the tree with `BOOKKEEPING_PATHS` removed, the two are the same key by
# construction — which is safe for exactly the reason D3 is safe: the suite may not
# read those paths (curate/store_guard.py fails the test that does).

#: Where verdicts live: the git common dir, beside the land receipts and for the same
#: reason — per-machine evidence about local runs, never tracked.
LAND_VERDICTS_DIRNAME = "land-verdicts"
#: `retention-enforced-by-code`. A verdict older than this is for a tree nobody is
#: about to land; trimmed on every write.
LAND_VERDICT_RETENTION_DAYS = 14

#: Set by `_ensure_lane_verdict` when the land had to build the lane's verdict itself
#: BEFORE its clock started (D2: that is session build time, not land time). Carried to
#: the receipt as `build_seconds` so the cost is on the record rather than hidden.
_LAND_BUILD: dict = {}


def _bookkeeping_pathspecs() -> list:
    return [p.rstrip("/") for p in BOOKKEEPING_PATHS]


def _land_suite_commands() -> list:
    """The configured gate commands that RUN A TEST SUITE — the part a land no longer
    runs. The sharded runner (`GATE_SUITE_RUNNER`) and a `-m unittest` invocation (a
    member's default gate is exactly that) both count; everything else in the gate is
    a cheap check and still runs at every land.

    Wider than `_gate_is_suite_command` on purpose, and kept separate from it: that
    predicate names the SHARDED runner for `poga test` and the suite-run counter, and
    widening it would relabel a member's serial run as sharded."""
    out = []
    for cmd in _gate_configured_commands():
        argv = cmd.split() if isinstance(cmd, str) else [str(part) for part in cmd]
        if _gate_is_suite_command(cmd) or (
                "-m" in argv and argv[argv.index("-m") + 1:argv.index("-m") + 2] == ["unittest"]):
            out.append(cmd)
    return out


def _land_suite_keys() -> frozenset:
    return frozenset(_gate_command_key(c) for c in _land_suite_commands())


def _code_tree(commit: str | None = None) -> str | None:
    """The tree of `commit` (or of the working tree, when None) with every
    `BOOKKEEPING_PATHS` entry removed — the key a suite verdict is filed under.

    Built in a PRIVATE index (GIT_INDEX_FILE), so nothing a concurrent session has
    staged is read or disturbed. The working-tree form seeds that index from the real
    one to keep git's stat cache, then `SWEEP_ADD`, which honours .gitignore (and drops
    bytecode, WI-0461) exactly as the land's own close commit does — so the tree a `poga test` verdict is filed under and
    the tree the land commits are the same tree. None on any git failure, which every
    caller reads as "no verdict"."""
    fd, idx = tempfile.mkstemp(prefix="poga-codetree-")
    os.close(fd)
    env = {**os.environ, "GIT_INDEX_FILE": idx}
    try:
        if commit:
            os.unlink(idx)
            if sh(["git", "read-tree", commit], check=False, env=env).returncode != 0:
                return None
        else:
            real = sh(["git", "rev-parse", "--path-format=absolute", "--git-path", "index"],
                      check=False).stdout.strip()
            if real and Path(real).is_file():
                shutil.copyfile(real, idx)
            else:
                os.unlink(idx)
                sh(["git", "read-tree", "HEAD"], check=False, env=env)
            if sh(SWEEP_ADD, check=False, env=env).returncode != 0:
                return None
        # `-f`: a private index read from one tree holds bookkeeping content that differs
        # from both HEAD and the working file whenever the lane edited an existing one,
        # and without it git refuses the WHOLE removal — leaving the paths in and calling
        # every such lane a code change. Checked, because a refusal here is a wrong key.
        if sh(["git", "rm", "-r", "-f", "--cached", "-q", "--ignore-unmatch", "--"]
              + _bookkeeping_pathspecs(), check=False, env=env).returncode != 0:
            return None
        r = sh(["git", "write-tree"], check=False, env=env)
        out = r.stdout.strip()
        return out if r.returncode == 0 and out else None
    except Exception:
        return None
    finally:
        with contextlib.suppress(OSError):
            os.unlink(idx)


def _suite_fingerprint() -> str:
    """What a verdict must agree on besides the tree: the suite command as configured,
    the interpreter, and the gate environment. A green from another Python or another
    runner is a different claim (WI-0320, WI-0353) and must not license a land."""
    import hashlib
    keys = sorted(_land_suite_keys())
    ver = ".".join(map(str, sys.version_info[:3]))
    raw = json.dumps([keys, sys.executable, ver, GATE_ENV_VAR], sort_keys=True)
    return hashlib.sha256(raw.encode()).hexdigest()[:16]


def _verdicts_dir() -> "Path | None":
    common = _git_common_dir()
    return None if common is None else common / LAND_VERDICTS_DIRNAME


def record_verdict(tree: str | None, green: bool, source: str, seconds: float,
                   detail: str = "") -> dict | None:
    """File a suite verdict for `tree`. Never raises; returns what it wrote.

    A RED verdict is filed too, so a land can say "this tree was tested and failed"
    rather than re-running a suite it already knows the answer to."""
    d = _verdicts_dir()
    if not tree or d is None:
        return None
    rec = {"tree": tree, "green": bool(green), "suite": _suite_fingerprint(),
           "source": source, "seconds": round(float(seconds), 3), "at": _now_iso(),
           "at_epoch": time.time(), "detail": detail[:300]}
    try:
        d.mkdir(parents=True, exist_ok=True)
        atomic_write(d / f"{tree}.json", json.dumps(rec, sort_keys=True))
        cutoff = time.time() - LAND_VERDICT_RETENTION_DAYS * 86400
        for f in d.glob("*.json"):
            with contextlib.suppress(OSError):
                if f.stat().st_mtime < cutoff:
                    f.unlink()
    except Exception:
        return None
    return rec


def lookup_verdict(tree: str | None) -> dict | None:
    """The verdict filed for `tree` under THIS suite fingerprint, or None."""
    d = _verdicts_dir()
    if not tree or d is None:
        return None
    try:
        rec = json.loads((d / f"{tree}.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(rec, dict) or rec.get("suite") != _suite_fingerprint():
        return None
    return rec


def _run_suite_for_verdict(cwd: "Path | None" = None, emit=print) -> tuple:
    """Run the gate's suite command once in `cwd` and classify it.

    Returns `(state, detail, seconds, named)` with `state` one of passed / failed /
    did-not-report (`_test_verdict`'s three), `named` the failing-test lines. The same
    command, interpreter, closed stdin and `POGA_GATE=1` the gate itself used, so the
    verdict it files means what a gate run would have meant."""
    started = time.monotonic()
    state, detail, named = "passed", "", []
    for cmd in _land_suite_commands():
        try:
            r = sh(_gate_argv(cmd), check=False, cwd=cwd, stdin=subprocess.DEVNULL,
                   env={**os.environ, GATE_ENV_VAR: "1"})
        except Exception as e:
            return "did-not-report", f"could not run the suite ({e})", \
                time.monotonic() - started, []
        err = r.stderr or ""
        state, detail = _test_verdict(err, r.returncode)
        named = [l for l in (err + "\n" + (r.stdout or "")).splitlines()
                 if l.startswith(GATE_IDENTITY_PREFIXES)][:GATE_RECEIPT_MAX_NAMED]
        if state != "passed":
            break
    return state, detail, time.monotonic() - started, named


def _lane_needs_verdict(base: str | None, tree: str | None) -> bool:
    """Does a lane whose code tree is `tree`, built on `base`, change any code?

    Equal code trees mean every difference is under `BOOKKEEPING_PATHS` (D3). Anything
    unreadable counts as a code change — fail closed, as ADR-0117 D3 did."""
    if not base or not tree:
        return True
    return _code_tree(base) != tree


def _ensure_lane_verdict(trunk: str, emit=print) -> tuple:
    """D2, run BEFORE the land's clock starts: make sure the lane's code tree has a
    green verdict, building it here if the session never ran the suite.

    Returns `(ok, info)`. `info` is what the in-loop check and the receipt need:
    `tree` (the lane's code tree, pre-rebase), `head`, `source` ("lane-verdict",
    "built-at-land", "neutral") and `build_seconds`. `ok` False means the lane's own
    suite is red and the land must not proceed — its failing tests are printed.

    "Told so, and runs the suite once in its own lane": the build runs HERE, in the
    lane's working tree, before `mark_ready_to_land`, because that time is the
    session's build time and not land time (brief D2). It is recorded on the receipt
    as `build_seconds`, never dropped."""
    _LAND_BUILD.clear()
    head = sh(["git", "rev-parse", "HEAD"], check=False).stdout.strip() or None
    tree = _code_tree(None)
    base = sh(["git", "merge-base", f"refs/heads/{trunk}", "HEAD"],
              check=False).stdout.strip() or None
    info = {"tree": tree, "head": head, "base": base, "build_seconds": 0.0}
    if not _land_suite_commands():
        # A gate with no suite in it: every command is a cheap check and runs at land.
        info["source"] = "no-suite"
        _LAND_BUILD.update(info)
        return True, info
    if not _lane_needs_verdict(base, tree):
        info["source"] = "neutral"
        _LAND_BUILD.update(info)
        return True, info
    have = lookup_verdict(tree)
    if have and have.get("green"):
        info["source"] = "lane-verdict"
        info["verdict_at"] = have.get("at")
        emit(f"verdict: GREEN for this lane's tree {str(tree)[:12]} "
             f"({have.get('source')}, {have.get('at', '')[:16]}) — the land runs no suite.")
        _LAND_BUILD.update(info)
        return True, info
    # A RED on file is said as RED, not "none" — a lane reading "none" right after its own
    # failing run concludes the verdict was lost (first real lane-A land, 2026-09-25).
    have_what = (f"RED on file ({have.get('source')}, {have.get('at', '')[:16]}) — "
                 f"re-running" if have else "none — running")
    emit(f"verdict: {have_what} the suite once for this lane's tree {str(tree)[:12]} "
         f"in this lane before landing (build time, not land time; `poga test` records "
         f"one as you work).")
    state, detail, seconds, named = _run_suite_for_verdict(ROOT, emit)
    after = _code_tree(None)
    info["build_seconds"] = round(seconds, 3)
    if after != tree:
        # The tree moved while the suite ran — something wrote into the lane. The run
        # verified neither tree, so it files nothing and the land proceeds on neither.
        emit("verdict: the lane's files changed while the suite ran; nothing was filed. "
             "Re-run the land.")
        return False, info
    record_verdict(tree, state == "passed", "built-at-land", seconds, detail)
    if state != "passed":
        emit(f"land:    BLOCKED — this lane's suite is {state.upper()} ({detail}).")
        for line in named:
            emit(f"         {line}")
        return False, info
    info["source"] = "built-at-land"
    emit(f"verdict: GREEN, filed for tree {str(tree)[:12]} ({seconds:.1f}s).")
    _LAND_BUILD.update(info)
    return True, info


def _land_gate(parent: str, tip: str, run, accepted: dict | None = None) -> tuple:
    """The whole of what a land checks before it merges (ADR-0148 D1–D4).

    Returns `(ok, report, info)`. `run(skip)` is the lander's own gate runner (a
    `_gate_commit` over the candidate); it is called with the SUITE command skipped, so
    only the cheap checks run — wi-check, the generated-file checks, citations. Those
    stay on the land path deliberately: they are seconds, and several of them read the
    very bookkeeping a neutral diff changes.

    The suite runs here in exactly one case: a lander that reached this point with no
    verdict established for the lane (`accepted` empty — the shared-tree and branch
    landers, which have no pre-clock step). That run is counted as validation, in the
    land's time, because it is.

    `accepted` persists across the lander's attempts. Once a verdict has been accepted
    for this land, a later attempt after a `moved` trunk lands on the clean rebase
    alone (D4): two independently-green lanes that are red together are the trunk
    check's to catch (D5), not a second suite run per race lost."""
    accepted = accepted if accepted is not None else {}
    info = {"suite_seconds": 0.0, "checks_seconds": 0.0, "gate_neutral": None,
            "verdict": None, "diff_class": "code", "trunk_check_refusal": ""}
    with contextlib.suppress(Exception):
        print(trunk_check_line())
    tip_tree = _code_tree(tip)
    neutral = tip_tree is not None and tip_tree == _code_tree(parent)
    if neutral:
        info["diff_class"] = "bookkeeping"
        info["gate_neutral"] = "every changed path is bookkeeping (ADR-0148 D3)"
    refusal = ""
    with contextlib.suppress(Exception):
        refusal = _trunk_check_refusal(not neutral, accepted.get("head"))
    if refusal:
        info["trunk_check_refusal"] = refusal
        # The lane's own verdict still goes on the refused receipt: "refused although
        # green on its tree" is the fact a reader of the receipt needs.
        info["verdict"] = {"source": accepted.get("source"), "tree": accepted.get("tree")}
        return False, refusal, info
    suite_keys = _land_suite_keys()
    if not suite_keys:
        accepted.setdefault("source", "no-suite")
    if neutral:
        info["verdict"] = {"source": "neutral", "tree": tip_tree}
        report_head = "gate:    suite not run — " + info["gate_neutral"]
    elif accepted.get("source") == "no-suite":
        info["verdict"] = {"source": "no-suite"}
        report_head = "gate:    no suite configured — every gate command runs as a check"
    elif accepted.get("source") in ("lane-verdict", "built-at-land", "land-validated"):
        rebased = accepted.get("tree") != tip_tree
        info["verdict"] = {"source": accepted["source"], "tree": accepted.get("tree"),
                           "suite": _suite_fingerprint(),
                           "rebased": rebased}
        if accepted.get("attempts_seen"):
            info["verdict"]["reason"] = ("moved: clean rebase onto the new trunk, no "
                                         "re-validation (ADR-0148 D4)")
        report_head = ("gate:    suite not run — green verdict for the lane's tree "
                       f"{str(accepted.get('tree'))[:12]} ({accepted['source']})"
                       + ("; rebased cleanly onto the trunk" if rebased else ""))
    else:
        have = lookup_verdict(tip_tree)
        if have and have.get("green"):
            accepted.update({"source": "lane-verdict", "tree": tip_tree})
            info["verdict"] = {"source": "lane-verdict", "tree": tip_tree,
                               "suite": _suite_fingerprint()}
            report_head = (f"gate:    suite not run — green verdict for tree "
                           f"{str(tip_tree)[:12]}")
        else:
            started = time.monotonic()
            ok, report = run(frozenset())
            info["suite_seconds"] = round(time.monotonic() - started, 3)
            record_verdict(tip_tree, ok, "land-validated", info["suite_seconds"])
            if ok:
                accepted.update({"source": "land-validated", "tree": tip_tree})
            info["verdict"] = {"source": "land-validated", "tree": tip_tree,
                               "suite": _suite_fingerprint(), "green": ok}
            accepted["attempts_seen"] = True
            return ok, report, info
    accepted["attempts_seen"] = True
    started = time.monotonic()
    ok, report = run(suite_keys)
    info["checks_seconds"] = round(time.monotonic() - started, 3)
    return ok, report_head + "\n" + report, info


#: Line prefixes that name WHICH test broke, in unittest's own output shape — the
#: `TextTestResult.printErrorList` header line, reproduced verbatim by
#: `curate/run_suite.py`'s `_print_error_list`, plus the unexpected-success roll-call
#: beside it. WI-0334: those lines are printed BEFORE the summary block, so a fixed
#: tail of a failing suite's output is STRUCTURALLY guaranteed to carry the verdict and
#: never the identity. The suite's last four lines are a separator, `Ran N tests in
#: Xs`, a blank line and `FAILED (failures=1)` — which is exactly four lines, and
#: exactly what the receipt used to keep. Not a near-miss that a longer tail fixes: the
#: identity is in the body, so the body is where it has to be found.
GATE_IDENTITY_PREFIXES = ("FAIL: ", "ERROR: ", "UNEXPECTED SUCCESS: ")

#: The marker every producer of a failed-command line in the gate report writes, and
#: the anchor `_pf_gate` finds it by. Named once because a reader that hunts for this
#: string and a writer that formats it are the same contract, and WI-0334's second half
#: is what a reader looking in the wrong PLACE costs: the preflight banner took the
#: report's first six lines, which are its preamble — the interpreter line and the
#: checks that passed — while `_run_gate` returns at the FIRST failure, so the failed
#: command and its receipt are always at the END. A head-slice of this report is
#: structurally guaranteed to show everything except what it exists to show.
GATE_FAIL_MARKER = "gate:    FAIL"

#: How many trailing lines of a failing command's output the receipt keeps. UNCHANGED
#: by WI-0334, deliberately: the tail carries the verdict and the failure counts, which
#: is worth keeping. It was never the wrong lines — it was never enough of them.
GATE_RECEIPT_TAIL = 4

#: Cap on identity lines lifted out of the body ([`cap-what-can-run-away`]). A run with
#: three hundred red tests must not paste three hundred lines into a receipt that is
#: read in a terminal and copied into a lane note. The overflow is COUNTED in the
#: receipt rather than dropped silently, so "ten named" never reads as "ten failed".
GATE_RECEIPT_MAX_NAMED = 10

#: The same cap for `poga test`, which prints the identities to a terminal beside a
#: path to the FULL output on disk. Higher than the receipt's, because nothing is lost
#: here — the file has everything — and the operator is standing right there.
GATE_TEST_NAMED_CAP = 20


def _gate_failure_receipt(text: str, tail: int = GATE_RECEIPT_TAIL,
                          max_named: int = GATE_RECEIPT_MAX_NAMED) -> list[str]:
    """The lines of a failed gate command's output worth keeping — identity first.

    WI-0334. The receipt a failing gate prints is the whole of what the operator gets:
    the gate runs in a throwaway worktree (`_gate_commit`) that is removed in a
    `finally`, so the output this function does not keep is not stored anywhere else
    and cannot be gone back for. "Re-run it by hand" is not a recovery path either —
    the run that failed is the one over the candidate tree, and reproducing it takes a
    detached worktree, `POGA_GATE=1` and a closed stdin before it is even the same
    question. So a receipt that names the verdict and not the subject sends the reader
    to do several minutes of work to learn a fact the process already had and threw
    away, which is the whole of the defect.

    WHAT IT KEEPS, in the output's own order:

      1. Every line from the body that NAMES a failing test, capped at `max_named`.
      2. A note for what was left out — separately for tests it could not name and for
         body lines it did not show, because those are different losses.
      3. The last `tail` lines verbatim — the verdict block, exactly as before.

    THREE OUTCOMES, NEVER TWO ([`declare-what-a-check-assumes`]). "Nothing in the body
    named a test" and "the body was elided" and "the command wrote nothing at all" are
    three different facts about a failure, and the receipt says which one it is. The
    last of those used to render as a `FAIL (exit 1)` line with NOTHING under it, which
    reads as a display bug rather than as the command's actual behaviour.

    NOT SUITE-SPECIFIC, though the suite is what motivated it. Every other gate command
    is a `--check` script whose whole diagnosis is a line or two at the end of its
    output; for those, no line matches the prefixes, nothing is elided, and the receipt
    is byte-identical to the pre-WI-0334 one. The change costs those commands nothing
    and cannot regress them."""
    lines = (text or "").strip().splitlines()
    if not lines:
        return ["(the command failed without writing to stdout or stderr)"]
    tail = max(0, tail)
    max_named = max(0, max_named)
    tail_start = max(0, len(lines) - tail)
    named = [i for i in range(tail_start)
             if lines[i].startswith(GATE_IDENTITY_PREFIXES)]
    kept = named[:max_named]
    out = [lines[i] for i in kept]
    over = len(named) - len(kept)
    # THE TWO NOTES PARTITION THE LOSS — they never double-count it. A named test that
    # the cap dropped is reported by `over` and must not be reported a second time as
    # an anonymous elided line, or a capped receipt says "5 more tests" and "5 lines
    # not shown" about the same five lines and reads as ten losses.
    elided = tail_start - len(kept) - over
    if over:
        out.append(f"… and {over} more failing test(s) not named here")
    if elided:
        out.append(f"… {elided} earlier line(s) not shown")
    out.extend(lines[tail_start:])
    return out


def _run_gate(cwd: Path | None = None, skip=frozenset()) -> tuple[bool, str]:
    """The merge gate (ADR-0056 D4): run the config `gate` command list, or the
    default (unittest iff a tests/ dir exists). FAIL-CLOSED — any nonzero exit, or
    a command that cannot even launch, blocks the merge. Returns (passed, report).

    `cwd` runs the checks somewhere other than the repo root — ADR-0058 D4 passes a
    scratch worktree holding the candidate commit, so the gate sees exactly what the
    trunk would become instead of the shared tree's in-flight edits.

    ADR-0124 D3 removed the `serial_derive_exit` parameter and the validation-reuse
    proof it drove. ADR-0122 D1 built that proof to answer "the land ran the suite twice
    — may the second run trust the first?", and the honest answer required binding a
    verdict to a candidate, an interpreter, a discovery set and an environment. With the
    serial derive out of the land path there is no first run to trust: the gate runs the
    suite exactly once, over the tree that lands. The requirement is met by construction
    rather than by evidence, which is the stronger of the two, so the mechanism went
    with the second run it existed to elide.

    WI-0347 — `skip` is the set of `_gate_command_key`s whose own measured input set
    the lane's diff does not touch. DEFAULTS TO EMPTY, and every caller that is not a
    land leaves it that way: preflight asks "is the gate green in this checkout", a
    question no diff narrows, and eliding checks there would report OK for checks that
    never ran. Under ADR-0148 the only land caller is `_land_gate`, which skips the
    suite command itself and nothing else."""
    cmds = _gate_configured_commands()
    version = ".".join(map(str, sys.version_info[:3]))
    lines = [f"gated with: python {version} ({sys.executable})"]
    if not cmds:
        return True, "\n".join(lines + ["gate:    (no checks configured) — passed vacuously"])
    suite_runs = 0
    for cmd in cmds:
        key = _gate_command_key(cmd)
        if key in skip:
            # A receipt, never a silence (ADR-0117 D5). The line names the command AND
            # the reason, because anything counting "gate:    ok" lines to decide
            # whether the gate ran needs the skipped ones visible in the same list.
            lines.append(f"gate:    skipped — {key} "
                         + ("(the suite never runs at land — ADR-0148 D1; the lane's "
                            "verdict and the trunk check cover it)"
                            if key in _land_suite_keys() else
                            "(diff touches none of its measured inputs)"))
            continue
        argv = _gate_argv(cmd)
        if _gate_is_suite_command(cmd):
            suite_runs += 1
        try:
            # WI-0168: the gate gets a CLOSED stdin, never the session's. Inheriting it
            # hung a land for 33 minutes with no output and no timeout — a test reached
            # `_read_hook_stdin`, whose `sys.stdin.read()` waited on EOF that a harness
            # socket never sends. The gate runs a test suite; it has no business reading
            # the session's input, and DEVNULL makes the whole class impossible here
            # rather than better-behaved.
            # ADR-0119 D4: the suite is TOLD it is the gate. Without this the five
            # machine-scoped probes cannot know to hold back, and the land's verdict stays
            # partly a reading of the operator's process table, tmux server and CLI login
            # (WI-0271, which measured it rather than suspected it).
            r = sh(argv, check=False, cwd=cwd, stdin=subprocess.DEVNULL,
                   env={**os.environ, GATE_ENV_VAR: "1"})
        except Exception as e:
            lines.append(f"{GATE_FAIL_MARKER} — could not launch `{' '.join(argv)}`: {e}")
            return False, "\n".join(lines)
        if r.returncode == 0:
            lines.append(f"gate:    ok — {' '.join(argv)}")
            continue
        lines.append(f"{GATE_FAIL_MARKER} (exit {r.returncode}) — {' '.join(argv)}")
        # WI-0334. The receipt is built from the output's BODY as well as its tail: for
        # the suite, the four lines at the end are the verdict and the identity of what
        # broke is above them. STREAM SELECTION IS UNCHANGED and remains a known
        # narrowing — `stderr or stdout` picks one, and a command that diagnoses on
        # stdout while writing one stray line to stderr would still be read by the
        # wrong half. No gate command does that today (the suite's summary and its
        # FAIL blocks are both on stderr; `wi-check` prints to stdout and writes
        # nothing to stderr, which is what makes the fallback load-bearing), so this
        # is named rather than changed.
        lines.extend(f"         {t}"
                     for t in _gate_failure_receipt(r.stderr or r.stdout or ""))
        return False, "\n".join(lines)
    lines.append(f"suite runs at land: {suite_runs}")
    return True, "\n".join(lines)


def _trunk_tip() -> str | None:
    """The commit the trunk currently points at — the parent a candidate builds on and
    the expected value of the compare-and-swap that lands it. Prefers `origin/<trunk>`
    when it is ahead, so a candidate is built on the newest known trunk."""
    trunk = _trunk()
    local = sh(["git", "rev-parse", "--verify", "--quiet", trunk], check=False)
    tip = local.stdout.strip() if local.returncode == 0 else None
    remote_ref = f"origin/{trunk}"
    if _ref_exists(remote_ref):
        r = sh(["git", "rev-parse", "--verify", "--quiet", remote_ref], check=False)
        remote = r.stdout.strip() if r.returncode == 0 else None
        # origin ahead (local is an ancestor of it) -> build on origin's tip instead.
        if remote and tip and sh(["git", "merge-base", "--is-ancestor", tip, remote],
                                 check=False).returncode == 0 and remote != tip:
            return remote
    return tip


def _gate_commit(sha: str, skip=frozenset()) -> tuple[bool, str]:
    """Run the gate against `sha` in a throwaway worktree (ADR-0058 D4).

    The shared working tree holds other sessions' in-flight edits, so gating *it* tests
    their half-finished work and makes the verdict depend on who else is mid-keystroke.
    Checking the candidate out somewhere else means the gate sees exactly what the trunk
    would become — nothing more. The worktree lives for the duration of one gate run.
    FAIL-CLOSED: if the scratch worktree cannot be created, nothing lands."""
    tmp = tempfile.mkdtemp(prefix=GATE_WORKTREE_PREFIX)
    wt = Path(tmp) / "wt"
    try:
        r = sh(["git", "worktree", "add", "--detach", "--quiet", str(wt), sha], check=False)
        if r.returncode != 0:
            return False, (f"{GATE_FAIL_MARKER} — could not stage a scratch worktree: "
                           f"{(r.stderr or r.stdout).strip()}")
        ok, report = _run_gate(cwd=wt, skip=skip)
        return ok, f"gated in: isolated {wt.resolve()}\n{report}"
    except Exception as e:
        return False, f"{GATE_FAIL_MARKER} — scratch worktree error: {e}"
    finally:
        sh(["git", "worktree", "remove", "--force", str(wt)], check=False)
        shutil.rmtree(tmp, ignore_errors=True)


class LandOutcome:
    """Why a land ended the way it did — the three answers a caller actually needs.

    WI-0263 (d). Every lander used to return a bare `bool` that its command discarded,
    so `session.py merge` exited 0 after printing "BLOCKED — main kept moving under us
    after 3 attempts. Nothing landed." A caller that trusts exit status — a script, a
    dispatched lane's wrapper, an agent reading `$?` — read a total failure to land as a
    success, and the WI-0150 lane burned turns verifying its work against a pre-rebase
    SHA because of it.

    The convention is `cmd_integrate`'s, deliberately, because one land vocabulary beats
    two ([P16](principles/master.md#p16--avoid-duplication)): **0** landed or there was
    nothing to do, **1** refused with the trunk untouched, **2** the trunk kept moving.
    Its docstring already states the principle this class exists to extend — "collapsing
    the last two is how 'we did not publish' gets read as 'we published'."

    Truthy iff the trunk advanced, so the ~45 existing `assertTrue(_land_...(...))`
    call sites and the `bool(landed)` at the `_dispatch_close_runtime` call keep their
    meaning unchanged. This is a widening, not a rewrite: nothing that reads the result
    as a boolean has to learn anything new, and only the two commands that own the
    process exit read `.exit_code`.

    `reason` is a stable short slug, not prose — the printed line is still the human
    surface, and a caller matching on `reason` must not break when the wording is
    improved. `"contended"` is the only one that maps to 2; it is the WI-0263 case."""

    __slots__ = ("landed", "reason")

    #: Reasons that mean "nothing to do", not "we failed" — exit 0 like `integrate`.
    BENIGN = frozenset({"nothing"})

    def __init__(self, landed: bool, reason: str = "") -> None:
        self.landed = bool(landed)
        self.reason = reason if not landed else ""

    def __bool__(self) -> bool:
        return self.landed

    def __repr__(self) -> str:
        return f"LandOutcome(landed={self.landed!r}, reason={self.reason!r})"

    @property
    def exit_code(self) -> int:
        """0 landed / nothing to do · 2 the trunk kept moving · 1 everything else."""
        if self.landed or self.reason in self.BENIGN:
            return 0
        return 2 if self.reason == "contended" else 1


class _CasBudget:
    """How many times a lost CAS is worth retrying — derived from what a retry costs.

    WI-0266. Every lander used to carry `attempts: int = 3` as a bare default parameter,
    passed by no caller and reachable from no CLI flag. The trouble is not that 3 is the
    wrong number; it is that it is a *number*. The gate runs INSIDE the compare-and-swap
    window (ADR-0058 D4/D5), so the window's width is the suite's runtime, and the odds
    of surviving one attempt fall as the suite grows. A constant beside a moving cost
    silently means something different every month.

    So the budget is derived: keep retrying while another FULL attempt still fits inside
    a wall-clock allowance, estimating the next attempt's cost from the longest one
    already observed. Three properties make that safe to ship fleet-wide:

      * **A floor.** `min_attempts` is the 3 this replaces, so no member ever gets fewer
        tries than it has today — including a member whose gate is slower than the whole
        allowance, where the estimate would otherwise permit one attempt and stop.
      * **A cap.** `max_attempts` bounds a member whose gate is fast enough that the
        allowance alone would permit hundreds ([P19](principles/master.md#p19--cap-what-can-run-away)).
      * **A wall clock.** The lane holds the land gate for every attempt (ADR-0114 D1),
        so this time is paid by the queue behind it. The allowance is under
        `LAND_LOCK_TTL_SECONDS`, so a lane retrying *within budget* is never reclaimed
        as a dead holder mid-land. The floor can exceed the TTL, but only where a
        SINGLE gate run already does — that is ADR-0114's exposure (the gate record is
        refreshed once per attempt, so a gate longer than its TTL lapses regardless of
        how many attempts follow it), not one this budget introduces. Filed separately;
        do not read the floor as the cause.

    Exhaustion is a *diagnosis*, not a shrug: `exhausted_line()` reports the attempts
    made, the time spent and which limit stopped it, because "the trunk advances faster
    than this gate can run" and "we were unlucky three times" need different responses
    and the old message could not tell them apart.
    """

    __slots__ = ("min_attempts", "max_attempts", "budget", "_now", "_t0",
                 "made", "durations", "stopped_by", "_started")

    def __init__(self, min_attempts: int = LAND_CAS_MIN_ATTEMPTS,
                 max_attempts: int = LAND_CAS_MAX_ATTEMPTS,
                 budget: float = LAND_CAS_BUDGET_SECONDS,
                 now=time.monotonic) -> None:
        self.min_attempts = max(1, int(min_attempts))
        self.max_attempts = max(self.min_attempts, int(max_attempts))
        self.budget = float(budget)
        self._now = now
        self._t0 = now()
        self.made = 0
        self.durations: list[float] = []
        self.stopped_by = ""
        self._started = self._t0

    @property
    def elapsed(self) -> float:
        return self._now() - self._t0

    def _another_fits(self) -> bool:
        """Is there room for one more attempt of the worst size we have seen?

        The estimate is the LONGEST observed attempt, not the mean: a budget that
        overruns because it averaged away a slow run is a budget that holds the land
        gate past the number it advertises."""
        if not self.durations:
            return True
        return self.elapsed + max(self.durations) <= self.budget

    def attempts(self):
        """Yield attempt numbers until the budget is spent. Records each attempt's cost
        as the caller comes back around for the next one; a caller that `break`s or
        returns mid-attempt simply never records that one, which is correct — it did not
        finish."""
        while True:
            n = self.made + 1
            if n > self.max_attempts:
                self.stopped_by = "cap"
                return
            if n > self.min_attempts and not self._another_fits():
                self.stopped_by = "budget"
                return
            self.made = n
            self._started = self._now()
            yield n
            self.durations.append(self._now() - self._started)

    def exhausted_line(self, trunk: str) -> str:
        """Why we stopped, in the terms that decide what to do about it."""
        spent = _fmt_wait(self.elapsed)
        if self.stopped_by == "cap":
            why = (f"stopped at the {self.max_attempts}-attempt cap — {trunk} is "
                   f"advancing faster than this gate can run, which is a contention "
                   f"problem, not an unlucky land")
        elif self.stopped_by == "budget":
            slowest = _fmt_wait(max(self.durations)) if self.durations else "?"
            why = (f"stopped after {spent} — another attempt costs about {slowest} and "
                   f"would exceed the {_fmt_wait(self.budget)} retry budget, which the "
                   f"queue behind this lane is paying for")
        else:
            why = f"stopped after {spent}"
        return (f"land:    BLOCKED — {trunk} kept moving under us. "
                f"{self.made} attempt(s), {why}.\n"
                f"         Nothing landed; the work is safe. Retry with "
                f"`session.py merge --continue`.")


def _cas_budget(attempts: int | None) -> "_CasBudget":
    """The retry budget for one land.

    `None` — every production caller — means the derived budget. An explicit integer
    pins it to exactly that many attempts, which is what the ~45 existing tests that
    pass `attempts=N` mean by it, and what the `--attempts` escape hatch means. The
    derived path is the DEFAULT and the fixed count is the opt-out, never the reverse:
    a fix that only works when someone remembers to pass a flag has not shipped."""
    if attempts is None:
        return _CasBudget()
    n = max(1, int(attempts))
    return _CasBudget(min_attempts=n, max_attempts=n)


def _moved_or_lost_line(outcome: str, attempt: int, trunk: str, parent: str,
                        budget: "_CasBudget") -> str:
    """The retry sentence, and it must not claim the wrong thing happened.

    ADR-0124 D1 splits what used to be one event into two, and they are genuinely
    different: `moved` means the trunk advanced while this candidate was VALIDATING and
    we declined to write anything — no swap was attempted, no work was lost, and the
    re-validation happens outside the queue. `failed` means the compare-and-swap itself
    was refused while we held the lock and had just verified the tip, which is a
    condition nothing in the current model produces. Collapsing them would report a
    routine rebase as an anomaly, or an anomaly as routine."""
    spent = (f"({_fmt_wait(budget.elapsed)} of a {_fmt_wait(budget.budget)} "
             f"retry budget spent)")
    if outcome == "moved":
        return (f"{_cas_loser_note(trunk, parent)}; nothing was written. Rebasing and "
                f"re-checking outside the queue — the suite does not re-run (ADR-0148 D4), "
                f"attempt {attempt} {spent}.")
    return (f"the swap was REFUSED on attempt {attempt} while the gate was held and the "
            f"tip verified — {_cas_loser_note(trunk, parent)}. Retrying {spent}.")


def _cas_loser_note(trunk: str, parent: str) -> str:
    """What actually advanced the trunk under us, said accurately.

    The old line asserted "another lane landed first". Since ADR-0114 serialized the
    land that is usually FALSE: the land gate makes lane lands mutually exclusive, but
    `poga work` / `poga ops` commit their store writes straight to the main checkout
    outside it, by design (ADR-0073) — so the commits a gate-holding lane loses to are
    mostly not lanes at all (WI-0272, observed while landing ADR-0114 itself).

    Reports the count and whether any Python changed. Deliberately NOT a path
    classification: a list of "paths that cannot matter" is a gate-inert set, ADR-0114
    D7 refuses to act on one, and WI-0267 warns specifically against growing a second
    list whose meaning readers will confuse with the first. This one decides nothing —
    it only makes the sentence true."""
    tip = _trunk_tip()
    if not tip or tip == parent:
        return "the swap was refused but the tip we built on is still current"
    n = len(sh(["git", "log", "--pretty=format:%H", f"{parent}..{tip}"],
               check=False).stdout.split())
    files = sh(["git", "diff", "--name-only", "--no-renames", parent, tip],
               check=False).stdout.split()
    if not n:
        return f"{trunk} moved off the tip we built on"
    code = " including a code change" if any(f.endswith(".py") for f in files) else \
           " none of them code changes"
    return f"{n} commit(s) arrived on {trunk},{code}"


def _land_candidate(paths: list[str], msg: str, push: bool = True,
                    attempts: int | None = None) -> "LandOutcome":
    """Land this session's attributed work on the trunk, alone (ADR-0058 D2/D5).

    No branch, no waiting on anyone: build the candidate on the current trunk tip, gate
    it in isolation, then advance the trunk with a compare-and-swap against the tip we
    built on. If another session landed first the swap fails and we rebuild on the new
    tip and re-gate — the ADR-0051 C3 'loser rebases' rule, enforced by the ref update
    rather than by a checkout, so it costs no shared-tree mutation.

    Returns True iff the trunk advanced. Every failure path leaves the working tree
    exactly as it was — the session's work is still on disk and still uncommitted, so
    nothing is lost and `session.py merge` retries."""
    mark_ready_to_land()                     # WI-0349 — see `_land_worktree_lane`
    trunk = _trunk()
    if not paths:
        print("land:    nothing attributed to this session — nothing to land.")
        return LandOutcome(False, "nothing")
    # ADR-0124 D1 (superseding ADR-0114 D2 narrowly): the candidate is BUILT and
    # VALIDATED outside the queue, and the serialized section holds only the advance and
    # its publication. A moved trunk is not a lost CAS here — it is caught by the
    # parent-equals-trunk check before anything is written, and the rebuild-and-revalidate
    # that follows happens outside the lock, where it costs the queue nothing.
    budget = _cas_budget(attempts)
    swapped = False
    accepted: dict = {}                      # ADR-0148 D4 — survives a `moved` retry
    for attempt in budget.attempts():
        queue_started = time.monotonic()
        # WI-0356. Replaces the bare fetch that used to be this line: the fetch still
        # happens, but its answer is now READ. Per attempt, not once before the loop —
        # a retry happens because the trunk moved, and origin may have moved with it.
        refusal = _require_trunk_current_for_land(trunk)
        if refusal:
            print("land:    nothing landed; the work is untouched on disk.")
            return LandOutcome(False, refusal)
        parent = _trunk_tip()
        if not parent:
            print(f"land:    FAIL — cannot resolve the {trunk} tip.")
            return LandOutcome(False, "trunk")
        sha = _candidate_commit(paths, msg, parent)
        if not sha:
            print("land:    FAIL — could not build the candidate commit.")
            return LandOutcome(False, "build")
        # R5a: a NEW number of ANY registered counter entering the trunk must have been
        # drawn, not picked. Iterating the registry (ADR-0076 D2) is what makes a newly
        # added counter defended by construction — there is no per-counter line here to
        # forget to add, which is exactly how an ungated namespace would otherwise ship.
        num_ok, num_msg = _all_counter_land_gates(sha, parent)
        if not num_ok:
            print(num_msg)
            print("land:    nothing landed; the work is untouched on disk.")
            return LandOutcome(False, "counter")
        # WI-0294: classify before gating — a diff the suite cannot read cannot
        # change its verdict, so it lands under the lock alone.
        #
        # ADR-0148: `_land_gate`, as in every lander. This one has no pre-clock verdict
        # step (the candidate is built from attributed paths inside the loop), so a code
        # diff with no filed verdict runs the suite here, once, counted as validation;
        # `accepted` then carries it across a `moved` retry (D4).
        validate_started = time.monotonic()
        ok, report, gate_info = _land_gate(parent, sha,
                                           lambda skip, _s=sha: _gate_commit(_s, skip),
                                           accepted)
        validated = time.monotonic() - validate_started
        print(report)
        if not ok:
            print(f"land:    BLOCKED — gate failed on this session's work. Nothing "
                  f"landed; the work is untouched on disk. Fix, then `session.py merge --continue`.")
            return LandOutcome(False, "gate")
        # ADR-0053 R3 conformance miner, folded in per phase2-followons — WARN only,
        # scoped to this session's own new commit(s) (parent..sha), never blocks.
        warn = _new_roledoc_violation(parent, sha)
        if warn:
            print(warn)

        def publish(stages, _sha=sha):
            # The trunk now contains our work. Refresh the shared checkout's view of it:
            # HEAD follows the ref when it is on the trunk, so the files we just committed
            # simply stop showing as modified. Other sessions' work is untouched.
            sh(["git", "reset", "--quiet"], check=False)
            if push:
                po = _push_trunk(trunk)
                if po.seconds:
                    stages["push"] = po.seconds
                if po.line:
                    print(po.line)
                if not po.ok:
                    stages["push_owed"] = po.owed

        outcome, hold, stages = _serialized_advance(trunk, parent, sha, publish,
                                                    verb="land-candidate")
        if outcome == "landed":
            gate_info["trunk_check"] = _trunk_check_spawn(trunk, sha)
        rec = _land_receipt("land-candidate", outcome, hold, stages,
                            time.monotonic() - queue_started - validated, validated,
                            attempt, trunk, parent, sha, verdict=gate_info)
        print(_land_hold_line(rec))
        if outcome == "landed":
            swapped = True
            break
        print(f"land:    {_moved_or_lost_line(outcome, attempt, trunk, parent, budget)}")
    if not swapped:
        print(budget.exhausted_line(trunk))
        return LandOutcome(False, "contended")
    print(f"landed:  {len(paths)} attributed path(s) → {trunk}"
          + _land_publish_suffix(push, stages, trunk))
    return LandOutcome(True)


def _land_branch(focus, blocked, version: str, push: bool = True,
                 renumber: bool = True) -> "LandOutcome":
    """Land the current session branch onto the trunk through the gate (ADR-0056 D3):
    rebase onto the fetched trunk (loser rebases), run the gate (fail-closed),
    ff-only merge, recompile the views on the trunk, stamp STATUS, commit, push,
    and delete the merged branch. Each failure surfaces and leaves the branch
    intact — the journal is already closed and the work is committed on the branch,
    so there is no data-loss path. Returns True iff the branch landed."""
    mark_ready_to_land()                     # WI-0349 — see `_land_worktree_lane`
    branch = _current_branch()
    if not branch.startswith("session/"):
        print(f"land:    not on a session branch (on '{branch}') — nothing to merge.")
        return LandOutcome(False, "not-a-branch")
    trunk = _trunk()
    # ADR-0124 D1: rebase and gate OUTSIDE the queue; the serialized section holds only
    # the advance and its publication. This lander had no retry loop at all before —
    # it gated under the lock, so by construction the trunk could not move under it, and
    # it never needed one. Moving the gate out gives the trunk a window, so the loop
    # comes with it. ADR-0117 D4's rule applies to this ADR as much as to that one: a
    # land-path change made in one lander and not the others ships as a known gap.
    budget = _cas_budget(None)
    landed = False
    accepted: dict = {}                      # ADR-0148 D4 — survives a `moved` retry
    for attempt in budget.attempts():
        queue_started = time.monotonic()
        # WI-0356, in this lander too (ADR-0117 D4). It replaces the bare fetch AND
        # the `onto = origin/<trunk>` that used to sit on the next line.
        #
        # DROPPING THAT SPECIAL CASE IS PART OF THE FIX, not a tidy-up beside it. It
        # existed to compensate for a trunk that might be stale — the very thing this
        # check now makes impossible — and it compensated in a direction that could
        # LOSE work: with the local trunk AHEAD of origin (an unpushed land, the
        # ordinary state after a rejected push), rebasing onto `origin/<trunk>` builds
        # a tip that does not contain those commits, and the CAS below then moves the
        # trunk to it against a `parent` that does. Rebasing onto the local trunk tip
        # can never drop anything, it is what the other two landers already do, and
        # after this check the local tip provably contains origin.
        refusal = _require_trunk_current_for_land(trunk)
        if refusal:
            print("         branch left intact; journal is closed, work is safe.")
            return LandOutcome(False, refusal)
        onto = trunk
        # Rebase — loser of a conflict rebases (ADR-0051 C3). A conflict is the one
        # genuinely-human case: abort, surface, leave the branch intact.
        rb = sh(["git", "rebase", onto], check=False)
        if rb.returncode != 0:
            sh(["git", "rebase", "--abort"], check=False)
            print(f"land:    BLOCKED — rebase onto {onto} conflicts. Resolve on '{branch}', "
                  f"then `session.py merge --continue`.\n"
                  f"         branch left intact; journal is closed, work is safe.")
            return LandOutcome(False, "conflict")
        # R5a: a NEW number of ANY registered counter must have been drawn, not picked.
        tip = sh(["git", "rev-parse", "HEAD"], check=False).stdout.strip()
        parent = sh(["git", "rev-parse", "--verify", "--quiet", f"refs/heads/{trunk}"],
                    check=False).stdout.strip()
        if tip and parent and renumber:
            newtip, rlines = _auto_renumber_collisions(tip, parent)   # WI-0169
            for line in rlines:
                print(line)
            if newtip:
                tip = newtip
        if tip and parent:
            num_ok, num_msg = _all_counter_land_gates(tip, parent)
            if not num_ok:
                print(num_msg)
                print("         branch left intact; journal is closed, work is safe.")
                return LandOutcome(False, "counter")
        # Gate (fail-closed), outside the queue.
        # WI-0294: classify before gating. `tip`/`parent` can be empty here, and the
        # classifier gates on a diff it cannot read — which is the right answer.
        # ADR-0148: `_land_gate`, as in every lander (see `_land_candidate`).
        validate_started = time.monotonic()
        ok, report, gate_info = _land_gate(parent, tip,
                                           lambda skip, _t=tip: _gate_commit(_t, skip),
                                           accepted)
        validated = time.monotonic() - validate_started
        print(report)
        if not ok:
            print(f"land:    BLOCKED — gate failed. Fix on '{branch}', then `session.py merge --continue`.\n"
                  f"         branch left intact; journal is closed, work is safe.")
            return LandOutcome(False, "gate")

        def publish(stages, _tip=tip):
            # The ref is already at `_tip` — `_serialized_advance` moved it by
            # compare-and-swap. The `git merge --ff-only <branch>` that used to BE the
            # advance here is gone with it: one advance mechanism, not two that can
            # disagree about which commit landed. Checking the trunk out is what is left,
            # and it is a working-tree move to the commit HEAD is already on.
            sh(["git", "checkout", trunk], check=False)
            # Recompile the views on the trunk (D2) with the landed journal, stamp
            # STATUS, and commit the regenerated views.
            started = time.monotonic()
            run_compile(CFG["tz"])
            # WI-0372: the reason was discarded here too. A land that recompiled the views
            # and stamped nothing is precisely the state that froze `last_active` for a
            # week while the system ran nightly — it gets named rather than swallowed.
            if (why := _stamp_status(version, focus, blocked)):
                print(f"status:  NOT stamped — {why}. Nothing was written; any freshness "
                      f"signal read from it is stale, not current.")
            sh(SWEEP_ADD)
            if _has_staged_changes():
                sh(["git", "commit", "-m", f"docs(handoff): compile after landing {branch}"])
            stages["recompile"] = round(time.monotonic() - started, 3)
            if push:
                # This lander runs with the trunk CHECKED OUT, which is why it historically
                # pushed bare; the explicit refspec says the same thing without depending on
                # which branch HEAD happens to be on when we get here.
                po = _push_trunk(trunk, refspec=f"{trunk}:{trunk}")
                if po.seconds:
                    stages["push"] = po.seconds
                if po.line:
                    print(po.line)
                if not po.ok:
                    stages["push_owed"] = po.owed
            sh(["git", "branch", "-d", branch], check=False)

        outcome, hold, stages = _serialized_advance(trunk, parent, tip, publish,
                                                    verb="land-branch")
        if outcome == "landed":
            gate_info["trunk_check"] = _trunk_check_spawn(trunk, tip)
        rec = _land_receipt("land-branch", outcome, hold, stages,
                            time.monotonic() - queue_started - validated, validated,
                            attempt, trunk, parent, tip, verdict=gate_info)
        print(_land_hold_line(rec))
        if outcome == "landed":
            landed = True
            break
        sh(["git", "checkout", branch], check=False)
        print(f"land:    {_moved_or_lost_line(outcome, attempt, trunk, parent, budget)}")
    if not landed:
        print(budget.exhausted_line(trunk))
        return LandOutcome(False, "contended")
    print(f"landed:  {branch} → {trunk}" + _land_publish_suffix(push, stages, trunk))
    return LandOutcome(True)


def _merge_onto(ours: str, theirs: str,
                policy: str = "generated") -> tuple[str | None, list[str], str]:
    """Merge `theirs` INTO `ours`, producing a merge commit. `(merge_tip, resolved, error)`.

    The operation WI-0153 found nothing in the substrate could produce. `ours` is the local
    trunk tip, `theirs` is `origin/<trunk>`; the result has BOTH as parents, so
    `origin/<trunk>` is an ancestor of it — the exact predicate a fast-forward push needs —
    and every commit on either side keeps its sha. That is what makes reconciliation
    CONVERGENT: a replay rewrites our side, so the peer's clone diverges from the trunk it
    was part of and the two machines take turns rewriting each other.

    Runs entirely in a THROWAWAY detached worktree, exactly as `_gate_commit` runs the gate
    — so nothing is checked out that another worktree holds, and neither
    `refs/heads/<trunk>` nor the lane branch is touched. This function only PRODUCES a
    candidate commit; the caller decides whether it may become the trunk.

    PARENT ORDER IS LOAD-BEARING, not cosmetic. `ours` is first, so first-parent history
    stays on this machine's line — which is what `_checkout_merge_base` and
    `_main_restore_verdict` walk to find where the main checkout was last materialized, and
    what makes `local -> merge` a strict fast-forward for `_sync_main_checkout`'s
    precondition. Merging in the other direction would leave the main checkout's own history
    on a side branch and quietly defeat both.

    CONFLICT POLICY, by the same named-class rule `_resolve_rebase_conflict` follows, and
    through the same predicate: under `generated`, a conflict `_conflict_is_resolvable`
    admits is resolved by taking OUR side and reported; anything else aborts the merge and
    returns an error naming the paths. `--ours` in a merge is the side being merged into —
    our trunk — and the safety argument is not that the views are unimportant but that they
    are DERIVED: the integrate regenerates them from the journals seconds later, so the side
    taken here is overwritten before anyone reads it. A conflict on an authored file is a
    real disagreement between two machines with no mechanical answer, and guessing is
    precisely how one is written away.

    The predicate is per-PATH (ADR-0102 re-expressed ADR-0097 D4 that way) and, for
    `ROADMAP.md`, per-REGION: stage 3 is the discarded side in a merge exactly as it is in a
    rebase, so the same question — *did the side we are giving up author anything?* — is
    asked here with no second implementation.

    FAIL-CLOSED: a scratch worktree that cannot be created is an error, never a silent
    no-op merge. Every failure path aborts the merge and leaves both input refs untouched —
    this function never writes a ref."""
    if policy not in RESOLVE_POLICIES:
        return None, [], f"unknown resolve policy '{policy}'"
    trunk = _trunk()
    tmp = tempfile.mkdtemp(prefix=GATE_WORKTREE_PREFIX)
    wt = Path(tmp) / "wt"
    env = {**os.environ, "GIT_EDITOR": "true"}
    try:
        w = sh(["git", "worktree", "add", "--detach", "--quiet", str(wt), ours], check=False)
        if w.returncode != 0:
            return None, [], ("could not stage a scratch worktree: "
                              f"{(w.stderr or w.stdout).strip()}")
        msg = (f"chore(integrate): merge origin/{trunk} into {trunk}\n\n"
               f"Reconciles two trunks that both advanced. Neither side is rewritten — "
               f"origin/{trunk} ({theirs[:7]}) becomes an ancestor, so the push is a "
               f"fast-forward (ADR-0102).\n")
        m = sh(["git", "merge", "--no-ff", "--no-edit", "-m", msg, theirs],
               check=False, cwd=wt, env=env)
        resolved: list[str] = []
        if m.returncode != 0:
            unmerged = sorted(set(sh(["git", "diff", "--name-only", "--diff-filter=U"],
                                     check=False, cwd=wt).stdout.split()))
            if not unmerged:
                sh(["git", "merge", "--abort"], check=False, cwd=wt)
                return None, [], (f"the merge failed with no conflicted paths: "
                                  f"{(m.stderr or m.stdout).strip()[:200]}")
            outside = [p for p in unmerged
                       if not _conflict_is_resolvable(p, policy, wt)]
            if outside:
                sh(["git", "merge", "--abort"], check=False, cwd=wt)
                return None, [], (f"merging origin/{trunk} conflicts on "
                                  f"{', '.join(outside)}")
            for p in unmerged:
                if sh(["git", "checkout", "--ours", "--", p],
                      check=False, cwd=wt).returncode != 0:
                    sh(["git", "merge", "--abort"], check=False, cwd=wt)
                    return None, [], f"could not take our side of {p}"
                if sh(["git", "add", "--", p], check=False, cwd=wt).returncode != 0:
                    sh(["git", "merge", "--abort"], check=False, cwd=wt)
                    return None, [], f"could not stage the resolved {p}"
                resolved.append(p)
            c = sh(["git", "commit", "--no-edit"], check=False, cwd=wt, env=env)
            if c.returncode != 0:
                sh(["git", "merge", "--abort"], check=False, cwd=wt)
                return None, [], (f"could not conclude the merge: "
                                  f"{(c.stderr or c.stdout).strip()[:200]}")
        tip = sh(["git", "rev-parse", "HEAD"], check=False, cwd=wt).stdout.strip()
        if not tip:
            return None, [], "could not resolve the merged tip"
        # Prove the property the whole verb rests on rather than assuming git honoured it:
        # a merge whose second parent is not origin's tip would push as a non-ff and the
        # failure would surface as a mystery rejection minutes later.
        if sh(["git", "merge-base", "--is-ancestor", theirs, tip],
              check=False).returncode != 0:
            return None, [], (f"the merge did not make origin/{trunk} an ancestor — "
                              f"refusing to publish a tip that cannot fast-forward")
        return tip, sorted(set(resolved)), ""
    except Exception as e:                                   # pragma: no cover - defensive
        return None, [], f"merge error: {type(e).__name__}: {e}"
    finally:
        sh(["git", "worktree", "remove", "--force", str(wt)], check=False)
        shutil.rmtree(tmp, ignore_errors=True)


def _park_unpushed_trunk(tip: str) -> str:
    """Push the un-integrable trunk tip to an ADDITIVE ref on origin, so a refusal never
    leaves the work on one disk.

    This is the move session ~157 made by hand when the push was rejected. It is safe to
    do unasked because it is purely additive: a new `refs/heads/parked/<trunk>-<sha>`,
    named after the commit it carries, so a repeat is a no-op rather than an overwrite,
    and nothing that exists is touched. Never forces. Reports what it did (or why it
    could not) — a backup nobody is told about is not a backup."""
    ref = f"refs/heads/parked/{_trunk()}-{tip[:12]}"
    p = sh(["git", "push", "origin", f"{tip}:{ref}"], check=False)
    if p.returncode == 0:
        return (f"integrate: parked — the trunk tip is safe off-machine at origin {ref}. "
                f"Retire it with `python3 session.py retire-parked` once its content is "
                f"on the trunk (WI-0141) — the verb proves that itself; nobody has to "
                f"assert it.")
    return ("integrate: could NOT park the tip off-machine — "
            f"{(p.stderr or p.stdout).strip()[:160]}")


def _escalate_to_integrate(trunk: str, stages: dict, resolve: str = "generated",
                           emit=print) -> None:
    """WI-0143's self-heal for a land whose push was REJECTED — run outside the land gate.

    ONE implementation for both callers (P16). `_land_worktree_lane` and
    `_resume_owed_publication` each had their own copy of this block inside their own
    `publish` closure, which is to say inside their own held section, which is the whole
    defect WI-0378 exists to remove. Two copies of "what do we do when the push bounced"
    is two chances to fix one of them.

    WHY IT IS SAFE TO RUN HERE AND NOT THERE, stated because ADR-0124 decided the other
    way and this overturns it. That ADR left the escalation inside the hold on the
    argument that releasing "mid-publication, with the local trunk already advanced and
    origin not" is a worse shape than a slow hold. The intermediate state is real — it is
    just not created by the release. It is created by the rejected push, one line earlier,
    and since ADR-0134 D2/D3 it is a named and reported state (`LANDED, PUSH OWED`) with a
    verb whose entire purpose is to clear it. Holding the gate does not make that state
    any less true; it only makes every queued lane wait through a second full suite for it.

    FAIL-OPEN AND NEVER SILENT, unchanged from the block it replaces: the land already
    succeeded and the publish step must not be able to turn it into a failure.

    `stages["escalated"]` is a STRING on purpose. `stages` is the per-stage breakdown of
    what happened INSIDE the hold, and every reader of the receipt — FL7's worst-hold
    line, the hold-line printer, the share-of-hold analysis this item was minted from —
    treats its numeric values as parts of `lock_seconds`. The escalation is no longer one
    of those parts, so recording its duration there would put time in the hold that the
    hold did not contain. The integrate writes its own receipt, under its own verb, with
    its own hold; this key exists so a land receipt still says the escalation happened."""
    emit("         integrating with origin (WI-0143) rather than asking for a "
         "hand — merge origin/{0} in, re-gate, CAS, push.".format(trunk))
    emit("         (outside the land gate since WI-0378 — nobody queues behind this)")
    stages["escalated"] = "integrate"
    try:
        _, lines = _integrate_trunk_with_remote(resolve=resolve)
    except Exception as exc:                     # pragma: no cover - defensive
        lines = [f"integrate: skipped ({type(exc).__name__}: {exc}) — the work is "
                 f"landed on the local {trunk}; run `session.py integrate`."]
    for line in lines:
        emit(line)
    # The integrate either published the trunk or did not; asking the refs is the only
    # honest way to know, since it swallows its own failures by design.
    #
    # "push" SPECIFICALLY, not "is anything owed". `_publication_owed` answers about two
    # stages, and a main checkout that is merely behind puts "sync" in that list — which
    # would have left this banner shouting PUSH OWED at a trunk origin was carrying
    # perfectly well. The banner is about one question and must ask it.
    if "push" not in _publication_owed(trunk, want_push=True):
        stages.pop("push_owed", None)


def _integrate_trunk_with_remote(push: bool = True, attempts: int | None = None,
                                 dry_run: bool = False,
                                 resolve: str = "generated") -> tuple[bool, list[str]]:
    """Reconcile the local trunk with `origin/<trunk>` from a lane. `(ok, report lines)`.

    Five cases, kept distinct because the right move differs and collapsing any two of
    them is how a wrong answer gets shaped like a right one:

      * **no remote / no remote trunk** — nothing to integrate; a plain push publishes.
      * **already equal** — nothing to do, said out loud rather than reported as work.
      * **behind** (local is an ancestor of origin) — CAS the trunk ref forward to
        origin's tip and bring the main checkout's tree along. Nothing to push, and no
        recompile: the views we would regenerate arrived compiled from the peer, and we
        hold no unlanded journal of our own in this case by definition.
      * **ahead** (origin is an ancestor of local) — the push is already a fast-forward;
        just push.
      * **diverged** — the case with no path before this verb: MERGE origin into the local
        trunk (never replay — WI-0153 / ADR-0102), gate, CAS, sync, recompile, push. The
        merge commit is what makes origin an ancestor, so the push is a fast-forward with
        neither side's commits rewritten.

    Every refusal leaves the local trunk EXACTLY where it was and parks its tip on origin,
    so the failure mode is 'not yet published', never 'lost'. The CAS is retried on a lost
    race the same way the land's is — a sibling landing between our replay and our swap
    costs one more attempt, not a clobber.

    WI-0378 — WHERE THE LAND GATE IS HELD, AND WHY IT MOVED. This function used to run
    entirely inside its caller's held gate, and the diverged branch runs a full suite. Of
    837.9s of gate hold across 184 receipts on this machine (2026-09-10 → 2026-09-17), the
    `integrate` stage was 356.2s — **42.5%, from four events**, and three of the four
    holds that breached the 30s budget. Two of those three cost 154.6s and 124.5s against
    a 131.9s median for one full suite: the expensive thing was the RE-GATE, nothing else.
    Merge was 0.14s and 0.08s in those same two receipts; push was 0.78s in both.

    So the section is now what ADR-0124 D1 made it for the three landers, and for the same
    argument: **validate outside, hold for the advance.** Per attempt, everything up to and
    including the gate is inert — `_merge_onto` builds in a throwaway worktree (ADR-0097
    D2), the counter gates read, `_gate_commit` gates a candidate — and writes nothing any
    other lane can see. That half runs with no lock at all. Only the ref move and its
    publication go through `_serialized_advance`, which brings the parent-equals-trunk
    check, the receipt and the `moved` release with it.

    **`moved` IS the yield.** A sibling that landed while we were gating costs us one more
    attempt and costs the queue nothing: the trunk is re-read under the lock, found to have
    moved, and the lock is released with nothing written — the same release ADR-0124 built,
    reached the same way. That is the bound this verb now carries, and it is placement
    rather than a timer: validation cannot overrun the hold budget because it does not hold
    the gate. A timer that fires mid-publication would have to choose between a half-
    published trunk and holding anyway; there is no such choice to make here.

    The two network calls are bounded as well (`_fetch_origin`, `_push_trunk`), because a
    hang is the one failure that reads as work in progress."""
    trunk = _trunk()
    out: list[str] = []
    if not _ref_exists(f"refs/heads/{trunk}"):
        return False, [f"integrate: FAIL — cannot resolve the local {trunk} tip."]
    if not sh(["git", "remote"], check=False).stdout.split():
        return True, ["integrate: no remote configured — the trunk is local by design."]
    f = _fetch_origin()
    if not f.ok:
        return False, [f"integrate: OFFLINE — could not fetch origin: {f.line}",
                       "           nothing changed; the work is on the local trunk. "
                       "Retry when the network is back."]
    remote_ref = f"refs/remotes/origin/{trunk}"

    def _push_line() -> tuple[bool, str, "PushOutcome"]:
        """The one push on this path, bounded. WI-0378: it was a bare `sh(["git","push"…])`
        with no timeout, beside a `_push_trunk` written precisely to stop that (ADR-0134
        D4). Same wording out, so nothing reading this report has to change."""
        po = _push_trunk(trunk)
        if po.ok:
            return True, f"integrate: pushed {trunk} → origin/{trunk}.", po
        return False, f"integrate: push STILL rejected — {po.line[:200]}", po

    budget = _cas_budget(attempts)
    for attempt in budget.attempts():
        # ── OUTSIDE THE GATE — classify, merge, gate. Nothing here is visible to any
        #    other lane, so none of it is worth anyone's queue time (WI-0378).
        local = sh(["git", "rev-parse", f"refs/heads/{trunk}"], check=False).stdout.strip()
        if not _ref_exists(remote_ref):
            if dry_run:
                return True, [f"integrate: (dry-run) origin has no {trunk} yet — "
                              f"would push {local[:7]} to create it."]
            ok, line, _ = _serialized_push_only(trunk, local, _push_line)
            return ok, out + [line]
        remote = sh(["git", "rev-parse", remote_ref], check=False).stdout.strip()
        if not remote:
            return False, out + [f"integrate: FAIL — cannot resolve {remote_ref}."]
        if local == remote:
            # DATED, NOT ASSERTED (WI-0283). The first attempt reaches here behind the
            # fetch above, so the clause reads as a positive receipt. A RETRY does not:
            # the re-fetches in this loop discard their return code, so on attempt 2+
            # this compares against refs that may never have been refreshed — and
            # "already agree" is the one line here that, if wrong, tells an operator
            # their work is published when it is on one disk.
            return True, out + [f"integrate: local {trunk} and origin/{trunk} already "
                                f"agree at {local[:7]} — nothing to integrate "
                                f"({_remote_clause(remote_ref)})."]
        behind = sh(["git", "merge-base", "--is-ancestor", local, remote],
                    check=False).returncode == 0
        ahead = sh(["git", "merge-base", "--is-ancestor", remote, local],
                   check=False).returncode == 0
        if ahead:
            if dry_run:
                return True, out + [f"integrate: (dry-run) origin/{trunk} is an ancestor "
                                    f"of local {trunk} — would push {local[:7]}."]
            ok, line, _ = _serialized_push_only(trunk, local, _push_line)
            return ok, out + [line]
        if behind:
            if dry_run:
                return True, out + [f"integrate: (dry-run) local {trunk} is behind "
                                    f"origin/{trunk} — would fast-forward "
                                    f"{local[:7]} → {remote[:7]}."]
            # WI-0356: this branch IS `_ff_trunk_to_origin`, and is now that function
            # rather than a second copy of it. The pre-land check needed the identical
            # act — CAS the trunk forward, bring the main checkout along — and a
            # second implementation of a trunk-ref move is the shape ADR-0117 D4 is
            # about. It also gained the `trunk_lock` this branch never took.
            #
            # WI-0378: and it gained the LAND gate, which it also never took. It was
            # covered only because `cmd_integrate` held the gate across the whole verb;
            # with that blanket hold gone, the one write here needs its own. It carries
            # no gate run, so it cannot approach the budget — `sync` medians 0.087s
            # across 122 receipts.
            with land_gate_lock():
                ok, lines = _ff_trunk_to_origin(trunk, local, remote, label="integrate")
            out.extend(lines)
            if not ok:
                out.append(f"integrate: retrying (attempt {attempt}).")
                _fetch_origin()
                continue
            return True, out

        # Diverged — the case this verb exists for.
        if dry_run:
            ours = sh(["git", "rev-list", "--count", f"{remote}..{local}"],
                      check=False).stdout.strip() or "?"
            theirs = sh(["git", "rev-list", "--count", f"{local}..{remote}"],
                        check=False).stdout.strip() or "?"
            return True, out + [
                f"integrate: (dry-run) local {trunk} ({local[:7]}) and origin/{trunk} "
                f"({remote[:7]}) have DIVERGED — {ours} commit(s) ours, {theirs} theirs. "
                f"Would MERGE origin into the local trunk (nothing rewritten on either "
                f"side), re-gate, CAS and push."]
        newtip, merged_views, err = _merge_onto(local, remote, resolve)
        if err or not newtip:
            return False, out + [
                f"integrate: REFUSED — {err}.",
                "           Nothing changed: the local trunk still holds the landed work "
                f"at {local[:7]} and origin still holds {remote[:7]}.",
                _park_unpushed_trunk(local),
                "           Two machines edited the same authored file, which has no "
                "mechanical answer. Land the reconciled content through a lane — it must "
                "incorporate origin's side, or the next merge conflicts identically — "
                "then run `session.py integrate` again."]
        if merged_views:
            out.append(f"integrate: took our side of {', '.join(merged_views)} in the "
                       f"merge — generated, and regenerated below, so nothing durable was "
                       f"chosen away.")
        num_ok, num_msg = _all_counter_land_gates(newtip, remote)
        if not num_ok:
            # The shared land-gate message names `session.py merge`, which is the right
            # verb at a land and the wrong one here — say what to do from THIS verb.
            return False, out + [
                num_msg,
                "integrate: REFUSED — the collision only exists once the two trunks are "
                "combined, so no single land could have caught it. Nothing changed "
                f"locally; the trunk still holds {local[:7]}.",
                _park_unpushed_trunk(local),
                "           Renumber the offending file in a lane, land it, then run "
                "`session.py integrate` again."]
        # THE EXPENSIVE STAGE, AND IT IS OUTSIDE THE GATE NOW (WI-0378). Measured at
        # 124.5s and 154.6s in the two receipts that carry it against a 131.9s median
        # full suite; every other lane used to queue behind all of it.
        #
        # ADR-0148 D1/D4: not any more. Both sides are trunks each machine already
        # landed, and a clean merge of two green trunks is the D4 case — what could
        # break only in combination is the trunk check's to find (D5), which the
        # integrate starts after the advance like every lander. The cheap checks still
        # run here, over the merged tree.
        validate_started = time.monotonic()
        ok, report = _gate_commit(newtip, _land_suite_keys())
        validated = time.monotonic() - validate_started
        out.append(report)
        if not ok:
            return False, out + [
                "integrate: REFUSED — the gate fails on the two trunks combined, which is "
                "a real conflict between the two machines' work, not a merge artefact. "
                "Nothing changed locally.",
                _park_unpushed_trunk(local)]

        # ── INSIDE THE GATE — the ref move and its publication, and nothing else. ──
        pushed: list = []

        def publish(stages, _local=local, _newtip=newtip):
            started = time.monotonic()
            sync = _sync_main_checkout(trunk, _local, _newtip)
            stages["sync"] = round(time.monotonic() - started, 3)
            if sync:
                out.append(sync)
            started = time.monotonic()
            views = _recompile_main_checkout(trunk, role_doc_version())
            stages["recompile"] = round(time.monotonic() - started, 3)
            if views:
                out.append(views)
            if not push:
                return
            pok, pline, po = _push_line()
            if po.seconds:
                stages["push"] = po.seconds
            if not pok:
                stages["push_owed"] = po.owed
            pushed.append((pok, pline))
            out.append(pline)

        queue_started = time.monotonic()
        outcome, hold, stages = _serialized_advance(trunk, local, newtip, publish,
                                                    verb="integrate")
        gate_info = {"suite_seconds": 0.0, "diff_class": "code",
                     "verdict": {"source": "integrate",
                                 "reason": "clean merge of two landed trunks (ADR-0148 D4)"}}
        if outcome == "landed":
            gate_info["trunk_check"] = _trunk_check_spawn(trunk, newtip)
        rec = _land_receipt("integrate", outcome, hold, stages,
                            time.monotonic() - queue_started, validated, attempt,
                            trunk, local, newtip, verdict=gate_info)
        out.append(_land_hold_line(rec))
        if outcome == "moved":
            # The yield. Nothing was written and the lock is already released; the next
            # attempt re-reads the world and re-gates OUTSIDE the queue, which is the
            # whole point of validating out there in the first place.
            out.append(f"integrate: a lane landed while we merged — rebuilding on the "
                       f"new {trunk} tip (attempt {attempt}/{budget.max_attempts}).")
            _fetch_origin()
            continue
        if outcome != "landed":
            return False, out + [
                f"integrate: REFUSED — the {trunk} ref would not advance {local[:7]} → "
                f"{newtip[:7]} under the land gate, with the tip verified a line earlier. "
                f"Nothing changed locally.",
                _park_unpushed_trunk(local)]
        out.append(f"integrate: merged origin/{trunk} ({remote[:7]}) into {trunk} — "
                   f"{local[:7]} → {newtip[:7]}. Neither side rewritten; origin is now an "
                   f"ancestor, so the push is a fast-forward.")
        if stages.get("publish_error"):
            return False, out + [
                f"integrate: the advance is made, but publishing raised "
                f"{stages['publish_error']} — the trunk carries {newtip[:7]}; "
                f"run `session.py integrate` again to finish the publication."]
        if not push:
            return True, out + ["integrate: local trunk integrated (push not requested)."]
        return (pushed[0][0] if pushed else True), out

    return False, out + [f"integrate: BLOCKED — {trunk} kept moving under us. "
                         f"{budget.made} attempt(s) over {_fmt_wait(budget.elapsed)}. "
                         f"Nothing changed; retry with `session.py integrate`."]


def _serialized_push_only(trunk: str, tip: str, do_push) -> tuple[bool, str, object]:
    """Publish an already-correct trunk under the land gate, with no ref to move.

    WI-0378. The `ahead` and `no-remote-trunk` branches of the integrate push a trunk that
    is already exactly where it should be. There is no compare-and-swap to make, but the
    push is still publication of shared state, so it is still serialized — ADR-0124 D1
    keeps the push inside the section and ADR-0134's rejected alternative records why
    moving it out is a separate decision nobody has taken.

    `_serialized_advance` with `parent == tip` would express this, and is deliberately not
    used: its contract is *advance the trunk from parent to tip*, and passing a no-op swap
    to say "publish only" makes the receipt read as a land that moved nothing. The sibling
    `_serialized_publish` is the resume case and asserts containment it does not need here.
    Bounded by `_push_trunk`'s own timeout, so it cannot overrun the hold budget."""
    with land_gate_lock():
        current = sh(["git", "rev-parse", "--verify", "--quiet", f"refs/heads/{trunk}"],
                     check=False).stdout.strip()
        if current != tip:
            # Somebody landed while we were classifying. Pushing now would publish a tree
            # this call never looked at.
            return False, (f"integrate: the {trunk} ref moved to {current[:7]} while we "
                           f"were reading it — nothing pushed; run `session.py integrate` "
                           f"again."), None
        return do_push()


def _rebase_in_progress() -> bool:
    """True while this worktree has a rebase stopped mid-flight.

    Asked through `git rev-parse --path-format=absolute --git-path`, never by assuming
    `<repo>/.git/rebase-merge`: in a LINKED worktree — the only place this runs — the
    per-worktree git dir is not the repo's, so a hardcoded path answers about the wrong
    tree, and it answers confidently."""
    for name in ("rebase-merge", "rebase-apply"):
        r = sh(["git", "rev-parse", "--path-format=absolute", "--git-path", name],
               check=False)
        if r.returncode == 0 and r.stdout.strip() and Path(r.stdout.strip()).exists():
            return True
    return False


def _unmerged_paths() -> list[str]:
    return sorted(set(sh(["git", "diff", "--name-only", "--diff-filter=U"],
                         check=False).stdout.split()))


def _resolve_rebase_conflict(policy: str = "generated") -> tuple[bool, list[str]]:
    """Resolve a stopped rebase under a NAMED policy. `(resolved, report lines)`.

    `generated` — the only policy that resolves anything — takes the TRUNK side on any
    conflict confined to this member's generated views, and refuses on anything else. The
    safety argument is not "these files are unimportant", it is that they are **derived**:
    `_recompile_main_checkout` regenerates both from the journals at the end of the very
    land this unblocks, so the side taken here is overwritten before anyone reads it. That
    is the same argument [ADR-0097](adr/0097-a-lane-integrates-the-trunk-with-its-remote.md)
    D4 makes one level up, and it is why the class is *generated files*, not *files that
    look mergeable*.

    **`ROADMAP.md` IS in the class as of WI-0252, per REGION rather than per file.**
    [ADR-0098](adr/0098-a-lane-repairs-main-and-clears-its-own-blocked-rebase.md) D7
    excluded it because *"it is authored prose with one writer per lane"* — and
    [ADR-0105](adr/0105-roadmap-is-a-compiled-trunk-only-view.md) D4 reversed that premise
    eight days later, making the file trunk-only and telling every lane not to touch it.
    The exclusion outlived its reason, and the cost compounded: a lane's roadmap divergence
    is now almost always the harness's own re-render, so *landing behind another lane*
    became close to a guaranteed refusal on a file the trunk regenerates seconds later, and
    the remedy printed with it ("this one needs a mind") sent a mechanical no-op to a human
    every time.

    It is admitted CONDITIONALLY, because the file is generated in regions and not in
    whole: `_conflict_is_resolvable` takes the trunk side only when the discarded side
    changed nothing OUTSIDE the generated markers. A lane that really did edit `## Now` —
    which the standard tells it never to do — still refuses, by name. That keeps both
    halves of the bound: the mechanical case stops costing a human, and the four
    hand-authored surfaces (including prose that exists in no other file) stay under a
    refusal rather than an automatic take.

    Leaves the rebase EXACTLY as it found it when it refuses — the caller aborts — so a
    refusal costs nothing and cannot half-apply."""
    if policy not in RESOLVE_POLICIES:
        return False, [f"resolve: unknown policy '{policy}' — "
                       f"one of {', '.join(RESOLVE_POLICIES)}."]
    if policy == "none":
        return False, []
    views = _generated_view_names()
    if not views:
        return False, ["resolve: this member declares no generated views, so the "
                       "'generated' policy can prove nothing here."]
    env = {**os.environ, "GIT_EDITOR": "true", "GIT_SEQUENCE_EDITOR": "true"}
    took: list[str] = []
    out: list[str] = []
    for _ in range(REBASE_RESOLVE_MAX_STEPS):
        unmerged = _unmerged_paths()
        if not unmerged:
            if not _rebase_in_progress():
                break
            # Stopped with nothing conflicted: the replay went empty. Skipping is the
            # only correct move and is not a loss — the content is already on the trunk.
            if sh(["git", "rebase", "--skip"], check=False, env=env).returncode != 0:
                return False, out + ["resolve: the rebase stopped with nothing "
                                     "conflicted and would not skip."]
            continue
        outside = [p for p in unmerged if not _conflict_is_resolvable(p, policy)]
        if outside:
            return False, out + [
                "resolve: REFUSED — the conflict is not confined to generated files. "
                f"Outside the '{policy}' policy: {', '.join(outside)}."]
        for p in unmerged:
            # `--ours` in a rebase is the side being replayed ONTO — the trunk. That is
            # the side the policy says wins, and getting this backwards would silently
            # publish the lane's stale view over the trunk's.
            if sh(["git", "checkout", "--ours", "--", p], check=False).returncode != 0:
                return False, out + [f"resolve: could not take the trunk side of {p}."]
            if sh(["git", "add", "--", p], check=False).returncode != 0:
                return False, out + [f"resolve: could not stage the resolved {p}."]
            took.append(p)
        cont = sh(["git", "rebase", "--continue"], check=False, env=env)
        if cont.returncode == 0 and not _rebase_in_progress():
            break
        if cont.returncode != 0 and not _unmerged_paths() and _rebase_in_progress():
            if sh(["git", "rebase", "--skip"], check=False, env=env).returncode != 0:
                return False, out + [
                    f"resolve: rebase --continue failed — "
                    f"{(cont.stderr or cont.stdout).strip()[:160]}"]
    else:
        return False, out + [f"resolve: gave up after {REBASE_RESOLVE_MAX_STEPS} steps — "
                             f"more conflicted commits than a bounded policy should paper "
                             f"over."]
    if _rebase_in_progress():
        return False, out + ["resolve: the rebase is still in progress after the policy "
                             "ran — refusing to guess further."]
    uniq = sorted(set(took))
    return True, out + [
        f"resolve: cleared a rebase conflict under the '{policy}' policy — took the trunk "
        f"side of {', '.join(uniq)}. Generated content only: the views are rewritten by "
        f"this land's recompile and the roadmap's regions by the `wi-render` inside it, "
        f"and any roadmap side carrying hand-authored change would have refused instead."]


def _exit_on_failed_land(outcome: "LandOutcome") -> None:
    """Carry a land's verdict into the process exit status, and ONLY on failure.

    WI-0263 (d). Nonzero on failure is the whole point; returning normally on success is
    equally deliberate, because `sys.exit(0)` still raises `SystemExit` and both `end`
    and `merge` are called directly, in-process, by ~8 tests that assert the close
    completes without an exception. Exiting only on failure keeps every one of them
    meaningful instead of rewriting them to catch a success.

    The land has already printed its own report by the time we get here, so this adds a
    single line naming the status code — the number is the part a script reads, and an
    exit code nobody can see is the same invisible-receipt problem in a new place
    ([`a-close-is-the-banner-not-the-sentence`](habits/master.md#a-close-is-the-banner-not-the-sentence))."""
    if outcome:
        return
    code = outcome.exit_code
    if code == 0:
        return                              # nothing to do is not a failure (`integrate`)
    print(f"exit:    {code} — nothing landed"
          + (" (the trunk kept moving; retry with `session.py merge --continue`)" if code == 2
             else f" ({outcome.reason})"))
    sys.exit(code)


def _merge_close_args(args: argparse.Namespace) -> argparse.Namespace:
    """The `end` namespace a closing `merge` runs under (WI-0288 R2).

    ONE CLOSE PATH, NOT TWO (P16). `merge`'s close does not re-implement the close — it
    IS `cmd_end`, called with `merge`'s own flags translated. Everything the close is
    made of comes along unchanged and cannot drift out of step: the ADR-0113 `--confirm`
    gate, the journal stamp, the `end-ran` receipt, the lane-reservation release, the
    banner, the dispatched-runtime shutdown, and the LandOutcome exit codes.

    `--commit` is the one translation. `end` reads a bare `--commit` (const "") as
    'derive the message' and an omitted one as 'do not commit'; `merge` has always
    committed what was in the tree, so an omitted `--commit` maps to the derived form
    rather than to silence.

    `verb` IS NOT A FLAG — it is the one thing the close needs to know that `merge` cannot
    pass as one: which verb the operator actually typed. `cmd_end`'s refusals are written
    for the person reading them, and on this path that person ran `merge`. WI-0340 found
    it the expensive way: a lane read a refusal naming `end` and `--session-id`, ran
    neither, and reached its land by elimination. Everything else here is a flag coming
    across unchanged; this is the seam itself declaring which side of it we are on."""
    return argparse.Namespace(
        verb="merge",
        title=getattr(args, "title", None),
        session_id=getattr(args, "session_id", None),
        commit=args.commit if getattr(args, "commit", None) is not None else "",
        # WI-0355: the fallback is the DEFAULT, not the old value. An in-process caller
        # building a bare namespace (several tests, and `cmd_end`'s own re-entry) would
        # otherwise keep landing local-only while the CLI published — the default flip
        # would have been half-applied, which is worse than not applied.
        push=getattr(args, "push", True),
        focus=getattr(args, "focus", None),
        blocked=getattr(args, "blocked", None),
        no_merge=False,
        confirm=getattr(args, "confirm", None),
        resolve=getattr(args, "resolve", "generated"),
        dry_run=getattr(args, "dry_run", False),
        no_renumber=getattr(args, "no_renumber", False))


def cmd_merge(args: argparse.Namespace) -> None:
    """Land the current session branch onto the trunk AND close the session — the
    default since WI-0288 R2. `--continue` lands without closing (ADR-0056 D3): the
    retry path for a session blocked at the rebase or the gate, the deferred-land path
    for an `end --no-merge`, and the genuine second package, which is now the exception
    you say out loud rather than the shape of a session.

    WHY THE DEFAULT INVERTED. The doctrine landed first, deliberately: 'open a lane,
    land one work item, and close' shipped across the fleet in 769178b while this verb
    still left the journal open, because a session that never stops re-reads its whole
    transcript every turn — 4.89B tokens over fourteen days, median 193k context per
    turn, and the longest sessions paid the most. The verb now does what the doctrine
    says.

    THE CLOSING HALF IS GATED EXACTLY AS `end` IS. An ungated closing `merge` would be a
    clean bypass of ADR-0113 — the same act, one verb over, with no receipt — so it runs
    through `cmd_end` and answers to `--confirm` or a resolved dispatch authorization.
    `--continue` is not a close and needs neither.

    Exit codes are `integrate`'s three, because one land vocabulary beats two: **0**
    landed (or there was nothing to land), **1** refused with the trunk untouched, **2**
    the trunk kept moving. Nonzero only on failure — a success returns normally rather
    than raising `SystemExit(0)` (WI-0263)."""
    if not getattr(args, "keep_open", False):
        cmd_end(_merge_close_args(args))
        return
    if CFG is None:
        raise SystemExit(f"session.py: {CONFIG_PATH.name} missing or invalid — cannot merge.")
    if not args.dry_run:
        _refuse_git_on_fixture("merge")     # WI-0035 — merge is git all the way down
    branch = _current_branch()
    version = role_doc_version()
    focus = getattr(args, "focus", None)
    blocked = getattr(args, "blocked", None)
    # ADR-0060: a worktree lane retries through the plumbing land, not the checkout land.
    if _on_worktree_lane():
        if args.dry_run:
            print(f"--- session merge (dry-run) --- would rebase + gate + CAS-advance "
                  f"'{branch}' → {_trunk()} (worktree lane)")
            return
        _exit_on_failed_land(
            _land_worktree_lane(focus, blocked, version, commit_msg=args.commit or None,
                                push=args.push,
                                resolve=getattr(args, "resolve", "generated"),
                                renumber=not getattr(args, "no_renumber", False)))
        # WI-0354. `--continue` is the route a gate-blocked lane actually lands through,
        # and it had no close: `cmd_end` runs the lane exit and the runtime close only
        # when the land IT ran succeeded, which by construction is not this case. The
        # helper reads the journal to decide whether this land was a close at all, so an
        # ordinary mid-session `--continue` is untouched.
        #
        # LAST, after `_exit_on_failed_land` — which returns only on a landed (or
        # nothing-to-land) outcome and exits nonzero otherwise, so a blocked retry is
        # never mistaken for a finished lane. The call may end this very process, so
        # nothing may follow it that the operator still needs to see.
        _dispatch_close_after_land()
        return
    if not branch.startswith("session/"):
        raise SystemExit(f"session.py merge: not on a session branch (on '{branch}').")
    if args.dry_run:
        print(f"--- session merge (dry-run) --- would rebase + gate + ff-merge "
              f"'{branch}' → {_trunk()}")
        return
    # Sweep any uncommitted work on the branch into a commit before landing (no held
    # commits — ADR-0051 C3). A message is required only if there is something to commit.
    sh(SWEEP_ADD)
    if _has_staged_changes():
        msg = args.commit or f"chore(session): work on {branch}"
        sh(["git", "commit", "-m", msg])
        print(f"committed: {msg}  (on {branch})")
    _exit_on_failed_land(
        _land_branch(focus, blocked, version, push=args.push,
                     renumber=not getattr(args, "no_renumber", False)))


def _main_checkout(at: Path | None = None) -> Path | None:
    """The MAIN checkout's working tree — the parent of the shared git common dir.
    Resolves to the same path whether called from the main checkout or from a lane
    (every linked worktree shares one common dir). None if git cannot report it.

    `at` asks the question OF ANOTHER TREE rather than of this process's cwd. Any caller
    comparing some path against "the main checkout" must pass the repo that path belongs
    to: a cwd-relative answer is about a different repo entirely, and comparing the two
    yields "these differ" — the shape of a real answer, computed from unrelated inputs.
    Caught by `test_wi_commit`, whose store lives in a temp repo: the cwd-relative form
    named the federation's own checkout and declared the temp repo a lane of it."""
    cmd = ["git"] + (["-C", str(at)] if at else [])
    r = sh(cmd + ["rev-parse", "--path-format=absolute", "--git-common-dir"], check=False)
    if r.returncode != 0 or not r.stdout.strip():
        return None
    return Path(r.stdout.strip()).resolve().parent


def _recompile_main_checkout(trunk: str, version: str = "",
                             focus: str | None = None,
                             blocked: str | None = None) -> str:
    """After a lane lands, regenerate the compiled views ON THE TRUNK, stamp `STATUS.md`,
    and commit them.

    The gap this closes (found session ~102: every session reported the same stale
    session number as the previous one). Two mechanisms each correctly declined to
    compile, and together they left nobody doing it:

      * `_land_worktree_lane` deliberately keeps generated views out of the lane's
        rebased history — folding them in made a CAS-losing lane collide on them during
        its re-rebase (the session-83 drill defect). Its comment defers the refresh to
        "the next session start (accept-lag)."
      * That heal is `run_compile` inside `_complete_lazy_start` — which no-ops on a
        session branch or lane by design ([ADR-0056](adr/0056-session-branch-gated-trunk.md) D2,
        the generated-file merge-hotspot rule).

    Each is right in isolation. The moment *every* session became a lane
    ([ADR-0070](adr/0070-worktree-lanes-are-fleet-substrate.md)), the handoff stopped
    regenerating entirely: it froze at the last close that ran from a main checkout, and
    every subsequent session injected THAT session's entry as "the prior session." A
    `force` parameter for exactly this existed on `run_compile`, documented in detail,
    with zero callers — *a mechanism that is merely available gets bypassed exactly when
    it matters* ([`numbers-are-drawn-never-picked`](habits/master.md#numbers-are-drawn-never-picked)'s
    reasoning, in a second namespace).

    Why a subprocess in the main checkout rather than `run_compile(force=True)` here:
    `ROOT` is module-global and derived from `__file__`, so an in-process forced compile
    from a lane would render the LANE's `session-handoff.md` — a file that is about to be
    torn down with the worktree — and would read `sessions/journal/` through the lane's
    own view. Running the main checkout's own `session.py compile` with `cwd` set to it
    gives the right paths and the right git context, and reuses the identical tested code
    path instead of forking a root-parameterised copy (P16).

    Preconditions are re-checked here rather than assumed from the sync above, because
    the sync may have skipped: only compile when the main checkout exists, is not this
    tree, sits on `trunk`, is clean, and holds no live session. Commits ONLY the two
    generated paths, and only if the compile actually changed them. Fail-open and never
    raises — the land already succeeded, and a stale view must never fail it.

    THE STATUS STAMP (WI-0127, reported by a member Architect). `compile` regenerates the
    census line only, so `version` and `last_active` were never touched on this path and
    froze at whatever the last NON-lane close left behind — while the commit landing
    beside them, titled as a views recompile, did modify the file. Every available signal
    said the file was maintained: it is, just not the two fields other systems actually
    read. `STATUS.md`'s own prose makes `last_active` the freshness signal (*"if it's old,
    treat the rest as stale"*), so a frozen value instructs every consumer to discount a
    status block that is current — and it does so most reliably for the members with the
    most lane traffic, since heavy poga use is exactly what keeps a system off the other
    two stamping paths. A wrong answer shaped like a right one, in the cross-system
    surface [ADR-0021](adr/0021-cross-system-status-surface.md) exists to make
    trustworthy. The stamp targets MAIN's copy explicitly; `--focus`/`--blocked` ride
    through from the lane's own `end`, which used to drop them silently here.

    Trunk churn, considered and accepted: this puts a SECOND commit on the trunk after
    the CAS, which a concurrent lane's own CAS will not expect. That costs no extra
    retry in the normal case — a sibling that rebased onto `parent` was going to lose
    its CAS the moment this lane landed *at all*, and the retry loop's rebase simply
    picks up whichever tip it finds, ours or ours-plus-views. The only new exposure is
    the narrow race where this commit lands between a sibling's fetch and its CAS,
    costing it one extra attempt of three. Two lanes landing at the same instant can
    also collide on the main checkout's index lock; that surfaces as a banner and heals
    on its own, because the next land recompiles from scratch and the operation is
    idempotent — it converges rather than corrupting.
    """
    try:
        main = _main_checkout()
        if main is None or main == ROOT.resolve() or not (main / ".git").exists():
            return ""
        head = sh(["git", "-C", str(main), "rev-parse", "--abbrev-ref", "HEAD"],
                  check=False).stdout.strip()
        # WI-0158 / ADR-0099 D4. Both of these used to end *"Run `python3 session.py
        # compile` there."* The COMMAND was never the defect — the bare deictic was. "There"
        # names a checkout the reading lane has no sanctioned route to, and it addresses a
        # session standing in the main checkout, which by standing policy never exists
        # (ADR-0098). `_main_checkout_lines` hit the identical problem under WI-0097 and
        # answered it the way both branches below now do: say what actually happened and
        # what will clear it, rather than issuing an order to a reader who is not in the
        # room. Note the happy path a dozen lines down does not ask ANYONE to compile — it
        # runs the compile itself with `cwd=main` — so the honest report here is which
        # precondition stopped that, and this function runs at every land and is
        # idempotent, so "the next land" is a real answer and not a shrug.
        if head != trunk:
            return (f"views:   NOT refreshed — the main checkout is on '{head}', not "
                    f"{trunk}, so a compile run in it would render the wrong branch's "
                    f"views. The next land that finds it on {trunk} regenerates them; "
                    f"the trunk keeps the views it already carries until it does.")
        if sh(["git", "-C", str(main), "status", "--porcelain"], check=False).stdout.strip():
            # This branch has a lane-runnable verb for its precondition, so it names one.
            # `main-restore` is WI-0097 / ADR-0098's repair: it restores only what it can
            # PROVE the trunk already superseded and reports the rest by name, so even the
            # judgement call is made from the lane reading this line.
            return ("views:   NOT refreshed — the main checkout has local changes. "
                    "`python3 session.py main-restore --dry-run` says which of them the "
                    "trunk has already superseded (drop --dry-run to repair those; "
                    "--show prints what the rest hold); the next land refreshes the "
                    "views once it is clean.")
        if _tree_has_live_session(main):
            return ("views:   NOT refreshed — a session is live in the main checkout; "
                    "it will compile at its own close.")
        r = subprocess.run([sys.executable, str(main / "session.py"), "compile"],
                           cwd=str(main), capture_output=True, text=True, timeout=120)
        if r.returncode != 0:
            return (f"views:   NOT refreshed — compile failed: "
                    f"{(r.stderr or r.stdout).strip()[:200]}")
        # WI-0114: compile regenerates the census; it does NOT touch the header fields.
        # Stamp them here, in the main checkout, for the same reason the compile runs
        # there — see `cmd_stamp_status`. Runs AFTER compile so the stamp is not undone
        # by the regeneration, and BEFORE the commit below so both land together.
        stamp_cmd = [sys.executable, str(main / "session.py"), "stamp-status",
                     "--version", version]
        if focus is not None:
            stamp_cmd += ["--focus", focus]
        if blocked is not None:
            stamp_cmd += ["--blocked", blocked]
        s = subprocess.run(stamp_cmd, cwd=str(main), capture_output=True,
                           text=True, timeout=60)
        if s.returncode != 0:
            # Fail-open like everything else on this path, but never silently: an
            # unstamped STATUS.md is exactly the wrong-answer-shaped-like-a-right-one
            # this whole item is about, so it gets named rather than swallowed.
            return (f"views:   recompiled, but STATUS.md NOT stamped: "
                    f"{(s.stderr or s.stdout).strip()[:200]}")
        # WI-0372: `stamp-status` EXITS 0 when it refuses — deliberately, because a member
        # with no STATUS.md is conformant rather than broken. So the returncode above is
        # structurally blind to a refusal, and this branch is what makes the land report
        # one. The verb's own line is the payload; it already names the reason.
        if "NOT stamped" in (s.stdout or ""):
            return (f"views:   recompiled, but STATUS.md NOT stamped: "
                    f"{s.stdout.strip()[:200]}")
        names = [p.name for p in (CFG.get("handoff"), CFG.get("status")) if p]
        if not names:
            return ""
        # Stamp the MAIN checkout's STATUS.md — the third close path, which never did
        # (WI-0127). Between the compile and the add, so it rides the commit this path
        # already makes rather than adding one. Fail-open like everything else here: a
        # stamp that cannot be written must not fail a land that already succeeded.
        status_cfg = CFG.get("status")
        if status_cfg is not None and version:
            try:
                _stamp_status(version, focus, blocked, status_path=main / status_cfg.name)
            except Exception:
                pass
        sh(["git", "-C", str(main), "add", "--", *names], check=False)
        if not sh(["git", "-C", str(main), "diff", "--cached", "--name-only"],
                  check=False).stdout.strip():
            return ""                      # already current — nothing to commit
        c = sh(["git", "-C", str(main), "commit", "-m",
                "docs(handoff): recompile views and stamp STATUS after lane land"],
               check=False)
        if c.returncode != 0:
            return (f"views:   compiled but NOT committed: "
                    f"{(c.stderr or c.stdout).strip()[:200]}")
        # the stale-materialization deadlock: this commit advanced main's HEAD past the tip `_sync_main_checkout`
        # just recorded, in main's own tree — so the tree is materialized HERE, and the
        # record has to follow or it names a commit the tree is one ahead of. A record
        # that is accurate at the moment it is written and stale a second later is worse
        # than none: the next start would compare the tree against it, find a difference
        # that is really this commit, and decline a materialization it should have made.
        with contextlib.suppress(Exception):
            new = sh(["git", "-C", str(main), "rev-parse", "HEAD"], check=False)
            if new.returncode == 0 and new.stdout.strip() and _tree_equals(
                    main, new.stdout.strip()):
                _record_main_materialization(main, new.stdout.strip())
        return "views:   session-handoff.md + STATUS.md recompiled on the trunk."
    except Exception as e:
        return f"views:   NOT refreshed ({type(e).__name__}) — run `session.py compile`."


def _main_materialized_at(main: Path) -> str | None:
    """The commit `main`'s working tree was last materialized at, or None when unrecorded.

    None is a THIRD ANSWER, not a soft no: every checkout on the fleet predates this record,
    and "I have no record" must never be readable as "the tree equals the record" — that
    collapse is what would license a reset over real work
    ([`declare-what-a-check-assumes`](habits/master.md#declare-what-a-check-assumes)).
    Never raises: an unreadable or malformed record is simply no record."""
    try:
        data = json.loads((main / ".session-state" / MAIN_MATERIALIZED_FILE)
                          .read_text(encoding="utf-8"))
        commit = (data.get("commit") or "").strip()
        return commit or None
    except Exception:
        return None


def _record_main_materialization(main: Path, commit: str) -> None:
    """Write down that `main`'s tree now holds `commit`. Best-effort and never raises — a
    missing record degrades to today's search, which is the behaviour this replaces, so a
    write failure costs performance and certainty but never correctness."""
    try:
        state = main / ".session-state"
        state.mkdir(exist_ok=True)
        atomic_write(state / MAIN_MATERIALIZED_FILE,
                     json.dumps({"commit": commit, "at": _now_iso()}, indent=2) + "\n")
    except Exception:
        pass


def _checkout_sync_base(main: Path, parent: str) -> tuple[str, str]:
    """Which commit does the MAIN checkout's index ACTUALLY sit at? `(base, note)`.

    WI-0133, reported by a member Architect. `_sync_main_checkout` merges `parent -> tip` where
    `parent` is the trunk tip immediately before THIS land. `read-tree -m -u` deliberately
    preserves whatever the checkout has of its own — exactly right while the checkout sits
    at `parent`. But the moment one sync is missed the tree is OLDER than `parent`, so the
    entire un-materialized gap reads as the checkout's own local content, and the next
    land carefully protects it. And the next. **A missed sync is therefore permanent and
    silently compounding — the repair mechanism becomes the thing holding the staleness in
    place.** Clearing that member's cost a human at a plain terminal.

    The fix is to merge from where the checkout REALLY is. The witness is an exact index
    match: walking back the trunk's first-parent history, the newest commit whose tree the
    index matches byte-for-byte is where this checkout was last materialized. Merging from
    THERE updates every path in the gap (the checkout has touched none of them), which is
    the "fast-forward it outright" case their part 2 asks for — reached without a second
    code path, because a two-tree merge from the true base already is one.

    **Falls back to `parent` whenever the answer is not exact**, which is deliberate and is
    the whole safety argument. A checkout sitting at `parent` with local edits of its own
    matches no commit exactly, and that is the common, healthy case — today's behaviour is
    correct for it and must not change. So an unproven base is never guessed at: this only
    ever moves the base when it can point at a specific commit and say the tree is that
    commit. The mixed case (stale AND locally edited) also lands here and is reported
    rather than silently repaired — it is the one case where "which of these differences
    are mine?" has no mechanical answer, and inventing one would overwrite real work.

    the stale-materialization deadlock: the RECORD is consulted first and short-circuits the walk entirely. When the
    substrate itself wrote down where it left this tree, that is not evidence to be weighed
    against a search — it is the answer, and re-deriving it can only turn a fact into a
    guess. The walk stays as the fallback for a checkout with no record yet (which is every
    checkout until its next materialization) and for a record the tree has since moved
    away from."""
    if sh(["git", "-C", str(main), "diff", "--cached", "--quiet", parent],
          check=False).returncode == 0:
        return parent, ""
    recorded = _main_materialized_at(main)
    if recorded and recorded != parent and sh(
            ["git", "-C", str(main), "diff", "--cached", "--quiet", recorded],
            check=False).returncode == 0:
        return recorded, (f"its tree was materialized at {recorded[:7]} (recorded, not "
                          f"searched for) — merged from there, not from {parent[:7]}")
    r = sh(["git", "-C", str(main), "rev-list", "--first-parent",
            f"-{CHECKOUT_BASE_SEARCH}", parent], check=False)
    if r.returncode != 0:
        return parent, ""
    history = r.stdout.split()
    for behind, commit in enumerate(history[1:], start=1):
        if sh(["git", "-C", str(main), "diff", "--cached", "--quiet", commit],
              check=False).returncode == 0:
            return commit, (f"its tree sat at {commit[:7]}, {behind} land(s) behind the "
                            f"trunk — merged from there, not from {parent[:7]}")
    return parent, ""


def _sync_main_checkout(trunk: str, parent: str, tip: str) -> str:
    """After a lane CAS-advances the trunk, bring the MAIN checkout along — or say why not.

    The session-89 defect (consultant F1): `_land_worktree_lane` advances
    `refs/heads/{trunk}` with `git update-ref` and no checkout, which is what makes the
    land cheap and lockless. But the main checkout has that ref as its HEAD, so its index
    and working tree stay at the PRE-advance tip while the ref moves ahead. The tree then
    reports a phantom staged deletion of everything the lane added (~2,032 lines after
    session 89), and — the sharp end — anything running from that tree operates on the old
    content: the nightly adopt-runner's `WorkingDirectory` is the main checkout, and
    `push-substrate` reads `session.py` from the working tree.

    The land path owns this because the land path caused it. Sync ONLY in the provably
    pure fast-forward case, where the checkout has nothing of its own to lose:

      * the main checkout is not this tree (a non-lane close needs no sync),
      * its HEAD is the trunk branch (not detached, not some other branch),
      * its HEAD is exactly `parent` — the tip we CAS'd away from, so the move is a
        strict fast-forward onto our own work,
      * `git status --porcelain` is empty — no staged, unstaged, or untracked content,
      * no session is provably live in it.

    Otherwise touch NOTHING and leave a banner naming the divergence. Never guess: a
    `reset --hard` into a tree that holds real content destroys it, and this runs
    unattended at every land. The precondition set is what makes the write non-destructive
    by construction rather than by hope (P9 — the confirm is discharged structurally,
    since there is provably nothing to confirm about).

    Cross-tree write vs P13 (single-writer-per-state): the land path is already the single
    writer of the trunk ref, and the checkout is a materialization of that ref, not
    independent state — so syncing it is the same writer finishing its own write. The
    fast-forward-only precondition is what keeps that true; the moment the tree holds
    anything of its own, it IS independent state and we stop.

    Fail-open and never raises: a sync hiccup must not fail a land that already succeeded.
    Returns a one-line report for the land output.
    """
    try:
        main = _main_checkout()
        if main is None:
            return "sync:    skipped — cannot resolve the main checkout."
        # STANDING IN THE CHECKOUT IS NOT THE SAME AS HAVING MATERIALISED IT (WI-0359).
        #
        # This used to return "" here — "landed from the main checkout; nothing to sync".
        # That assumed the caller advanced the trunk by an operation that moves the working
        # tree. It does not: the trunk is advanced by a CAS `git update-ref`, which is
        # exactly what makes a land cheap and lockless, and `update-ref` on the branch you
        # are standing on moves HEAD and leaves the index and tree where they were.
        #
        # THE FAILURE THIS PREVENTS: `integrate` run IN the process checkout merges origin,
        # pushes, and reports success with the ref level with origin — while tracked files
        # stay stale on disk. The federation's scheduled jobs run from that tree, so the
        # runner would keep executing pre-merge code after a SUCCESSFUL integrate, and one member's deploy stayed refused by a schema bug that
        # had already been fixed and landed. A green receipt over stale running code is a
        # false receipt — the same shape as a land reporting success while the push is owed.
        #
        # So we fall through and materialise this tree like any other. The materialisation
        # below is non-destructive by construction (`read-tree -m -u` preserves local
        # modifications and refuses rather than clobbering), so running it on our own
        # checkout is safe for the same reason it is safe on someone else's.
        own_tree = (main == ROOT.resolve())
        if not (main / ".git").exists():
            return f"sync:    skipped — {main} is not a checkout."

        def banner(reason: str) -> str:
            # WI-0158 / ADR-0099 D4. The `fix:` line used to read *"inspect, then
            # `git -C {main} reset --hard {trunk}` once you are sure nothing here is worth
            # keeping."* — a remedy REFUSED TWICE for whoever reads this file: check-bash
            # denies `reset --hard` outright under P9 confirm-destructive-ops, and a lane
            # reader's worktree-isolation guard denies the `git -C <other tree>` form on
            # top of that. So the marker this function writes to explain a failed sync was
            # itself an escalation generator, and the escalation target is always operator
            # (`never-route-your-own-work-through-the-user`).
            #
            # `main-restore` (WI-0097 / ADR-0098) is the verb that owns exactly this
            # repair and is runnable from a lane. It also discharges the "once you are
            # sure" clause structurally rather than delegating it: it restores only paths
            # it can prove the trunk already superseded, refuses wholesale while a session
            # is live in main, and names everything it kept and why. That is the same move
            # D3 makes everywhere — the judgement belongs to the verb, not to a human
            # reading a warning file.
            try:
                state = main / ".session-state"
                state.mkdir(exist_ok=True)
                atomic_write(state / "stale-checkout.txt",
                             f"{_now_iso()}  {trunk} advanced {parent[:7]} -> {tip[:7]} "
                             f"by a lane land; this checkout was NOT synced.\n"
                             f"reason: {reason}\n"
                             f"fix:    `python3 session.py main-restore --dry-run`, from "
                             f"any lane or from here, says which of this checkout's changes {trunk} "
                             f"has already superseded; drop --dry-run to restore exactly "
                             f"those, and --show prints what the rest hold. The sync "
                             f"itself retries at the next land.\n")
            except Exception:
                pass
            return f"sync:    main checkout NOT synced — {reason}"

        head_ref = sh(["git", "-C", str(main), "symbolic-ref", "--quiet", "HEAD"], check=False)
        if head_ref.returncode != 0 or head_ref.stdout.strip() != f"refs/heads/{trunk}":
            return banner(f"its HEAD is not refs/heads/{trunk} "
                          f"({head_ref.stdout.strip() or 'detached'})")

        # NOTE: `git status` is NOT the test here, and reaching for it is the trap. In the
        # very condition we are fixing, status is LOUD — HEAD already resolves through the
        # advanced ref while the tree sits at `parent`, so status reports the whole delta
        # as a staged deletion (the ~2,032-line phantom of session 89). "Clean tree" would
        # therefore never fire on the case it exists to handle. `rev-parse HEAD` is useless
        # for the same reason: it reports `tip`, not what the tree holds.
        #
        # The honest witnesses are the index and the tree, each compared to `parent`:
        #   1. index == parent            — nothing staged of its own
        #   2. tree == index              — nothing modified of its own
        #   3. no untracked files         — nothing new of its own
        # Together these say the checkout is byte-for-byte the pre-advance commit, so
        # resetting it to `tip` can destroy nothing. Any one failing means real content.
        # WI-0133: merge from where the checkout ACTUALLY is, which is `parent` in the
        # healthy case and an older commit once a sync has been missed. Everything below
        # — the staged/modified witnesses and the read-tree itself — keys on this rather
        # than on the land's parent, or a stale checkout would keep reading its own
        # un-materialized gap as local content it must protect.
        base, base_note = _checkout_sync_base(main, parent)
        idx = sh(["git", "-C", str(main), "diff", "--cached", "--quiet", base], check=False)
        staged = idx.returncode != 0
        wt = sh(["git", "-C", str(main), "diff", "--quiet"], check=False)
        modified = wt.returncode != 0

        unt = sh(["git", "-C", str(main), "ls-files", "--others", "--exclude-standard"],
                 check=False)
        if unt.returncode != 0:
            return banner("cannot enumerate its untracked files")
        untracked = len(unt.stdout.strip().splitlines()) if unt.stdout.strip() else 0

        # The live-session guard protects SOMEONE ELSE's tree from being moved under them.
        # When the tree is our own, the live session it would find is this process, and
        # refusing on that basis is the bug: the ref has already advanced, so declining to
        # materialise leaves HEAD ahead of the tree — the exact non-rest state WI-0040 and
        # WI-0067 were, with the whole advance rendering as a staged reversal. The content
        # checks below still apply, and `read-tree` still refuses rather than clobbering.
        if not own_tree and _tree_has_live_session(main):
            return banner("a session is live in it right now")

        # BAILING OUT IS NOT NEUTRAL — that was the bug (WI-0040, WI-0067).
        #
        # The old code required the checkout to be byte-identical to `parent` and
        # otherwise touched nothing. But "touch nothing" leaves HEAD at `tip` while the
        # index and tree sit at `parent`, which is not a rest state: git then reports the
        # entire advance as a STAGED REVERSAL, and the next `git commit` from that tree —
        # a routine act, on a tree that looks like it merely has pending work — commits a
        # revert of everything the lane just landed. WI-0040 is that happening to another
        # session's journal (07d139e reverted 49 lines of a concurrent session's own
        # checkpoint, then stamped `ended` onto the reverted body, so it looked closed);
        # WI-0067 is the same trap caught before it fired. Three occurrences in one
        # session, all through the sanctioned path, none of them anyone's mistake.
        #
        # `read-tree -m -u` is the primitive that actually fits: a two-tree merge from
        # `parent` to `tip` that updates the index AND working tree for paths the checkout
        # has not touched, PRESERVES its local modifications, and exits non-zero rather
        # than overwriting anything it would clobber. So the common case (main dirty only
        # on files this land did not touch — e.g. the work-item store) now syncs correctly
        # instead of being abandoned mid-state, and the genuinely conflicting case still
        # stops and says so. Non-destructive by construction, as before, but the safe set
        # is now "paths with nothing of their own" rather than "the whole tree".
        rt = sh(["git", "-C", str(main), "read-tree", "-m", "-u", base, tip], check=False)
        if rt.returncode != 0:
            return banner("its local changes overlap this land — "
                          f"{(rt.stderr or rt.stdout).strip() or 'read-tree refused'}")
        # WI-0134: retire the marker on EVERY success, not just the pristine one. The
        # unlink used to sit after the early return below, so the "fast-forwarded, kept
        # its own content" path — a full success — left the banner file asserting a
        # failure that had just been repaired. Measured 2026-08-15: three of ten converged
        # checkouts carried the marker while their index matched HEAD, so every live
        # instance of it on the fleet was false. A detector nobody retires is a detector
        # nobody can believe, which is the same neglect a member's brief names from the
        # other side (nothing CONSUMES it) — a marker has to be cleared by whatever fixes
        # the condition, or it decays into noise the first reader learns to skip.
        try:
            (main / ".session-state" / "stale-checkout.txt").unlink(missing_ok=True)
        except Exception:
            pass
        # A converged stale checkout says so. Repairing weeks of drift and reporting it
        # identically to a routine one-commit advance would hide the single most useful
        # fact this function can produce.
        tail = f"  [{base_note}]" if base_note else ""
        if staged or modified or untracked:
            kept = ", ".join(p for p, c in (("staged", staged), ("modified", modified),
                                            (f"{untracked} untracked", untracked)) if c)
            # NOT recorded. The tree is at `tip` PLUS content of its own, so it is not
            # byte-identical to any commit and writing `tip` here would assert a match that
            # a later reset would act on. A materialization point that is only usually true
            # is worse than none: the search below still answers this case correctly.
            return (f"sync:    main checkout fast-forwarded {base[:7]} -> {tip[:7]} "
                    f"(its own {kept} content kept){tail}")
        _record_main_materialization(main, tip)
        return f"sync:    main checkout fast-forwarded {base[:7]} -> {tip[:7]}{tail}"
    except Exception as exc:
        return f"sync:    skipped — {exc}"


def _materialize_main_checkout(trunk: str, tip: str) -> str:
    """Bring the MAIN checkout's tree to `tip` when it provably holds nothing of its own.
    One line, or "" when there is nothing to say. the stale-materialization deadlock.

    The verb the deadlock was missing. `main-restore` repairs authored paths, `main-sync`
    commits harness-written ones, and a STALE COPY is neither: it must be materialized, and
    committing it would revert the trunk. This is that third answer, and it does not care
    which half a path falls in — a superseded version is a superseded version.

    Preconditions mirror every other cross-tree write on this path (main resolvable and not
    this tree, HEAD on the trunk, no provably-live session), because the safety argument is
    the same one: the checkout is a materialization of a ref this process already writes,
    not independent state — right up until it holds something of its own, which is exactly
    what the proof rules out.

    Fail-open and never raises. Verifies in the configuration it creates: the tree is
    re-read after the write and success is claimed only against a clean status, never
    against the command's own exit code
    ([`verify-in-the-created-configuration`](habits/master.md#verify-in-the-created-configuration))."""
    try:
        main = _main_checkout()
        if main is None or main == ROOT.resolve() or not (main / ".git").exists():
            return ""
        head = sh(["git", "-C", str(main), "symbolic-ref", "--quiet", "HEAD"], check=False)
        if head.returncode != 0 or head.stdout.strip() != f"refs/heads/{trunk}":
            return ""
        if _tree_has_live_session(main):
            return ""
        if not tip:
            return ""
        recorded = _main_materialized_at(main)
        if recorded == tip and _tree_equals(main, tip):
            return ""                              # already there, and it says so
        safe, why = _main_holds_nothing_of_its_own(main)
        if not safe:
            # ONE row, deliberately. This is the genuine signal — main holds work nobody
            # here can account for — and the old report spent eleven lines on it. A signal
            # that costs a screen is a signal the reader learns to scroll past.
            return (f"main:    the shared checkout holds AUTHORED work and was NOT "
                    f"materialized ({why}) — `python3 session.py main-restore --show` "
                    f"prints what it holds.")
        if _tree_equals(main, tip):
            _record_main_materialization(main, tip)
            return ""                              # nothing moved; only the record was owed
        base = recorded if (recorded and _tree_equals(main, recorded)) else None
        if base:
            # The tree IS `base`, so a two-tree merge from there updates every path in the
            # gap and can conflict with nothing. `read-tree` rather than `reset --hard`
            # for the reason it is used everywhere else on this path: it refuses rather
            # than clobbers, so a proof that was somehow wrong fails closed.
            wrote = sh(["git", "-C", str(main), "read-tree", "-m", "-u", base, tip],
                       check=False).returncode == 0
        else:
            # No single base commit to merge from — the paths were proven one at a time,
            # so they are brought forward one at a time, to the tip.
            st = sh(["git", "-C", str(main), "status", "--porcelain"], check=False)
            rels = [p for p in (_porcelain_rel(l)
                                for l in (st.stdout or "").splitlines() if l.strip())
                    if p]
            wrote = bool(rels)
            for rel in rels:
                if sh(["git", "-C", str(main), "restore", f"--source={tip}", "--staged",
                       "--worktree", "--", rel], check=False).returncode != 0:
                    wrote = False
        if not wrote:
            return (f"main:    could not materialize the shared checkout onto "
                    f"{tip[:7]} — left exactly as it was.")
        after = sh(["git", "-C", str(main), "status", "--porcelain"], check=False)
        if after.returncode != 0 or (after.stdout or "").strip():
            # Do NOT record: the tree is not the tip, whatever the write said. Recording it
            # here is how a wrong answer becomes a durable one.
            return (f"main:    materialization onto {tip[:7]} left the shared checkout "
                    f"not clean — `python3 session.py main-status` has the detail.")
        _record_main_materialization(main, tip)
        was = f"{recorded[:7]} -> " if recorded else ""
        # Names "the main checkout" rather than "the shared checkout" because this line is
        # also the journal's record of the event, read months later out of every context
        # that makes "shared" resolvable.
        return (f"main:    the main checkout was behind its own trunk and was "
                f"materialized {was}{tip[:7]} — {why}.")
    except Exception:
        return ""


def _materialize_main_auto() -> str:
    """The session-start caller (the stale-materialization deadlock), run at the ADR-0055 materialization point beside
    the ADR-0091 harness sweep — and BEFORE it, which is load-bearing rather than tidy: the
    sweep refuses on a non-empty index, and a stale materialization is a non-empty index, so
    running it second is what lets it run at all.

    Says so in one journal line and nowhere else. Silence is the common case: a start that
    materializes nothing writes nothing, anywhere. Never raises."""
    try:
        tip = _trunk_tip()
        if not tip:
            return ""
        line = _materialize_main_checkout(_trunk(), tip)
        if line:
            _journal_note(line.split("main:", 1)[-1].strip())
        return line
    except Exception:
        return ""


def _main_checkout_state() -> dict | None:
    """The MAIN checkout's working-tree state, read from a lane. None when we are not on a
    lane, when main cannot be located, or when git will not answer.

    **A lane is structurally blind to the tree it depends on.** The harness refuses both
    routes from an isolated worktree — `git -C <main>` ("a worktree-isolated session's git
    operations must target its own worktree") and a direct edit of a shared-checkout path.
    Both guards are right and neither should be bypassed. But the consequence was that a
    lane could not even *look*, so main's state was discovered only when something tripped
    over it: a land that declines to fast-forward main, a `push-substrate` that refuses
    because the working tree differs from the trunk, or — the sharp one — a session-end run
    from main that sweeps the dirt into a commit verbatim (WI-0089: that would have
    silently reverted landed ROADMAP prose, a revert dressed as routine housekeeping).

    Reading it through a substrate verb is not a bypass of those guards: the land path
    already reads and writes main under a defined contract (`_sync_main_checkout`), and
    what the guards exist to prevent is a hand-run git command against a tree the session
    does not own. This looks and reports; it changes nothing."""
    try:
        if not _on_worktree_lane():
            return None
        main = _main_checkout()
        if main is None or main == ROOT.resolve():
            return None
        r = sh(["git", "-C", str(main), "status", "--porcelain"], check=False)
        if r.returncode != 0:
            return {"path": main, "readable": False, "dirty": [], "live": False}
        dirty = [l for l in (r.stdout or "").splitlines() if l.strip()]
        return {"path": main, "readable": True, "dirty": dirty,
                "live": _tree_has_live_session(main)}
    except Exception:
        return None


def _main_checkout_state_here() -> dict | None:
    """WI-0461: the same state as `_main_checkout_state`, for a process standing IN the
    main checkout. None anywhere else (a lane uses `_main_checkout_state`; an unrelated
    repo gets nothing).

    The land's printed advice names `main-restore`, and a newcomer reads it in main —
    where this verb used to answer "not on a worktree lane" and stop. The per-path proof
    is the same from either side. Only the liveness question changes: the asker's OWN
    session is live here by definition, so it is excluded; any OTHER live session still
    refuses the whole repair."""
    try:
        if _on_worktree_lane():
            return None
        main = _main_checkout()
        if main is None or main != ROOT.resolve():
            return None
        r = sh(["git", "-C", str(main), "status", "--porcelain"], check=False)
        if r.returncode != 0:
            return {"path": main, "readable": False, "dirty": [], "live": False}
        dirty = [l for l in (r.stdout or "").splitlines() if l.strip()]
        return {"path": main, "readable": True, "dirty": dirty,
                "live": _tree_has_live_session(main, exclude_csid=_claude_session_id())}
    except Exception:
        return None


def _main_checkout_lines() -> list[str]:
    """Orientation lines naming the main checkout's state when it is something a lane
    should know about, preceded by this lane's distance from the trunk (ADR-0108 D3).
    Silent when main is clean AND the lane is current — the overwhelmingly common case."""
    lines: list[str] = _lane_trunk_distance_lines()
    st = _main_checkout_state()
    if st is None:
        return lines
    if not st["readable"]:
        # Distinct from clean, deliberately. "I could not ask" must never render as "fine"
        # ([`declare-what-a-check-assumes`](habits/master.md#declare-what-a-check-assumes)).
        return lines + [f"main:    NOT CHECKED — git would not report on {st['path']}."]
    if not st["dirty"]:
        return lines
    # ADR-0091 D4: harness-written records are the harness's job, not conversation
    # material — they are named once as "pending sweep" and committed at this session's
    # first activity (D3). Only AUTHORED dirt keeps the warning: that is the genuine
    # signal, and burying it under the substrate's own housekeeping is how the user
    # ends up garbage-collecting for the machinery.
    harness, authored = _classify_dirt(st["dirty"])
    if harness and not st["live"]:
        lines.append(f"main:    {len(harness)} harness-written record(s) pending — "
                     f"swept into a commit at this session's first activity (ADR-0091).")
    if not authored:
        if st["live"] and harness:
            lines.append(f"main:    {len(harness)} harness-written record(s) there, and "
                         f"a session is live in the main checkout — its own close "
                         f"commits them; nothing to do here.")
        return lines
    # ONE ROW (the stale-materialization deadlock). This block used to run to eleven lines: a header, up to
    # MAIN_DIRT_REPORT_CAP dirt entries, an elision line, a consequences paragraph and a fix
    # line — every session, on a condition that was usually not authored work at all but a
    # stale materialization the substrate could have repaired for itself. Now that the
    # stale case is materialized automatically before this ever renders, what is left here
    # is the genuine, rare signal: main holds work nobody in this lane can account for. A
    # rare signal stays readable only by actually being rare, and by fitting on one line.
    # `--show` is named because it is what moves the judgement into THIS lane, which is the
    # whole point of WI-0097's verb.
    # The PATHS stay on the row. Dropping them to hit "one line" would trade a block
    # nobody reads for a line nobody can act on, and the names are the only part of the
    # old report that ever answered a question — `main-restore --show` is a second step
    # you take BECAUSE you recognised a filename here. Capped inline for P19.
    named = ", ".join(_porcelain_rel(l) or l.strip() for l in authored[:MAIN_DIRT_REPORT_CAP])
    more = (f", +{len(authored) - MAIN_DIRT_REPORT_CAP} more"
            if len(authored) > MAIN_DIRT_REPORT_CAP else "")
    tail = ("a session is live there — probably its work in progress; leave it alone"
            if st["live"] else
            "`python3 session.py main-restore --show` prints what they hold")
    lines.append(f"main:    the shared checkout holds {len(authored)} uncommitted AUTHORED "
                 f"change(s), not yours and not this lane's to guess about — "
                 f"{named}{more} ({tail}).")
    return lines


