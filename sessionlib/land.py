# ── WI-0097 / ADR-0098: repairing the MAIN checkout's working tree from a lane ──
#
# FOUND session ~125, reopened ~145. main's working `ROADMAP.md` was STALE — missing prose
# a concurrent lane had landed — so committing it verbatim would have REVERTED that prose.
# The `wi-render` guard caught it and refused: working as designed. operator then explicitly
# authorised the repair (`git -C <main> restore ROADMAP.md`, a discard of strictly-stale
# content since HEAD is newer) and the lane **could not run it**: the runtime's worktree-isolation guard
# refuses `git -C` at the shared checkout, and Edit refuses shared-checkout paths. Both
# guards are right. Routing around them with a subprocess or a raw write would have been
# the same bypass wearing a different hat, so the authorised repair went back to the operator's
# shell — the one outcome that whole session existed to eliminate.
#
# The banner made it worse: with no live session in main it printed *"open one in the main
# checkout to resolve them"*, an instruction addressed to a session that by standing policy
# never exists (operator, ~145: sessions never run in main). A nag
# whose only remedy is a place policy forbids trains the reader to skim the block.
#
# THE PREDICATE, and it is stronger than the one the item specified. WI-0097 proposed
# "restore only where the working copy is a STRICT SUBSET of HEAD (no content present in
# the working copy that HEAD lacks)". That is computable, but it has a false positive with
# teeth: a human deliberately DELETING a paragraph in main also produces a diff with no
# added lines, and discarding that destroys real work. What is asked instead is whether the
# working copy is **byte-identical to some ancestor commit's version of that path** — i.e.
# provably content the trunk has already superseded, still reachable in history, so the
# discard cannot lose anything even in principle. It answers YES for the stale-materialization
# case this item is about and NO for a human's edit, which no commit matches. Strictly
# stronger, and [P9](principles/master.md#p9--destructive-ops-confirmed) is discharged
# structurally rather than by an operator's judgement in the moment — the same argument
# `_sync_main_checkout` already makes for its own cross-tree write.


def _main_restore_verdict(main: Path, rel: str, untracked: bool) -> tuple[bool, str]:
    """May `rel` in the main checkout be restored from the trunk? `(restorable, why)`.

    Untracked is never restorable: there is nothing in history to restore it TO, so the
    only "repair" would be deletion, which is destructive by definition and is exactly what
    this predicate exists to refuse.

    For a tracked path, ask whether the WORKING COPY is byte-identical to a committed
    version OF THIS PATH. The first exact match is the proof.

    the stale-materialization deadlock corrected what is walked. This used to enumerate the trunk's last
    `CHECKOUT_BASE_SEARCH` commits and diff the path against each — a window over the
    TREE's history, walked whether or not those commits ever touched the file. Two things
    were wrong with it, and the second is the one with teeth. It is wasteful: a file that
    changes twice a year is compared against two hundred commits holding two distinct
    versions of it. And it is WRONG PAST THE WINDOW: a stale copy whose version was
    superseded more than two hundred commits ago matches nothing inside it and comes back
    "it holds something of its own" — a human's-edit verdict, handed to a stale copy, on
    precisely the checkout that has been behind long enough to need this verb most.

    Walking the path's OWN history fixes both. `rev-list HEAD -- <path>` yields the commits
    where the file actually changed, so the walk covers every version the file has ever had
    on this line and terminates on the file's history rather than the tree's. `HEAD` is
    prepended because the path need not have changed at HEAD, and the identical-to-HEAD case
    (a phantom staged state) has its own answer. Still bounded, for the reason
    `CHECKOUT_BASE_SEARCH` exists ([P19](principles/master.md#p19--cap-what-can-run-away)) —
    but it now bounds versions of this file rather than commits of the tree, which is both
    the right thing to cap and a far more generous cap in practice.

    A MISSING tracked file — the commonest shape of all, since a stale checkout reports
    every path the land ADDED as a staged deletion — is answered by the same question with
    no special case, but only if the walk can still reach a commit where the path did not
    exist. That state is precisely what a path-filtered history omits: `rev-list -- <path>`
    yields the commits where the file CHANGED, and "before it was ever added" is not one of
    them. So the first parent of the oldest touching commit is appended explicitly. Without
    it a file added by the very land that left this checkout behind reads as "it holds
    something of its own" — the tree holding *nothing* at that path, described as content of
    its own, which is exactly backwards."""
    if untracked:
        return False, ("untracked — nothing in history to restore it to, and deleting it "
                       "would be destructive")
    r = sh(["git", "-C", str(main), "rev-list", "--first-parent",
            f"-{CHECKOUT_BASE_SEARCH}", "HEAD", "--", rel], check=False)
    if r.returncode != 0:
        return False, "could not read the main checkout's history"
    head = sh(["git", "-C", str(main), "rev-parse", "HEAD"], check=False)
    if head.returncode != 0:
        return False, "could not read the main checkout's history"
    touched = r.stdout.split()
    before = []
    if touched:
        p = sh(["git", "-C", str(main), "rev-parse", "--verify", "--quiet",
                f"{touched[-1]}^"], check=False)
        if p.returncode == 0 and p.stdout.strip():
            before = [p.stdout.strip()]
    revs, seen = [], set()
    for rev in [head.stdout.strip()] + touched + before:
        if rev and rev not in seen:
            seen.add(rev)
            revs.append(rev)
    for n, rev in enumerate(revs):
        d = sh(["git", "-C", str(main), "diff", "--quiet", rev, "--", rel], check=False)
        if d.returncode == 0:
            if n == 0:
                return True, ("already identical to HEAD — restoring only clears a "
                              "phantom staged state")
            return True, (f"byte-identical to its version at {rev[:7]} — content the "
                          f"trunk has already superseded")
        if d.returncode > 1:
            return False, "git would not diff this path"
    return False, (f"matches none of the {len(revs)} committed version(s) of this path — "
                   f"it holds something of its own")


def _main_restore(dry_run: bool = False, show: bool = False) -> tuple[bool, list[str]]:
    """Restore the MAIN checkout's working tree to the trunk, path by path, under proof.

    `(ok, report lines)`. Reads and writes main through the substrate contract
    `_main_checkout_state` already establishes — the land path writes there too — never as
    a hand-run git command against a tree this session does not own.

    Refuses wholesale when a session is LIVE in main: whatever is there is probably its
    work in progress, and the per-path proof cannot distinguish "stale" from "being edited
    right now" for a file that happens to match an old commit.

    Harness-written records are left strictly alone — they are `main-sync`'s job (ADR-0091
    D3), and two verbs writing the same files is the P13 violation this substrate keeps
    finding. Every path is reported either way: restored with the commit that proves it, or
    kept with what it holds. A repair that silently skipped what it could not prove would be
    the same wrong-answer-shaped-like-a-right-one the proof exists to prevent."""
    st = _main_checkout_state() or _main_checkout_state_here()
    if st is None:
        return True, ["main-restore: not on a worktree lane or in the main checkout "
                      "(or main not locatable) — nothing here to repair."]
    main = st["path"]
    if not st["readable"]:
        return False, [f"main-restore: NOT CHECKED — git would not report on {main}."]
    if not st["dirty"]:
        return True, [f"main-restore: {main} is clean — nothing to repair."]
    if st["live"]:
        return False, ["main-restore: REFUSED — a session is live in the main checkout. "
                       "What is there is probably its work in progress, and no per-path "
                       "proof can tell that from stale. Nothing touched."]
    harness, authored = _classify_dirt(st["dirty"])
    out: list[str] = []
    if harness:
        out.append(f"main-restore: {len(harness)} harness-written record(s) left alone — "
                   f"they are `session.py main-sync`'s job (ADR-0091 D3), not this verb's.")
    if not authored:
        return True, out + ["main-restore: no authored dirt in the main checkout."]
    restorable: list[tuple[str, str]] = []
    kept: list[tuple[str, str]] = []
    for line in authored:
        rel = _porcelain_rel(line)
        if rel is None:
            kept.append((line.strip(), "could not read a path out of this status line"))
            continue
        ok, why = _main_restore_verdict(main, rel, untracked=line.startswith("??"))
        (restorable if ok else kept).append((rel, why))
    for rel, why in restorable:
        if dry_run:
            out.append(f"main-restore: (dry-run) would restore {rel} — {why}.")
            continue
        r = sh(["git", "-C", str(main), "restore", "--source=HEAD", "--staged",
                "--worktree", "--", rel], check=False)
        if r.returncode == 0:
            out.append(f"main-restore: restored {rel} — {why}.")
        else:
            out.append(f"main-restore: could NOT restore {rel} — "
                       f"{(r.stderr or r.stdout).strip()[:160]}")
    for rel, why in kept:
        out.append(f"main-restore: KEPT {rel} — {why}.")
        if show:
            d = sh(["git", "-C", str(main), "diff", "HEAD", "--", rel], check=False)
            body = (d.stdout or "").rstrip()
            out.extend(f"           | {l}" for l in body.splitlines()[:MAIN_RESTORE_DIFF_LINES])
            if len(body.splitlines()) > MAIN_RESTORE_DIFF_LINES:
                out.append(f"           | … {len(body.splitlines()) - MAIN_RESTORE_DIFF_LINES} "
                           f"more line(s).")
    if kept and not show:
        out.append("main-restore: `session.py main-restore --show` prints what the kept "
                   "file(s) hold, so the call can be made from THIS lane rather than by "
                   "opening a session in main.")
    return True, out


