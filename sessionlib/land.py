def _pf_gate() -> _PreflightResult:
    """The gate decides whether work can LAND, and a machine where it is red can be
    worked in all day before anyone finds out — which is exactly what devbox was until
    session ~161 ran the suite there.

    The slowest check by a wide margin (the federation's own gate is ~1,956 tests plus
    three staleness checks), so `--quick` drops it. Dropping it reports SKIPPED, never
    OK: a check that did not run is not a check that passed."""
    ok, report = _run_gate()
    lines = [l for l in report.splitlines() if l.strip()]
    if ok:
        return _PreflightResult(
            "gate", PREFLIGHT_OK,
            f"{len(lines)} configured check(s) passed in this checkout.")
    # WI-0334, second half. This banner is the surface a session start actually puts
    # in front of the operator, and it used to render `lines[:6]` — the report's
    # PREAMBLE. Fixing the truncation inside `_run_gate` while leaving this slice alone
    # would have produced a receipt that names the failing test and a banner that still
    # never shows it ([`retire-the-class-not-the-instance`]). So the banner starts at
    # the failure and runs to the end of the report.
    #
    # NO SECOND CAP, deliberately. What follows the marker is one command's line plus
    # `_gate_failure_receipt`'s output, and that function is already bounded — ten
    # named tests, two elision notes, four verdict lines. Capping a bounded thing again
    # here would re-open the exact hole this change closes, one layer up, and this is
    # the layer that reads "work done here cannot land".
    start = next((i for i, l in enumerate(lines)
                  if l.strip().startswith(GATE_FAIL_MARKER)), None)
    if start is None:
        # The report failed without a line this function recognises — a shape neither
        # producer writes today. Say so rather than silently showing the preamble
        # again ([`declare-what-a-check-assumes`]); the whole report is short enough to
        # print, and guessing which end holds the reason is what got us here.
        body = ["(no recognised failure line in the gate report — printing it whole)"] + lines
    else:
        body = lines[start:]
    first = (lines[start].strip() if start is not None
             else next((l.strip() for l in lines), ""))
    return _PreflightResult(
        "gate", PREFLIGHT_FAIL,
        f"the land gate is RED in this checkout — work done here cannot land.\n"
        + "\n".join(f"           {'':<19} {l}" for l in body),
        f"Fix the gate before working: {first or 'see the report above'}")


def _preflight_narrow_skips() -> tuple:
    """The gate checks `POGA_SKIP_PREFLIGHT_CHECKS` removes, or () (WI-0463).

    Only onboarding and workspace-trust can be named, and only with a live login standing
    in for them: `_pf_auth` must answer OK, or the skip is refused and both checks run.
    That cost (a network call) is paid only by someone who set the variable. Every
    outcome is announced on stderr, so a narrowed launch never reads as a verified one
    (ADR-0096 D7)."""
    raw = os.environ.get(PREFLIGHT_SKIP_CHECKS_ENV, "").strip()
    if not raw:
        return ()
    wanted, ignored = [], []
    for part in raw.split(","):
        name = PREFLIGHT_SKIP_ALIASES.get(part.strip().lower(), part.strip().lower())
        if not name:
            continue
        if name in PREFLIGHT_NARROW_SKIPPABLE:
            if name not in wanted:
                wanted.append(name)
        else:
            ignored.append(part.strip())
    if ignored:
        print(f"poga: NOTE — {PREFLIGHT_SKIP_CHECKS_ENV} can skip only "
              f"{', '.join(PREFLIGHT_NARROW_SKIPPABLE)}; still checking: "
              f"{', '.join(ignored)}.", file=sys.stderr)
    if not wanted:
        return ()
    auth = _pf_auth()
    if auth.verdict != PREFLIGHT_OK:
        print(f"poga: NOTE — {PREFLIGHT_SKIP_CHECKS_ENV} refused: it needs a live login "
              f"in place of {', '.join(wanted)}, and auth is {auth.verdict} — "
              f"{auth.detail} Running every check.", file=sys.stderr)
        return ()
    print(f"poga: NOTE — {PREFLIGHT_SKIP_CHECKS_ENV}: {', '.join(wanted)} NOT checked; "
          f"auth stood in ({auth.detail}). Every other launch check runs.",
          file=sys.stderr)
    fns = {"onboarding": _pf_onboarding, "workspace-trust": _pf_workspace_trust}
    return tuple(fns[n] for n in wanted)


def _preflight_gate() -> None:
    """The launch gate (ADR-0096) — run before poga allocates a lane, so a machine that
    cannot host a session says so instead of failing halfway into creating one.

    WHY IT REFUSES ONLY ON `FAIL`, NEVER ON `UNKNOWN`. A gate that blocks on "could not
    determine" would refuse a launch whenever `$TERM` is unset (every non-interactive
    invocation) or `~/.claude.json` is momentarily unreadable — turning an unanswered
    question into a locked door. So UNKNOWN warns, loudly and by name, and lets you
    through; only a PROVEN failure refuses. That is not the same compromise as folding
    UNKNOWN into a pass: the warning is printed, the operator sees exactly what was not
    verified, and `poga preflight` gives the full answer on demand.

    WHY IT RUNS BEFORE `alloc_lane`. Identical to the ADR-0082 D4 argument for resolving
    the runtime first: a refusal after a worktree and a branch already exist is confusing
    to read and leaves litter to clean up — the failure WI-0105 is open about.

    SILENT ON A CLEAN PASS. A gate that narrates its own success on every launch is noise
    that trains people to stop reading it, and this one runs in front of every session.

    IT REPAIRS BEFORE IT REFUSES (ADR-0109 D5), and this AMENDS ADR-0096, which said in
    terms that the gate "is not a health check and must not grow into one." That sentence
    was written against a gate that could only observe. the operator's ruling — preflight problems
    are fixed by the system and work carries on, not reported to him — makes refusing with a correct
    command the defect rather than the fix, and a local `tic -x` passes ADR-0096 D3's own
    membership test unchanged: local, instant, launch-fatal. What does NOT change is the
    cost on a healthy machine, which is still zero: a repair only ever runs for a check
    that actually FAILED.

    IT ANNOUNCES WHAT IT REPAIRED (D6). Silence is for observation. A gate that mutates
    the machine and says nothing is a gate nobody can audit — and a repaired launch that
    reads identically to a clean one is how a machine's real state goes unnoticed."""
    checks = tuple(c for c in PREFLIGHT_GATE_CHECKS
                   if c not in _preflight_narrow_skips())
    results = [c() for c in checks]
    by_name = {r.name: fn for fn, r in zip(checks, results)}
    unknown = [r for r in results if r.verdict == PREFLIGHT_UNKNOWN]

    for r in unknown:
        print(f"poga: preflight could not verify {r.name} — {r.detail}", file=sys.stderr)

    repairing = os.environ.get(PREFLIGHT_NO_REPAIR_ENV) != "1"
    if repairing and any(r.verdict == PREFLIGHT_FAIL for r in results):
        try:
            results, narration = _preflight_repair(
                results, allow_guided=True, checks_by_name=by_name)
        except Exception as e:
            narration = [f"the repair pass could not run ({type(e).__name__}: {e})"]
        for line in narration:
            print(f"poga: preflight {line}", file=sys.stderr)

    failed = [r for r in results if r.verdict == PREFLIGHT_FAIL]
    if not failed:
        raise SystemExit(0)

    print(f"poga: REFUSING to create a lane — {len(failed)} precondition(s) failed on "
          f"{detect_machine()} and could not be repaired here.", file=sys.stderr)
    for r in failed:
        print(f"  {r.name}: {r.detail}", file=sys.stderr)
        why = PREFLIGHT_REPAIRS[r.name].why if r.name in PREFLIGHT_REPAIRS else ""
        if why:
            print(f"    (not repairable here: {why})", file=sys.stderr)
        if r.remedy:
            print(f"    -> {r.remedy}", file=sys.stderr)
    print(f"  (`poga preflight` checks all nine, including auth and the land gate. "
          f"To launch anyway despite the above, {PREFLIGHT_BYPASS_ENV}=1 poga …; "
          f"to skip only onboarding and workspace-trust when auth is live, "
          f"{PREFLIGHT_SKIP_CHECKS_ENV}=onboarding,workspace-trust poga …; "
          f"to refuse without repairing, {PREFLIGHT_NO_REPAIR_ENV}=1.)",
          file=sys.stderr)
    raise SystemExit(1)


def _wi_land_hint(branch: str) -> str:
    """The remedy for a work-item id stranded on `branch` — named, not left to the reader.

    Three shapes, because the repair genuinely differs and a wrong verb is worse than
    none. A poga lane has two land paths that are not interchangeable: `resume` + `merge`
    for a lane that still needs a mind, `recover` for one whose session is provably over
    (`poga --help`). A REMOTE ref is not a lane at all and has neither — the id is already
    published and this checkout is simply behind it, so the repair is a refresh. Any other
    local branch has no verb, and saying so beats naming a command that will not apply.
    """
    if branch == _trunk():
        # A LOCAL TRUNK is neither a lane nor a remote: there is nothing to land and
        # nothing to fetch — this checkout is simply behind it
        # ([ADR-0108](adr/0108-a-read-names-the-tree-and-commit-it-read.md)),
        # which is the state a lane sits in for its whole life by design.
        return (f"nothing is stranded — `{branch}` already carries it and THIS CHECKOUT "
                f"is behind that ref (ADR-0108); read it from `{branch}`, or land this "
                f"lane with `python3 session.py merge`, which lands on the newest trunk")
    if "/" in branch and not branch.startswith("worktree-"):
        return (f"nothing is stranded — `{branch}` already carries it and this checkout "
                f"is behind that ref; refresh with `git fetch` + `git pull --ff-only`")
    m = re.match(r"^worktree-poga-(\d+)$", branch)
    if not m:
        return f"`{branch}` is not a poga lane — recover the file from that branch by hand"
    n = m.group(1)
    return (f"`poga resume {n}` then `python3 session.py merge` from the lane, or "
            f"`poga recover --lane {n}` if its session is over")
