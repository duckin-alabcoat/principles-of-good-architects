def _push_if_ahead() -> None:
    """The deferred half of the start sync (ADR-0055): push prior sessions'
    unpushed commits at FIRST ACTIVITY rather than at SessionStart — the one
    outward act a phantom preload must never perform. Uses the fetch state the
    start already established; strictly-ahead only (never resolves divergence).
    Best-effort, fail-open."""
    try:
        rev = sh(["git", "rev-list", "--left-right", "--count", "@{u}...HEAD"], check=False)
        if rev.returncode != 0:
            return
        behind, ahead = (int(x) for x in rev.stdout.split())
        if ahead and not behind:
            sh(["git", "push"], check=False)
    except Exception:
        pass


# --- session branch → gated trunk (ADR-0056, concurrency Phase 2 / C3) --------
#
# Every session works on `session/<session-id>`, cut from the trunk at first
# activity (the same heartbeat that materializes the journal, ADR-0055 — so a
# phantom never branches). It lands onto the trunk through a fail-closed gate via
# rebase + ff-only merge. The compiled views regenerate on the trunk ONLY (D2);
# a branch cut from the trunk already carries every landed journal, so ordinals /
# compile work on the branch with no cross-branch reading.

def _trunk() -> str:
    return (CFG or {}).get("trunk", "main")


def _wi_landed_evidence(wid: str) -> tuple[str, str]:
    """Find a substantive trunk commit citing a WI, directly or through its journal.

    Return (state, sha): landed, in-flight, absent, or unknown. Store-only commits
    cannot prove delivery; they are the very false positive this guard prevents.
    """
    trunk = f"refs/heads/{_trunk()}"
    if sh(["git", "rev-parse", "--verify", "--quiet", trunk],
          cwd=ROOT, check=False).returncode != 0:
        return "unknown", ""

    def substantive(sha: str) -> bool:
        r = sh(["git", "diff-tree", "--root", "--no-commit-id", "--name-only",
                "-r", sha], cwd=ROOT, check=False)
        if r.returncode != 0:
            return False
        return any(not (p.startswith(f"{WI_DIRNAME}/") or
                        p.startswith("sessions/journal/") or
                        p in {"session-handoff.md", "STATUS.md", "ROADMAP.md"})
                   for p in r.stdout.splitlines())

    def matching_commits(ref_args: list[str]) -> list[str] | None:
        r = sh(["git", "log", *ref_args, "--fixed-strings", f"--grep={wid}",
                "--format=%H%x1f%B%x1e"], cwd=ROOT, check=False)
        if r.returncode != 0:
            return None
        return [sha for record in r.stdout.split("\x1e")
                if "\x1f" in record
                for sha, body in [record.strip().split("\x1f", 1)]
                if re.search(rf"(?<![A-Za-z0-9]){re.escape(wid)}(?!\d)", body)
                and substantive(sha)]

    landed = matching_commits([trunk])
    if landed is None:
        return "unknown", ""
    if landed:
        return "landed", landed[0]

    # Closing lanes cite the item in journal frontmatter; their squash subjects
    # cite the journal ID. Read the journal FROM the trunk, never from a lane's
    # working tree, or an unlanded file would masquerade as delivery.
    journals = sh(["git", "grep", "-l", "-F", wid, trunk, "--",
                   "sessions/journal/"], cwd=ROOT, check=False)
    if journals.returncode not in (0, 1):
        return "unknown", ""
    for entry in journals.stdout.splitlines():
        path = entry.split(":", 1)[1]
        content = sh(["git", "show", entry], cwd=ROOT, check=False)
        if content.returncode != 0:
            return "unknown", ""
        front = content.stdout.split("\n---", 1)[0]
        if not any(line.startswith("work-items:") and
                   re.search(rf"(?<![A-Za-z0-9]){re.escape(wid)}(?!\d)", line)
                   for line in front.splitlines()):
            continue
        sid = Path(path).stem
        commits = sh(["git", "log", trunk, "--format=%H%x1f%s%x1e", "--", path],
                     cwd=ROOT, check=False)
        if commits.returncode != 0:
            return "unknown", ""
        for record in commits.stdout.split("\x1e"):
            if "\x1f" not in record:
                continue
            sha, subject = record.strip().split("\x1f", 1)
            if sid in subject and substantive(sha):
                return "landed", sha

    in_flight = matching_commits(["--all", "--not", trunk])
    if in_flight is None:
        return "unknown", ""
    if in_flight:
        return "in-flight", in_flight[0]
    # A closing lane's commit may name only its journal, just like a landed
    # close. Search unlanded journal commits as well so the refusal gives the
    # correct remedy for that common shape.
    pending = sh(["git", "log", "--all", "--not", trunk,
                  "--format=%H%x1f%s%x1e", "--", "sessions/journal/"],
                 cwd=ROOT, check=False)
    if pending.returncode != 0:
        return "unknown", ""
    for record in pending.stdout.split("\x1e"):
        if "\x1f" not in record:
            continue
        sha, subject = record.strip().split("\x1f", 1)
        if not subject.startswith("docs(handoff): close ") or not substantive(sha):
            continue
        changed = sh(["git", "diff-tree", "--root", "--no-commit-id",
                      "--name-only", "-r", sha, "--", "sessions/journal/"],
                     cwd=ROOT, check=False)
        if changed.returncode != 0:
            return "unknown", ""
        for path in changed.stdout.splitlines():
            if Path(path).stem not in subject:
                continue
            journal = sh(["git", "show", f"{sha}:{path}"], cwd=ROOT, check=False)
            if journal.returncode != 0:
                return "unknown", ""
            front = journal.stdout.split("\n---", 1)[0]
            if any(line.startswith("work-items:") and
                   re.search(rf"(?<![A-Za-z0-9]){re.escape(wid)}(?!\d)", line)
                   for line in front.splitlines()):
                return "in-flight", sha
    return "absent", ""


def _require_wi_landed_evidence(wid: str) -> None:
    state, sha = _wi_landed_evidence(wid)
    if state == "landed":
        return
    trunk = f"refs/heads/{_trunk()}"
    detail = (f"a citing commit {sha[:12]} exists outside {trunk} but has not landed"
              if state == "in-flight" else
              "the trunk citation could not be checked" if state == "unknown" else
              "no substantive citing commit was found")
    print(f"wi-status: refusing {wid} -> done: {detail}. Nothing was written.\n"
          f"           Looked on {trunk} for a commit message citing {wid}, or a\n"
          f"           landed close commit naming a journal whose work-items: cites {wid}.\n"
          f"           Work-item-only and generated-view commits do not count.\n"
          f"           Remedy: land the lane with its work and journal, then retry.\n"
          f"           If the work is already landed without a citation, land a\n"
          f"           substantive correction commit citing {wid}; a note alone is\n"
          f"           not evidence of shipped work.")
    sys.exit(2)


def _checkout_staleness(ttl: int = CHECKOUT_FETCH_TTL_SECONDS, ref: str = "HEAD",
                        root: Path | None = None, fetch: bool = True,
                        timeout: int = CHECKOUT_FETCH_TIMEOUT_SECONDS,
                        ) -> tuple[int | None, str, str, float | None]:
    """How far `ref` is behind its upstream: `(behind, upstream, why, age)`.

    THREE OUTCOMES, NEVER TWO (`declare-what-a-check-assumes`):

      behind is an int >= 0   we looked, and this is the answer
      behind is None          CANNOT TELL, and `why` says what stopped us

    "I could not look" must never render as "nothing is wrong". That collapse is the
    defect this whole neighbourhood keeps producing, and here it would be worse than
    usual: the caller that REFUSES a draw would quietly start allowing it again, leaving
    the allocator unguarded precisely when git is in a state nobody understands.

    `age` is how old the fetch this answer rests on is, in seconds — None when unknown,
    0.0 when we just fetched. It exists so the report can say how fresh its knowledge is
    rather than implying it is current.

    THE CACHE IS THE POINT (WI-0222, the operator's call session ~187). A network fetch
    costs several times what a local `poga work list` does, on a verb typed constantly —
    so refreshing every time was rejected. Never refreshing was rejected too,
    and for a worse reason: a remote-tracking ref nobody has updated reports "current"
    while you are hundreds of commits behind, which is the false all-clear. So refresh at most once
    per `ttl` seconds, and report the age of anything older.

    `ttl=0` means always refresh, with no stamp read and no stamp write — `attach` uses it,
    because it runs rarely and deliberately and would rather pay the second than be wrong.
    """
    root = root or ROOT
    try:
        r = sh(["git", "rev-parse", "--abbrev-ref", "--symbolic-full-name", f"{ref}@{{u}}"],
               check=False, cwd=root)
        if r.returncode != 0 or not (r.stdout or "").strip():
            return None, "", f"no upstream is tracked for {ref}", None
        upstream = r.stdout.strip()
        age, tried = (None, None) if ttl <= 0 else _fetch_ages(root, upstream)
        # `fetch=False` answers from the refs already on disk and leaves `age` as whatever
        # we actually know — usually None, i.e. "this answer may be arbitrarily old".
        # Offered for a caller that would rather be fast than sure; it must never be the
        # default, because that IS the false all-clear.
        if fetch and (ttl <= 0 or tried is None or tried >= ttl):
            ok = False
            try:
                f = subprocess.run(["git", "fetch", "--quiet"], cwd=root, text=True,
                                   capture_output=True, check=False, timeout=timeout)
                ok = f.returncode == 0
                why = "" if ok else (
                    ((f.stderr or "").strip().splitlines() or ["fetch failed"])[-1])
            except subprocess.TimeoutExpired:
                why = f"it did not answer within {timeout}s"
            finally:
                if ttl > 0:
                    _fetch_stamp_write(root, upstream, ok)
            if not ok:
                # CANNOT TELL, and the age we hand back is the age of the refs we DID NOT
                # manage to refresh — never 0.0, which would date the answer to a refresh
                # that failed.
                return None, upstream, f"the refresh failed ({why})", age
            age = 0.0
        c = sh(["git", "rev-list", "--count", f"{ref}..{upstream}"], check=False, cwd=root)
        if c.returncode != 0:
            return None, upstream, f"could not count {ref}..{upstream}", age
        behind = int((c.stdout or "0").strip() or 0)
    except Exception as e:
        return None, "", f"the check itself failed ({type(e).__name__})", None
    return behind, upstream, "", age


def _has_no_remote(root) -> bool:
    """True only when git ANSWERED and named no remote. A failed probe is not "none"."""
    try:
        r = sh(["git", "remote"], check=False, cwd=root)
    except Exception:
        return False
    return r.returncode == 0 and not (r.stdout or "").strip()


def _report_checkout_staleness(verb: str) -> None:
    """One line before the verb runs, when the store's checkout is not provably current.

    SILENT WHEN CURRENT — the common case must cost nothing to read, or the line stops
    being read at all. On STDERR, because `N=$(session.py adr-next)` captures stdout and a
    warning that corrupted a capture would be worse than the staleness it warns about."""
    if verb in CHECKOUT_QUIET_VERBS:
        return
    root = _shared_work_root()
    behind, upstream, why, age = _checkout_staleness(ref=_trunk(), root=root)
    if behind is None and not upstream and _has_no_remote(root):
        # A LOCAL-ONLY PROJECT IS CURRENT BY CONSTRUCTION. With no remote configured
        # there is no other copy to be behind, so "I could not look" is the wrong answer:
        # there is nothing to look at. `poga init` makes exactly this project by default
        # (WI-0452), and the basic acceptance drill (WI-0455) printed this warning ahead
        # of every `poga work` verb there. A repo WITH a remote but no upstream still warns.
        return
    if behind is None:
        print(f"poga: CANNOT TELL whether {root} is current — {why}. What follows may be "
              f"stale; nothing here can rule it out.", file=sys.stderr)
        return
    if behind > 0:
        print(f"poga: {root} IS {behind} COMMIT(S) BEHIND {upstream}"
              f"{_staleness_as_of(age)}. You are reading and running old code, and the "
              f"store below is that old too. Pull there, then re-run. (Reporting only; "
              f"nothing pulls under you.)", file=sys.stderr)
        return
    # A COUNT OF ZERO IS NOT AN ALL-CLEAR IF NOTHING EVER REFRESHED. Caught by running the
    # real path with the network down (WI-0222): the attempt-throttle correctly skips the
    # retry, `rev-list` then answers 0 against remote-tracking refs that were never
    # updated, and the honest "I could not look" renders byte-identical to "nothing is
    # wrong" — the exact collapse `declare-what-a-check-assumes` names, rebuilt by the fix
    # for it. `age is None` is the tell: there is no successful refresh to date the answer.
    if age is None:
        print(f"poga: CANNOT TELL whether {root} is current — it matches {upstream} as "
              f"recorded here, but nothing has refreshed that record successfully, so "
              f"'matches' may only mean 'unchanged since we last managed to look'.",
              file=sys.stderr)
        return
    # AND A COUNT OF ZERO IS NOT AN ALL-CLEAR IF THE LAST SUCCESSFUL REFRESH HAS AGED OUT.
    # Third layer of one collapse, found by running the real path again after the land
    # (WI-0222). While refreshes keep FAILING, `tried` advances on every attempt and `at`
    # does not — so between two failed attempts the throttle skips the refresh, the count
    # comes back 0 against refs that may be hours old, and silence claims a freshness
    # nothing established. The TTL is already this code's own definition of "fresh enough";
    # an answer older than it does not get to be reported as if it were inside it.
    if age >= CHECKOUT_FETCH_TTL_SECONDS:
        print(f"poga: CANNOT TELL whether {root} is current — it matches {upstream}"
              f"{_staleness_as_of(age)}, and no refresh has succeeded since. Treat "
              f"'matches' as 'unchanged since we last managed to look'.", file=sys.stderr)
        return


# ── Is the shared trunk current with origin, before we land on it? (WI-0356) ──────
#
# THE DEFECT, measured rather than reasoned about. `_report_checkout_staleness` above
# prints `IS N COMMIT(S) BEHIND origin/main ... (Reporting only; nothing pulls under
# you.)` and the land then runs anyway. On 2026-09-13 the shared trunk sat 1 behind
# origin — the Runner's own deploy-receipt push — and lands kept stacking on the stale
# trunk. Within the hour it was 19 AHEAD and 1 BEHIND, diverged, and the push was
# rejected non-fast-forward. Recovery cost an `integrate` (merge + full re-gate) and
# reached operator, which is the failure this exists to remove.
#
# A warning the tool itself then ignores is not a safeguard; it is a record that the tool
# knew. One-behind is trivially recoverable and diverged is not, so the warning fired in
# exactly the window where acting was free and declined to act.
#
# THREE STATES, NEVER TWO (`declare-what-a-check-assumes`), and the third is why this is
# a gate and not merely a louder print:
#
#   BEHIND ONLY   ahead == 0, behind > 0 — FAST-FORWARD the trunk, then land on it.
#                 Nothing is rewritten and nothing can be lost, because `local` is an
#                 ancestor of `remote` by construction. This is the state where acting is
#                 free, and shipping the act as the DEFAULT is the whole point: a fix that
#                 ends in "and then someone runs a pull" leaves the defect in place with a
#                 manual step bolted on.
#   DIVERGED      ahead > 0 AND behind > 0 — REFUSE, naming `session.py integrate`.
#                 Reconciling a diverged trunk is a merge plus a full re-gate; that is
#                 integrate's job and must not happen implicitly inside someone else's
#                 land, where a conflict would surface as a mysterious land failure and
#                 the lane would hold the queue through two suite runs.
#   CANNOT TELL   the refresh failed, or the count could not be read — REFUSE. "I could
#                 not look" rendering as "nothing is wrong" is the precise collapse
#                 `declare-what-a-check-assumes` names, and here it IS the item:
#                 proceeding on an unverified trunk is what cost.
#
# NOT A STATE, and deliberately kept out of all three: a checkout with no remote, or an
# origin that has no trunk yet. There is nothing there to be behind. Collapsing that into
# CANNOT TELL would refuse every land in a local-only checkout — including every suite
# fixture — which is the failure direction this must not have.


class _TrunkOrigin:
    """Where the shared trunk stands against origin, and whether a land may proceed.

    `state` is one of:

      "current"    the trunk contains origin's tip — equal to it, or ahead of it with
                   nothing of origin's missing. Land.
      "behind"     ahead == 0 and behind > 0. Fast-forward, then land.
      "diverged"   ahead > 0 AND behind > 0. Refuse; `session.py integrate` is the verb.
      "unknown"    we could not look, and `why` says what stopped us. Refuse.
      "unremoted"  no remote, or origin has no trunk. Nothing to check. Land.

    AHEAD IS NOT A PROBLEM and does not get its own refusal: unpushed local commits are
    the ordinary state of a trunk between a land and its push, and the land about to run
    is what adds more of them. Only the *combination* with behind is unrecoverable.
    """

    __slots__ = ("state", "ahead", "behind", "local", "remote", "upstream", "why")

    def __init__(self, state: str, ahead: int = 0, behind: int = 0, local: str = "",
                 remote: str = "", upstream: str = "", why: str = "") -> None:
        self.state = state
        self.ahead = ahead
        self.behind = behind
        self.local = local
        self.remote = remote
        self.upstream = upstream
        self.why = why

    @property
    def may_land(self) -> bool:
        """True for the states a land may proceed from with NO action taken first.

        `behind` is excluded on purpose: it is recoverable, not acceptable. The caller
        fast-forwards and only then proceeds, so nothing can read this property and
        conclude that landing on a stale trunk is fine."""
        return self.state in ("current", "unremoted")

    def __repr__(self) -> str:                                  # pragma: no cover
        return (f"_TrunkOrigin({self.state!r}, ahead={self.ahead}, "
                f"behind={self.behind}, why={self.why!r})")


def _trunk_vs_origin(trunk: str, fetch: bool = True,
                     timeout: int = CHECKOUT_FETCH_TIMEOUT_SECONDS,
                     root: "Path | None" = None) -> "_TrunkOrigin":
    """Classify the SHARED trunk against origin. Pure ref reads plus one fetch; no lock.

    The trunk here is `refs/heads/<trunk>` read from THIS worktree, and that is not an
    approximation of the shared one — it IS the shared one. Every lane is a linked
    worktree of a single git common dir (`_shared_work_root` resolves the main checkout
    from exactly that fact), so the ref store is shared and a lane reads the same
    `refs/heads/<trunk>` that the main checkout holds as its HEAD.

    ALWAYS FETCHES, with no TTL and no stamp — `_checkout_staleness`'s `ttl=0` mode, for
    the reason that mode already states: this runs rarely and deliberately and would
    rather pay the second than be wrong. The 10-minute cache exists for verbs typed
    constantly; a land is not one of them, and a ten-minute-old "current" is precisely how
    one-behind became diverged. `fetch=False` answers from the refs already on disk and
    exists for a caller that has just refreshed for itself; it must never be the default,
    because an unrefreshed remote-tracking ref reporting "current" IS the false all-clear.
    """
    root = root or ROOT
    if not sh(["git", "remote"], check=False, cwd=root).stdout.split():
        return _TrunkOrigin("unremoted", why="no remote is configured")
    local = sh(["git", "rev-parse", "--verify", "--quiet", f"refs/heads/{trunk}"],
               check=False, cwd=root).stdout.strip()
    if not local:
        return _TrunkOrigin("unremoted", why=f"there is no local {trunk} yet")
    up = sh(["git", "rev-parse", "--abbrev-ref", "--symbolic-full-name", f"{trunk}@{{u}}"],
            check=False, cwd=root)
    upstream = (up.stdout or "").strip() if up.returncode == 0 else ""
    if fetch:
        try:
            f = subprocess.run(["git", "fetch", "--quiet"], cwd=root, text=True,
                               capture_output=True, check=False, timeout=timeout)
            if f.returncode != 0:
                last = ((f.stderr or "").strip().splitlines() or ["fetch failed"])[-1]
                return _TrunkOrigin("unknown", local=local, upstream=upstream,
                                    why=f"the refresh failed ({last})")
        except subprocess.TimeoutExpired:
            return _TrunkOrigin("unknown", local=local, upstream=upstream,
                                why=f"the refresh did not answer within {timeout}s")
        except Exception as e:
            return _TrunkOrigin("unknown", local=local, upstream=upstream,
                                why=f"the refresh itself failed ({type(e).__name__})")
    # Resolved AFTER the fetch: the first fetch is what CREATES
    # `refs/remotes/origin/<trunk>` in a clone that has never seen it, so asking before
    # would answer about the wrong world. A configured upstream wins when there is one;
    # `origin/<trunk>` is the fallback for a trunk nobody set tracking on, which is the
    # ordinary state of a lane's local trunk.
    if not upstream:
        upstream = f"origin/{trunk}"
    # Asked with `cwd=root` rather than through `_ref_exists`, which asks ROOT. Every
    # caller today passes the default, so the two agree — but a parameter honoured by
    # four reads out of five is a trap laid for the first caller who uses it, and this
    # is the read that decides whether there is anything to compare against at all.
    if not sh(["git", "rev-parse", "--verify", "--quiet", upstream],
              check=False, cwd=root).stdout.strip():
        return _TrunkOrigin("unremoted", local=local, upstream=upstream,
                            why=f"origin has no {trunk} yet")
    remote = sh(["git", "rev-parse", "--verify", "--quiet", upstream],
                check=False, cwd=root).stdout.strip()
    if not remote:
        return _TrunkOrigin("unknown", local=local, upstream=upstream,
                            why=f"could not resolve {upstream}")
    c = sh(["git", "rev-list", "--left-right", "--count", f"{local}...{remote}"],
           check=False, cwd=root)
    try:
        if c.returncode != 0:
            raise ValueError(((c.stderr or "").strip().splitlines() or ["failed"])[-1])
        ahead, behind = (int(x) for x in c.stdout.split())
    except Exception as e:
        return _TrunkOrigin("unknown", local=local, remote=remote, upstream=upstream,
                            why=f"could not count {trunk}...{upstream} ({e})")
    state = "diverged" if (ahead and behind) else ("behind" if behind else "current")
    return _TrunkOrigin(state, ahead, behind, local, remote, upstream)


def _ff_trunk_to_origin(trunk: str, local: str, remote: str,
                        label: str = "land") -> tuple[bool, list[str]]:
    """Fast-forward the shared trunk ref to `remote`, and bring the main checkout along.

    PURE FAST-FORWARD BY CONSTRUCTION: every caller has first established that `local` is
    an ancestor of `remote` (ahead == 0), so nothing of ours is rewritten and there is
    nothing of ours to lose. That is exactly why this case can be taken automatically and
    the diverged one cannot.

    The CAS carries `local` as the expected old value, so a sibling that moved the trunk
    between the classification and here costs nothing: the update is refused, we write
    nothing, and the caller looks again.

    Extracted from `_integrate_trunk_with_remote`'s `behind` branch rather than copied
    beside it (P16). ADR-0117 D4's lesson is that a land-path move made in one place and
    not the others ships as a known gap the same day; "origin is ahead and we hold nothing
    of our own" now has one implementation, and it gained the `trunk_lock` that branch
    never took while it was the only one."""
    with trunk_lock():
        cas = sh(["git", "update-ref", f"refs/heads/{trunk}", remote, local], check=False)
    if cas.returncode != 0:
        return False, [f"{label}: the {trunk} ref moved while we were fast-forwarding it "
                       f"— nothing was written."]
    lines = [f"{label}: fast-forwarded {trunk} {local[:7]} → {remote[:7]} — origin was "
             f"ahead and we held nothing of our own, so this runs on current code."]
    sync = _sync_main_checkout(trunk, local, remote)
    if sync:
        lines.append(sync)
    return True, lines


#: How many times a LOST FAST-FORWARD CAS is worth re-reading the world for.
#
# A NUMBER, deliberately, and the reason it is not derived the way `_cas_budget` is
# (WI-0266) is that the cost it bounds does not move. `_cas_budget` exists because a
# lander's retry re-runs the whole suite, so the odds of surviving one attempt fall as
# the suite grows and a constant beside that silently means something different every
# month. What is retried HERE is one fetch and one `update-ref` — milliseconds of
# window, fixed forever. Losing it three times running is not contention to be sized
# for; it is a signal that the trunk is being hammered, which the land's own CAS budget
# is the right instrument to report.
TRUNK_FF_CAS_ATTEMPTS = 3

#: Land on a trunk we could not verify against origin. THE OPT-OUT, NEVER THE DEFAULT.
#
# Refusing on CANNOT TELL is the decided rule and it stays the default. This exists
# because the rule has one genuine cost and it is worth naming: the refusal fires on a
# failed refresh, and a failed refresh is not always origin's fault — a machine's route
# to the git host can be measurably flaky (`PUSH_UNREACHABLE_MARKERS` records 1 failure in
# 4 probes, and a 75 s timeout when it goes). Without an escape, a safeguard against a
# stale trunk becomes a machine that cannot land at all while its network is sick, and
# a safeguard that locks the door is the failure `_preflight_gate` already argues
# against: an unanswered question must not become a locked door.
#
# So: automatic path as the DEFAULT, escape as a deliberate opt-out an operator TYPES
# — never a silent fallback to the refs on disk, which would be the false all-clear
# wearing the fix's clothes. Using it prints what was traded away.
#
