def _board_gate(status: object, feed: object, now: float) -> tuple[bool, str]:
    """The startup board-gate decision, pure so every branch is testable: is the board
    PROPERLY SHOWING this system's work items right now?

    Three requirements, each with its own refusal sentence
    ([`declare-what-a-check-assumes`]): the status file parses with a schema this gate
    knows; the board's render loop wrote it recently (a dead board's file goes stale by
    itself); and the feed stamp it echoes for THIS system is current against the live
    feed, allowing one declared poll interval of honest lag. Anything else is "not
    showing" — fail-open to the full list, re-decided every session, because a one-time
    switch freezes 'worked when we checked' into config
    ([`a-close-is-the-banner-not-the-sentence`])."""
    if not isinstance(status, dict) or status.get("schema") != 1:
        return False, "board status: missing or unknown schema"
    if not isinstance(feed, dict) or not isinstance(
            feed.get("generated_epoch"), (int, float)):
        return False, "no published feed to compare against"
    written = status.get("written_epoch")
    if not isinstance(written, (int, float)):
        return False, "board status: no written_epoch"
    poll = status.get("poll_seconds")
    if not isinstance(poll, (int, float)) or poll <= 0:
        poll = 0
    allowance = max(2 * poll, BOARD_FRESH_FLOOR_SECONDS)
    if now - written > allowance:
        return False, (f"board status stale — written {int(now - written)}s ago, "
                       f"allowance {int(allowance)}s")
    sysid = feed.get("system", "")
    echo = (status.get("workitems") or {}).get(sysid)
    egen = echo.get("feed_generated_epoch") if isinstance(echo, dict) else None
    if not isinstance(egen, (int, float)):
        return False, f"board is not rendering system '{sysid}'"
    if feed["generated_epoch"] - egen > allowance:
        # Deliberately reports NO lag duration (WI-0121). The available difference is
        # between two CONSECUTIVE feed generations, so after a quiet store it equals the
        # quiet period, not the board's lag: a write ending a 2h silence made this branch
        # say "6906s behind" about a board that was under 1s behind and caught up on its
        # next poll. The board's own staleness is already measured by the written_epoch
        # check above, which this branch reports instead — so every number here is one
        # that was actually measured ([`no-fabricated-data`], [`declare-what-a-check-assumes`]).
        return False, (f"board has not picked up the current feed — it echoes generation "
                       f"{int(egen)}, live feed is {int(feed['generated_epoch'])}; the "
                       f"board itself wrote {int(now - written)}s ago "
                       f"(allowance {int(allowance)}s)")
    return True, "live"


def _gate_top_prefix(rel: str) -> str:
    """Top-level component of a repo-relative path, trailing slash for a directory.

    `sessions/journal/x.md` -> `sessions/`; `session.py` -> `session.py`.

    THE GRAIN IS DELIBERATE and it is the safety property. A per-file set would tempt
    the classifier to call an unlisted *file* inside a read *directory* neutral — and
    it is not, because a suite that globs a directory reads whatever later appears in
    it. Session ~206 found exactly that trap by hand: `_attention_session_is_over`
    globs every file under `sessions/journal/`, so a journal nobody has measured is
    still an input the moment it exists. Classifying at the directory grain makes that
    impossible to get wrong.

    This is the one rule the deriver and the land must agree on, so it lives here —
    the file every member ships — and `curate/gate_inputs.py` imports it rather than
    keeping a second copy ([P16](principles/master.md#p16--avoid-duplication))."""
    head, _, tail = rel.partition("/")
    return f"{head}/" if tail else head


def _gate_command_key(cmd) -> str:
    """The name one gate command is filed under, in the record and in the gate.

    WI-0347. The deriver measures each configured gate command separately and the land
    looks each one up again; the two must agree on the spelling or every lookup misses
    and every command runs (fail-closed, but the feature is then dead weight). So the
    rule is here, in the file every member ships, and `curate/gate_inputs.py` imports
    it — the same argument `_gate_top_prefix` carries one function up.

    THE KEY IS THE COMMAND AS CONFIGURED, before `python3` is rewritten to
    `sys.executable`. That substitution happens in `_run_gate` and depends on which
    interpreter is running, so a key taken after it would differ between the machine
    that derived the record and the machine that reads it — the record would be
    unusable on any box but the one that wrote it, and unusably in the permissive
    direction is not what this costs: an unmatched key runs its command."""
    argv = cmd.split() if isinstance(cmd, str) else [str(part) for part in cmd]
    return " ".join(argv)


#: The script a gate command runs to execute the test suite. ONE definition, because
#: `_run_gate` counts suite runs by it and `curate/gate_inputs.py` decides by it which
#: command's measured input set the serial probe's own measurement belongs to — and two
#: copies of a rule that names a filename is the drift that makes the record attribute a
#: measurement to the wrong command ([P16](principles/master.md#p16--avoid-duplication)).
GATE_SUITE_RUNNER = "curate/run_suite.py"


def _gate_is_suite_command(cmd) -> bool:
    """Does this configured gate command run the test suite?"""
    argv = cmd.split() if isinstance(cmd, str) else [str(part) for part in cmd]
    return any(part == GATE_SUITE_RUNNER for part in argv)


def _gate_argv(cmd) -> list:
    """One configured gate command as an argv, with `python3` resolved to the
    interpreter actually running.

    WI-0320 / WI-0328: the config spells `python3` because that is what a person
    types, and `python3` means whatever the operator's PATH says — on a dev machine that
    can be a newer package-manager Python while the harness runs the system one, and the two disagree
    about the suite's verdict. THE KEY IS TAKEN BEFORE THIS (`_gate_command_key`), so
    the record stays machine-independent; the spawn happens after it, so the run is
    the harness's own interpreter.

    Extracted here for WI-0353: `session.py test` now spawns the gate's suite command
    rather than a second transcription of it, and a rewrite rule with two copies is
    the drift that makes the verb and the gate run different Pythons again."""
    argv = cmd.split() if isinstance(cmd, str) else [str(part) for part in cmd]
    if argv and argv[0] == "python3":
        argv[0] = sys.executable
    return argv


def _gate_suite_command():
    """The gate's own suite command, exactly as configured — or None when the gate
    runs no such command here.

    WI-0353. `session.py test` and the land gate held two independent definitions of
    "the suite": the verb ran a serial `unittest discover` (~12 minutes) while the
    gate ran `curate/run_suite.py` sharded (~60s), so the run an Architect reached for
    was both the slow one AND not the one that decides the land. Deriving the verb's
    command from this list rather than restating it is what makes the two ONE
    definition structurally — a gate whose runner changes takes the verb with it, and
    there is no second place to forget.

    NONE IS A REAL ANSWER, not a failure. `curate/` is federation-only — it is absent
    from `curate/push-substrate.py`'s manifest while THIS file is in it, so every
    member ships this code and no member ships the sharded runner. On a member the
    gate's default is the serial `unittest discover` itself (`_gate_configured_commands`),
    which contains no `GATE_SUITE_RUNNER` part, so the answer is None and the caller
    runs serially — not as a degraded fallback, but because there the serial suite IS
    the gate's suite."""
    for cmd in _gate_configured_commands():
        if _gate_is_suite_command(cmd):
            return cmd
    return None


def _gate_configured_commands() -> list:
    """The gate's command list — the authority on what the gate actually runs.

    `derive-a-checks-subjects-from-the-authority`. The record is a claim ABOUT this
    list, never a substitute for it: a command added to `session.config.json` today is
    in the gate today and in no record until the next derive, and the only safe
    reading of that gap is that the new command runs. Reading the list here rather than
    trusting the record's own inventory is what makes that the default.

    Kept identical to `_run_gate`'s own construction, including the default."""
    cmds = (CFG or {}).get("gate")
    if cmds is None:
        cmds = ([[sys.executable, "-m", "unittest", "discover", "-s", "tests"]]
                if (ROOT / "tests").is_dir() else [])
    return list(cmds)


def _gate_suite_tree(root: Path) -> str:
    """Hash test paths and contents, excluding generated Python bytecode.

    Content rather than HEAD: the isolated candidate may hold tests awaiting its
    derived-record commit. Length framing makes path/content boundaries unambiguous.
    """
    import hashlib
    digest = hashlib.sha256()
    for path in sorted((root / "tests").rglob("*")):
        if "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo"):
            continue
        if path.is_file():
            for value in (path.relative_to(root).as_posix().encode(), path.read_bytes()):
                digest.update(len(value).to_bytes(8, "big"))
                digest.update(value)
    return digest.hexdigest()


# ADR-0148 D6 (WI-0427): `_gate_record_freshness` is gone. It decided whether the
# nightly record could license a gate-neutral skip; the land no longer reads the
# record at all, so a stale or red nightly cannot touch land speed.


#: The three answers `trunk_suite_verdict` gives, named because two consumers format
#: them and a test pins that they never collapse into one another.
TRUNK_SUITE_GREEN = "GREEN"
TRUNK_SUITE_RED = "RED"
TRUNK_SUITE_UNKNOWN = "UNKNOWN"

#: How old the trunk's gate-input record may be before a GREEN in it stops being
#: reportable as green. OPS-0009 derives nightly, so this is one whole missed night of
#: slack: a late or skipped run does not cry wolf, and an obligation that has genuinely
#: lapsed stops certifying a trunk nobody has measured since. The direction is the same
#: asymmetry the rest of this neighbourhood runs on — a needless "go check" costs a
#: minute, a false all-clear costs the diagnosis this item exists to stop paying twice.
TRUNK_SUITE_TTL_SECONDS = 48 * 3600


def _fmt_record_age(seconds: float) -> str:
    """A measurement's age in the unit a human would use. Hours up to two days, then
    days — a record old enough to matter is never usefully reported in minutes."""
    if seconds < 3600:
        return f"{seconds / 60:.0f}m"
    if seconds < 48 * 3600:
        return f"{seconds / 3600:.0f}h"
    return f"{seconds / 86400:.0f}d"


#: WI-0431. Where the OPS-0009 nightly writes its outcome, relative to the MAIN checkout
#: (the runner refuses to run anywhere else). A red night lands no record, so the record
#: on the trunk keeps saying whatever the last GREEN night said; this file is the only
#: place the red night is written down.
NIGHTLY_STATUS_REL = ".session-state/gate-inputs-runner.status.json"

#: How many failing test ids the one-line suite verdict names before it says "+N more".
NIGHTLY_NAMES_SHOWN = 5


def _nightly_status(path: Path | None = None) -> dict | None:
    """The nightly runner's last status, or None when there is none to read."""
    if path is None:
        main = _main_checkout()
        if main is None:
            return None
        path = main / NIGHTLY_STATUS_REL
    try:
        d = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return d if isinstance(d, dict) else None


def _red_night_detail(status: dict | None, record_at: float | None,
                      now: float) -> str | None:
    """A sentence about a red nightly that is NEWER than the record, or None.

    Only `outcome: red` counts: a refused or errored night produced no verdict, so it
    cannot speak about the suite, and a red night OLDER than the record has since been
    answered by a green night that landed."""
    if not status or status.get("outcome") != "red":
        return None
    try:
        finished = datetime.fromisoformat(str(status.get("finished"))).timestamp()
    except ValueError:
        return None
    if record_at is not None and finished <= record_at:
        return None
    names = [n for n in status.get("failing") or [] if isinstance(n, str)]
    total = status.get("failing_total")
    shown = names[:NIGHTLY_NAMES_SHOWN]
    more = (total if isinstance(total, int) else len(names)) - len(shown)
    named = (f" Failing: {', '.join(shown)}" + (f" (+{more} more)" if more > 0 else "")
             + f". Full list: {NIGHTLY_STATUS_REL} in the main checkout." if shown
             else " That run predates WI-0431 and did not record which tests.")
    return (f"the nightly serial run that finished {str(status.get('finished'))[:16]} "
            f"({_fmt_record_age(now - finished)} ago) was RED — "
            f"{status.get('reason') or 'no reason recorded'}.{named}")


def trunk_suite_verdict(trunk: str | None = None,
                        now: float | None = None,
                        nightly: dict | None | bool = True) -> tuple[str, str]:
    """Was the TRUNK's suite green the last time anything measured it? `(state, detail)`.

    WI-0333. THE SIGNAL ALREADY EXISTED AND NOTHING READ IT. `gate-inputs.json` carries
    `suite_ok`, OPS-0009 refreshes it nightly, and the only consumers were
    `_gate_input_prefixes` and `curate/gate_inputs.py`'s `load()` — both of which fold a
    RED into `None`, "no usable record, gate everything". That is right for THEIR
    question (may this diff skip the suite?) and it destroys the answer to a different
    one (is the trunk broken before I build on it?). So a red trunk was discoverable
    only by running the gate and reading a failure, and on 2026-09-10 two lanes an hour
    apart each spent the same diagnosis on the same trunk-wide breakage, neither knowing
    the other was on it.

    THREE STATES, NEVER TWO (`declare-what-a-check-assumes`):

      GREEN    a readable measurement, inside the TTL, that passed
      RED      a readable measurement that failed
      UNKNOWN  there is no measurement this can speak for — absent, unparseable,
               wrong-shaped, or a green too old to still be about anything

    UNKNOWN IS NOT GREEN AND MUST NEVER RENDER AS IT. A member with no record, or with
    one the nightly stopped refreshing, has not been checked and found fine; nobody has
    checked it. Collapsing that into "green" would rebuild the false all-clear one layer
    up from the one this function exists to expose.

    SCHEMA-INDEPENDENT ON PURPOSE, unlike `_gate_input_prefixes` beside it. That reader
    pins `GATE_INPUTS_SCHEMA` because it licenses a SKIP off the record's `read_prefixes`,
    and a set measured under an older schema may mean something else. This reader licenses
    nothing: it reports one boolean the format has carried unchanged since schema 1, so
    pinning the schema here would turn every record written the day before a schema bump
    into "cannot tell" — throwing away a true RED for a version number. The shape is
    checked instead (`suite_ok` a bool over a positive `tests`), which is what actually
    establishes the field was measured rather than guessed at.

    READ FROM THE TRUNK REF, never from this tree. A lane's working copy is at the lane's
    base commit — this lane was three commits behind main at the session that wrote this —
    so the file on disk answers "what did the trunk say when I branched", which is a
    different and quietly older question.

    A RED NIGHT OUTRANKS AN OLDER GREEN RECORD (WI-0431). The nightly lands its record
    only when the suite is green, so after a red night the trunk's record still carries
    the previous green — and on 2026-09-25 and 09-26 this line said "trunk GREEN" over
    two red nights. `nightly` is the runner's status (`True` reads it from the main
    checkout; tests pass a dict or None)."""
    trunk = trunk or _trunk()
    now = now if now is not None else time.time()
    if nightly is True:
        nightly = _nightly_status()
    remedy = (f"`python3 curate/gate_inputs.py --derive` records one (OPS-0009 runs it "
              f"nightly).")
    r = sh(["git", "show", f"refs/heads/{trunk}:{GATE_INPUTS_RECORD}"], check=False)
    if r.returncode != 0 or not (r.stdout or "").strip():
        return TRUNK_SUITE_UNKNOWN, (
            f"there is no {GATE_INPUTS_RECORD} on {trunk}, so nothing has measured this "
            f"trunk's suite. That is not a green trunk, it is an unmeasured one. {remedy}")
    try:
        d = json.loads(r.stdout)
    except ValueError:
        return TRUNK_SUITE_UNKNOWN, (
            f"{GATE_INPUTS_RECORD} on {trunk} does not parse as JSON. {remedy}")
    if not isinstance(d, dict):
        return TRUNK_SUITE_UNKNOWN, (
            f"{GATE_INPUTS_RECORD} on {trunk} is not a record. {remedy}")
    ok, tests = d.get("suite_ok"), d.get("tests")
    if not isinstance(ok, bool) or not isinstance(tests, int) or tests <= 0:
        return TRUNK_SUITE_UNKNOWN, (
            f"{GATE_INPUTS_RECORD} on {trunk} carries no measured suite verdict "
            f"(suite_ok={ok!r} over tests={tests!r}). {remedy}")
    at = str(d.get("derived_at_commit") or "")[:12]
    when = str(d.get("derived_at") or "")
    age = None
    with contextlib.suppress(Exception):
        age = now - datetime.fromisoformat(when).timestamp()
    where = f"{at or 'an unrecorded commit'} ({when[:10] or 'undated'}" \
            + (f", {_fmt_record_age(age)} ago)" if age is not None else ")")
    red_night = _red_night_detail(nightly or None,
                                  now - age if age is not None else None, now)
    if red_night:
        return TRUNK_SUITE_RED, (
            f"{red_night} A red night lands no record, so {trunk}'s last landed "
            f"measurement, at {where}, is older and does not speak for today.")
    if not ok:
        return TRUNK_SUITE_RED, (
            f"{trunk}'s last full measurement, at {where} over {tests} tests, "
            f"FAILED. A gate failure on this land is as likely to be {trunk}'s breakage "
            f"as yours, and a peer may already be fixing it: check `poga lanes` before "
            f"you spend the diagnosis.")
    # A green whose age cannot be established is a green about an unknown moment. It goes
    # to UNKNOWN rather than GREEN for the same reason the absent record does: the claim
    # a reader would take from it is one this function cannot support.
    if age is None:
        return TRUNK_SUITE_UNKNOWN, (
            f"{GATE_INPUTS_RECORD} on {trunk} reports a green suite but carries no "
            f"readable derived_at ({when!r}), so how old that green is cannot be "
            f"established. {remedy}")
    if age > TRUNK_SUITE_TTL_SECONDS:
        return TRUNK_SUITE_UNKNOWN, (
            f"{trunk}'s last measurement, at {where}, was green — but the nightly derive "
            f"has not run since, and a green nobody has re-measured in "
            f"{_fmt_record_age(age)} is not evidence about today's trunk. {remedy}")
    return TRUNK_SUITE_GREEN, (
        f"{trunk}'s last full measurement, at {where} over {tests} tests, passed. "
        f"That is what the nightly derive last saw, not a claim about the tip.")


def trunk_suite_line(trunk: str | None = None) -> str:
    """The one-line form both consumers print — session start, and every land before it
    gates and queues.

    ONE FORMATTER, TWO CALLERS. The wording is the whole deliverable here: a lane that
    reads "trunk RED" and goes looking for a peer is the saving, and a lane that reads
    two differently-worded versions of it learns to skim both."""
    state, detail = trunk_suite_verdict(trunk)
    return f"suite:   trunk {state} — {detail}"


def landing_line(days: float = LAND_DURATION_WINDOW_DAYS) -> str:
    """The session-start `landing:` line — FL7's own reading (ADR-0148 D7): p90 of
    ready-to-landed over the window, code and bookkeeping separately, each against its
    own target. A goal, never a gate; nothing reads it to refuse a land."""
    parts, red, any_n = [], False, False
    for cls, goal in (("code", LAND_DURATION_GOAL_SECONDS),
                      ("bookkeeping", LAND_BOOKKEEPING_GOAL_SECONDS)):
        st = land_duration_stats(days=days, diff_class=cls)
        if not st.get("n"):
            parts.append(f"{cls} none")
            continue
        any_n = True
        over = st["p90"] > goal
        red = red or over
        parts.append(f"{cls} p90 {st['p90']:.1f}s over {st['n']} (goal {goal:.0f}s"
                     + (", OVER" if over else "") + ")")
    if not any_n:
        return f"landing: no land measured in {days:.0f}d"
    return (f"landing: {'OVER GOAL' if red else 'within goal'} — "
            + "; ".join(parts) + f" · {days:.0f}d")

def _gate_input_prefixes() -> set[str] | None:
    """The measured input set, or None when there is no usable measurement.

    None means GATE to every caller, and all five unusable shapes — absent,
    unparseable, unknown schema, measured over zero tests, and (WI-0337) carrying no
    child-process audit receipt — collapse to it on purpose. Operationally they mean
    one thing, "nobody has measured this", and giving them separate answers would
    invite a caller to decide one of them was good enough.
    `declare-what-a-check-assumes`: "I could not tell" must not share a return value
    with "I checked and it's fine".

    THE CHILD-AUDIT CHECK IS STRUCTURAL, NOT A THRESHOLD. `sys.addaudithook` binds one
    interpreter, so a deriver that only hooks its own process cannot see what the
    suite's subprocesses read — and 67 of 112 test modules spawn one. A record missing
    those reads does not make this function cautious, it makes it permissive: fewer
    measured prefixes means MORE diffs classify neutral, so the failure mode is a
    suite that should have run and did not. Requiring the receipt is how a record
    derived by a blind probe stops licensing skips, without this file having to know
    anything about how the measurement was taken."""
    try:
        d = json.loads((ROOT / GATE_INPUTS_RECORD).read_text(encoding="utf-8"))
    except Exception:
        return None
    if not isinstance(d, dict) or d.get("schema") != GATE_INPUTS_SCHEMA:
        return None
    if d.get("suite_ok") is False:
        return None
    prefixes = d.get("read_prefixes")
    if not isinstance(prefixes, list) or not prefixes:
        return None
    if not isinstance(d.get("tests"), int) or d["tests"] <= 0:
        return None
    child = d.get("child_audit")
    if not isinstance(child, dict) or child.get("ok") is not True:
        return None
    return {str(p) for p in prefixes}


