def now_stamp() -> str:
    """'2026-06-04 22:20 UTC' (or the configured zone's own abbreviation) — via %Z so it's correct year-round."""
    return datetime.now(CFG["tz"]).strftime("%Y-%m-%d %H:%M %Z")


def topmost_entry(text: str) -> dict | None:
    """The newest dated session entry: its header fields and whether it's closed."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = ENTRY_RE.match(line)
        if m:
            # Scan to the next entry header to find this block's End line.
            has_end = False
            for j in range(i + 1, len(lines)):
                if ENTRY_RE.match(lines[j]):
                    break
                if lines[j].startswith("**End:**"):
                    has_end = True
                    break
            return {
                "date": m.group(1),
                "number": m.group(2),
                "title": m.group(3),
                "closed": has_end,
                "corrupt": m.group(2).upper().endswith("NC"),
                "header_index": i,
            }
    return None


def _banner_file(session_id: str | None) -> Path:
    """Per-session banner path. Keyed by session_id so `start` and `announce`
    (same trigger, same session_id on stdin) rendezvous on the same file and a
    stale prior-session banner can never be picked up. Falls back to the unkeyed
    legacy name for a manual run with no hook stdin.

    **Both branches resolve at CALL time**, which is the load-bearing part. The legacy
    branch used to return the module constant `SESSION_BANNER_FILE`, computed from
    `SESSION_STATE_DIR` at import — so a fixture that pinned the DIRECTORY, as every
    correct fixture does, still wrote `announce.txt` into the operator's real
    `.session-state/`. Measured 2026-09-13 across a full 4,234-test run: 35 of the 52
    real-store escapes came through this one line, from a module whose `setUp` pins the
    anchor properly and is green under `test_live_store_fixture_guard`. Same defect and
    same fix as `_log_guard_firing` (2026-08-07, 432 of 532 records were fixtures);
    this was the half that never got converted. WI-0286 / ADR-0133."""
    if session_id:
        return SESSION_STATE_DIR / f"announce-{session_id}.txt"
    return SESSION_STATE_DIR / BANNER_NAME


def _clear_stale_banners(keep: Path) -> None:
    """Remove leftover per-session banner files (crashed sessions that never got
    consumed) plus the legacy unkeyed file, preserving only `keep` (this
    session's). Best-effort — never raises."""
    try:
        stale = list(SESSION_STATE_DIR.glob("announce-*.txt"))
        legacy = SESSION_STATE_DIR / BANNER_NAME
        if legacy.is_file():
            stale.append(legacy)
        for p in stale:
            if p != keep:
                p.unlink(missing_ok=True)
    except Exception:
        pass


def _log_guard_firing(guard: str, op: str) -> None:
    """Append one JSON line recording a guard firing. Best-effort, never raises — a
    telemetry-write failure must never break the guard it rides on (fail-open, the
    guard invariant). `op` is truncated so a pathological command can't bloat the log.

    **The path is resolved at CALL time, not bound at import.** `GUARD_FIRINGS_FILE` is a
    module constant computed from `SESSION_STATE_DIR` when the module loads, so every test
    that exercised a guard through the real module appended to the REAL log. Measured
    2026-08-07: **432 of 532 records were test fixtures** — `git -C /x reset --hard HEAD~1`
    and friends, logged 147 times each by repeated suite runs.

    That is not untidiness, it defeats the artifact's only purpose. The
    [`denial-audit-log`](habits/master.md#denial-audit-log) habit exists so that *a spike
    in blocked actions is a signal someone sees* — and a log where a routine test run is
    indistinguishable from a real burst of denials cannot carry a threshold. Resolving here
    lets a test point `SESSION_STATE_DIR` somewhere disposable and keeps the fleet-wide
    telemetry `curate/metrics.py` reads made of real events only."""
    try:
        SESSION_STATE_DIR.mkdir(exist_ok=True)
        line = json.dumps({
            "ts": _now_iso(),
            "guard": guard,
            "op": (op or "")[:200],
            "repo": ROOT.name,
        }, ensure_ascii=False)
        with open(SESSION_STATE_DIR / "guard-firings.jsonl", "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except Exception:
        pass


def _entry_start_dt(text: str, prev: dict) -> datetime | None:
    """The Start datetime of entry `prev` (topmost), parsed from its Start line."""
    lines = text.splitlines()
    for j in range(prev["header_index"] + 1, len(lines)):
        if ENTRY_RE.match(lines[j]):
            break
        if lines[j].startswith("**Start:**"):
            return parse_start_dt(lines[j])
    return None


def _fmt_banner(kind: str, n, version: str, machine: str, stamp: str,
                dur: str | None = None, tail: str | None = None) -> str:
    """One session-boundary banner line. `kind` is 'start' or 'end'."""
    core = f"Session {n} {kind} · {CFG['architect_name']} v{version} · {machine} · {stamp}"
    if dur:
        core += f" · {dur}"
    if tail:
        core += f" · {tail}"
    return f"{BANNER_RULE} {core} {BANNER_RULE}"


def _topmost_end_banner(text: str) -> str | None:
    """If the topmost entry carries an End line, render it as an end banner —
    used to surface a just-auto-closed orphan's end stamp at the next start."""
    ent = topmost_entry(text)
    if ent is None:
        return None
    lines = text.splitlines()
    for j in range(ent["header_index"] + 1, len(lines)):
        if ENTRY_RE.match(lines[j]):
            break
        if lines[j].startswith("**End:**"):
            body = lines[j].split("**End:**", 1)[1].strip()
            return f"{BANNER_RULE} Session {ent['number']} end · {body} {BANNER_RULE}"
    return None


def _stage_banner(path: Path, lines: list[str]) -> None:
    """Best-effort stage of the banner (into this session's per-session file) for
    the `announce` hook to poll+print. `lines == []` stages an empty sentinel —
    the early-return paths use it to tell a waiting `announce` there is nothing to
    show (so it resolves its poll immediately instead of timing out). Atomic, so a
    polling reader never sees a half-written file. Never raises — a banner failure
    must not break the start it rides on (fail-open)."""
    try:
        SESSION_STATE_DIR.mkdir(exist_ok=True)
        atomic_write(path, ("\n".join(lines) + "\n") if lines else "")
    except Exception:
        pass


def render_journal(meta: dict, body: str | None = None) -> str:
    """A session journal: fixed-order frontmatter + narrative body. `ended` is empty
    until close. Deterministic (stable key order, trailing newline)."""
    out = ["---"]
    for k in JOURNAL_FM_KEYS:
        out.append(f"{k}: {meta.get(k, '')}")
    out.append("---")
    out.append("")
    if body is None:
        body = _STUB_BODY
    out.append(body.rstrip("\n"))
    return "\n".join(out).rstrip("\n") + "\n"


def parse_journal(text: str) -> tuple[dict, str]:
    """(frontmatter dict, body). Mirrors the brief/apply frontmatter parser: a leading
    `---` block of `key: value` lines terminated by a line starting `---`. Missing/
    malformed frontmatter yields ({}, whole-text) — never raises."""
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    fm: dict = {}
    for line in text[3:end].splitlines():
        if ":" in line and not line.strip().startswith("#"):
            k, _, v = line.partition(":")
            fm[k.strip()] = v.strip()
    body = text[end + 4:].lstrip("\n")
    return fm, body


#: The frontmatter keys a journal cannot be a journal without. `session-id` is the one
#: every compiled view filters on — `_load_journals`, `_open_journal_paths` and
#: `_journals_in` each drop a file that lacks it — so without it the journal is present
#: on disk and absent from every rendering of the record.
JOURNAL_REQUIRED_FM = ("session-id",)


def journal_frontmatter_defect(text: str) -> str | None:
    """The named reason this text cannot serve as a journal, or None when it can.

    ONE predicate, three readers (WI-0332): the close refuses on it, the compile reports
    it, and `unreadable_journals` enumerates by it. It is a function rather than the test
    inlined at each site because inlining is precisely how this defect stayed invisible —
    four independent filters that each dropped the file in their own idiom and not one of
    which could say what it had dropped or why
    ([`declare-what-a-check-assumes`](habits/master.md#declare-what-a-check-assumes))."""
    fm, _body = parse_journal(text)
    if not fm:
        return ("no parseable frontmatter — the leading `---` block is gone. A WHOLE-FILE "
                "write over a staged journal destroys it (append to the body instead); "
                "with it go `session-id` and the `base-commit` the record keeps as "
                "causality-as-fact")
    missing = [k for k in JOURNAL_REQUIRED_FM if not str(fm.get(k) or "").strip()]
    if missing:
        return (f"frontmatter carries no {', '.join(missing)} — the key every compiled "
                f"view filters on, so the session would render nowhere")
    return None


def require_journal_frontmatter(path: Path | None, text: str) -> tuple[dict, str]:
    """(frontmatter, body) — or a named refusal that stops the caller dead.

    The AUTOMATIC close-and-compile path's half of a rule the BY-HAND surgery verbs have
    always enforced (`journal-title`, `addendum`, `resolve-orphan` all refuse unparseable
    frontmatter). Only the automatic path failed open, which is the wrong way round: the
    hand verbs have a human reading the output, and the close does not.

    `SystemExit` deliberately, on the precedent `_refuse_journal_write_on_fixture` sets
    and for its reason: several callers on the close path sit inside fail-open
    `except Exception` handlers, and a normal raise there would degrade this guard into
    exactly the silent no-op it exists to end. It is also the safe direction here — a
    refused close costs a re-run, while a close that proceeds writes a session out of the
    record and lands the erasure on the trunk
    ([`add-structural-guard-on-recurrence`](habits/master.md#add-structural-guard-on-recurrence)).
    """
    why = journal_frontmatter_defect(text)
    if why is not None:
        name = path.name if path is not None else "this session's journal"
        # The recovery command names the member's DECLARED journal directory, not a
        # hard-coded `sessions/journal` — a path key is read from the layout block, never
        # assumed (WI-0029). Degrades to the bare filename if the layout cannot be read,
        # because a refusal must never fail while composing its own explanation.
        rel = ""
        with contextlib.suppress(Exception):
            rel = f"{_journal_dir_rel()}/"
        raise SystemExit(
            f"session.py: refused to close {name} — {why}. NOTHING WAS WRITTEN and the "
            f"narrative in the file is untouched. Restore the frontmatter block (the "
            f"last committed copy has it: `git show HEAD:{rel}{name}`; `render_journal` "
            f"is the shape it must take) and run the close again. WI-0332.")
    fm, body = parse_journal(text)
    return fm, body


def unreadable_journals() -> list[tuple[Path, str]]:
    """[(path, named reason)] for every file in the journal directory the compilers drop.

    The detector shipped with the guard above
    ([`ship-the-detector-with-the-capability`](habits/master.md#ship-the-detector-with-the-capability)).
    The close now refuses, but a journal can still be clobbered by any hand that is not
    the close, and the compile is deliberately left FAIL-OPEN: one unreadable file must
    never brick the trunk views for every other session on the machine. Fail-open is only
    tolerable if it is loud, so this is what `run_compile` reports — "dropped, and here is
    which and why" instead of a record with a session quietly missing from it.

    Never raises: a reporting path must not be able to fail the compile it reports on."""
    out: list[tuple[Path, str]] = []
    if not JOURNAL_DIR.is_dir():
        return out
    try:
        candidates = sorted(JOURNAL_DIR.glob("*.md"))
    except Exception:
        return out
    for p in candidates:
        try:
            why = journal_frontmatter_defect(p.read_text(encoding="utf-8"))
        except Exception as exc:
            why = f"could not be read — {exc}"
        if why:
            out.append((p, why))
    return out


def finalize_journal(text: str, ended: str, duration: str, title: str | None = None,
                      confirm: str | None = None, closed_by: str | None = None,
                      work_items: list[str] | None = None,
                      superseded_by: str | None = None,
                      path: Path | None = None) -> str:
    """Stamp a journal's close: set the `ended` frontmatter field (idempotent — a
    re-close overwrites), record the duration, and — when given — the final `title`
    and the user's verbatim `close-confirm` (the receipt half of the interactive-close
    guard, consultant brief 2026-07-26-consultant-unprompted-mid-session-closeouts:
    an auditable field, not tamper-proof, but a fabricated quote is a no-fabricated-
    data violation sitting where the ADR-0053 miner can catch it), preserving the
    body verbatim. The surgery is on the parsed frontmatter, never LLM text-editing
    (P15)."""
    # WI-0332. This used to be `if not fm: return text` — a close whose journal had lost
    # its frontmatter got the file back BYTE-IDENTICAL, and `cmd_end` then printed its end
    # banner over it and exited 0. This is the choke point every automatic close reaches
    # bytes through, so the refusal lives here and covers the close verbs it has not met
    # yet ([`retire-the-class-not-the-instance`](habits/master.md#retire-the-class-not-the-instance)).
    # The machine-close sweeps (reaper, lane teardown, janitor) never arrive here with a
    # frontmatter-less journal: each one filters on `fm`/`session-id` upstream, so their
    # fail-open posture is unchanged.
    fm, body = require_journal_frontmatter(path, text)
    fm["ended"] = ended
    fm.setdefault("duration", duration)
    fm["duration"] = duration
    if title:
        fm["title"] = title
    if confirm:
        # FLATTENED TO ONE LINE, and the reason is a hole found while adding the second
        # close authorization (WI-0331). This frontmatter is rendered as `key: value`
        # lines, so a newline anywhere in `confirm` does not merely wrap — it FORGES
        # KEYS. Measured: a value carrying `\nordinal: 999\n` renders a second `ordinal`
        # into the journal, and `ordinal` is the field the handoff compiles sessions by.
        #
        # THE CLASS, NOT THE INSTANCE. Three sources reach this argument and every one of
        # them can carry a newline: `--confirm` (an agent composes it), the dispatch
        # citation (interpolates `POGA_DISPATCH` from the environment), and the unattended
        # citation (same, for `POGA_UNATTENDED_RUN`). Each id also gets a shape check at
        # its own read, but those are the callers; this is the choke point where the value
        # becomes frontmatter, and it is the only place that covers all three plus the
        # next one. Flatten rather than reject: a close must not fail because the receipt
        # was oddly shaped, and the whole value is preserved — just on one line.
        fm["close-confirm"] = " ".join(str(confirm).split())
    if closed_by:
        # A MACHINE closed this, and the record must say so. Without the field an
        # `ended` stamp is indistinguishable from an Architect's own sign-off, which
        # would make the janitor a quiet manufacturer of clean-looking history — the
        # same class of harm as a fabricated `close-confirm`
        # ([`a-close-is-the-banner-not-the-sentence`](habits/master.md#a-close-is-the-banner-not-the-sentence)).
        fm["closed-by"] = closed_by
    if work_items is not None:
        # ADR-0093 D1/D3. Written as an EXTRA key — deliberately not added to
        # JOURNAL_FM_KEYS — so that a journal closed before this shipped gains nothing
        # when it is next re-rendered. In the canonical list every journal would render
        # `work-items:` empty, and empty MEANS "this session held nothing": the record
        # would quietly assert a fact about sessions that predate the mechanism. Absent
        # and empty are different answers and must stay that way.
        fm["work-items"] = ", ".join(work_items)
    if superseded_by:
        # WI-0391. An EXTRA key, for the same reason `work-items` is one: absent and empty
        # are different answers, and every journal closed before this shipped would
        # otherwise render `superseded-by:` empty and assert a fact about itself that
        # nobody established. Flattened like `close-confirm` because this frontmatter is
        # rendered as `key: value` lines and a newline in a value FORGES KEYS.
        fm["superseded-by"] = " ".join(str(superseded_by).split())
    return _rerender_journal(fm, body)


def _rerender_journal(fm: dict, body: str) -> str:
    """Re-render a journal from parsed parts: the fixed keys in their canonical order
    first, then any extra keys the journal grew, body preserved verbatim.

    Shared by every frontmatter surgery — the close stamp above and the ADR-0082 prep
    adoption — so the two cannot drift into writing different field orders for the same
    file ([P16](principles/master.md#p16--avoid-duplication)). Journals are read by the
    compiler and by miners keyed on field position, so a second hand-rolled renderer is
    exactly the copy that goes wrong quietly."""
    out = ["---"]
    for k in JOURNAL_FM_KEYS:
        out.append(f"{k}: {fm.get(k, '')}")
    for k, v in fm.items():
        if k not in JOURNAL_FM_KEYS:
            out.append(f"{k}: {v}")
    out.append("---")
    out.append("")
    out.append(body.rstrip("\n"))
    return "\n".join(out).rstrip("\n") + "\n"


def journal_path(session_id: str) -> Path:
    return JOURNAL_DIR / f"{session_id}.md"


def _refuse_journal_write_on_fixture(p: Path) -> None:
    """Hard-stop before a TEST writes a journal into the real repo (WI-0068).

    Deliberately `SystemExit` rather than a normal exception: `write_start_journal` is
    fail-open by design (`except Exception: return None`) so a journal failure can never
    break the start it rides on. A normal raise would be swallowed there and this guard
    would degrade into a silent no-write — present, passing, and enforcing nothing.
    `SystemExit` derives from `BaseException`, so it escapes that handler and the run
    goes red, which is the point: a red test costs one run, a fabricated session costs
    an ordinal and a push.

    Fixtures that patch `JOURNAL_DIR` to a temp tree are unaffected — the path simply
    isn't under the real journal dir, and this returns without comment."""
    if not _under_test():
        return
    try:
        p.resolve().relative_to(_REAL_JOURNAL_DIR.resolve())
    except Exception:
        return          # a properly-built fixture (or a path we cannot judge) — allow
    raise SystemExit(
        f"session.py: refused — a test tried to write the journal '{p.name}' into the "
        f"REAL repo at {_REAL_JOURNAL_DIR}. Patch `session.JOURNAL_DIR` to a temp dir "
        f"(see StampTest in tests/test_session.py) or pass --dry-run. WI-0068.")


def _display_ordinal(n, *, settled: bool = False) -> str:
    """The ordinal as it may be DISPLAYED (ADR-0068 companion; the session-90 five-way
    collision). `~N` unless the caller can show the number is SETTLED.

    WHAT THIS USED TO KEY ON, AND WHY THAT WAS THE BUG (WI-0152). It returned `~N` when
    `_on_worktree_lane()` and a bare `N` otherwise — surface, not moment. The reasoning
    behind the tilde is that the number is a presentation label owned by the TRUNK
    compile (`frozen_max` + rank over the journals actually landed), so a value derived
    before that compile has run over the final set is an estimate. Nothing in that
    reasoning is about worktrees. `_load_journals` (this module) orders ascending by
    (`started`, session-id) and `render_handoff` assigns `frozen_max + 1 + rank` over
    that order, so ANY session whose journal is not yet in the compiled set and whose
    `started` precedes yours is inserted AHEAD of you and shifts your number up. A session on the trunk cannot see an in-flight lane's journal — it lives
    on that lane's branch — so the trunk's start-time ordinal is an estimate by exactly
    the mechanism the lane's is, and `_on_worktree_lane()` was a proxy for "am I a
    concurrent writer?" that answers false for a concurrent writer.

    MEASURED, not argued. WI-0152 observed two devbox sessions an hour apart both
    stamped 162; the item's later sweep found six journals sharing 191, six sharing 174
    and six sharing 129. Those collisions are what a bare `N` at start was asserting
    away.

    THE DEFAULT IS PROVISIONAL ON PURPOSE. What sits on the other side of this guard is
    a false claim of uniqueness on the one field a human navigates the record by, so a
    caller who forgets the flag must land on the honest render, not the asserting one
    (`add-structural-guard-on-recurrence`: the direction is set by what the guard
    protects). `settled=True` is the narrow case — the close path on the trunk, where
    the compile has already run over the landed union and the number is the one going
    into the close-commit message. A lane never passes it, and must never assert an
    ordinal in a close-commit message either (that path uses the session-id instead).

    AN UNKNOWN ORDINAL PASSES THROUGH UNTOUCHED. Two callers hand this the literal `"?"`
    when `compiled_ordinal` found no journal to rank. `~?` would be worse than either
    honest form — it decorates a non-answer as though it were an estimate of something.
    `?` already says the only true thing, so it is left alone."""
    if not str(n).lstrip("-").isdigit():
        return str(n)
    return str(n) if settled else f"~{n}"


def _fetch_stamp_path(root: Path) -> Path:
    """Where the last fetch is remembered. Under `.session-state/`, which is gitignored —
    so this is machine-local state that never travels in a commit, and a lane and the main
    checkout share one stamp because they share one set of remote-tracking refs."""
    return root / ".session-state" / "fetch-stamp.json"


def _fetch_stamp_write(root: Path, upstream: str, ok: bool) -> None:
    """Record the attempt — SUCCESS OR FAILURE. `at` advances only on success (it dates the
    refs); `tried` advances either way (it throttles retries). Best-effort by design: a
    stamp we cannot write costs a redundant fetch next time, never a skipped one."""
    p = _fetch_stamp_path(root)
    try:
        rec = json.loads(p.read_text(encoding="utf-8"))
        if not isinstance(rec, dict):
            rec = {}
    except Exception:
        rec = {}
    now = time.time()
    entry = rec.get(upstream) if isinstance(rec.get(upstream), dict) else {}
    entry = dict(entry)
    entry["tried"] = now
    if ok:
        entry["at"] = now
    rec[upstream] = entry
    try:
        p.parent.mkdir(parents=True, exist_ok=True)
        atomic_write(p, json.dumps(rec, indent=2, sort_keys=True) + "\n")
    except Exception:
        pass


def _journal_dir_rel() -> Path:
    """The repo-relative journal directory from the member's declared layout.

    Read from the config rather than off `JOURNAL_DIR`, because the caller below needs
    this path relative to OTHER checkouts (a lane's), and because `JOURNAL_DIR` is a
    module constant the tests patch to an unrelated temp dir — deriving from it would
    make the lookup depend on how a test was set up."""
    return Path(layout_of(CFG_RAW, "journal_dir"))


def _holder_journal_dirs() -> list[Path]:
    """Every journal directory a coordination write might have to look in, nearest first.

    WI-0061 CAUSE 2. A coordination write is nearly always made through the MAIN-checkout-
    anchored front door (`poga work`, `adr-next` — both correct by ADR-0073, so a lane
    never drives the store with its own possibly-stale harness). That makes `JOURNAL_DIR`
    MAIN's journal directory while the session actually doing the writing lives in a lane.
    Looking only there is why the `journal` field came back empty for EVERY lane record,
    Claude sessions included: the journal was never where the lookup was pointed. Probed
    live session ~121 — a claim taken from a lane whose journal was on disk recorded
    `journal: ""`.

    Never raises: a coordination write must not fail because a directory could not be
    listed."""
    dirs: list[Path] = []

    def add(p: Path | None) -> None:
        if p is None:
            return
        try:
            r = p.resolve()
            if r.is_dir() and r not in dirs:
                dirs.append(r)
        except Exception:
            pass

    add(JOURNAL_DIR)                       # this checkout — MAIN when anchored
    rel = _journal_dir_rel()
    try:
        wt = _shared_work_root() / ".claude" / "worktrees"
        if wt.is_dir():
            for lane in sorted(wt.iterdir()):
                add(lane / rel)
    except Exception:
        pass
    invoked = os.environ.get("POGA_INVOKED_FROM", "")
    if invoked:
        add(Path(invoked) / rel)
    return dirs


def _journals_in(d: Path) -> list[tuple[Path, dict]]:
    """[(path, frontmatter)] for EVERY journal in `d`, open or closed. Never raises.

    The wider half of the pair, added by [ADR-0119](adr/0119-the-gates-three-side-doors-are-shut.md) D2
    for the one caller that can afford it: `_find_holder_journal`'s exact-key Claude
    search. `_open_journals_in` filters this."""
    out: list[tuple[Path, dict]] = []
    try:
        if not d.is_dir():
            return out
        for p in sorted(d.glob("*.md")):
            try:
                fm, _ = parse_journal(p.read_text(encoding="utf-8"))
            except Exception:
                continue
            if fm.get("session-id"):
                out.append((p, fm))
    except Exception:
        pass
    return out


def _open_journals_in(d: Path) -> list[tuple[Path, dict]]:
    """[(path, frontmatter)] for every journal in `d` with no `ended`. Never raises.

    STILL MEANS OPEN, deliberately (WI-0254: *"two paths, two answers — do not widen
    both"*). Two callers read this to mean *not yet closed* — `_resolve_orphan_candidates`
    and `cmd_resolve_orphan` — and `_journal_in_checkout` resolves a non-Claude session by
    UNIQUENESS within a checkout, which closed journals would destroy on the second
    session any checkout ever ran. Only the exact-key path widened, to `_journals_in`."""
    return [(p, fm) for p, fm in _journals_in(d) if not fm.get("ended")]


def _find_holder_journal() -> tuple[Path, dict] | None:
    """This session's own open journal, wherever its checkout happens to be — or None
    when the question cannot be answered honestly.

    Two paths, because the two runtime families leave different evidence:

    * A **Claude** session exports `CLAUDE_CODE_SESSION_ID`, which its journal carries as
      `claude-session-id`. That is an exact key, so every candidate directory can be
      searched and the match is unambiguous — INCLUDING closed journals (ADR-0119 D2).
      This search used to stop at open ones, which meant a session stopped owning its own
      coordination records the moment it closed its journal. That is not an edge: `end`
      and `merge` close the journal and THEN land, so the land — the one place ownership
      of a drawn number is decided — always asked after the answer had been thrown away
      (WI-0254; the unexplained refusal WI-0237 recorded). An exact key is exactly as
      unambiguous for a closed journal as an open one, so nothing is traded for it.
    * A **non-Claude** session (codex, antigravity) sets no such variable and its journal's
      `claude-session-id` is EMPTY — there is no key to match on. So we fall back to the
      one checkout the caller actually stood in (`POGA_INVOKED_FROM`, exported by `poga`
      before it cd's to the anchor) and accept its open journal only when there is
      exactly ONE. Two open journals in one checkout is genuinely ambiguous, and a guess
      recorded as fact is the failure this whole item exists to remove — so we return
      None and let the field read empty ([`declare-what-a-check-assumes`])."""
    sid = _claude_session_id()
    if sid:
        for d in _holder_journal_dirs():
            for p, fm in _journals_in(d):
                if fm.get("claude-session-id") == sid:
                    return p, fm
        return None
    # WI-0106: the checkout the process is ACTUALLY IN, before the one the operator
    # launched from. For a lane-created non-Claude session these differ — `poga` exports
    # `POGA_INVOKED_FROM` as wherever the operator typed the command (main), then creates
    # the lane and runs the runtime inside it. Asking main first is asking the one
    # checkout that provably does not hold this session's journal.
    try:
        here = _journal_in_checkout(Path.cwd().resolve())
        if here is not None:
            return here
    except Exception:
        pass
    invoked = os.environ.get("POGA_INVOKED_FROM", "")
    if not invoked:
        return None
    return _journal_in_checkout(Path(invoked))


