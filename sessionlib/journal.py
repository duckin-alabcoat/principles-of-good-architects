def _ops_render_section() -> str:
    """ROADMAP's operational section (ADR-0076 D6). Overdue first, then never-run, then
    scheduled — an overdue obligation belongs at the top of the human-facing view, where
    it is visible rather than merely stored."""
    items = [it for it in _ops_parse() if it.get("status") not in OPS_TERMINAL]
    if not items:
        return "*(no open operational obligations — create one with `session.py ops-new`.)*\n"
    today = _today()
    rank = {"overdue": 0, "never run": 1}
    items.sort(key=lambda it: (rank.get(_ops_state(it, today), 2),
                               it.get("due") or "9999", it["id"]))
    out = []
    for it in items:
        name = _ops_filename_for(it["id"]) or f"{it['id']}.md"
        state = _ops_state(it, today)
        cadence = it.get("cadence") or "one-time"
