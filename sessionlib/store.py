def orphan_triage(text: str, prev: dict, session_id: str | None) -> tuple[str, str, list[str]]:
    """Evidence-based orphan handling (ADR-0036). `prev` is the topmost entry,
    Start-without-End and not corrupt. Returns (verdict, new_text, lines):
      'autoclosed' — closed at the evidence time; open the new session.
      'concurrent' — a fresh heartbeat says it is LIVE elsewhere; surface, do NOT
                     open (operator decides wait / proceed).
      'residual'   — no decisive evidence; surface bad/keep + git evidence, do NOT
                     open (Architect runs resolve-orphan, then re-runs start).
    """
    n = prev["number"]
    ev = _sidecar_evidence(n)
    out: list[str] = []

    # 1. Clean exit — .ended marker present -> auto-close at marker time.
    if ev["has_ended"]:
        new_text = _synth_end(text, prev, _parse_iso(ev["ended_at"]))
        out.append(f"ORPHAN:  session {n} exited cleanly (close ritual skipped) — "
                   f"auto-closed at {ev['ended_at'] or 'marker time'}.")
        return ("autoclosed", new_text, out)

    # 2. Live heartbeat, no .ended -> fresh = concurrent elsewhere; stale = crash.
    if ev["has_live"] and ev["beat_age_min"] is not None:
        if ev["beat_age_min"] <= HEARTBEAT_STALE_MIN and ev["session_id"] != session_id:
            out.append(
                f"CONCURRENT: session {n} is LIVE on {ev['machine'] or 'another machine'} "
                f"(heartbeat {ev['beat_age_min']:.0f}m ago). NOT opening a competing session "
                f"and NOT touching its entry. If it is actually dead, run "
                f"`python3 session.py resolve-orphan --keep` (or --bad) then re-run start; "
                f"to intentionally run concurrently, proceed manually.")
            return ("concurrent", text, out)
        new_text = _synth_end(text, prev, _parse_iso(ev["last_beat"]))
        out.append(f"ORPHAN:  session {n} looks CRASHED (heartbeat "
                   f"{ev['beat_age_min']:.0f}m stale, no clean-exit marker) — auto-closed "
                   f"at its last heartbeat.")
        return ("autoclosed", new_text, out)

    # 3. No sidecar (legacy / pre-rollout) -> git-evidence fallback (session-46 lesson).
    commits = _commits_since(_entry_start_dt(text, prev))
    if commits:
        out.append(
            f"ORPHAN:  session {n} ({prev['date']}) has a Start, no End, and NO liveness "
            f"sidecar — but {len(commits)} commit(s) exist since its Start stamp, so it is "
            f"almost certainly a REAL unclosed session. RECONSTRUCT it (entry from those "
            f"commits + `resolve-orphan --keep --end-at <last-commit-time>`); do NOT mark "
            f"it NC. Commits since its start:")
        out.extend(f"           {c}" for c in commits[:8])
        out.append(f"         Then re-run start. (Session {n}'s stamp was NOT written.)")
        return ("residual", text, out)

    out.append(
        f"ORPHAN:  session {n} ({prev['date']}) has a Start but no End, and no liveness "
        f"sidecar or commits since its start — likely a clean exit whose ritual was "
        f"skipped. Ask {CFG['user_name']} bad/keep: `resolve-orphan --keep` (real, "
        f"zero-work) or `--bad` (corrupt → NC), then re-run start. (Number NOT written.)")
    return ("residual", text, out)


def _adr_prefix() -> str:
    """The literal prefix this member's ADR filenames carry, or "" (WI-0128).

    Declared as `adr_prefix` beside `adr_dir`, because they describe one arrangement:
    a member declared the directory correctly and was still invisible, since its files
    were named `ADR-024-slug.md` and the pattern was anchored on a bare number."""
    v = (CFG or {}).get("adr_prefix")
    return v.strip() if isinstance(v, str) and v.strip() else ""


def _adr_num_re() -> re.Pattern:
    """The ADR filename pattern, composed from the declared prefix.

    RESOLVED PER CALL, like `_adr_dir` and for the same reason — the counter registry is
    built once and cached, so a pattern frozen at first use would outlive a config change
    (and every test that repoints CFG between calls).

    Three or four digits, deliberately asymmetric with what we WRITE. Reading tolerantly
    means one member's existing `ADR-024` files are counted, so the max is 29 and the next
    draw is `0030` — which sorts after them and cannot collide. Writing canonically at
    four digits means the store converges on one width instead of preserving a legacy one
    forever. A member that never declares a prefix gets `^(\\d{3,4})-`, which matches
    every name the old `^(\\d{4})-` did (the quantifier is greedy, so a four-digit name
    still yields all four) — no existing member changes behaviour.

    The machinery was always capable of this: the SIBLING `wi` counter in the same
    registry carries a literal prefix and a capture group in exactly this shape. Only the
    ADR row had the narrower pattern, and nothing required that."""
    return re.compile(rf"^{re.escape(_adr_prefix())}(\d{{3,4}})-")


def _adr_dir() -> str:
    """Repo-relative directory holding this member's ADRs, as a git pathspec.

    Declared via `adr_dir` in session.config.json; defaults to `adr` — the federation's
    own layout, which every one of the five sites below used to hardcode. A member that keeps ADRs
    at `docs/adr/` had all five see an empty directory: `adr-next` returned 0001 on a
    repo holding dozens of ADRs, AND the land gate built specifically to make that collision
    impossible filtered its diff to `adr/` and certified clean. Both layers of a
    two-layer safety mechanism blind on one assumption, so neither could catch the
    other — and the output was indistinguishable from a correct one. Reported by that
    member, after the ritual handed it a number already in use."""
    v = (CFG or {}).get("adr_dir")
    v = v.strip().strip("/") if isinstance(v, str) and v.strip() else "adr"
    return v


def _adr_existing_max() -> int:
    """Highest 4-digit prefix among <adr_dir>/*.md files; 0 if none."""
    return _counter_existing_max(_counter("adr"))


def _adr_reserve_next(identity: str | None = None, tries: int = 64) -> int | None:
    """Atomically reserve the next free ADR number (Rule 3). None if the coord store is
    unavailable — the caller falls back to an unguarded max+1."""
    return _counter_reserve_next(_counter("adr"), identity, tries)


def cmd_adr_next(_args: argparse.Namespace) -> None:
    """Rule 3: print (and reserve) the next free ADR number, zero-padded, on stdout — so
    `N=$(python3 session.py adr-next)` is safe under concurrent lanes."""
    adr_dir, existing = _adr_dir(), _adr_existing_max()
    n = _adr_reserve_next()
    if n is None:
        _refuse_undrawn("ADR", "adr-next", str(adr_dir))
    print(f"{n:04d}")
    # Print the BASIS on stderr, so `N=$(… adr-next)` still captures only the number.
    # A wrong maximum is invisible in a bare `0001` and obvious in "after 0000 in adr/"
    # — the capture-the-probe discipline applied to the tool's own output. This is
    # exactly how that member's defect would have announced itself instead of handing
    # over a number already in use.
    print(f"adr-next: next after {existing:04d} in {adr_dir}/", file=sys.stderr)


# ── WI-0290: the ADR renumberer (ADR-0120) ───────────────────────────────────────
# The third counter's renumberer, and deliberately NOT a third caller of
# `_store_renumber_batch`. That path parses a fielded record and re-renders it through
# the store's sole writer; an ADR is authored prose, so a renumber here is a text edit on
# a document. What it SHARES with the store path is everything that is not the record:
# numbers drawn by the land (`_auto_renumber_collisions`), the lane-provenance citation
# pass (`_remap_citations`), the history carve-out, and the pathspec'd commit.
#
# What is DIFFERENT, each from ADR-0120:
#   * D3 — a landed ADR is never renumbered. The store path has no such rule because a
#     work item's number is not a citation target the way an Accepted decision is. The
#     test is "is this file on the trunk", never the Status field: an unlanded Accepted
#     ADR is a draft (D2), and a landed Proposed one may already be cited.
#   * D4 — the record names itself. H1, filename and body all carry the number, so the
#     move rewrites them together or the file misidentifies itself.
#   * The tombstone is a ROW, not a file. `adr/README.md`'s `## Unused numbers` table is
#     already the ADR counter's declaration of a spent number: the allocator skips what it
#     lists (WI-0379) and the doc check's D5 accepts a hole only when it is listed there.
#     A tombstone FILE would be a fake ADR that D3 of that check says needs an index row.
#   * Provenance lives in the moved ADR, not in a notes directory — `adr/` has none, and an
#     unlanded ADR is not yet immutable (D2), so the one place a reader of the record will
#     certainly look is the record.

#: Written into the moved ADR's header block AFTER the citation pass, for the same reason
#: the store path writes its note last: it names the old id on purpose, and a pass that
#: rewrites old ids on lane-authored lines would otherwise rewrite it into "X -> X".
ADR_RENUMBER_PROVENANCE = (
    "**Renumbered:** filed as {old} and moved to {new} on {when}, before it landed. "
    "Numbers drawn in a lane cannot see what a sibling lands first, so {old} names a "
    "different record on the trunk (the federation's ADR-0120: renumbering an unlanded "
    "ADR is an identifier correction). Anything written before this line that cites "
    "{old} and means this decision means {new}.")

#: The `## Unused numbers` row left at a number a renumber VACATES. Column two is when the
#: number was spent, which is the renumber, not the draw — the draw date is not recorded
#: anywhere this code can read, and a guessed one would be fabricated.
ADR_RENUMBER_TOMBSTONE = (
    "| {num} | {when} | **Vacated by a renumber.** Drawn for \"{title}\", which moved to "
    "{new} before it landed. Nothing was lost; the number is never reissued. |")

_ADR_STATUS_RE = re.compile(r"^\*\*Status:\*\*\s*(.+?)\s*$", re.MULTILINE)


def _adr_names_at(ref: str) -> list[str] | None:
    """Basenames under the ADR directory at `ref`, or None when git cannot say.

    None is load-bearing: every caller treats it as a refusal, because "the trunk has no
    such file" is the answer that permits a rename and an unreadable ref must never be
    allowed to give it (ADR-0120 D3)."""
    d = _adr_dir()
    t = sh(["git", "ls-tree", "--name-only", ref, f"{d}/"], check=False)
    if t.returncode != 0:
        return None
    return [n[len(d) + 1:] for n in (t.stdout or "").split() if n.startswith(f"{d}/")]


def _adr_names_numbered(c: _Counter, names, num: int) -> list[str]:
    out = []
    for n in names:
        m = c.basename_re.match(n)
        if m and int(m.group(1)) == num:
            out.append(n)
    return sorted(out)


def _adr_tree_names(c: _Counter) -> list[str]:
    try:
        return [p.name for p in (ROOT / c.dirname()).glob(c.glob)]
    except Exception:
        return []


def _adr_retarget_self(text: str, old_num: int, new_num: int,
                       old_stem: str, new_stem: str) -> str:
    """The moved ADR's text with every self-reference on the new number (ADR-0120 D4).

    The WHOLE file, not lane-added lines: the file itself is what this lane authored, and
    a draft citing the trunk's same-numbered record is impossible by construction — the
    lane could not see that record when it wrote this one."""
    text = text.replace(old_stem, new_stem)
    return re.sub(rf"\bADR-0*{old_num}\b", f"ADR-{new_num:04d}", text)


def _adr_insert_provenance(text: str, line: str) -> str:
    """`line` placed after the header block's last `**Field:**` line, or straight after
    the H1 when there is no header block. Position matters only for a reader: it is the
    block the Status and Date live in, which is where someone checking identity looks."""
    lines = text.splitlines(keepends=True)
    h1 = next((i for i, ln in enumerate(lines) if ln.startswith("# ")), None)
    if h1 is None:
        return line + "\n\n" + text
    last = h1
    for j in range(h1 + 1, len(lines)):
        s = lines[j].strip()
        if s.startswith("**"):
            last = j
        elif s == "" and last == h1:
            continue
        else:
            break
    if not lines[last].endswith("\n"):
        lines[last] += "\n"
    lines.insert(last + 1, (line + "\n") if last > h1 else ("\n" + line + "\n"))
    return "".join(lines)


def _adr_declare_vacated(c: _Counter, num: int, new_id: str, title: str,
                         when: str) -> tuple[str | None, str]:
    """Append the tombstone row to the counter's `## Unused numbers` table.

    Returns (repo-relative index path, "") on success, or (None, why) — never silent,
    because a vacated number with no row is exactly the unexplained hole D5 refuses and
    the WI-0379 allocator would hand out again."""
    if c.hole_index is None:
        return None, "this counter declares no hole index"
    path = c.hole_index()
    try:
        text = path.read_text(encoding="utf-8")
    except Exception:
        return None, f"{path.name} is not readable"
    lines = text.splitlines(keepends=True)
    want = COUNTER_HOLE_SECTION.lower()
    start = depth = None
    for i, ln in enumerate(lines):
        m = re.match(r"^(#{1,6})\s+(.*?)\s*$", ln)
        if m and m.group(2).strip().lower() == want:
            start, depth = i + 1, len(m.group(1))
            break
    if start is None:
        return None, f"{path.name} has no '## {COUNTER_HOLE_SECTION}' section"
    last_row = None
    for j in range(start, len(lines)):
        h = re.match(r"^(#{1,6})\s", lines[j])
        if h and len(h.group(1)) <= depth:
            break
        if lines[j].lstrip().startswith("|"):
            last_row = j
        elif last_row is not None:
            break                               # the first table in the section only
    if last_row is None:
        return None, f"the '{COUNTER_HOLE_SECTION}' section of {path.name} holds no table"
    if not lines[last_row].endswith("\n"):
        lines[last_row] += "\n"
    lines.insert(last_row + 1, ADR_RENUMBER_TOMBSTONE.format(
        num=f"{num:04d}", when=when, new=new_id,
        title=" ".join(title.replace("|", "/").split())) + "\n")
    atomic_write(path, "".join(lines))
    try:
        return str(path.relative_to(ROOT)), ""
    except ValueError:
        return str(path), ""


def _adr_source_refusal(c: _Counter, old_id: str, trunk: list[str],
                        tree: list[str]) -> tuple[str | None, str]:
    """(the one unlanded file to move, "") or (None, why it cannot be moved).

    Everything that can refuse WITHOUT knowing the new number, split out so the verb can
    ask it before drawing one: a number drawn for a renumber that then refuses is a number
    burned (`validate-before-you-draw-an-id`)."""
    pre = f"           {old_id}:"
    try:
        old_num = int(old_id.rsplit("-", 1)[-1])
    except ValueError:
        return None, f"{pre} not an {c.label} id — nothing renumbered."
    here = _adr_names_numbered(c, tree, old_num)
    if not here:
        return None, f"{pre} no file in {c.dirname()}/ carries it — nothing renumbered."
    lane = [n for n in here if n not in trunk]
    if not lane:
        status = "status unread"
        with contextlib.suppress(Exception):
            m = _ADR_STATUS_RE.search(
                (ROOT / c.dirname() / here[0]).read_text(encoding="utf-8"))
            status = m.group(1) if m else "no Status line"
        return None, (f"{pre} REFUSED — {here[0]} is already on the trunk ({status}). A "
                      f"landed ADR is never renumbered (ADR-0120 D3): other records may "
                      f"cite it. Two landed ADRs on one number are resolved by a "
                      f"superseding record, not a rename.")
    if len(lane) > 1:
        return None, (f"{pre} REFUSED — {len(lane)} unlanded files carry it "
                      f"({', '.join(lane)}), so there is no telling which one to move. "
                      f"Move one by naming its new number from `{c.draw_cmd}` in its "
                      f"filename and H1, then re-run.")
    return lane[0], ""


def _adr_renumber_one(c: _Counter, old_id: str, new_id: str,
                      trunk: list[str]) -> tuple[dict | None, list[str]]:
    """Move one UNLANDED ADR onto `new_id`. Returns (what moved, report); None when it
    refused, and every refusal names its reason — nothing is changed on any of them."""
    pre = f"           {old_id}:"
    tree = _adr_tree_names(c)
    source, why = _adr_source_refusal(c, old_id, trunk, tree)
    if source is None:
        return None, [why]
    d = ROOT / c.dirname()
    old_num = int(old_id.rsplit("-", 1)[-1])
    try:
        new_num = int(new_id.rsplit("-", 1)[-1])
    except ValueError:
        return None, [f"{pre} {new_id} is not an {c.label} id — nothing renumbered."]
    lane = [source]
    taken = (_adr_names_numbered(c, tree, new_num)
             + _adr_names_numbered(c, trunk, new_num))
    if taken:
        return None, [f"{pre} REFUSED — {new_id} already has a file ({taken[0]}); a "
                      f"renumber never moves onto a live number."]
    old_name = lane[0]
    m = c.basename_re.match(old_name)
    new_name = old_name[:m.start(1)] + f"{new_num:04d}" + old_name[m.end(1):]
    old_stem, new_stem = old_name[:-3], new_name[:-3]   # glob is *.md
    try:
        text = (d / old_name).read_text(encoding="utf-8")
    except Exception as e:
        return None, [f"{pre} could not read {old_name} ({type(e).__name__}) — nothing "
                      f"renumbered."]
    atomic_write(d / new_name, _adr_retarget_self(text, old_num, new_num,
                                                   old_stem, new_stem))
    (d / old_name).unlink(missing_ok=True)
    h1 = re.search(r"^# [^:\n]*:\s*(.+)$", text, re.MULTILINE)
    rep = [f"{pre[:-1]} -> {new_id}   {old_name} -> {new_name}   "
           f"(self-references rewritten)"]
    # Our hold on the number we are giving up. Never forced: a record that is not ours
    # belongs to whoever drew it.
    if _coord_release(c.namespace, f"{old_num:04d}", _coord_identity(),
                      reason="renumbered"):
        rep.append(f"             released this lane's reservation on "
                   f"{c.namespace}/{old_num:04d}")
    return {
        "old_id": old_id, "new_id": new_id, "old_num": old_num,
        "new_name": new_name, "title": h1.group(1).strip() if h1 else old_stem,
        "changed": [f"{c.dirname()}/{new_name}", f"{c.dirname()}/{old_name}"],
        # The citation keys: the id, the file stem (links and paths), and the index
        # row's bare-number link text — `[0067](0067-slug.md)` names the number twice.
        "cites": {old_id: new_id, old_stem: new_stem,
                  f"[{m.group(1)}]({old_name}": f"[{new_num:04d}]({new_name}"},
    }, rep


def _adr_renumber_batch(c: _Counter, pairs: list[tuple[str, int]],
                        parent: str | None = None,
                        commit: bool = True) -> tuple[dict[str, str], list[str]]:
    """Remap every `(old_id, new_number)` in one operation. Returns (mapping, report).

    The same contract as `_store_renumber_batch`, so the land's loop over counter rows
    needs no branch for this one. FAILS CLOSED WITHOUT A TRUNK, where the store path only
    skips citations: the trunk is the thing D3 is decided against, and "could not tell
    whether it landed" must never read as "it did not"."""
    report: list[str] = []
    if not parent:
        return {}, [f"           {c.label}: REFUSED — no trunk ref to compare against, "
                    f"so a landed ADR cannot be told from a draft (ADR-0120 D3). "
                    f"Nothing renumbered."]
    trunk = _adr_names_at(parent)
    if trunk is None:
        return {}, [f"           {c.label}: REFUSED — the trunk's {c.dirname()}/ could "
                    f"not be read, so a landed ADR cannot be told from a draft "
                    f"(ADR-0120 D3). Nothing renumbered."]
    mapping: dict[str, str] = {}
    changed: list[str] = []
    cites: dict[str, str] = {}
    moved: list[dict] = []
    for old_id, new_num in pairs:
        res, rep = _adr_renumber_one(c, old_id, f"{c.label}-{new_num:04d}", trunk)
        report += rep
        if res:
            mapping[old_id] = res["new_id"]
            changed += res["changed"]
            cites.update(res["cites"])
            moved.append(res)
    if not mapping:
        return mapping, report
    # Lane-authored lines only, this checkout only: the index row this lane added, the
    # habits, principles and work items that cite the draft. A line already on the trunk
    # cites the trunk's record and is left alone; history is reported, never rewritten.
    ch, rep = _remap_citations(cites, parent)
    changed += ch
    report += rep
    # Provenance and tombstones LAST — both name the old number on purpose.
    when = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    d = ROOT / c.dirname()
    tree = _adr_tree_names(c)
    for res in moved:
        p = d / res["new_name"]
        with contextlib.suppress(Exception):
            atomic_write(p, _adr_insert_provenance(
                p.read_text(encoding="utf-8"),
                ADR_RENUMBER_PROVENANCE.format(old=res["old_id"], new=res["new_id"],
                                               when=when)))
        # Vacated only when NOTHING holds the old number afterwards. In a real collision
        # the trunk's record still sits on it, and a row declaring it unused would be a
        # false statement about a live ADR.
        if (_adr_names_numbered(c, trunk, res["old_num"])
                or _adr_names_numbered(c, tree, res["old_num"])):
            continue
        rel, why = _adr_declare_vacated(c, res["old_num"], res["new_id"],
                                        res["title"], when)
        if rel:
            changed.append(rel)
            report.append(f"             tombstone: {res['old_id']} declared unused in "
                          f"{rel}, pointing at {res['new_id']}.")
        else:
            report.append(f"             tombstone NOT written for {res['old_id']} — "
                          f"{why}. The number is now an undeclared hole; add its row "
                          f"by hand.")
    report.append(f"           provenance: {len(moved)} ADR(s) now record what they "
                  f"were filed as.")
    if commit:
        sha = _renumber_commit(
            changed, f"fix({c.dirname()}): renumber "
            + ", ".join(f"{o}->{n}" for o, n in mapping.items())[:120])
        if sha:
            report.append(f"           committed {sha} — the remap is SAVED.")
    return mapping, report


def cmd_adr_renumber(args: argparse.Namespace) -> None:
    """WI-0290 — renumber colliding UNLANDED ADRs. See `_cmd_store_renumber`, which
    carries the argument handling for all three counters; the row's renumberer is what
    differs.

    Named ids are checked against the trunk FIRST, dry run included, because the shared
    verb draws each replacement before the renumberer runs: a refusal found after the
    draw burns the number, and a dry run that says "would draw" for a landed ADR
    describes a run that would never happen."""
    c = _counter("adr")
    if not getattr(args, "all", False) and getattr(args, "ids", None):
        parent = _trunk_tip()
        trunk = _adr_names_at(parent) if parent else None
        if trunk is None:
            print("adr-renumber: REFUSED — the trunk's ADR directory could not be read, "
                  "so a landed ADR cannot be told from a draft (ADR-0120 D3). Nothing "
                  "drawn, nothing renumbered.")
            sys.exit(1)
        tree = _adr_tree_names(c)
        refusals = []
        for raw in args.ids:
            for part in raw.replace(",", " ").split():
                iid = (part if part.upper().startswith(f"{c.label}-")
                       else f"{c.label}-{int(part):04d}")
                if _counter_holds_id(c, iid):     # unknown ids: the shared verb says so
                    src, why = _adr_source_refusal(c, iid, trunk, tree)
                    if src is None:
                        refusals.append(why)
        if refusals:
            for why in refusals:
                print(why)
            print("adr-renumber: nothing drawn, nothing renumbered.")
            sys.exit(1)
    _cmd_store_renumber(c, args)


def _wi_dir(base: Path | None = None) -> Path:
    """The work-item store, under ROOT by default. `base` overrides the root — pass
    `_shared_work_root()` when a caller must read the MAIN checkout's store rather than
    this worktree's, which is a lane's tracked copy frozen at its base commit."""
    return (base or ROOT) / WI_DIRNAME


def _wi_slug(title: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return s[:40].rstrip("-") or "item"


def _wi_filename_for(wid: str) -> str | None:
    """The existing on-disk filename for `wid` (whatever slug it currently carries), or
    None if no file for that number exists yet."""
    num = wid.split("-", 1)[1]
    try:
        matches = sorted(_wi_dir().glob(f"WI-{num}-*.md"))
    except Exception:
        matches = []
    return matches[0].name if matches else None


def _wi_render_item(item: dict) -> str:
    """One WI file's full text, in the format `_wi_parse_text` reads back losslessly."""
    blocked = ", ".join(item.get("blocked_by") or [])
    lines = [
        f"# {item['id']}: {item['title']}",
        "",
        f"- status: {item.get('status', 'open')}",
        f"- section: {item.get('section', 'backlog')}",
        f"- blocked-by: {blocked}",
        f"- group: {item.get('group', '')}",
        # ADR-0074: provenance. When an item was minted by triaging a receipt-ritual
        # brief, this names the brief file — the item is a HANDLE, never a restatement
        # (`single-source-and-deliver`, the "point" mechanism). Empty for items that
        # originated as work rather than as inbound mail.
        f"- source: {item.get('source', '')}",
        # The release axis. `impact` is authored (it is a judgment about the work);
        # `version` is stamped by the release step (it is a fact about what shipped).
        f"- impact: {item.get('impact', WI_IMPACT_UNSET)}",
        # Deployment warning, not a version input (ADR-0081). Written only when set, so
        # the common case (no migration) adds no line to 50-odd item files.
        *([f"- migration: {item['migration']}"] if item.get("migration") else []),
        # WI-0323: WHAT KIND OF WORK this is (harness | product | mixed), authored at
        # creation. Written ALWAYS, like `impact` and unlike `migration` — the two shapes
        # answer different questions. `migration` is absent-means-no, so a missing line is
        # a real answer; `scope` has no default answer at all, and an item that predates
        # the field must be visibly UNSCOPED rather than indistinguishable from one whose
        # line nobody has written yet. The empty line is what makes the legacy backlog
        # countable on the board instead of inferred from an absence.
        f"- scope: {item.get('scope', WI_SCOPE_UNSET)}",
        # WI-0408: WHO this item is waiting on — an actor token, never an item id (that is
        # `blocked-by`, and the two refuse each other's values on purpose; see
        # `WI_WAITING_ON_RE`). Written only when set, like `migration` and unlike `scope`,
        # because the shapes differ in what an absence MEANS: an unscoped item is a gap to
        # close, so its empty line must be visible, while "nobody is waiting on a human
        # here" is already the right answer and needs no line to say it. That choice is
        # also what makes this field cost the fleet nothing — 400-odd existing item files
        # are byte-identical before and after it arrives, and no member edits anything.
        *([f"- waiting-on: {item['waiting_on']}"] if item.get("waiting_on") else []),
        f"- version: {item.get('version', WI_VERSION_UNSET)}",
        # WI-0308: the premise-probe receipt — "the mechanical premises of this body were
        # re-probed clean at this commit". Written only when set, like `migration`, so an
        # item nobody has probed carries no line rather than an empty promise of one. It
        # is deliberately NOT called `verified`: what it certifies is that the citations
        # resolve and the counts are young, never that a human re-read the argument.
        *([f"- probed: {item['probed']}"] if item.get("probed") else []),
        "",
    ]
    # WI-0181: the authored BODY, never the compiled view. `notes_body` is what a parse
    # read out of this file; `notes` may have had records folded into it for display, and
    # writing THAT back would duplicate every record into the item file and rebuild the
    # append hotspot the records exist to remove. The fallback keeps a freshly-built item
    # dict (`wi-new`, which sets only `notes`) rendering exactly as before.
    notes = (item.get("notes_body") if item.get("notes_body") is not None
             else item.get("notes") or "").strip()
    if notes:
        lines.append(notes)
        lines.append("")
    return "\n".join(lines)


def _wi_parse_text(wid: str, text: str) -> dict:
    """One item's dict from its file text: id, title, status, section,
    blocked_by (list[str]), group, notes."""
    lines = text.splitlines()
    title = wid
    if lines:
        m = WI_TITLE_RE.match(lines[0])
        if m:
            title = m.group(2).strip()
    item = {"id": wid, "title": title, "status": "open", "section": "backlog",
            "blocked_by": [], "group": "", "source": "",
            "impact": WI_IMPACT_UNSET, "migration": "", "scope": WI_SCOPE_UNSET,
            "waiting_on": WI_WAITING_ON_UNSET,
            "version": WI_VERSION_UNSET, "probed": ""}
    notes: list[str] = []
    for line in lines[1:]:
        fm = WI_FIELD_RE.match(line)
        if fm:
            key, val = fm.group(1), fm.group(2).strip()
            if key == "blocked-by":
                item["blocked_by"] = [x.strip() for x in val.split(",") if x.strip()]
            elif key == "waiting-on":
                # Hyphenated on disk, snake_case in the dict and in the feed — the same
                # split `blocked-by`/`blocked_by` already carries, so it cannot join the
                # pass-through tuple below, which assumes the two spellings are identical.
                item["waiting_on"] = val
            elif key in ("status", "section", "group", "source", "impact",
                         "migration", "scope", "version", "probed"):
                item[key] = val or item[key]
            continue
        notes.append(line)
    item["notes"] = "\n".join(notes).strip()
    # WI-0181: keep the file's own text under its own key, so a render can put back exactly
    # what it read even after a caller has compiled records into `notes` for display.
    item["notes_body"] = item["notes"]
    return item


def _wi_parse(base: Path | None = None) -> list[dict]:
    """Every item under `work-items/`, sorted by id. [] if the directory is absent.
    `base` selects which checkout's store to read (see `_wi_dir`).

    Notes come back COMPILED (WI-0181) — the item file's body followed by its note records
    in time order — because every reader of this function wants the item as it reads, not
    as it is stored. `notes_body` carries the file's own half for anything that writes."""
    items: list[dict] = []
    try:
        paths = sorted(_wi_dir(base).glob("WI-*.md"))
    except Exception:
        return items
    for p in paths:
        m = WI_FILENAME_RE.match(p.name)
        if not m:
            continue
        try:
            item = _wi_parse_text(f"WI-{m.group(1)}", p.read_text(encoding="utf-8"))
        except Exception:
            continue
        item["notes"] = _notes_compiled(WI_DIRNAME, item, base)
        items.append(item)
    return items


def _wi_derive_bump(items: list[dict]) -> tuple[str | None, list[str]]:
    """The release bump implied by a set of items, and the ids blocking that call.

    `(bump, unlabelled_ids)` — bump is **"minor" or "patch" only**, or **None** when any
    item is unlabelled. Returning None rather than a best guess is the point: it refuses
    on incomplete input instead of quietly rounding an unclassified item down to a patch
    (understating a release) or up to a feature (overstating one). The caller reports the
    unlabelled ids and a human labels them; nothing here decides on their behalf.

    **It can never return "major", by design (ADR-0081).** A major means the system was
    fundamentally altered — which may or may not break anything — and that is a judgment
    about significance, not a property of any item. There is nothing here to compute it
    from and no honest way to invent one, so a major is DECLARED by naming a milestone.
    Two concrete failures the old `breaking → major` rule produced: cutting items from a
    named major as its date approached could remove the last `breaking` item and quietly
    demote the release to a minor after it had been promised; and a lone breaking item
    shipping on its own cut a major nobody had named.

    Consumed by the release step (WI-0044) — this function is only the *semantics* of the
    impact labels, which is why it lives beside them rather than with the release records.
    """
    unlabelled = [it["id"] for it in items if not it.get("impact")]
    if unlabelled:
        return None, unlabelled
    labels = {it["impact"] for it in items}
    if "feature" in labels:
        return "minor", []
    return "patch", []


def _wi_receipt_where(root: Path, main: Path | None) -> str:
    """The half of the store receipt that says WHERE the commit landed, relative to the
    reader's own checkout. Pure so it can be tested in all three states — the sentence is
    the load-bearing part of the receipt and it was wrong for a whole class of callers.

    Three outcomes, never two ([`declare-what-a-check-assumes`]): committed in the main
    checkout (the `poga work` path, which anchors there by design), committed in THIS tree
    (a lane driving `session.py` directly), and cannot tell. The third must borrow neither
    sentence — "I could not determine this" is its own answer, not a synonym for either
    of the confident ones."""
    if main is None:
        return ("Could not determine whether this is the main checkout or a lane, so "
                "where it lands relative to your own `git status` is unverified.")
    if main == root.resolve():
        return ("It lives in the main checkout, so a lane's own `git status` will not "
                "show it. Nothing is owed to another checkout and there is nothing for "
                "the user to run.")
    return (f"That is THIS lane, not the main checkout — it rides the lane's land like "
            f"any other commit here, and main's copy at {main} is unchanged until then. "
            f"Nothing for the user to run.")


# ── WI-0193: a shared-store write cannot be BORN stranded in a lane ────────────────
#
# WHAT HAPPENED. OPS-0006 — a monthly Auditor-class spot audit, already 43 days overdue —
# was created with `python3 session.py ops-new` from inside lane poga-2. A lane's checkout
# holds its own tracked copy of `ops-items/`, frozen at the lane's base commit, and NO
# OTHER CHECKOUT EVER READS IT. So the obligation existed, rendered in that lane's own
# startup banner as a real overdue item, and was invisible to `poga work list`, to the
# board, and to every other session on the machine. It reached main only because
# someone noticed the discrepancy between two banners and went looking. OPS-0004 did not
# get that luck: drawn in a lane, never landed, deleted, and its number permanently burned
# because main's allocator had already moved past it.
#
# WHY THE FRONT DOOR WAS NOT ENOUGH. WI-0125 built `poga ops` for exactly this and
# `require_repo` anchors it on the MAIN checkout, so `poga ops new` from inside a lane
# writes the one real store. That fixed the door people are TOLD to use and left the door
# they actually typed wide open: `session.py` is on disk in every lane, its `--help` lists
# `ops-new`, and nothing between the verb and the file asked which checkout it was about to
# write. A front door only helps if the back door is shut ([`add-structural-guard-on-
# recurrence`]) — the two-surfaces-of-one-fact shape this substrate keeps rediscovering.
#
# REFUSE RATHER THAN REDIRECT, and the alternative was real. The other half of the
# acceptance was to make these verbs anchor on main themselves, matching the front door.
# Rejected on the reason `cmd_work` in `poga` already gives for the front door existing:
# EVERY worktree carries its own `session.py`, and a lane's copy is whatever it was cut
# with — so a redirect here would let a lane's possibly-weeks-old harness drive TODAY's
# live store, which is the second hazard the front door was built to remove. A redirect
# also has to REPLACE THIS PROCESS to be honest about which code runs, and this is the
# choke point every verb passes through, including in-process callers. Refusing costs the
# caller one word in a command a machine is typing anyway; redirecting costs a class of
# silent wrong-version writes. The cost of the refusal is bounded and visible; the cost of
# the thing on the other side of it was an unrecoverable burned number.
#
# THE SET IS DERIVED, NOT CURATED. `test_lane_store_writes.py` walks the harness AST and
# fails if any `cmd_wi_*` / `cmd_ops_*` that reaches `_wi_write_item` / `_ops_write_item`
# is in neither list below — so a verb added tomorrow cannot forget a rule that is not its
# to remember, which is the same argument that put `_store_autocommit` at one hook point.
LANE_STRANDED_STORE_VERBS = frozenset({
    "wi-new", "wi-edit", "wi-status", "wi-move", "wi-stale",
    "ops-new", "ops-edit", "ops-status", "ops-ran",
})

# DELIBERATELY LANE-LOCAL — do not "fix" these into the set above; `poga work renumber`
# and `poga ops renumber` carry the same carve-out for the same reason, spelled out at
# their front doors.
#
#   * `wi-renumber` / `ops-renumber` (WI-0169, WI-0245): the subject is a record that
#     exists ONLY in this lane — that is what makes its number collide with the trunk —
#     and the citations to follow are found by diffing the lane's working tree against
#     main. Run against main it would find neither, and report success having done nothing.
#   * `wi-commit`: it saves whatever store files the tree it is standing in has left
#     uncommitted, and it is the retry `_store_autocommit` PRINTS when its own commit
#     fails. A refusal here would name a front door that cannot reach the lane's files.
LANE_LOCAL_STORE_VERBS = frozenset({"wi-renumber", "ops-renumber", "wi-commit"})

# Exit 4 — distinct from argparse's 2 ("you used it wrong") and `_refuse_undrawn`'s 3
# ("could not draw"). This is neither: the request is well-formed and answerable, it is
# addressed to the wrong checkout. A caller that wants to react to exactly this needs to
# be able to tell it from the other two.
LANE_STORE_REFUSAL_EXIT = 4


def _store_front_door(verb: str) -> str:
    """`wi-new` -> `poga work new`, `ops-ran` -> `poga ops ran`.

    A RULE, not a table. `poga`'s `cmd_work` and `cmd_ops` route by exactly this rewrite,
    so deriving it here keeps one spelling of the mapping instead of a second copy that
    drifts the first time a verb is renamed ([P16](principles/master.md#p16--avoid-duplication))."""
    ns, _, rest = verb.partition("-")
    return f"poga {'work' if ns == 'wi' else 'ops'} {rest}"


def _refuse_lane_store_write(verb: str, argv: list[str] | None = None) -> None:
    """Refuse a shared-store WRITE issued from a linked worktree, naming the front door.

    THREE OUTCOMES, never two ([`declare-what-a-check-assumes`]). Git can say this is the
    main checkout (proceed, silently — the common case must cost nothing), or that it is a
    linked worktree (refuse), or it can fail to answer at all. The third borrows neither
    sentence: it says out loud that the guard did not run, because a guard that cannot tell
    and stays quiet is indistinguishable from one that checked and approved — and the whole
    class this exists for is a write that looked exactly like a successful one.

    `_main_checkout(at=ROOT)` asks the question OF THE TREE THIS HARNESS LIVES IN, never of
    the process cwd. That distinction is load-bearing and is the bug its own docstring
    records: a cwd-relative answer is about a different repo entirely, so a test whose store
    is a temp repo would have this guard declare that repo a lane of the federation and
    refuse every write in the suite."""
    if verb not in LANE_STRANDED_STORE_VERBS:
        return
    main = _main_checkout(at=ROOT)
    if main is None:
        print(f"{verb}: CANNOT TELL whether {ROOT} is the main checkout or a lane, so the "
              f"stranded-store check did not run. If this is a lane, what you are about to "
              f"write lands in a copy of the store no other checkout reads — use "
              f"`{_store_front_door(verb)}` instead, which anchors on the main checkout.",
              file=sys.stderr)
        return
    if main == ROOT.resolve():
        return
    rest = argv if argv is not None else (sys.argv[2:] if sys.argv[1:2] == [verb] else [])
    line = " ".join([_store_front_door(verb)] + [shlex.quote(a) for a in rest])
    print(f"{verb}: REFUSING to write the store from a lane — {ROOT} is a linked worktree, "
          f"and its `{WI_DIRNAME}/` and `{OPS_DIRNAME}/` are a TRACKED COPY frozen at this "
          f"lane's base commit. Nothing outside this lane reads them, so an item or "
          f"obligation created here is invisible to `poga work list`, to the board, "
          f"and to every other session on this machine until the lane lands — which it may "
          f"never do.\n"
          f"          That is not hypothetical: OPS-0006 was filed this way and sat "
          f"unreadable while it ran overdue, and OPS-0004's number was burned outright "
          f"(WI-0193, WI-0125).\n"
          f"          The front door anchors on the main checkout and works from right "
          f"here, inside this lane. Run:\n\n"
          f"              {line}\n\n"
          f"          The main checkout is {main}. Nothing was written.",
          file=sys.stderr)
    sys.exit(LANE_STORE_REFUSAL_EXIT)


def _wi_write_item(item: dict, commit: bool = True) -> list[str]:
    """Atomically write ONE item's file — the sole writer path (new or updated). A
    changed title regenerates the slug and removes the stale filename so an id never
    ends up with two files. Returns the filenames it touched.

    Being the sole writer is why the WI-0056 auto-commit hangs here rather than on each
    of `wi-new`/`wi-edit`/`wi-status`/`wi-move`: one hook point cannot be forgotten by
    the next verb someone adds.

    `commit=False` (WI-0308) writes the file and DEFERS the commit + feed rebuild to the
    caller, which must then run both itself. The one caller that needs it is the stamp
    pass, which touches every clean item in the store at once: committing per item would
    put sixty single-file commits in the log for one probe run, and rebuild the board
    feed sixty times, for a change that is one event. Everything else keeps the default
    — the sole-writer hook point is preserved either way, only its batching moves."""
    d = _wi_dir()
    d.mkdir(exist_ok=True)
    old_name = _wi_filename_for(item["id"])
    new_name = f"{item['id']}-{_wi_slug(item['title'])}.md"
    atomic_write(d / new_name, _wi_render_item(item))
    if old_name and old_name != new_name:
        (d / old_name).unlink(missing_ok=True)
    changed = [new_name] + ([old_name] if old_name and old_name != new_name else [])
    if not commit:
        return changed
    _store_autocommit(WI_DIRNAME, changed,
                      f"chore(work-items): {'update' if old_name else 'add'} "
                      f"{item['id']} — {item['title'].strip()[:60]}",
                      "poga work commit")
    _wi_feed_write()                              # the feed a board renders rides
    # every store write, from the one hook point a new verb cannot forget.
    return changed


def _wi_existing_max() -> int:
    """Highest WI number among work-items/*.md filenames; 0 if none."""
    return _counter_existing_max(_counter("wi"))


def _wi_reserve_next(identity: str | None = None, tries: int = 64) -> int | None:
    """Atomically reserve the next free WI number. None if the coord store is
    unavailable — the caller falls back to an unguarded max+1."""
    return _counter_reserve_next(_counter("wi"), identity, tries)


def _wi_remap_edges(old_id: str, new_id: str) -> tuple[list[str], list[str]]:
    """`blocked-by` is the only machine-validated cross-reference in the WORK-ITEM store,
    and the WI row is the only row that declares one. Rewritten through the sole writer
    so the file is re-rendered exactly as any other edit renders it.

    Miss this and `wi-check` goes red on a store the renumber just "fixed" — which is why
    it is a declared row hook rather than something the generic renumberer could be
    forgiven for not knowing about."""
    changed: list[str] = []
    report: list[str] = []
    for other in _wi_parse():
        if other["id"] in (old_id, new_id):
            continue
        if old_id not in (other.get("blocked_by") or []):
            continue
        other["blocked_by"] = [new_id if b == old_id else b for b in other["blocked_by"]]
        _wi_write_item(other)
        nm = _wi_filename_for(other["id"])
        if nm:
            changed.append(f"{WI_DIRNAME}/{nm}")
        report.append(f"             {other['id']}: blocked-by {old_id} -> {new_id}")
    return changed, report


def cmd_wi_next(_args: argparse.Namespace) -> None:
    """Print (and reserve) the next free WI number, e.g. `WI-0047`."""
    existing = _wi_existing_max()
    n = _wi_reserve_next()
    if n is None:
        _refuse_undrawn("work-item", "wi-next", WI_DIRNAME)
    print(f"WI-{n:04d}")
    print(f"wi-next: next after {existing:04d} in {WI_DIRNAME}/", file=sys.stderr)


# -- WI-0289: prose reaches the store as FILE BYTES, never as a shell argument --------
#
# HIT LIVE, session ~208, filing WI-0288. `--notes` prose containing backticks -- the
# natural way to quote a verb or a filename in Markdown -- is COMMAND SUBSTITUTION inside a
# double-quoted shell argument. The shell ran it, it produced nothing, and the empty result
# is what got stored. Three fragments were lost before anyone read them; the only signal was
# three `command not found` lines on stderr, above a success message, in a tool whose output
# is normally skimmed. The item committed cleanly and looks fine unless you already know
# what the sentence was supposed to say.
#
# THE FIX IS A ROUTE, NOT AN INSTRUCTION. `--notes-file` hands the store a PATH; the bytes
# are read here, so nothing in the prose is ever a shell token. That is the whole mechanism,
# and it is why "remember to single-quote your notes" was not an acceptable answer -- a fix
# that ends in "and then remember to X" has left the defect exactly where it was.
#
# WHY A LENGTH RULE AND NOT A CORRUPTION DETECTOR. By the time argv reaches this process the
# eaten text is GONE. There is nothing left to detect -- that absence IS the failure mode --
# so the guard cannot ask "was this corrupted?". It can only ask "is this the kind of payload
# that gets corrupted", and the honest proxy is length: a value short enough to be a phrase is
# typed and read back in one glance; prose is not. The refusal says that out loud rather than
# implying it caught something (`declare-what-a-check-assumes`).
#
# FAIL-CLOSED, deliberately. `add-structural-guard-on-recurrence` sets a guard's direction by
# what is on the other side of it. Here it is the silent and UNRECOVERABLE loss of the
# reasoning this store exists to keep: a lost line number can be looked up again, a lost
# "do not conflate these two budgets" cannot, because nobody knows it was ever there. The
# cost of a false refusal is one file write the caller was free to do anyway.
NOTES_INLINE_MAX = 240

# Named per verb so the remedy is the command the reader was actually running, not a generic
# one they have to translate. A verb missing from here still gets a runnable line.
_NOTES_VERB_EXAMPLE = {
    "wi-new": 'poga work new "<title>"',
    "wi-edit": "poga work edit <id>",
    "ops-new": 'poga ops new "<title>"',
    "ops-ran": "poga ops ran <id> --result pass",
    "ops-edit": "poga ops edit <id>",
}

# The quoted heredoc in the remedy is load-bearing: `<<'NOTES'` suppresses expansion, so the
# prose survives the one shell it does still touch. A remedy has to be runnable by the reader
# it is printed to (WI-0158) -- including the reader who was just bitten by quoting.
_NOTES_FILE_REMEDY = """
             cat > /tmp/notes.md <<'NOTES'
             ...your prose, verbatim -- backticks, $(...) and [brackets] need no escaping...
             NOTES
             {cmd} {opt}-file /tmp/notes.md"""


def _notes_from_args(args: argparse.Namespace, verb: str, flag: str = "notes") -> str | None:
    """Resolve `--notes`/`--notes-file` (or `--append-notes`/`--append-notes-file`) to text.

    Returns the resolved prose, or the flag's own sentinel untouched when neither was given
    -- `None` where the caller distinguishes "not passed" from "set to empty" (`wi-edit`), `""`
    where it does not (`wi-new`). Preserving that distinction here is the point: the five call
    sites each already mean something specific by their default, and one resolver that
    flattened them into a single sentinel would silently re-author bodies nobody asked to
    change.

    The file's trailing newline is dropped and nothing else is touched. Every writer in this
    store `.strip()`s a notes body on the way to disk, so a trailing newline would not survive
    to be compared anyway; every other byte -- leading whitespace, interior blank lines, and
    the metacharacters this whole route exists for -- reaches the record exactly as authored.
    """
    attr = flag.replace("-", "_")
    inline = getattr(args, attr, None)
    path = getattr(args, attr + "_file", None)
    opt = "--" + flag
    if path:
        # The parser already refuses this pair (they share a mutually exclusive group); this
        # arm covers the direct-Namespace callers -- the tests, and anything in-process.
        if inline:
            print(f"{verb}: pass {opt} or {opt}-file, not both -- two sources for one field "
                  f"have no defensible winner, so neither is chosen.")
            sys.exit(2)
        try:
            text = Path(path).read_text(encoding="utf-8")
        except UnicodeDecodeError:
            print(f"{verb}: {opt}-file {path} is not UTF-8 text.")
            sys.exit(2)
        except OSError as e:
            print(f"{verb}: cannot read {opt}-file {path} -- {e.strerror or e}.")
            sys.exit(2)
        if not text.strip():
            print(f"{verb}: {opt}-file {path} is empty. A file route exists to carry prose, "
                  f"and an empty one is a mistake far more often than an intention -- most "
                  f"often a heredoc that never ran. To clear a notes body, pass {opt} '' "
                  f"instead.")
            sys.exit(2)
        return text.rstrip("\n")
    if inline and len(inline) > NOTES_INLINE_MAX:
        cmd = _NOTES_VERB_EXAMPLE.get(verb, 'poga work new "<title>"')
        print(f"{verb}: {opt} is {len(inline)} characters; anything over {NOTES_INLINE_MAX} "
              f"goes in a file (WI-0289). Backticks and $(...) in prose are command "
              f"substitution inside a double-quoted shell argument -- the shell runs them and "
              f"stores the empty result, which is how three fragments of WI-0288's notes were "
              f"lost behind nothing but a `command not found` above a success message.\n"
              f"         THIS IS A LENGTH RULE, NOT A CORRUPTION DETECTOR: whatever a shell "
              f"already ate is gone before this process starts, so there is nothing here to "
              f"check. Write the prose to a file and pass the path:\n"
              + _NOTES_FILE_REMEDY.format(cmd=cmd, opt=opt))
        sys.exit(2)
