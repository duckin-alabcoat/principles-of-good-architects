def _wi_feed_build(base: Path | None = None) -> dict:
    """The feed dict — everything a renderer needs, nothing that couples it to store
    internals. Claim `expires_epoch` is included so a reader derives expiry from the
    clock without any write happening; the stamp is as-of generation (a heartbeat
    refresh alone does not regenerate — deliberately, the heartbeat path stays cheap),
    so a long-lived claim can look shorter-lived than it is until the next mutation."""
    base = base or _shared_work_root()
    claims = {}
    with contextlib.suppress(Exception):
        for name, rec in _coord_list("claims").items():
            # WI-0174: the board is a published surface, and a drill's claim names an
            # item `_chart_rows` will never return — so it can only ever render as a
            # claim on nothing. The live rehearsal stays visible where it belongs, on
            # the start banner and `poga work claims`.
            if _is_drill_item(name):
                continue
            claims[name] = {
                "session_id": rec.get("session_id", ""),
                "branch": rec.get("branch", ""),
                "journal": rec.get("journal", ""),
                "runtime": rec.get("runtime", ""),
                "machine": rec.get("machine", ""),
                "claimed_at": rec.get("created_at", ""),
                "expires_epoch": rec.get("expires_at"),
                "expires_iso": rec.get("expires_iso", ""),
            }
    items = []
    for it in _chart_rows(base):
        items.append({
            "id": it.get("id", ""),
            "kind": it.get("kind", "dev"),
            "title": it.get("title", ""),
            "status": it.get("status", "open"),
            "section": it.get("section", ""),
            "state": it.get("state", ""),
            "blocked_by": it.get("blocked_by", []),
            "group": it.get("group", ""),
            "impact": it.get("impact", ""),
            # WI-0323. Additive, and the feed schema is deliberately NOT bumped: the feed
            # contract puts rendering in the consumer's hands, and a consumer that does not know
            # the key ignores it. Bumping would be the board's problem, not a description
            # of anything that changed for it. An OPS row carries no `scope` key at all
            # (see `_ops_render_item`), so it reads as "" here — the same empty cell the
            # `section` column already leaves for an obligation.
            "scope": it.get("scope", ""),
            # WI-0408. Empty string, never a missing key — the board reads this feed BY
            # KEY, and a missing key and an empty one are different bugs on
            # the other side of that contract. An OPS row carries no `waiting-on` field
            # at all (see `_ops_render_item`), so an obligation reads as "" here: a
            # standing obligation is owed on a DATE, never waiting on a person's answer.
            "waiting_on": it.get("waiting_on", ""),
            "version": it.get("version", ""),
            "due": it.get("due", ""),
            "cadence": it.get("cadence", ""),
        })
    # Hash over the content, not the stamp — two generations of an unchanged store
    # compare equal, so a reader can tell "regenerated" from "changed".
    digest = hashlib.sha256(json.dumps({"items": items, "claims": claims},
                                       sort_keys=True).encode("utf-8")).hexdigest()[:16]
    now = time.time()
    return {
        "schema": WI_FEED_SCHEMA,
        "system": _system_id(),
        # WI-0408 half two. A MEMBER-LEVEL declaration, beside the member identity it
        # qualifies: this member's harness writes the waiting marker.
        #
        # It is the difference between "nobody is waiting on you here" and "this member
        # cannot answer that question", which without it are the same empty list — and a
        # consumer that cannot tell them apart must render `cannot tell` for the whole
        # portfolio (ADR-0101's three-state rule). See `WI_FEED_WRITES_WAITING_MARKER`
        # for why it is a constant rather than derived from the item set, and why the
        # feed schema is not bumped to carry it.
        #
        # NOT in the hashed dict above, deliberately: `store_hash` answers "did the STORE
        # change", so folding a build-time constant into it would be a value that can
        # never vary pretending to be content.
        "writes_waiting_marker": WI_FEED_WRITES_WAITING_MARKER,
        "generated_epoch": now,
        "generated_iso": _coord_iso(now),
        "store_hash": digest,
        "items": items,
        "claims": claims,
    }


def _wi_feed_write() -> None:
    """Regenerate the feed, best-effort — called from the store's sole-writer paths and
    the claim mutation points. MUST never raise: the store write it rides on has already
    succeeded, and a feed failure turning that into an error would be the tail wagging
    the dog. A repo with no store publishes an empty item set, which is itself honest."""
    try:
        path = _wi_feed_path()
        path.parent.mkdir(exist_ok=True)
        atomic_write(path, json.dumps(_wi_feed_build(path.parent.parent),
                                      ensure_ascii=False, indent=2) + "\n")
    except Exception:
        pass


def cmd_wi_feed(_args: argparse.Namespace) -> None:
    """CLI entry (`poga work feed`): rebuild the feed standalone and print the receipt.
    The rebuild path for a feed that is missing, stale, or doubted — same posture as
    every other generated artifact (never hand-edited, always rebuildable)."""
    base = _shared_work_root()
    feed = _wi_feed_build(base)
    path = _wi_feed_path(base)
    path.parent.mkdir(exist_ok=True)
    atomic_write(path, json.dumps(feed, ensure_ascii=False, indent=2) + "\n")
    live = sum(1 for it in feed["items"]
               if it["kind"] == "dev" and it["status"] not in WI_TERMINAL)
    waiting = sum(1 for it in feed["items"] if it.get("waiting_on"))
    # WI-0408: the declaration is ON the receipt because a capability nothing reports is
    # one nobody can see was shipped (`ship-the-detector-with-the-capability`). The count
    # beside it is the fact the declaration makes readable — with the declaration, `0` is
    # "nobody is waiting"; without it, `0` would be unreadable.
    print(f"wi-feed: wrote {path} — schema {feed['schema']}, system "
          f"'{feed['system']}', {len(feed['items'])} row(s) ({live} live dev), "
          f"{len(feed['claims'])} claim(s), hash {feed['store_hash']}"
          + (f", waiting-marker declared ({waiting} item(s) waiting)"
             if feed.get("writes_waiting_marker") else ""))


#: WI-0154. The two files `poga_board_ensure` sources, in the order it sources them.
#: The machine-level one is the single source for a fact about the BOX — which board,
#: which port, which checkout — and the repo-local one is the per-member override that
#: was the only option before. Relative to `$HOME` and to the main checkout respectively.
BOARD_ENSURE_MACHINE_REL = ".config/poga/poga.local"
BOARD_ENSURE_REPO_NAME = "poga.local"
#: An assignment at the START of a line (leading whitespace and an `export` /
#: `readonly` keyword allowed), never anywhere in it. See `board_ensure_config`.
_BOARD_CMD_ASSIGN_RE = re.compile(r"^\s*(?:export\s+|readonly\s+)?POGA_BOARD_CMD=")


def board_ensure_paths(home: Path | None = None,
                       base: Path | None = None) -> list[Path]:
    """The candidate files, machine-first — the same order, and the same two places,
    that `poga_board_ensure` reads. Parameterised so a test names its own home and
    checkout instead of the developer's (`ambient_fixture`'s subject: a probe that
    reads ambient state passes or fails on who ran it)."""
    return [(home or Path.home()) / BOARD_ENSURE_MACHINE_REL,
            (base or _shared_work_root()) / BOARD_ENSURE_REPO_NAME]


def board_ensure_config(home: Path | None = None,
                        base: Path | None = None) -> tuple[str, str]:
    """Will this machine bring the board back up by itself, and from where?

    WHY THIS IS A CHECK AT ALL (`ship-the-detector-with-the-capability`). WI-0028 shipped
    `poga_board_ensure` with no way to tell a machine that has it configured from one
    that has not — both are silent, by the hook's own best-effort contract. So when the
    board moved to another machine and that machine became the one every lane runs on, the fact
    that NO `poga.local` existed anywhere on it was invisible: the hook was a dead
    no-op for days, the board survived only because a human had started it by hand, and
    nothing would have brought it back. The capability's own exemption from
    `no-server-outlives-its-session` rests on this lifecycle, which makes "is the
    lifecycle actually wired here?" the question the exemption assumes and nothing asked.

    Three outcomes, never two (`declare-what-a-check-assumes`):

      ``configured``    — a candidate file assigns POGA_BOARD_CMD;
      ``unconfigured``  — NEITHER file exists, so there is provably nothing to source;
      ``unknown``       — a file is there but unreadable, or readable and carrying no
                          assignment this scan can recognise.

    WHAT THIS SCAN ASSUMES, stated because the honest answer depends on it: it READS the
    file as text and looks for an assignment. It does not source it — running a shell out
    of a status probe is the thing a status probe must never do. A file that sets the
    variable by indirection is therefore real configuration this cannot see, and it
    reports ``unknown`` rather than laundering "I could not tell" into "nothing is set".
    """
    seen: list[str] = []
    for path in board_ensure_paths(home, base):
        try:
            text = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            continue
        except Exception as e:
            return "unknown", f"{path} exists but is unreadable ({type(e).__name__})"
        # ANCHORED, and that is the whole guard. `poga.local.example` is almost
        # entirely commented-out assignments, so an unanchored search would certify
        # every machine that had merely copied the template and edited nothing — the
        # exemption-that-defaults-to-pass shape, reporting a lifecycle that does not
        # exist. An explicit `startswith("#")` branch was written here first and a
        # mutation run proved it unreachable: a comment can never satisfy the anchor,
        # so the branch could not change an answer and was removed rather than left as
        # a guard nothing can exercise.
        for line in text.splitlines():
            if _BOARD_CMD_ASSIGN_RE.match(line):
                return "configured", f"POGA_BOARD_CMD set in {path}"
        seen.append(str(path))
    if seen:
        return "unknown", (f"{', '.join(seen)} present but no POGA_BOARD_CMD assignment "
                           f"this scan can see (it reads the file, it does not run it)")
    return "unconfigured", (
        "no poga.local at " + " or ".join(str(p) for p in board_ensure_paths(home, base))
        + " — nothing will start the board when it is not running")


def board_ensure_line(home: Path | None = None, base: Path | None = None) -> str:
    """One line naming the lifecycle state, for `board-check`. Deliberately NOT on the
    startup path and deliberately NOT part of any exit code: whether the board is
    SHOWING and whether it would COME BACK are two different questions, and folding the
    second into the first's 0/1/2 contract would make a healthy board with no lifecycle
    read as a failure — and a dead board with a perfect lifecycle read as fine."""
    try:
        state, why = board_ensure_config(home, base)
    except Exception as e:
        # `Path.home()` and `_shared_work_root()` can both fail to resolve, and this is a
        # REPORT: it says it could not tell, the third outcome, rather than raising out of
        # a diagnostic verb whose whole job is to answer a question about a broken machine.
        return ("board-ensure: unknown — CANNOT TELL; resolving the config paths "
                f"failed ({type(e).__name__})")
    label = {"configured": "will restart at the next lane launch",
             "unconfigured": "WILL NOT restart — no lane launch can bring it back",
             "unknown": "CANNOT TELL whether it would restart"}[state]
    return f"board-ensure: {state} — {label}; {why}"


def _board_live() -> tuple[dict | None, str]:
    """Read-side wrapper for the gate: (board status dict, 'live') when the board is
    properly showing this system's items, else (None, the specific refusal). File reads
    only — no sockets on the startup path (the operator's latency call)."""
    try:
        status = json.loads(_board_status_path().read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None, "no board status file (board not running here, or predates the status-file contract)"
    except Exception as e:
        return None, f"board status unreadable ({type(e).__name__})"
    try:
        feed = json.loads(_wi_feed_path().read_text(encoding="utf-8"))
    except Exception:
        return None, "no published feed yet (`poga work feed` writes one)"
    ok, why = _board_gate(status, feed, time.time())
    return (status, why) if ok else (None, why)


def _wi_short_lines(status: dict) -> list[str]:
    """The short startup view: one summary line pointing at the live
    board, then the code-filtered candidate set the session recommends from — overdue
    or never-run ops obligations always, then unclaimed, unblocked `next`-section dev
    items, in id order, capped. The FILTER is mechanism; PICKING two or three to
    recommend, with reasons, is the session's judgment (P15) — the store carries no
    priority field to compute a ranking from, and inventing one here would be
    fabricated data. The full list is one command away and its ordinal mapping was
    pinned by the caller, so `do 3` means the same thing it always did.

    THE JUDGMENT HALF HAS A STATED PREFERENCE NOW (WI-0323, R4 of the 2026-09-07
    consultant brief), and this is the code path that applies it:

        Favor finishing existing harness work before starting additional
        discretionary improvements. Continue recording defects honestly.

    It is a PREFERENCE the session applies when choosing which two or three of these
    candidates to put in front of operator — read `scope` on the rows below and lean toward
    the `harness` ones already in flight. It is deliberately NOT a filter here, and the
    reason is the same one that keeps the ranking out of code: the rows this function
    returns are the mechanical candidate set, and a preference compiled into the filter
    would silently hide product work rather than rank it lower. It creates no obligation
    on a session that discovers a defect, no closure debt, and no incentive to close
    unverified work — operator declined the close-one rule that would have (WI-0287).

    Items that predate the field carry `scope` unset; an unset row is not a product row
    and must not be read as one (`WI_SCOPE_UNSET`)."""
    rows_all = _chart_rows()
    claims = {}
    with contextlib.suppress(Exception):
        claims = _coord_list("claims")
    live_ids = {it["id"] for it in rows_all if it.get("status") not in WI_TERMINAL}
    open_n = sum(1 for it in rows_all
                 if it.get("kind") == "dev" and it.get("status") not in WI_TERMINAL)
    ops_due = [it for it in rows_all if it.get("kind") == "ops"
               and (it.get("state") == "overdue" or it.get("state") == "never run")]
    candidates = [it for it in rows_all
                  if it.get("kind") == "dev"
                  and it.get("status") == "open"
                  and it.get("section") == "next"
                  and it["id"] not in claims
                  and not [b for b in it.get("blocked_by", []) if b in live_ids]]
    url = str(status.get("url", "")).strip() or "(board url unset)"
    lines = [f"Work items: {open_n} open · {len(claims)} claimed · live list on the "
             f"board — {url}  (`poga work list` prints the full view here)"]
    shown = (ops_due + candidates)[:10]
    rows = [(it["id"], it.get("state", ""), it.get("section", ""),
             _wi_truncate(it["title"], 70), it.get("status", "open"), False)
            for it in shown]
    lines += _wi_format_rows(rows, _wi_colour_enabled())
    dropped = len(ops_due) + len(candidates) - len(shown)
    if dropped > 0:
        lines.append(f"  (+{dropped} more candidate(s) — the board has the whole list.)")
    return lines


def cmd_board_check(_args: argparse.Namespace) -> None:
    """`board-check` — the DEEP verification the startup gate deliberately skips:
    the full HTTP round-trip against the live board, comparing what the
    server actually serves with the current feed. The go-live acceptance probe and the
    debugging tool; never ambient. Exit 0 = showing, 1 = not showing, 2 = cannot tell.
    Each assumption failure gets its own sentence, never folded into a lookalike.

    WI-0154 adds a SECOND, INDEPENDENT axis to the report: the board's LIFECYCLE — is
    this machine configured to bring the board back up when it is not running? The two
    are orthogonal (a live board with no lifecycle is one crash from dark; a dead board
    with a good one is a lane launch from back), so the lifecycle prints as its own line
    and changes no exit code. D4 is why it lives here rather than in the banner: this
    class of check is an explicit verb, never ambient."""
    base = _shared_work_root()
    feed_path = _wi_feed_path(base)
    try:
        feed = json.loads(feed_path.read_text(encoding="utf-8"))
    except Exception:
        print(f"board-check: CANNOT TELL — no readable feed at {feed_path} "
              f"(`poga work feed` writes one).")
        raise SystemExit(2)
    board, why = _board_live()
    print(f"board-check: startup gate says {'LIVE' if board else 'not live'} — {why}")
    # WI-0154: printed BEFORE the not-live exit, because a board that is down is exactly
    # when "is anything going to bring it back?" is the question worth answering.
    print(board_ensure_line())
    if board is None:
        raise SystemExit(1)
    url = str(board.get("url", "")).strip()
    if not url:
        print("board-check: CANNOT TELL — status file names no url to probe.")
        raise SystemExit(2)
    import urllib.request
    try:
        with urllib.request.urlopen(f"{url.rstrip('/')}/state.json", timeout=3) as r:
            served = json.loads(r.read().decode("utf-8"))
    except Exception as e:
        print(f"board-check: NOT SHOWING — status file is fresh but the server did not "
              f"answer ({type(e).__name__}: {e}). The file proves the render loop wrote; "
              f"only this round-trip proves the server serves.")
        raise SystemExit(1)
    sysid = feed.get("system", "")
    echo = (served.get("workitems") or {}).get(sysid) if isinstance(served, dict) else None
    egen = echo.get("feed_generated_epoch") if isinstance(echo, dict) else None
    if not isinstance(egen, (int, float)):
        print(f"board-check: NOT SHOWING — server answered but its state carries no "
              f"work-item echo for system '{sysid}'.")
        raise SystemExit(1)
    lag = feed.get("generated_epoch", 0) - egen
    verdict = "SHOWING" if lag <= max(
        2 * (board.get("poll_seconds") or 0), BOARD_FRESH_FLOOR_SECONDS) else "NOT SHOWING"
    print(f"board-check: {verdict} — server renders feed generated "
          f"{str(feed.get('generated_iso', '?'))[:19]} for '{sysid}' "
          f"({int(lag)}s behind the live feed), {len(feed.get('items', []))} row(s), "
          f"hash {feed.get('store_hash', '?')}.")
    raise SystemExit(0 if verdict == "SHOWING" else 1)


