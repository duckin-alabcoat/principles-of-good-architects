def _duplicate_note_records() -> list[str]:
    """Note records filed under more than one item id — one record, two owners.

    WI-0307 half one. Three records lived under both a pre- and a post-renumber id
    (`0167`=`0183`, `0172`=`0188`, `0173`=`0189`) and `wi-check` called the store sound
    the whole time, because nothing it ran read the notes tree at all.

    THE NAME IS THE PROOF, which is why this check is cheap and certain rather than a
    content heuristic. `_note_write` names a record `<utc-stamp>-<machine>-<rand>.md`, so
    the name is unique by construction. The same name under two ids cannot be two records
    that happen to match and cannot be a naming collision — it is one record in two
    places, and at most one of them is its real owner.

    IT REPORTS AND NEVER REPAIRS. Which copy is stale is a question about what the record
    SAYS and which item that describes — a read, not a derivation — so choosing is the
    operator's ([P15](principles/master.md#p15--code-for-mechanism-not-judgment)). A
    validator that guessed would eventually delete the live copy and leave the stale one,
    which is strictly worse than the duplicate it set out to fix.

    BOTH STORES, one pass. `work-items/` and `ops-items/` keep notes under the same
    `<store>/notes/<ID>/` shape (WI-0165); checking one of them would be the
    [`ship-the-detector-with-the-capability`](habits/master.md#ship-the-detector-with-the-capability)
    gap one directory over. The owner index is deliberately global across both, because
    the stamp is globally unique — a record under a WI id and an OPS id is the same
    two-owner fault, not a coincidence the check should excuse.

    Fail-open per directory: an unreadable notes tree yields no finding rather than a
    false one, and reports nothing it did not actually see."""
    owners: dict[str, list[str]] = {}
    for store in (WI_DIRNAME, OPS_DIRNAME):
        try:
            item_dirs = sorted(p for p in (ROOT / store / NOTES_DIRNAME).iterdir()
                               if p.is_dir())
        except Exception:
            continue          # no notes tree here — the normal empty state, not a fault
        for d in item_dirs:
            try:
                names = sorted(p.name for p in d.glob("*.md"))
            except Exception:
                continue
            for name in names:
                owners.setdefault(name, []).append(d.name)
    out: list[str] = []
    for name, who in sorted(owners.items()):
        if len(who) > 1:
            out.append(
                f"note record {name} is filed under {len(who)} items "
                f"({', '.join(who)}) — a record's name is unique by construction, so "
                f"this is ONE record with two owners. Read it, decide which item it "
                f"describes, and delete the other copy.")
    return out


def _wi_validate() -> list[str]:
    """Every structural problem in the store. [] when sound.

    The third gap (session ~103). Nothing checked that the data was internally
    consistent, so a bad status, a `blocked-by` naming an id that never existed, or a
    superseded item that names no successor all sat there looking fine. A store is only
    'managed by code' if code can say whether it is *valid*, not just write to it.
    """
    problems = _wi_missing_numbers()
    items = _wi_parse()
    known = {it["id"] for it in items}
    # WI-0239: probed ONCE, before the loop, so a store with a dozen items citing the same
    # lane-minted blocker pays for one branch scan and the problem lines keep their
    # per-item order. Empty in the normal case, where the probe never runs at all.
    absent_cause = _wi_absent_cause(sorted(
        {b for it in items for b in (it.get("blocked_by") or []) if b not in known}))
    for it in items:
        wid = it["id"]
        if it.get("status") not in WI_STATUSES:
            problems.append(f"{wid}: status '{it.get('status')}' is not one of "
                            f"{', '.join(WI_STATUSES)}")
        if it.get("section") not in WI_SECTIONS:
            problems.append(f"{wid}: section '{it.get('section')}' is not one of "
                            f"{', '.join(WI_SECTIONS)}")
        if not (it.get("title") or "").strip() or it["title"] == wid:
            problems.append(f"{wid}: has no title")
        for b in it.get("blocked_by") or []:
            if b not in known:
                # The CLOSEST SIBLING of the gap check — same function, same caller, same
                # exit-1 path — and it was the one WI-0191 did not teach. Mint an id on a
                # lane, name it as a blocker from the trunk, and every citing item reported
                # its real dependency as a fiction. It still FAILS (the operator's ruling, session
                # ~187, for the lane-held gap): there is a body off the trunk and a real
                # action someone must take. Only the diagnosis changes.
                problems.append(
                    f"{wid}: blocked-by names {b}, which is not in this tree's store. "
                    + (absent_cause.get(b) or "No ref carries it and no live draw holds "
                       "the number, so the citation is dangling."))
            if b == wid:
                problems.append(f"{wid}: is blocked by itself")
        # A superseded item must say what replaced it, or the id resolves to a dead end —
        # the very failure that made deletion look acceptable in the first place. The
        # successor may be an OPS id, not only a WI one: ADR-0076 D7 supersedes the three
        # operational items INTO the ops namespace, and a WI-only pattern would have
        # rejected exactly the migration the ADR prescribes.
        if (it.get("status") == "superseded"
                and not re.search(r"(?:WI|OPS)-\d{4}", it.get("notes") or "")):
            problems.append(f"{wid}: superseded but its notes name no successor item")
        if (it.get("impact") or WI_IMPACT_UNSET) not in ("",) + WI_IMPACTS:
            # `breaking` was a valid value until ADR-0081 retired it. Name the migration
            # explicitly rather than printing a bare "not one of" — an operator hitting
            # this is holding a label that USED to be right, and the useful thing to tell
            # them is where its two halves went.
            extra = (" — `breaking` was retired (ADR-0081): a major is declared, not "
                     "derived. Use fix|feature for the size, and `--migration yes` if "
                     "members must edit their own files."
                     if it.get("impact") == "breaking" else "")
            problems.append(f"{wid}: impact '{it['impact']}' is not one of "
                            f"{', '.join(WI_IMPACTS)}{extra}")
        if (it.get("migration") or "") not in ("",) + WI_MIGRATION_VALUES:
            problems.append(f"{wid}: migration '{it['migration']}' is not one of "
                            f"{', '.join(WI_MIGRATION_VALUES)}")
        # WI-0323. THE VALUE IS VALIDATED; THE ABSENCE IS NOT, and the asymmetry with
        # `impact` two checks below is deliberate rather than an oversight.
        #
        # `impact` reports every unlabelled item as debt, and could afford to: it arrived
        # when the store was small, and the release cut refuses on it anyway, so the debt
        # has a second enforcer. `scope` arrives to a store of 367 items and THIS FUNCTION
        # IS WHAT THE LAND GATE RUNS. One problem per unscoped legacy item is 367
        # problems — a permanently red trunk until a 367-file backfill lands, and that
        # backfill collides with every item in flight. Landing a field by breaking every
        # land is not shipping the field.
        #
        # So the pressure sits where it converges instead: `cmd_wi_new` REFUSES an
        # unscoped new item, `cmd_wi_status` scopes an old one as it is touched, and the
        # count of unset items is PRINTED as its own bucket by `curate/finish_line.py`'s
        # exit-1 evidence — visible, never silently folded into `product`, which is the
        # one thing R4 asks for by name.
        if (it.get("scope") or WI_SCOPE_UNSET) not in ("",) + WI_SCOPES:
            problems.append(f"{wid}: scope '{it['scope']}' is not one of "
                            f"{', '.join(WI_SCOPES)}")
        # WI-0408. Same asymmetry, same reason: the VALUE is validated, the absence
        # never. An item with no `waiting-on` is not waiting on anyone, which is a real
        # answer and not debt — so there is nothing here for the land gate to go red
        # about, and the 400-odd items that predate the field validate unchanged.
        #
        # The id-shaped refusal gets its own sentence because it is the one mistake this
        # field exists to prevent. a member Architect asked for `blocked-by: operator`,
        # discovered that field is validated as a real cross-reference, and withdrew the
        # request itself; the mirror error — an item id in here — would quietly create a
        # second, UNVALIDATED dependency edge that no `wi-check` would ever resolve.
        # Naming the other field in the refusal is what keeps the two from converging
        # back into one ambiguous field by accident.
        waiting = (it.get("waiting_on") or WI_WAITING_ON_UNSET).strip()
        if waiting and WI_WAITING_ON_ID_RE.match(waiting):
            problems.append(f"{wid}: waiting-on names {waiting}, which is an item id. "
                            f"`waiting-on` holds an ACTOR — who is being waited on — "
                            f"and a dependency on another item belongs in `blocked-by`, "
                            f"where it is validated as a real cross-reference.")
        elif waiting and not WI_WAITING_ON_RE.match(waiting):
            problems.append(f"{wid}: waiting-on '{waiting}' is not an actor token — "
                            f"lowercase, starting with a letter, no spaces "
                            f"(e.g. `operator`).")
        # An unlabelled item is not malformed — it is UNCLASSIFIED, and it silently
        # blocks the derived bump (`_wi_derive_bump` refuses rather than guessing). Report
        # it as a problem so the debt is visible on the surface built to find debt, instead
        # of surfacing for the first time as a refusal on the day a release is cut.
        if not it.get("impact") and it.get("status") != "superseded":
            problems.append(f"{wid}: no impact label — set fix/feature "
                            f"(`wi-status {wid} --impact …`)")
        # A version can only be stamped by a release, and only onto work that is finished.
        if it.get("version") and it.get("status") not in WI_TERMINAL:
            problems.append(f"{wid}: carries version '{it['version']}' but is not closed — "
                            f"a version is stamped at release, onto shipped work only")
    # ADR-0076: ops items validate under their OWN rules, in the SAME command. One
    # `wi-check` covers both namespaces for the same reason one chart shows both — a
    # second validate verb is a second thing to remember to run, and the obligation this
    # kind exists to catch is precisely the one nobody remembers.
    for it in _ops_parse():
        problems.extend(_ops_validate(it))
    # WI-0307: the notes tree is store state too. Nothing validated it, so one record
    # with two owners read as sound for as long as nobody happened to look.
    problems.extend(_duplicate_note_records())
    return problems


def cmd_wi_commit(_args: argparse.Namespace) -> None:
    """Commit any uncommitted store files (WI-0056) — the catch-up and repair path.

    Every store mutation now commits itself, so in normal running this finds nothing.
    It exists for the two cases auto-commit cannot cover: files left dirty by a session
    that ran BEFORE auto-commit shipped, and a write whose own commit failed (a locked
    index, a mid-rebase checkout) and reported so on stderr. Without it the only exit
    from that residue is a hand-run git command from a lane, which is the route the
    runtime's worktree-isolation guard closed.

    Sweeps BOTH namespaces since WI-0125. It used to read `work-items/` alone, so run
    against a dirty `ops-items/` it answered *"work-items/ is clean — nothing to
    commit"*: true, and useless, and indistinguishable to the reader from "your store is
    saved". The verb an operator reaches for is `poga work commit`; scoping it to one of
    the two namespaces that render in the same chart is the asymmetry this item is about.

    Reports what it committed by name rather than a count: a sweep that says "3 files"
    is indistinguishable from a sweep that took something you did not expect it to."""
    root = ROOT
    dirs = [WI_DIRNAME, OPS_DIRNAME]
    # `-uall` is load-bearing, not a flourish: plain `--porcelain` COLLAPSES an untracked
    # directory to a single `work-items/` entry, so the sweep would stage the whole
    # directory while reporting "1 file". That both understates what it took and hands it
    # a concurrent lane's in-flight item as collateral. Listing every file individually is
    # what makes the by-name report true.
    r = sh(["git", "-C", str(root), "status", "--porcelain", "-uall", "--", *dirs],
           check=False)
    if r.returncode != 0:
        print(f"wi-commit: git could not read {'/, '.join(dirs)}/ "
              f"({(r.stderr or r.stdout).strip()[:120]}).")
        sys.exit(1)
    specs = []
    for line in r.stdout.splitlines():
        if not line.strip():
            continue
        path = line[3:].strip()
        if " -> " in path:                      # a rename reads "R  old -> new"
            old, new = path.split(" -> ", 1)
            specs.extend([old.strip().strip('"'), new.strip().strip('"')])
        else:
            specs.append(path.strip('"'))
    if not specs:
        print(f"wi-commit: {' + '.join(f'{d}/' for d in dirs)} are clean — "
              f"nothing to commit.")
        return

    # WI-0081: SORT the dirty files by who wrote them before committing any of them.
    # This verb used to commit whatever was dirty, which is not what WI-0056 specified
    # and is not what its own name promises. Observed session ~118: run from lane
    # poga-2, it took WI-0033 and WI-0068 — two files that session had never opened,
    # left in the main checkout by other sessions — and blended them into one commit
    # whose subject claimed them as this session's work.
    #
    # THREE buckets, because there are genuinely three cases and collapsing them is the
    # bug ([`declare-what-a-check-assumes`]):
    #
    #   mine      — recorded in this session's attribution set. Commit them.
    #   sibling   — recorded by a session that is PROVABLY LIVE right now. REFUSE. This
    #               is the dangerous one: a lane may be mid-write, and taking the file
    #               attributes their in-flight work to us and pulls it out from under
    #               them.
    #   residue   — attributed to nobody live: a pre-attribution write, or a session
    #               that died holding it. Nobody is coming back for these, and refusing
    #               them would strand the store permanently — which is the exact
    #               no-route-out condition this verb exists to end. So they ARE
    #               committed, but SEPARATELY, under a subject that says what they are.
    #
    # Separating the commits is half the fix. The original harm was not only which
    # files were taken, it was that they arrived in a commit asserting authorship of
    # them ([P2] — the audit trail is the point).
    me = _claude_session_id() or None
    mine_set = set(_touched_paths(me))
    siblings = _live_sibling_csids(me) if me else []
    theirs: set[str] = set()
    for s in siblings:
        theirs.update(_touched_paths(s))

    mine = [s for s in specs if s in mine_set]
    held = [s for s in specs if s not in mine_set and s in theirs]
    residue = [s for s in specs if s not in mine_set and s not in theirs]

    for s in held:
        print(f"  LEFT       {s}  — a live session is holding it; not ours to commit")

    committed: list[str] = []

    def _commit(paths: list[str], subject: str, label: str) -> bool:
        if not paths:
            return True
        sh(["git", "-C", str(root), "add", "--", *paths], check=False)
        c = sh(["git", "-C", str(root), "commit", "-m", subject, "--", *paths],
               check=False)
        if c.returncode != 0:
            print(f"wi-commit: FAILED committing {label} — "
                  f"{(c.stderr or c.stdout).strip()[:200]}")
            return False
        for s in paths:
            print(f"  committed  {s}")
        committed.extend(paths)
        return True

    def _scope(paths: list[str]) -> str:
        # Names what was ACTUALLY swept, not both namespaces unconditionally — a commit
        # subject saying `work-items` over an ops-only sweep is a small lie in the audit
        # trail, and the audit trail is the point ([P2]).
        return ",".join(d for d in dirs
                        if any(s.startswith(f"{d}/") for s in paths)) or WI_DIRNAME

    ok = _commit(mine, f"chore({_scope(mine)}): commit {len(mine)} uncommitted store "
                       f"file{'s' if len(mine) != 1 else ''}", "this session's files")
    if ok:
        # Said in the subject, not just here: a reader of `git log` in six months has
        # only the subject, and "adopted" is the difference between "this session did
        # this work" and "this session found this lying around".
        ok = _commit(residue,
                     f"chore({_scope(residue)}): adopt {len(residue)} unattributed "
                     f"store file{'s' if len(residue) != 1 else ''} left by an earlier "
                     f"session", "unattributed residue")
    if not ok:
        sys.exit(1)

    if not committed and held:
        print(f"wi-commit: nothing committed — all {len(held)} dirty file(s) belong to "
              f"a live session. Nothing is owed; they save themselves when it writes "
              f"or closes.")
        return
    if not committed:
        print("wi-commit: nothing to commit.")
        return
    # WI-0237. THE REPAIR PATH OWES THE SAME RELEASE AS THE NORMAL ONE. This verb exists
    # for the case where a store write's own commit failed — precisely the case where
    # `_store_autocommit` deliberately does NOT release, because an uncommitted file's
    # number is still doing real work. Saving the file here is what ends that, so the
    # release belongs here too; without it the one path that reaches these files is the
    # one path that leaves their tickets behind.
    _release_committed_numbers(committed)
    tail = (f"  {len(held)} left with their live owner." if held else "")
    print(f"wi-commit: {len(committed)} file(s) committed in {root}.{tail}")


def cmd_wi_check(args: argparse.Namespace) -> None:
    """Report every structural problem in the store; exit 1 if any. `--status` prints one
    line for the startup surface and stays silent when sound."""
    try:
        problems = _wi_validate()
    except Exception as e:                                    # fail open, always
        if not getattr(args, "status", False):
            print(f"wi-check: could not run ({e}).")
        return
    try:
        abandoned = _wi_abandoned_draws()
    except Exception:                                         # fail open, always
        abandoned = []
    # Stated, never silent: a consumed-but-unused id is a real fact about the allocator
    # and the operator should be able to see it — it just is not a fault in the store,
    # so it does not fail (`declare-what-a-check-assumes`).
    note = (f"note: {', '.join('WI-%04d' % n for n in abandoned)} "
            f"{'was' if len(abandoned) == 1 else 'were'} drawn but never created — "
            f"consumed allocator draw(s), not deletions; nothing to restore."
            if abandoned else "")
    if not problems:
        if not getattr(args, "status", False):
            print(f"wi-check: sound — {len(_wi_parse())} item(s), no gaps, "
                  f"all fields valid, every blocked-by resolves.")
            if note:
                print(note)
        return
    if getattr(args, "status", False):
        print(f"Work items: {len(problems)} structural problem(s) — "
              f"run `python3 session.py wi-check`.")
        return
    print(f"wi-check: {len(problems)} problem(s):")
    for p in problems:
        print(f"  - {p}")
    if note:
        print(note)
    sys.exit(1)


def _wi_symbol_defs(symbol: str, rev: str | None = None,
                    repo: Path | None = None) -> list[str]:
    """Files defining `symbol` (as a def/class) at `rev`, or in the working tree.

    Deliberately a definition search, not a mention search: an item's notes and the
    code both *mention* names constantly, and a mention that moved tells us nothing.
    What matters is whether the thing the note is ABOUT still exists and whether its
    own definition has since been rewritten.
    """
    # POSIX ERE, not Python's: `git grep -E` has no `\s` and no `\b`, and an invalid
    # escape here does not error — it just never matches, which reads as "nothing has
    # changed" and is the exact false-green this whole item is about. Character classes
    # instead; the trailing `[^A-Za-z0-9_]` is the word boundary (a def is always
    # followed by `(`), so `_stamp_status` cannot match `_stamp_status_extra`.
    pat = rf"^[[:space:]]*(def|class)[[:space:]]+{re.escape(symbol)}[^A-Za-z0-9_]"
    argv = ["git", "grep", "-lE", pat]
    if rev:
        argv.append(rev)
    r = sh(argv, check=False, cwd=repo)
    out = []
    for line in (r.stdout or "").splitlines():
        # `git grep <rev>` prefixes each path with "<rev>:"
        out.append(line.split(":", 1)[1] if rev and ":" in line else line)
    return [p for p in out if p.endswith(".py")]


def _wi_note_watermark(name: str, repo: Path | None = None,
                       wid: str = "") -> str | None:
    """The commit at which this item's notes last changed — the honest 'as of when'.

    Drawn from git rather than a new `verified:` field on the item, because a field
    someone must remember to update is the very mechanism whose absence this item
    documents. An uncommitted item has no watermark and is reported as unknown, never
    silently treated as fresh.

    BOTH PATHSPECS since WI-0181, and this is not optional: an appended note is now its own
    record under `notes/<ID>/` and does NOT touch the item file, so asking only about the
    item file would answer with the last time a FIELD changed and call it the last time the
    notes changed. The staleness report would then re-verify every citation in a note added
    minutes ago against a watermark from weeks earlier, and flag the lot. `wid` is optional
    only so the older single-argument call shape keeps working."""
    specs = [f"{WI_DIRNAME}/{name}"] if name else []
    if wid:
        specs.append(f"{WI_DIRNAME}/{NOTES_DIRNAME}/{wid}/")
    if not specs:
        return None
    r = sh(["git", "log", "-1", "--format=%H", "--", *specs], check=False, cwd=repo)
    return (r.stdout or "").strip() or None


def _py_def_block(text: str, symbol: str) -> str | None:
    """`symbol`'s definition as source text, or None when `text` does not define it.

    By INDENTATION, not by `ast`: this reads files at arbitrary historical revs, and a
    rev carrying syntax the running interpreter cannot parse would raise where the honest
    answer is "cannot tell". Indentation has no such failure mode, and it keys off the
    same `def|class` shape `_wi_symbol_defs` uses to FIND the file — so the two halves of
    the probe cannot disagree about what counts as a definition.

    A decorator line above the `def` is deliberately NOT part of the block: it is a
    separate statement, and folding it in would report a decorator edit as a rewrite of
    the function it sits on.
    """
    pat = re.compile(r"^([ \t]*)(?:def|class)[ \t]+" + re.escape(symbol)
                     + r"(?![A-Za-z0-9_])")
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = pat.match(line)
        if not m:
            continue
        indent = len(m.group(1).expandtabs())
        block = [line]
        for nxt in lines[i + 1:]:
            if not nxt.strip():                       # blank lines belong to the body
                block.append(nxt)
                continue
            flat = nxt.expandtabs()
            if len(flat) - len(flat.lstrip()) <= indent:
                break
            block.append(nxt)
        while block and not block[-1].strip():        # ...but never trailing ones
            block.pop()
        return "\n".join(block)
    return None


def _wi_symbol_body(symbol: str, rev: str, repo: Path | None = None,
                    hint: str = "") -> str | None:
    """`symbol`'s definition text at `rev`, wherever it lived then — None when unfindable.

    `hint` is the path it occupies NOW and is tried first, because most commits move
    nothing and a `git show` is far cheaper than a tree-wide grep. The grep runs only
    when the hint misses, which is exactly the moved-file case this exists to answer.
    """
    paths = ([hint] if hint else []) + [
        p for p in _wi_symbol_defs(symbol, rev, repo=repo) if p != hint]
    for path in paths[:3]:
        r = sh(["git", "show", f"{rev}:{path}"], check=False, cwd=repo)
        block = _py_def_block(r.stdout or "", symbol)
        if block is not None:
            return block
    return None


def _wi_symbol_commits(symbol: str, path: str, since_rev: str,
                       repo: Path | None = None) -> tuple[bool, list[str]]:
    """`(rewritten, evidence shas)` for `symbol`'s own definition since `since_rev`.

    THE VERDICT IS A TEXT COMPARISON, NOT `git log -L`, and that inversion is WI-0335.
    `-L` is anchored to a PATH: it cannot follow a rename (`-M` and `--find-renames`
    change nothing there — measured), its walk stops dead at the commit that created the
    file, and it counts a hunk that merely NAMES the function in its `@@` header. All
    three were measured on this repo across the ADR-0118 `session.py` -> `sessionlib/`
    split (`d01050ae`):

      - FALSE POSITIVE, the rename — `_wi_note_watermark` moved byte for byte and `-L`
        named the split as a rewrite of it. Over the exposed population (the 675 symbols
        in `sessionlib/` that predate the split) `-L` flagged 668, or 99%; the comparison
        below flags 64. A report that fires on nearly everything is one a reader learns
        to skip, which costs more than the staleness it was built to surface.
      - FALSE POSITIVE, the adjacent hunk — `_wi_reserve_next`'s body is byte-identical
        at `ab7b101c^` and `ab7b101c`, and `-L` still reported that commit: the insertion
        landed just after the function, so git's hunk header carried its name. Line-range
        tracking is not definition tracking.
      - FALSE NEGATIVE, the pre-move rewrite — for 14 symbols measured over a window
        spanning the split, `-L` on the current path named the split AND NOTHING ELSE
        while the definition really had changed earlier (`cmd_wi_edit` and `_ops_parse`
        at `b03aef05`, `_triage_debt` at `d119bd2d`). So merely filtering the split sha
        out of `-L`'s answer — the obvious fix — would have turned fourteen true findings
        into clean ones, which is the worse of the two errors.

    The question asked instead is the one the caller actually has: is this definition
    different now from what it was when the notes were written. That is blind to which
    file it sits in, to how many commits it took to get there, and to what happened on
    the lines around it.

    `-L` still supplies the EVIDENCE — which commits to go read — over the current path,
    plus the pre-move window when the symbol changed file inside the window. Evidence is
    best-effort by construction; the verdict is not, and an empty sha list never softens
    a `True`.

    `declare-what-a-check-assumes`: when the definition cannot be read at one end or the
    other — a rev git declines, a path that will not show, a `def` this module's regex
    does not match — there is no comparison to make, and the answer falls back to `-L`'s.
    That is the old behaviour, kept as a stated fallback rather than a hidden default.
    """
    then = _wi_symbol_body(symbol, since_rev, repo=repo, hint=path)
    now = _wi_symbol_body(symbol, "HEAD", repo=repo, hint=path)
    if then is not None and now is not None and then == now:
        return False, []                  # moved, or churned around, but not rewritten
    shas = [s for s in (sh(["git", "log", "--format=%h", "-s", f"-L:{symbol}:{path}",
                            f"{since_rev}..HEAD"], check=False,
                           cwd=repo).stdout or "").split() if s]
    was = _wi_symbol_defs(symbol, since_rev, repo=repo)
    if shas and was and path not in was:
        # The symbol changed file inside the window, so the walk above terminated where
        # it ARRIVED at `path` — `shas[-1]` is that boundary (git logs newest first).
        # Everything earlier is invisible to it and is recovered on the path it had back
        # then; without this, `_wi_reserve_next`'s real rewrite stays unnamed.
        shas += [s for s in (sh(["git", "log", "--format=%h", "-s",
                                 f"-L:{symbol}:{was[0]}", f"{since_rev}..{shas[-1]}^"],
                                check=False, cwd=repo).stdout or "").split()
                 if s and s not in shas]
    if then is None or now is None:
        return bool(shas), shas
    return True, shas


def _wi_commit_date(rev: str, repo: Path | None = None) -> datetime | None:
    """`rev`'s committer date as an aware datetime, or None when git cannot answer.

    None is a real third answer and callers must treat it as one: an age computed from a
    missing date would be either "infinitely old" (every item flagged) or "brand new"
    (nothing ever flagged), and both are confident lies about a question git declined."""
    r = sh(["git", "log", "-1", "--format=%cI", rev], check=False, cwd=repo)
    raw = (r.stdout or "").strip()
    if not raw:
        return None
    try:
        return datetime.fromisoformat(raw)
    except ValueError:
        return None


def _wi_adr_premises(notes: str, watermark: str,
                     repo: Path | None = None) -> tuple[list, list]:
    """`(changed, gone)` for the ADRs an item's notes cite. Read-only.

    An ADR is IMMUTABLE once Accepted (adr/README.md) except to flip its status — so
    "this file has a commit since the watermark" is very nearly a synonym for "the
    decision this item stands on has been superseded, deprecated or re-decided", at a
    fraction of the code a status diff would cost. That immutability is exactly why the
    symbol probe cannot see this class: the ADR changes and the item never moves.

    Each `changed` row carries the CURRENT status line, because the actionable half of
    the finding is which way it flipped, and a reader who has to open the ADR to learn
    that will not.
    """
    adr_dir = _adr_dir()
    changed, gone, seen = [], [], set()
    for num in WI_CITED_ADR_RE.findall(notes):
        num = num.zfill(4)
        if num in seen or len(seen) >= WI_STALE_ADR_CAP:
            continue
        seen.add(num)
        try:
            matches = sorted((repo or ROOT).joinpath(adr_dir).glob(
                f"{_adr_prefix()}{num}-*.md")) or sorted(
                (repo or ROOT).joinpath(adr_dir).glob(f"{_adr_prefix()}{num.lstrip('0')}-*.md"))
        except Exception:
            matches = []
        if not matches:
            # Only a signal if it RESOLVED when the notes were written — same discipline
            # as the English-word-in-backticks guard. An ADR number cited before that ADR
            # existed (a plan referring forward) is not a deletion.
            r = sh(["git", "ls-tree", "--name-only", f"{watermark}:{adr_dir}"],
                   check=False, cwd=repo)
            if any(n.startswith(f"{_adr_prefix()}{num}-") for n in
                   (r.stdout or "").splitlines()):
                gone.append(f"ADR-{num}")
            continue
        rel = f"{adr_dir}/{matches[0].name}"
        shas = [s for s in (sh(["git", "log", "--format=%h", f"{watermark}..HEAD",
                                "--", rel], check=False, cwd=repo).stdout or "").split()]
        if shas:
            changed.append((f"ADR-{num}", _adr_status_line(matches[0]), shas))
    return changed, gone


def _adr_status_line(path: Path) -> str:
    """The ADR's declared decision status, or "" when the record does not carry one in
    the expected shape — never a guess. `declare-what-a-check-assumes`: a missing status
    prints as unknown at the call site rather than defaulting to "Accepted", which would
    silently certify exactly the supersession this probe exists to catch."""
    try:
        head = path.read_text(encoding="utf-8")[:2000]
    except Exception:
        return ""
    m = re.search(r"^\*{0,2}Status:?\*{0,2}\s*(.+?)\s*$", head, re.M | re.I)
    return re.sub(r"[*`\[\]]", "", m.group(1)).strip() if m else ""


def _wi_id_premises(notes: str, self_id: str, watermark: str, live: dict,
                    repo: Path | None = None) -> tuple[list, list]:
    """`(changed, gone)` for the work/ops ids an item's notes cite. Read-only.

    THE MEASURED CASE (session 241): WI-0296 was closed by another item's fix while its
    citers still read as live work, and WI-0217 named a blocker that had been renumbered
    out from under it. Both are premises stated as an ID, and an id is the one citation
    shape this store can resolve exactly — so this is the highest-yield of the four.

    A status is compared against the status AT THE WATERMARK, read out of git, not
    against "open". An item that was already `done` when these notes were written is not
    news; one that closed since is the whole point.
    """
    changed, gone, seen = [], [], set()
    for cid in WI_CITED_ID_RE.findall(notes):
        if cid == self_id or cid in seen or len(seen) >= WI_STALE_ID_CAP:
            continue
        seen.add(cid)
        was = _wi_status_at(cid, watermark, repo)
        now = live.get(cid)
        if now is None:
            # Absent NOW. Only a finding if it resolved then — otherwise the notes cite a
            # number that never existed in this tree (a lane-minted id, a typo), which is
            # `wi-check`'s subject and diagnosed properly there, not guessed at here.
            if was:
                gone.append((cid, was))
            continue
        if was and was != now:
            changed.append((cid, was, now))
    return changed, gone


def _wi_status_at(cid: str, rev: str, repo: Path | None = None) -> str | None:
    """`cid`'s status as of `rev`, or None if no file for it existed then.

    Reads the file out of git rather than the working tree — the question is what the
    author could have known when they wrote the note, and today's file cannot answer it.
    """
    store = OPS_DIRNAME if cid.startswith("OPS-") else WI_DIRNAME
    r = sh(["git", "ls-tree", "--name-only", f"{rev}:{store}"], check=False, cwd=repo)
    name = next((n for n in (r.stdout or "").splitlines()
                 if n.startswith(f"{cid}-") and n.endswith(".md")), None)
    if not name:
        return None
    r = sh(["git", "show", f"{rev}:{store}/{name}"], check=False, cwd=repo)
    m = re.search(r"^- status:\s*(\S+)\s*$", r.stdout or "", re.M)
    return m.group(1) if m else None


def _wi_blocker_premises(item: dict, live: dict) -> list[tuple[str, str]]:
    """Blockers of `item` that are no longer blocking — `(id, status)` each.

    WATERMARK-INDEPENDENT, unlike every other probe here, and deliberately so: "I am
    blocked" is a claim about NOW, not a claim as of some past commit, so whether the
    blocker closed before or after the notes were written changes nothing about the fact
    that the item is currently sitting in the wrong state. `wi-status --blocked-by` is
    the fix, and nothing here applies it — an item can have a real reason to sit still
    that its blocker field never captured.

    Blockers that do not RESOLVE are left alone: `wi-check` already reports those and
    diagnoses them properly (lane-minted, live draw, or genuinely dangling), and a second
    half-diagnosis in a different verb is the duplication P16 is about.
    """
    return [(b, live[b]) for b in (item.get("blocked_by") or [])
            if b in live and live[b] in WI_TERMINAL]


def _wi_count_premises(notes: str) -> list[str]:
    """The quoted measurements in an item body, each with the clause it sits in.

    NOTHING HERE RE-DERIVES A COUNT, and that is a decision rather than a shortcut. The
    predicate is unstated prose — "84 of 104" does not say what was counted — so any
    re-derivation would have to guess what the author meant, and a probe that guesses
    manufactures findings, which is worse than the gap it covers. What this returns is
    the honest fact: here are the numbers this item stands on, and nothing in this repo
    can tell you whether they are still true.

    So these are a DECLARED LIMIT, not a finding, and the caller must keep them out of
    the clean/flagged verdict on both sides. They must not fail an item — the item has
    done nothing wrong by quoting a measurement, and there is no edit that would resolve
    the line. And they must not be silenced by the stamp either, or the probe would be
    answering its own open question, which is exactly the false provenance the stamp is
    worded to avoid. They print every run, next to the age of the body that quotes them,
    and a human decides whether that is old enough to go and re-count.
    """
    seen, out = set(), []
    for m in WI_QUOTED_COUNT_RE.finditer(notes):
        phrase = m.group(0)
        if phrase.lower() in seen or len(seen) >= WI_COUNT_CAP:
            continue
        seen.add(phrase.lower())
        # A WINDOW ROUND THE MATCH, not the head of its line. Item bodies are written as
        # long single-line paragraphs, so clipping from the line start showed the same
        # opening sentence beside three different counts and told the reader nothing
        # about any of them.
        lo = notes.rfind("\n", 0, m.start()) + 1
        hi = notes.find("\n", m.end())
        hi = len(notes) if hi < 0 else hi
        left, right = max(lo, m.start() - 55), min(hi, m.end() + 65)
        out.append(f"{phrase} — {'…' if left > lo else ''}"
                   f"{notes[left:right].strip()}{'…' if right < hi else ''}")
    return out


def _wi_premise_watermark(name: str, item: dict, repo: Path | None = None) -> str | None:
    """The commit these premises were last known good at — the probe stamp when it is
    still the later of the two, otherwise where the notes last moved.

    The stamp cannot simply WIN. A note appended after a probe is new material that the
    probe never saw, so the honest 'as of' falls back to the note — hence the ancestry
    test rather than a preference. Getting this backwards would make one probe run
    silence an item permanently, which is the false-green this whole item is about.
    """
    notes_wm = _wi_note_watermark(name, repo, item["id"]) if name else None
    stamp = (item.get("probed") or "").split()[-1:] or [""]
    sha = stamp[0]
    if not sha:
        return notes_wm
    if sh(["git", "cat-file", "-e", f"{sha}^{{commit}}"],
          check=False, cwd=repo).returncode != 0:
        return notes_wm                       # stamp names a commit this tree cannot see
    if notes_wm and sh(["git", "merge-base", "--is-ancestor", notes_wm, sha],
                       check=False, cwd=repo).returncode != 0:
        return notes_wm                       # notes moved after the probe — notes win
    return sha


def _wi_stale_report(items: list[dict] | None = None,
                     base: Path | None = None) -> list[dict]:
    """For each open item, which of its premises have since moved. Read-only.

    Returns one dict per item: `{id, title, watermark, changed, gone, adr_changed,
    adr_gone, id_changed, id_gone, blockers, counts, unknown, clean}`.
    NOTHING is closed, reopened, or edited here — the finding is always "re-verify this
    before you build it", never "this is done." The failure mode of a wrong auto-close
    (work silently dropped) is strictly worse than the failure mode this exists to fix
    (work re-verified), so the tool is not given the ability to make that mistake.

    FOUR PREMISE CLASSES BESIDE THE CODE ONE (WI-0308), because code was never where the
    rot was. Session 240 re-probed the open set and found 84 of 104 premises stale;
    session 241 re-probed eighteen delegated items by hand and four changed answer — a
    cited item that had been closed, a quoted count that was wrong, a blocker renumbered
    out from under its citer, and a capability that turned out to be a spelling gap. Only
    the last is anywhere near a code citation. So: cited ADRs, cited item ids, blocker
    status, and quoted counts, each with its own verdict rather than folded into one
    "stale" flag, because they are fixed by four different actions.

    CLEAN ITEMS ARE RETURNED TOO, carrying `clean: True` — the caller stamps them, and a
    report that dropped them on the floor could not tell "probed and fine" from "never
    looked at", which is the distinction the stamp exists to record.
    """
    items = items if items is not None else _wi_parse(base)
    # Every git question below is asked of the checkout the STORE lives in, never of
    # `ROOT`. `sh()` defaults to ROOT, which from a lane is the lane — so the default
    # would have compared main's item files against a lane's history and quietly
    # answered about the wrong repo.
    repo = _wi_dir(base).parent
    # Resolved ONCE for the whole pass, over BOTH namespaces: an id citation may name an
    # ops item (ADR-0076 D7 supersedes work items into that namespace), and a WI-only map
    # would report every OPS citation as a dangling id — a fabricated finding in the
    # verb built to stop fabricated premises. Anchored on `repo`, not on `base`, so the
    # two halves of this map always come out of the SAME checkout: reading work items
    # from a lane's frozen store and ops items from wherever ROOT happened to point is
    # how a citation gets resolved against a tree that never held it.
    live = {it["id"]: (it.get("status") or "open")
            for it in list(items) + _ops_parse(repo)}
    # THE CAP APPLIES TO WHAT IS ACTUALLY PROBED, not to the store (WI-0308). It used to
    # slice `items` first: with 310 files on disk and a cap of 200, everything from about
    # WI-0200 up was dropped before the status filter ever saw it, so a third of the open
    # set was reported as "no staleness" having never been read — this verb committing
    # the exact false-green it exists to catch. Measured at the time: 27 items probed out
    # of 78 open.
    #
    # And the status set is now "not terminal" rather than a literal list. The old list
    # named `blocked`, which is not one of `WI_STATUSES` and therefore matched nothing,
    # while `in-progress` and `held` — items someone is mid-way through or has parked to
    # come back to, i.e. exactly the ones whose premises will be leaned on next — matched
    # nothing either, because they were not named at all.
    live_items = [it for it in items if it.get("status") not in WI_TERMINAL]
    out: list[dict] = []
    for item in live_items[:WI_STALE_ITEM_CAP]:
        name = _wi_filename_for(item["id"])
        watermark = _wi_premise_watermark(name, item, repo) if name else None
        if watermark is None:
            out.append({"id": item["id"], "title": item["title"], "watermark": None,
                        **_WI_PREMISE_EMPTY, "unknown": True, "clean": False})
            continue
        notes = item.get("notes", "")
        cited = list(WI_CITED_SYMBOL_RE.findall(notes))
        cited += [f"cmd_{v.replace('-', '_')}" for v in WI_CITED_VERB_RE.findall(notes)]
        seen, changed, gone = set(), [], []
        for sym in cited:
            if sym in seen or len(seen) >= WI_STALE_SYMBOL_CAP:
                continue
            seen.add(sym)
            now = _wi_symbol_defs(sym, repo=repo)
            if not now:
                # Only a real signal if it EXISTED when the note was written. Otherwise
                # it is an English word in backticks, and calling that a deletion is the
                # noise that makes a metric worthless.
                if _wi_symbol_defs(sym, watermark, repo=repo):
                    gone.append(sym)
                continue
            # ONE row per symbol, not one per defining file (WI-0335). The verdict below
            # compares the DEFINITION at two revs rather than walking one path's commits,
            # so asking it once per path would put the same answer on the report twice.
            # The first definition found is the one reported; a name defined in two files
            # is rare enough that naming the second adds noise, not information.
            rewritten, shas = _wi_symbol_commits(sym, now[0], watermark, repo=repo)
            if rewritten:
                changed.append((sym, now[0], shas))
        adr_changed, adr_gone = _wi_adr_premises(notes, watermark, repo)
        id_changed, id_gone = _wi_id_premises(notes, item["id"], watermark, live, repo)
        blockers = _wi_blocker_premises(item, live)
        when = _wi_commit_date(watermark, repo)
        age = ((datetime.now(timezone.utc) - when).total_seconds() / 86400
               if when else None)
        row = {"id": item["id"], "title": item["title"], "watermark": watermark,
               "changed": changed, "gone": gone, "adr_changed": adr_changed,
               "adr_gone": adr_gone, "id_changed": id_changed, "id_gone": id_gone,
               "blockers": blockers, "counts": _wi_count_premises(notes),
               "age_days": age, "unknown": False}
        row["clean"] = not any(row[k] for k in _WI_PREMISE_KEYS)
        out.append(row)
    return out


# The premise verdicts, in report order. Named once so the empty row, the clean test and
# the printer cannot drift apart — a new premise class added to one and forgotten in
# another would read as "checked and fine", which is the exact false-green (`clean`
# defaulting to True on an unexamined class) this item exists to remove.
#
# `counts` is NOT here and must not be added: it is a declared limit rather than a
# verdict (see `_wi_count_premises`), so an item that quotes a measurement is still
# clean — the tool has no complaint about it, only an admission about itself.
_WI_PREMISE_KEYS = ("changed", "gone", "adr_changed", "adr_gone",
                    "id_changed", "id_gone", "blockers")
_WI_PREMISE_EMPTY = {k: [] for k in (*_WI_PREMISE_KEYS, "counts")}


def cmd_wi_stale(args: argparse.Namespace) -> None:
    """Flag open items whose premises have moved since they were last confirmed.

    WI-0095: an item's notes are written when it is FILED, and nothing updates them
    when adjacent work incidentally satisfies them. Of six items picked up in session
    ~125, THREE were already partly or wholly shipped and still read as open work —
    found only because each premise was checked in code first. The danger is not the
    wasted hour; it is building a second implementation beside the first, which is the
    P16 drift class arriving through the backlog.

    WI-0308 widened it past code, because code was the premise class that rotted LEAST.
    Session 240 re-probed the open set and found 84 of 104 item premises stale; session
    241 re-probed eighteen delegated items and four changed answer, none of them through
    a code citation. So the verb now also asks whether the ADRs an item cites have been
    superseded, whether the items it names have closed or been renumbered, whether its
    blocker is still blocking, and how old its quoted counts are — and stamps `probed:`
    on the items that come back clean, so the next reader can tell a checked item from an
    unlooked-at one without re-running anything.

    It still reports and never closes: the four new classes are four new FINDINGS, not
    four new authorities. A blocker that has closed is printed, not cleared; a count that
    is old is printed, not recomputed.

    Deliberately ON DEMAND, never a startup hook: this runs `git log -L` per cited symbol
    and `git show` per cited id, and startup checks are file reads (no cost on the
    startup path, by rule).
    """
    try:
        rows = _wi_stale_report()
    except Exception as e:                                        # fail open, always
        print(f"wi-stale: could not run ({e}).")
        return
    flagged = [r for r in rows if not r["unknown"] and not r["clean"]]
    clean = [r for r in rows if r.get("clean")]
    unknown = [r for r in rows if r["unknown"]]
    if not flagged:
        print(f"wi-stale: {len(clean)} open item(s) probed, none with a premise that has "
              f"moved since it was last confirmed.")
    for r in flagged:
        print(f"\n{r['id']}  {r['title'][:70]}")
        print(f"  premises as of {r['watermark'][:9]}")
        for sym, path, shas in r["changed"]:
            # An empty list is a real third case since WI-0335: the definition differs
            # across the window but git could not name a commit for it (the rewrite
            # predates a move that `-L` cannot walk past). Saying "0 commit(s)" would
            # read as a contradiction of the finding it is evidence for.
            where = (f" ({len(shas)} commit(s): {', '.join(shas[:4])})" if shas else
                     " — git could not name which commit; read the definition itself")
            print(f"  - `{sym}` in {path} rewritten since{where}")
        for sym in r["gone"]:
            print(f"  - `{sym}` no longer exists — it did when these notes were written")
        for adr, status, shas in r["adr_changed"]:
            print(f"  - {adr} changed since ({len(shas)} commit(s)) — now "
                  f"{status or 'of unstated status'}")
        for adr in r["adr_gone"]:
            print(f"  - {adr} no longer resolves — it did when these notes were written")
        for cid, was, now in r["id_changed"]:
            print(f"  - {cid} was {was} when this was written, is now {now}")
        for cid, was in r["id_gone"]:
            print(f"  - {cid} no longer resolves — it was {was} when this was written "
                  f"(renumbered, or the citation is to another tree)")
        for cid, status in r["blockers"]:
            print(f"  - blocked-by {cid}, which is {status} — this item is not actually "
                  f"blocked")
    quoting = [r for r in rows if r.get("counts")]
    if quoting:
        # Its own section, deliberately not folded in above. Everything above is "this
        # premise moved"; this is "this premise cannot be checked by anything here" —
        # a different sentence, owed a different heading, and never a reason to hold an
        # item back ([`declare-what-a-check-assumes`]).
        print(f"\nNOT RE-DERIVABLE ({len(quoting)}): these items stand on counts somebody "
              f"measured once. Nothing in this repo can re-derive them — the predicate is "
              f"prose — so they are listed, never judged.")
        for r in quoting:
            age = (f"body last moved {r['age_days']:.0f}d ago"
                   if r.get("age_days") is not None else "age unknown")
            print(f"  {r['id']}  ({age})")
            for phrase in r["counts"]:
                print(f"    - {phrase}")
    if unknown:
        # `declare-what-a-check-assumes`: an item with no commit is not a fresh item.
        print(f"\nNOT CHECKED ({len(unknown)}): no commit touches these item files yet, "
              f"so there is no 'as of' to measure against — "
              f"{', '.join(r['id'] for r in unknown[:8])}")
    # Said OUT LOUD, for the same reason. The cap is a real bound (P19) and a real bound
    # silently reached is indistinguishable from a clean sweep — which is how a third of
    # the open set went unprobed while this verb printed nothing but good news.
    try:
        n_live = len([it for it in _wi_parse() if it.get("status") not in WI_TERMINAL])
    except Exception:
        n_live = len(rows)
    if n_live > len(rows):
        print(f"\nNOT REACHED ({n_live - len(rows)}): the per-run cap is "
              f"{WI_STALE_ITEM_CAP} items and there are {n_live} live ones, so the tail "
              f"of the store was not probed this run. Nothing above is a statement "
              f"about them.")
    if flagged:
        print("\nRe-verify these before building them. Nothing was closed or edited: a "
              "wrong auto-close drops work silently, which is worse than the staleness "
              "this reports.")
    if getattr(args, "stamp", True):
        _wi_stamp_probed(clean)
    elif clean:
        print(f"\n{len(clean)} item(s) passed; not stamped (--no-stamp), so nothing "
              f"records that they were checked.")


def _wi_stamp_probed(clean: list[dict]) -> None:
    """Write the `probed:` receipt onto every item whose premises came back clean.

    ON BY DEFAULT (`--no-stamp` opts out), because a probe whose result has to be
    re-derived on every run is not a probe, it is a chore — the next reader of the item
    still cannot tell "checked yesterday, fine" from "nobody has ever looked", which is
    the state that let 84 of 104 premises rot unnoticed.

    IT STAMPS ONLY WHAT IT FULLY CHECKED. An item carrying a quoted-count finding is
    never in `clean`, precisely because that finding says a human must look: stamping it
    would have the tool answer its own open question, and a receipt that certifies a
    check nobody performed is worse than no receipt. Same reason it never touches status,
    section, or notes — the receipt is the ONLY field this verb may write.

    One commit for the whole pass (`_wi_write_item(commit=False)` plus a single
    `_store_autocommit`), and one feed rebuild: sixty single-file commits for one probe
    run would bury the store's real history under its own bookkeeping.
    """
    # Asked of the checkout the STORE lives in, for the same reason `_wi_stale_report`
    # does: `sh()` defaults to ROOT, and a stamp naming a commit from a DIFFERENT repo
    # than the one whose history the probe read is a receipt that points nowhere.
    repo = _wi_dir().parent
    head = (sh(["git", "rev-parse", "--short", "HEAD"], check=False,
               cwd=repo).stdout or "").strip()
    if not head:
        print("\nNot stamped: could not read HEAD, so there is no commit to stamp "
              "against. The report above stands; nothing was written.")
        return
    today = datetime.now(timezone.utc).date().isoformat()
    stamp = f"{today} {head}"
    items = _wi_parse()
    names: list[str] = []
    for r in clean:
        item = next((it for it in items if it["id"] == r["id"]), None)
        # SKIPPED ON THE DATE, not on the exact stamp, and the difference is the whole
        # reason this is idempotent. The stamp lands in the item FILE, so writing it moves
        # that file's last commit — which is what the watermark is read from. Comparing
        # shas meant every run saw a HEAD that its own previous run had advanced, and
        # re-stamped all 53 clean items forever: a commit per run whose only content was
        # the receipt for that commit. Day granularity is all the receipt claims anyway
        # ("recently probed" versus "never looked at"), and it caps the store's churn at
        # one commit per day on which somebody actually runs the probe.
        if item is None or (item.get("probed") or "").split(" ")[0] == today:
            continue
        item["probed"] = stamp
        names.extend(_wi_write_item(item, commit=False))
    if not names:
        return
    _store_autocommit(WI_DIRNAME, names,
                      f"chore(work-items): stamp {len(names)} item(s) premise-probed "
                      f"at {head}", "poga work commit")
    _wi_feed_write()
    print(f"\nStamped `probed: {stamp}` on {len(names)} item(s) whose premises all "
          f"resolved. That records the mechanical check only — it does not say anyone "
          f"re-read the argument.")


def _wi_colour_enabled() -> bool:
    """ANSI only where it will actually render. `NO_COLOR` (the de-facto standard) wins
    over everything; otherwise require a TTY. Getting this wrong is not cosmetic — escape
    codes relayed through a session's tool output reach the user as literal `\\033[2m`
    garbage, which is worse than no colour at all."""
    if os.environ.get("NO_COLOR"):
        return False
    if os.environ.get("POGA_FORCE_COLOR"):
        return True
    try:
        return sys.stdout.isatty()
    except Exception:
        return False


def _wi_truncate(text: str, width: int) -> str:
    """One line, at most `width` chars, ellipsised. Titles are single-line by schema, but
    a pasted newline would otherwise break every column below it."""
    t = " ".join((text or "").split())
    return t if len(t) <= width else t[: width - 1].rstrip() + "…"


def _wi_format_rows(rows: list[tuple], paint: bool) -> list[str]:
    """Align the cells into columns and colour by state.

    Widths are computed from the actual content rather than hardcoded, so one long lane
    name cannot shear the column off the rest of the table."""
    if not rows:
        return []
    w_id = max(len(r[0]) for r in rows)
    w_state = max(len(r[1]) for r in rows)
    w_sec = max(len(r[2]) for r in rows)
    out = []
    for ident, state, sec, title, status, blocked in rows:
        line = (f"  {ident:<{w_id}}  {state:<{w_state}}  "
                f"{sec:<{w_sec}}  {title}")
        if paint:
            if status in WI_TERMINAL:
                line = f"{WI_ANSI['dim_green']}{line}{WI_ANSI['reset']}"   # finished
            elif blocked:
                line = f"{WI_ANSI['yellow']}{line}{WI_ANSI['reset']}"      # cannot start
            elif status == "in-progress" or "·" in state:
                line = f"{WI_ANSI['red']}{line}{WI_ANSI['reset']}"         # in flight

        out.append(line)
    return out


def _wi_render_snapshot_lines(all_states: bool = False,
                              colour: bool | None = None) -> list[str]:
    """The numbered, claim-joined work-item list. Pins an ordinal→id snapshot (D2) to
    `.session-state/wi-snapshot-<csid>.json` so a later 'do 3' resolves against what was
    actually shown, even if the store changes underneath. Returns the lines to
    print/append — no direct printing, so callers (the CLI, the start orientation block)
    can place them where they need to.

    ONE LIST (session ~103, the operator's ruling: the store is one list, nothing is ever removed
    from it, items are only marked finished, and partitioned views are multiple lists by
    another name). Every item is shown,
    in id order, with its **state** carried as a tag rather than by being filtered out of
    view. The earlier version scoped to `section: next` and dropped `done`, so answering
    "what's on the list?" meant reading three partitioned views and stitching them
    together — the same duplication ADR-0074 removed between the inbox and the store,
    reappearing as *display* rather than storage. Section is now just another tag.

    `all_states=False` is the compact startup view: terminal items (done/superseded) are
    summarised as a count rather than printed, because a startup banner should not grow
    without bound. Nothing is *excluded from the list* — `wi-list --all` prints every row,
    and the ids never move, because ordinals are assigned over the full ordered set either
    way. That is what makes "do 3" mean the same thing in both views.
    """
    # BOTH namespaces (ADR-0076 D6). The startup banner is the surface the operator
    # actually reads, so an ops obligation absent from it is an obligation nobody sees —
    # which is the failure this kind was built to prevent, reintroduced by its own store.
    all_items = _chart_rows()
    if not all_items:
        return ["Work items: (none — draw one with `session.py wi-new`.)"]
    live_ids = {it["id"] for it in all_items if it.get("status") not in WI_TERMINAL}
    claims = _coord_list("claims")
    snapshot_id = f"S-{secrets.token_hex(3)}"
    paint = _wi_colour_enabled() if colour is None else colour
    mapping = {}
    rows, hidden = [], 0
    for i, it in enumerate(all_items, start=1):
        mapping[str(i)] = it["id"]          # ordinals span the WHOLE list, always
        terminal = it.get("status") in WI_TERMINAL
        if terminal and not all_states:
            hidden += 1
            continue
        blocked = [b for b in it["blocked_by"] if b in live_ids]
        status = it.get("status", "open")
        # The STATE cell carries everything that changes what you'd do about the row —
        # status, who holds it, whether it can even be started — so the reader never has
        # to cross-reference a second column to answer "is this actionable?" For an ops
        # row that answer is date-derived (`overdue` / `never run` / `due …`), already
        # computed into `state` by `_chart_rows`.
        if blocked:
            state = "blocked"
        elif it["id"] in claims:
            rec = claims[it["id"]]
            state = f"{status}·{_coord_short_holder(rec)}"
        else:
            state = it.get("state", status)
        # Ordinal is what `poga dispatch 1-10` resolves against. It equals the WI number
        # in every store where no id was ever skipped, so printing both is noise — but it
        # is NOT guaranteed to, and a silently-wrong ordinal would dispatch the wrong
        # item. Shown only when it actually diverges.
        ident = it["id"] if str(i) == it["id"].split("-")[1].lstrip("0") else f"{i}→{it['id']}"
        rows.append((ident, state, it.get("section", "backlog"),
                     _wi_truncate(it["title"], 70), status, bool(blocked)))
    lines = [f"Work items (snapshot {snapshot_id}) — {len(all_items)} total"
             + (f", {hidden} done/superseded not shown (`wi-list --all`)" if hidden else "")
             + ":"]
    lines += _wi_format_rows(rows, paint)
    try:
        state_dir = ROOT / ".session-state"
        state_dir.mkdir(exist_ok=True)
        sid = os.environ.get("CLAUDE_CODE_SESSION_ID", "app")
        atomic_write(state_dir / f"wi-snapshot-{sid}.json",
                     json.dumps({"snapshot_id": snapshot_id, "mapping": mapping},
                                ensure_ascii=False, indent=2) + "\n")
    except Exception:
        pass
    return lines


def cmd_wi_list(args: argparse.Namespace) -> None:
    """CLI entry: print the numbered work-item list (see `_wi_render_snapshot_lines`).
    `--all` includes terminal (done/superseded) rows; ordinals are identical either way."""
    for line in _wi_render_snapshot_lines(all_states=getattr(args, "all", False)):
        print(line)


