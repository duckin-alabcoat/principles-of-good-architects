def _ops_add_months(iso_date: str, months: int) -> str:
    """`iso_date` + n months, clamped to the last valid day of the target month, as
    ISO. Month arithmetic by hand because the harness carries no date library beyond the
    stdlib and must stay dependency-free across the fleet. Clamping matters: a monthly
    obligation completed on the 31st must not skip a 30-day month."""
    d = datetime.strptime(iso_date, "%Y-%m-%d").date()
    total = (d.year * 12 + (d.month - 1)) + months
    year, month = divmod(total, 12)
    month += 1
    # Last day of the target month, without calendar: day 1 of the next month, minus 1.
    if month == 12:
        nxt = datetime(year + 1, 1, 1)
    else:
        nxt = datetime(year, month + 1, 1)
    last_day = (nxt - timedelta(days=1)).day
    return f"{year:04d}-{month:02d}-{min(d.day, last_day):02d}"


def _ops_derive_due(cadence: str, last_completed: str, authored_due: str = "") -> str:
    """`due` for an ops item.

    A RECURRING item's due date is never typed by a human (ADR-0076 D3): if it were,
    every cycle would depend on someone remembering to push the date forward — which is
    precisely the silently-lapsing chore this whole kind exists to catch, reintroduced as
    its own bookkeeping. So with a cadence set, `due = last-completed + cadence`,
    computed. A never-run recurring item has no derivable due and is owed NOW, which
    renders as an empty due rather than a fabricated date.

    Without a cadence the item is one-time and `due` is whatever was authored.

    A DAY-based cadence (`weekly`) rolls forward by a fixed day count and is checked
    first; the month-based ones keep the end-of-month clamping in `_ops_add_months`,
    which a fixed day count must not be routed through."""
    if cadence in OPS_CADENCE_DAYS:
        if not last_completed:
            return ""
        try:
            d = datetime.strptime(last_completed, "%Y-%m-%d").date()
            return (d + timedelta(days=OPS_CADENCE_DAYS[cadence])).isoformat()
        except Exception:
            return ""
    if cadence not in OPS_CADENCE_MONTHS:
        return authored_due
    if not last_completed:
        return ""
    try:
        return _ops_add_months(last_completed, OPS_CADENCE_MONTHS[cadence])
    except Exception:
        return ""


def _ops_state(item: dict, today: str) -> str:
    """The STATE cell for an ops item — what a reader needs to know to act.

    Distinct from a dev item's status because the question is different: not "has anyone
    picked this up?" but "is this owed?". A recurring item that has never run is `never
    run` (owed now, and the alarm a generic staleness check stays silent about); one past
    its due date is `overdue`; one with a future due is `due <date>`."""
    if item.get("status") in OPS_TERMINAL:
        return item["status"]
    if item.get("status") in ("held", "in-progress"):
        return item["status"]
    cadence, due = item.get("cadence", ""), item.get("due", "")
    if cadence and not item.get("last_completed"):
        return "never run"
    if due and due < today:
        return "overdue"
    if due:
        return f"due {due}"
    return item.get("status", "open")


def _ops_render_item(item: dict) -> str:
    """One OPS file's full text, in the format `_ops_parse_text` reads back losslessly.
    No `impact` and no `version` — see D1. NO `scope` EITHER (WI-0323), and on its own
    argument rather than by inheriting D1's.

    `scope` exists to do two things: split the created/closed trend by kind of work, and
    carry the planning preference that favours FINISHING existing harness work. An
    obligation recurs by construction — that is the whole property ADR-0076 gave it its
    own kind for — so it is never created-then-closed and can never be finished. It
    cannot appear in the trend the field feeds, and the preference the field serves has
    no purchase on it.

    The cheap move refused here is the same one D1 refused: NOT adding a fourth `scope`
    value meaning "operational". A value meaning "this field does not apply" reads as a
    classification in every count that groups by scope — the
    `ship-the-detector-with-the-capability` shape, where a not-applicable branch that
    reads as a pass does not merely miss a gap but certifies one."""
    lines = [
        f"# {item['id']}: {item['title']}",
        "",
        f"- status: {item.get('status', 'open')}",
        f"- cadence: {item.get('cadence', OPS_CADENCE_UNSET)}",
        f"- last-completed: {item.get('last_completed', '')}",
        f"- last-result: {item.get('last_result', OPS_RESULT_UNSET)}",
        f"- due: {item.get('due', '')}",
        f"- group: {item.get('group', '')}",
        f"- source: {item.get('source', '')}",
        "",
    ]
    # WI-0181, same invariant as `_wi_render_item`: the authored BODY, never the compiled
    # view. Writing the compiled view back would fold every note record into the file and
    # rebuild the append hotspot the records exist to remove.
    notes = (item.get("notes_body") if item.get("notes_body") is not None
             else item.get("notes") or "").strip()
    if notes:
        lines.append(notes)
        lines.append("")
    return "\n".join(lines)


def _ops_parse_text(oid: str, text: str) -> dict:
    """One ops item's dict from its file text."""
    lines = text.splitlines()
    title = oid
    if lines:
        m = OPS_TITLE_RE.match(lines[0])
        if m:
            title = m.group(2).strip()
    item = {"id": oid, "title": title, "status": "open",
            "cadence": OPS_CADENCE_UNSET, "last_completed": "",
            "last_result": OPS_RESULT_UNSET, "due": "", "group": "", "source": ""}
    notes: list[str] = []
    for line in lines[1:]:
        fm = OPS_FIELD_RE.match(line)
        if fm:
            key, val = fm.group(1), fm.group(2).strip()
            key = {"last-completed": "last_completed", "last-result": "last_result"}.get(
                key, key)
            if key in item:
                item[key] = val or item[key]
            continue
        notes.append(line)
    item["notes"] = "\n".join(notes).strip()
    item["notes_body"] = item["notes"]                  # WI-0181 — see `_wi_parse_text`
    return item


def _ops_parse(base: Path | None = None) -> list[dict]:
    """Every item under `ops-items/`, sorted by id. [] if the directory is absent.
    `base` selects which checkout's store to read (see `_ops_dir`)."""
    items: list[dict] = []
    try:
        paths = sorted(_ops_dir(base).glob("OPS-*.md"))
    except Exception:
        return items
    for p in paths:
        m = OPS_FILENAME_RE.match(p.name)
        if not m:
            continue
        try:
            item = _ops_parse_text(f"OPS-{m.group(1)}", p.read_text(encoding="utf-8"))
        except Exception:
            continue
        item["notes"] = _notes_compiled(OPS_DIRNAME, item, base)   # WI-0181
        items.append(item)
    return items


def _ops_write_item(item: dict) -> None:
    """Atomically write ONE ops item's file — the sole writer path.

    The auto-commit hangs here for the same reason it hangs on `_wi_write_item`: one hook
    point the next verb cannot forget. It was missing until WI-0125, so every ops write
    was a write the operator had to notice and save by hand — and from a lane there was
    no route to save it at all, since the store lives in the main checkout and the
    runtime's worktree-isolation guard (correctly) denies the `git -C <main>` redirect."""
    d = _ops_dir()
    d.mkdir(exist_ok=True)
    old_name = _ops_filename_for(item["id"])
    new_name = f"{item['id']}-{_wi_slug(item['title'])}.md"
    atomic_write(d / new_name, _ops_render_item(item))
    if old_name and old_name != new_name:
        (d / old_name).unlink(missing_ok=True)
    changed = [new_name] + ([old_name] if old_name and old_name != new_name else [])
    _store_autocommit(OPS_DIRNAME, changed,
                      f"chore(ops-items): {'update' if old_name else 'add'} "
                      f"{item['id']} — {item['title'].strip()[:60]}",
                      "poga ops commit")
    _wi_feed_write()                              # ops rows are feed rows too


def _ops_existing_max() -> int:
    return _counter_existing_max(_counter("ops"))


