def cmd_wi_edit(args: argparse.Namespace) -> None:
    """Edit an item's TITLE, NOTES or GROUP through the store's own writer.

    The gap this closes (session ~103: the store should be managed by code). `wi-new`
    and `wi-status` covered creation and state, but title/notes/group had no command —
    so changing a note meant opening the file in an editor, and that hand-edit path is
    exactly how WI-0022 came to be *deleted* rather than superseded. Every field an
    operator routinely touches needs a command, or the invariants are only as good as
    whoever last opened the file.

    `--append-notes` is the common case (adding a finding to an existing item without
    re-typing what is already there); `--notes` replaces outright. Retitling regenerates
    the slug and removes the stale filename via `_wi_write_item`, so an id never ends up
    with two files.
    """
    name = _wi_filename_for(args.id)
    if not name:
        print(f"wi-edit: '{args.id}' not found in {WI_DIRNAME}/.")
        sys.exit(1)
    item = _wi_parse_text(args.id, (_wi_dir() / name).read_text(encoding="utf-8"))
    # WI-0289: both prose fields resolve BEFORE anything is written, so a bad path or an
    # oversized inline value refuses with the item untouched rather than half-edited.
    notes = _notes_from_args(args, "wi-edit")
    append = _notes_from_args(args, "wi-edit", "append-notes")
    changed = []
    rewrite = False
    if getattr(args, "title", None):
        item["title"] = args.title.strip()
        changed.append("title")
        rewrite = True
    if notes is not None:
        # Replaces the item file's BODY. Note records are append-only by construction and
        # are NOT touched — said out loud below rather than left for someone to discover,
        # because "replace the notes" not replacing all of what `wi-show` prints is exactly
        # the kind of quiet mismatch this store keeps paying for.
        item["notes_body"] = notes
        item["notes"] = notes
        changed.append("notes")
        rewrite = True
    if getattr(args, "group", None) is not None:
        item["group"] = args.group.strip()
        changed.append("group")
        rewrite = True
    if append:
        # WI-0181: its own record. The item FILE is deliberately not touched, which is what
        # makes two machines appending to the same item a pair of adds instead of a
        # conflict — so this runs after `rewrite` is decided and never sets it.
        if _note_append(WI_DIRNAME, item["id"], append, "poga work commit"):
            changed.append("notes(+)")
        else:
            print("wi-edit: the note could not be written — nothing changed.")
            sys.exit(1)
    if not changed:
        print("wi-edit: nothing to change — pass --title / --notes[-file] / "
              "--append-notes[-file] / --group.")
        sys.exit(2)
    if rewrite:
        _wi_write_item(item)
    else:
        _wi_feed_write()          # the board's surface still rides every store write
    print(f"{item['id']}: updated {', '.join(changed)}")
    if notes is not None:
        kept = len(_notes_records(WI_DIRNAME, item["id"]))
        if kept:
            print(f"         {kept} note record(s) kept — they are append-only and are "
                  f"not replaced by --notes; `poga work show {item['id']}` shows all of it.")


#: How an id the operator TYPED maps to a store. `poga work show` is the one read
#: surface an operator reaches for by reflex, and the two stores share one numbering
#: habit, so it has to answer for both or send the reader back to opening files by hand
#: — which is the exact path `wi-show` exists to remove (WI-0370).
ITEM_ID_RE = re.compile(r"^(?:(WI|OPS)-)?0*(\d+)$", re.IGNORECASE)


def _resolve_item_id(raw: str) -> tuple[str, str] | None:
    """`(store dirname, canonical id)` for an id an operator typed, or None if it matches
    no shape this store knows.

    WI-0370. The old inline form was `raw if raw.upper().startswith("WI-") else
    f"WI-{int(raw):04d}"`, which raised `ValueError: invalid literal for int()` on every
    OPS id — a traceback, not an answer, on a surface whole reviews are read through.

    Three shapes in, never a raise:
      * `OPS-7` / `OPS-0007` -> the obligations store
      * `WI-7`  / `WI-0370`  -> the work-item store
      * `7`                  -> the work-item store, as it has always meant

    Case and short numbers are normalised on the way through, because both were already
    silent wrong answers: `wi-0370` found the FILE (the glob is on the number) and then
    missed the parsed item, whose id is upper-case — an `AttributeError` one line later —
    and `WI-7` found nothing at all while looking like a typo that should have worked.
    """
    m = ITEM_ID_RE.match((raw or "").strip())
    if not m:
        return None
    kind = (m.group(1) or "WI").upper()
    ident = f"{kind}-{int(m.group(2)):04d}"
    return (OPS_DIRNAME if kind == "OPS" else WI_DIRNAME), ident


def cmd_wi_show(args: argparse.Namespace) -> None:
    """Print ONE item in full — every field plus its notes.

    The read-side gap (session ~103: once code manages the store, reading it needs a
    command too). `wi-list` gives titles only, so seeing an item's reasoning, its linked
    brief, or why it is blocked meant opening the file — which put reads back on the
    hand-editing path that `wi-edit` exists to remove, and is where the risk actually
    lives: an operator with the file already open is one keystroke from editing it.

    Accepts `WI-0007`, `OPS-0007` or bare `7` (see `_resolve_item_id`); an OPS id is
    handed to `ops-show`. Resolves live claim and blocked-by state at read time,
    like `wi-list`, rather than trusting what the file says about other items.
    """
    raw = args.id
    resolved = _resolve_item_id(raw)
    if resolved is None:
        # Named, not raised. The shapes are the answer to "what should I have typed?",
        # which a `ValueError` traceback never was.
        print(f"wi-show: '{raw}' is not an id I recognise — expected OPS-0007 (an "
              f"obligation in {OPS_DIRNAME}/), WI-0370 (a work item in {WI_DIRNAME}/), "
              f"or a bare number (7 means WI-0007).")
        sys.exit(2)
    store, wid = resolved
    if store == OPS_DIRNAME:
        # Delegated, never re-rendered. `ops-show` is the one renderer for an obligation
        # and its fields are not this function's fields — state, cadence, last run, due.
        # A second copy here would drift the moment either grew a row.
        return cmd_ops_show(argparse.Namespace(id=wid))
    name = _wi_filename_for(wid)
    if not name:
        print(f"wi-show: '{wid}' not found in {WI_DIRNAME}/.")
        sys.exit(1)
    items = _wi_parse()
    item = next((it for it in items if it["id"] == wid), None)
    live = {it["id"] for it in items if it.get("status") not in WI_TERMINAL}
    claims = _coord_list("claims")
    print(f"{item['id']}: {item['title']}")
    print(f"  status:     {item.get('status')}")
    print(f"  section:    {item.get('section')}")
    if item.get("group"):
        print(f"  group:      {item['group']}")
    blocked = [b for b in item.get("blocked_by") or [] if b in live]
    if item.get("blocked_by"):
        done_deps = [b for b in item["blocked_by"] if b not in live]
        print(f"  blocked-by: {', '.join(item['blocked_by'])}"
              + (f"  (open: {', '.join(blocked)})" if blocked else "  (all resolved)")
              + (f"  (closed: {', '.join(done_deps)})" if done_deps and blocked else ""))
    if item.get("source"):
        print(f"  source:     {item['source']}")
    # Always printed, even when empty — an unset impact is a thing to DO (label it), so
    # hiding the row would make the gap invisible on the one surface built to show an
    # item in full.
    print(f"  impact:     {item.get('impact') or '(unset — `wi-status <id> --impact …`)'}")
    # WI-0323, same argument as `impact` above: always printed, because an unscoped item
    # is a thing to DO and hiding the row makes the one surface built to show an item in
    # full the one surface that cannot see the gap.
    print(f"  scope:      {item.get('scope') or '(unset — `wi-status <id> --scope …`)'}")
    # WI-0408, and the OPPOSITE call to `impact` and `scope` above: printed only when set.
    # Those two are always printed because an unset one is a thing to DO, and hiding the
    # row would make the one surface built to show an item in full the one surface that
    # cannot see the gap. An item waiting on nobody is not a gap — it is the normal case —
    # so a permanent `waiting-on: (nobody)` row would be noise on every item in the store
    # while making the rare real marker harder to spot, which is the whole job of this row.
    if item.get("waiting_on"):
        print(f"  waiting-on: {item['waiting_on']}  (a human owes this an answer; "
              f"clear it with `wi-status <id> --waiting-on ''`)")
    if item.get("migration") == "yes":
        # Only when true — a "migration: no" line on 50 items is noise, and this one is
        # a warning that should stand out where it applies.
        print("  migration:  YES — members must edit their own files when this ships")
    if item.get("version"):
        print(f"  version:    {item['version']}")
    elif item.get("status") in WI_TERMINAL:
        print("  version:    (closed, not yet released)")
    # WI-0308. Printed as what it is — the last time the MECHANICAL premises resolved,
    # not an endorsement of the body — because the whole risk of a receipt is a reader
    # who takes it for more than it says.
    if item.get("probed"):
        print(f"  probed:     {item['probed']}  (citations resolved; not a re-read)")
    if wid in claims:
        rec = claims[wid]
        print(f"  claimed by: {rec.get('branch') or rec.get('session_id', '?')}")
    print(f"  file:       {WI_DIRNAME}/{name}")
    if item.get("notes"):
        print("\n" + item["notes"])


def cmd_wi_move(args: argparse.Namespace) -> None:
    """Move MANY items between sections/statuses in one call.

    The second gap (session ~103). Curating the list — demoting fifteen items from Next
    to Backlog — took fifteen invocations, which is why Next had grown to 21 items and
    stopped meaning "now": the tool made the bloat cheaper to live with than to fix.
    Accepts ids in either `WI-0007` or bare `7` form, reports each one, and refuses the
    whole batch if any id is unknown rather than half-applying it.

    THE STATUS GUARDS RUN AS A PRE-PASS, over every id, before the first write
    (WI-0385). This verb's own contract is all-or-nothing — that is what the unknown-id
    check above is for — and a guard that refused from inside the write loop would
    break it in the one way that is hardest to see afterwards: ids before the offender
    already written, ids after it untouched, and a non-zero exit suggesting nothing
    happened. Checking the whole batch first costs one extra parse per item and keeps
    the promise the verb already makes.
    """
    ids = []
    for raw in args.ids:
        for part in raw.replace(",", " ").split():
            ids.append(part if part.upper().startswith("WI-") else f"WI-{int(part):04d}")
    missing = [i for i in ids if not _wi_filename_for(i)]
    if missing:
        print(f"wi-move: unknown id(s): {', '.join(missing)} — nothing changed.")
        sys.exit(1)
    if not args.section and not args.status:
        print("wi-move: pass --section and/or --status.")
        sys.exit(2)

    def _load(wid: str) -> dict:
        return _wi_parse_text(
            wid, (_wi_dir() / _wi_filename_for(wid)).read_text(encoding="utf-8"))

    if args.status:
        for wid in ids:
            _guard_wi_status_transition(_load(wid), args.status)
    for wid in ids:
        item = _load(wid)
        if args.section:
            item["section"] = args.section
        if args.status:
            item["status"] = args.status
        _wi_write_item(item)
    print(f"wi-move: {len(ids)} item(s) -> "
          + " ".join(x for x in (f"section={args.section}" if args.section else "",
                                 f"status={args.status}" if args.status else "") if x))


